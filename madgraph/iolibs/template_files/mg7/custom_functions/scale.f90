! Custom energy scale for MG7, in Fortran. Generated by bin/init_custom_func.
!
! It is called once per phase-space point and returns
! the renormalization and factorization scale in GeV for one phase-space
! point. The run card scale_factor is applied on top, and fixed scales still
! take precedence.
!
! Parameters:
! particle_count  number of external particles, incoming ones first
! pdg_ids         PDG ids of the external particles
! momenta         momenta(:, i) = (E, px, py, pz) of particle i in GeV, lab frame
!
! Run `make` in this directory to build ../lib/custom_scale.so.

function custom_scale(particle_count, pdg_ids, momenta) bind(C, name="custom_scale") result(value)
    use iso_c_binding
    implicit none
    integer(c_int), value :: particle_count
    integer(c_int), intent(in) :: pdg_ids(particle_count)
    real(c_double), intent(in) :: momenta(0:3, particle_count)
    real(c_double) :: value
    real(c_double) :: p(0:3)

    ! Example: H_T / 2, the scalar sum of the final-state transverse masses.
    ! integer :: i
    ! value = 0d0
    ! do i = 3, particle_count
    !     value = value + sqrt(max(momenta(0, i)**2 - momenta(3, i)**2, 0d0))
    ! end do
    ! value = value / 2d0

    ! default: partonic center-of-mass energy sqrt(s_hat)
    p = momenta(:, 1) + momenta(:, 2)
    value = sqrt(max(p(0)**2 - p(1)**2 - p(2)**2 - p(3)**2, 0d0))
end function custom_scale
