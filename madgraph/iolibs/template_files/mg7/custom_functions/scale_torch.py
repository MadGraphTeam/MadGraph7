"""
Custom energy scale for MG7, in Python with PyTorch. Generated by bin/init_custom_func.

custom_scale is called once per batch of phase-space points, with one array
entry per point. It returns a float64 tensor of shape (batch,) with
the renormalization and factorization scale in GeV per event. The run
card scale_factor is applied on top, and fixed scales still take precedence.

It runs on the device of the run, CPU or GPU. On the CPU, MG7 limits torch
to one thread, since it already calls the function from several threads.

Parameters:
momenta     float64 tensor of shape (batch, particle_count, 4), the momenta
            (E, px, py, pz) of the external particles in GeV, lab frame,
            incoming ones first
pdg_ids     int32 tensor of shape (batch, particle_count), their PDG ids

Enable it in Cards/run_card.toml with
[custom_functions]
scale = "custom_scale/custom_scale.py"
"""

import torch

FRAMEWORK = "torch"


def custom_scale(momenta, pdg_ids):
    # Example: H_T / 2, the scalar sum of the final-state transverse masses.
    # final = momenta[:, 2:]
    # mt = torch.sqrt(torch.clamp(final[..., 0] ** 2 - final[..., 3] ** 2, min=0.))
    # return mt.sum(dim=1) / 2.

    # default: partonic center-of-mass energy sqrt(s_hat)
    p = momenta[:, 0] + momenta[:, 1]
    return torch.sqrt(torch.clamp(p[:, 0] ** 2 - (p[:, 1:] ** 2).sum(dim=1), min=0.))
