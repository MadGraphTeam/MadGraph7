"""
Custom energy scale for MG7, in Python with numpy. Generated by bin/init_custom_func.

custom_scale is called once per batch of phase-space points, with one array
entry per point. It returns a float64 array of shape (batch,) with
the renormalization and factorization scale in GeV per event. The run
card scale_factor is applied on top, and fixed scales still take precedence.

It runs on the CPU only. Use the python-torch template for GPU runs.

Parameters:
momenta     float64 array of shape (batch, particle_count, 4), the momenta
            (E, px, py, pz) of the external particles in GeV, lab frame,
            incoming ones first
pdg_ids     int32 array of shape (batch, particle_count), their PDG ids

Enable it in Cards/run_card.toml with
[custom_functions]
scale = "custom_scale/custom_scale.py"
"""

import numpy as np

FRAMEWORK = "numpy"


def custom_scale(momenta, pdg_ids):
    # Example: H_T / 2, the scalar sum of the final-state transverse masses.
    # final = momenta[:, 2:]
    # mt = np.sqrt(np.maximum(final[..., 0] ** 2 - final[..., 3] ** 2, 0.))
    # return mt.sum(axis=1) / 2.

    # default: partonic center-of-mass energy sqrt(s_hat)
    p = momenta[:, 0] + momenta[:, 1]
    return np.sqrt(np.maximum(p[:, 0] ** 2 - (p[:, 1:] ** 2).sum(axis=1), 0.))
