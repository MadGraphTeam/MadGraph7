class Sample(object):
    def __init__(self, spec):
        parts = spec.split(":")
        if len(parts) < 2:
            raise ValueError(
                "expected LABEL:PATH[:CROSS_SECTION], got %r" % spec
            )
        self.label = parts[0]
        self.path = parts[1]
        self.cross_section = float(parts[2]) if len(parts) > 2 else None
        if not os.path.exists(self.path):
            raise ValueError("no such file: %s" % self.path)

    def __str__(self):
        return self.label


def analyse(sample, args):
    if sample.cross_section is None:
        sample.cross_section = read_cross_section(sample.path)
        if sample.cross_section is not None:
            print(
                "  %s: cross section %g pb read from the file"
                % (sample.label, sample.cross_section)
            )
        else:
            print(
                "  %s: no cross section given or found, normalising to unit area"
                % sample.label
            )

    histograms = DJRHistograms(
        sample.label, args.n_djr, args.bins, args.log_min, args.log_max
    )
    for weight, pdgs, momenta in read_hepmc(sample.path, args.max_events):
        selected = visible_final_state(
            pdgs, momenta, args.eta_max, args.exclude_pdg
        )
        djrs = differential_jet_rates(selected, args.radius, args.n_djr)
        histograms.fill(djrs, weight)
    histograms.normalise(sample.cross_section)
    print("  %s: %d events" % (sample.label, histograms.event_count))
    return histograms


def smoothness_across(centres, total, errors, qcut, window=2):
    """How big a step the summed distribution has across the merging scale.

    Interpolate log(sum) across qcut from the `window` bins on each side and
    compare with what is actually in the bins that straddle it. A merging that
    works gives 1 within the uncertainty; a normalisation mismatch between the
    samples, or a qcut they do not agree on, shows up as a departure from 1.

    Interpolating locally rather than extrapolating a fit from each side
    matters: a DJR distribution has a maximum not far from qcut, and a
    straight-line fit through a curved distribution lands well off the mark and
    reports a step that is not there.

    Returns (ratio, uncertainty) or (None, None) when the bins around qcut are
    not filled well enough to say anything.
    """
    log_qcut = math.log10(qcut)
    width = centres[1] - centres[0]
    index = int(np.searchsorted(centres, log_qcut))

    left = slice(max(index - 1 - window, 0), max(index - 1, 0))
    right = slice(index + 1, index + 1 + window)
    middle = slice(max(index - 1, 0), index + 1)

    x = np.concatenate([centres[left], centres[right]])
    y = np.concatenate([total[left], total[right]])
    if len(x) < 2 or np.any(y <= 0):
        return None, None

    slope, intercept = np.polyfit(x, np.log(y), 1)
    predicted = np.exp(slope * centres[middle] + intercept)
    observed = total[middle]
    if len(observed) == 0 or np.any(predicted <= 0):
        return None, None

    ratio = float(np.mean(observed / predicted))
    # statistical uncertainty of the straddling bins, plus the scatter of the
    # bins the interpolation is built on
    statistical = float(
        np.sqrt(np.sum(errors[middle] ** 2)) / max(np.sum(observed), 1e-30)
    )
    residual = np.log(y) - (slope * x + intercept)
    scatter = float(np.sqrt(np.mean(residual**2)))
    return ratio, ratio * math.sqrt(statistical**2 + scatter**2)


def report_smoothness(histograms, args):
    """Print the step in the summed distribution at qcut, per jet rate."""
    if not args.qcut:
        return
    print(
        "\nContinuity of the summed distribution across qcut = %g GeV\n"
        "(what is in the bins straddling qcut, over what the neighbouring bins\n"
        " interpolate to; 1 means the samples hand over without a step)"
        % args.qcut
    )
    centres = histograms[0].centres
    for index in range(args.n_djr):
        total = sum(h.values[index] for h in histograms)
        errors = np.sqrt(sum(h.errors2[index] for h in histograms))
        ratio, uncertainty = smoothness_across(centres, total, errors, args.qcut)
        name = "d%d%d" % (index, index + 1)
        if ratio is None:
            print("  %s : not enough filled bins on both sides of qcut" % name)
            continue
        pull = abs(ratio - 1.0) / uncertainty if uncertainty else float("inf")
        verdict = "smooth" if pull < 2.0 else "STEP"
        print(
            "  %s : ratio %6.3f +- %5.3f  (%.1f sigma)  %s"
            % (name, ratio, uncertainty, pull, verdict)
        )


def write_table(path, histograms, args):
    """Plain columns, so the numbers can be checked without matplotlib."""
    with open(path, "w") as out:
        out.write("# differential jet rates reconstructed from the showered event record\n")
        out.write(
            "# kT algorithm, R = %g, |eta| < %g, visible final state\n"
            % (args.radius, args.eta_max)
        )
        if args.qcut:
            out.write("# qcut = %g GeV (log10 = %.4f)\n" % (args.qcut, math.log10(args.qcut)))
        for index in range(args.n_djr):
            out.write("\n# d%d%d : dsigma/dlog10(DJR) [pb]\n" % (index, index + 1))
            header = ["log10(DJR)"] + [h.label for h in histograms] + ["sum"]
            out.write("# " + "  ".join("%16s" % name for name in header) + "\n")
            total = sum(h.values[index] for h in histograms)
            for bin_index, centre in enumerate(histograms[0].centres):
                row = [centre] + [h.values[index][bin_index] for h in histograms]
                row.append(total[bin_index])
                out.write("  " + "  ".join("%16.8g" % value for value in row) + "\n")
    print("wrote %s" % path)


def make_plots(prefix, histograms, args):
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import matplotlib.gridspec as gridspec
    except ImportError:
        print(
            "matplotlib is not available, so only the table was written; "
            "plot %s_djr.dat by hand or install matplotlib" % prefix
        )
        return

    for index in range(args.n_djr):
        figure = plt.figure(figsize=(6.5, 5.5))
        grid = gridspec.GridSpec(2, 1, height_ratios=[4, 1])
        grid.update(hspace=0.05)
        main = plt.subplot(grid[0])
        ratio = plt.subplot(grid[1])

        centres = histograms[0].centres
        total = sum(h.values[index] for h in histograms)
        total_error = np.sqrt(sum(h.errors2[index] for h in histograms))

        for histogram in histograms:
            main.step(
                centres,
                histogram.values[index],
                where="mid",
                label=histogram.label,
                linewidth=1.2,
            )
        main.step(
            centres, total, where="mid", label="sum", color="black", linewidth=1.8
        )
        main.fill_between(
            centres,
            total - total_error,
            total + total_error,
            step="mid",
            color="black",
            alpha=0.2,
            linewidth=0,
        )

        if args.qcut:
            for axis in (main, ratio):
                axis.axvline(
                    math.log10(args.qcut), color="grey", linestyle="--", linewidth=1
                )
            main.text(
                math.log10(args.qcut),
                main.get_ylim()[1],
                " qcut",
                va="top",
                color="grey",
                fontsize=9,
            )

        main.set_yscale("log")
        main.set_ylabel(r"$d\sigma/d\log_{10}(\mathrm{DJR})$ [pb]")
        main.set_title("Differential jet rate $d_{%d%d}$" % (index, index + 1))
        main.set_xticklabels([])
        main.legend(loc="best", fontsize=9, ncol=2)

        # each sample's share of the total: this is where a step at qcut shows
        with np.errstate(divide="ignore", invalid="ignore"):
            for histogram in histograms:
                share = np.where(total > 0, histogram.values[index] / total, np.nan)
                ratio.step(centres, share, where="mid", linewidth=1.2)
        ratio.set_ylim(0.0, 1.05)
        ratio.set_ylabel("fraction")
        ratio.set_xlabel(r"$\log_{10}(\mathrm{DJR}/\mathrm{GeV})$")

        path = "%s_d%d%d.%s" % (prefix, index, index + 1, args.format)
        figure.savefig(path, bbox_inches="tight")
        plt.close(figure)
        print("wrote %s" % path)


def build_parser():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--sample",
        action="append",
        required=True,
        metavar="LABEL:PATH[:XSEC_PB]",
        help="a jet-multiplicity sample; repeat once per sample",
    )
    parser.add_argument(
        "--qcut",
        type=float,
        default=None,
        help="merging scale in GeV, drawn as a line on the plots",
    )
    parser.add_argument(
        "--radius",
        type=float,
        default=DEFAULT_RADIUS,
        help="jet radius, i.e. JetMatching:coneRadius (default %(default)s)",
    )
    parser.add_argument(
        "--eta-max",
        type=float,
        default=DEFAULT_ETA_MAX,
        help="acceptance for the clustered particles, i.e. "
        "JetMatching:etaJetMax (default %(default)s, no cut)",
    )
    parser.add_argument(
        "--n-djr",
        type=int,
        default=DEFAULT_N_DJR,
        help="how many jet rates to compute (default %(default)s)",
    )
    parser.add_argument("--bins", type=int, default=50)
    parser.add_argument("--log-min", type=float, default=0.0)
    parser.add_argument("--log-max", type=float, default=3.0)
    parser.add_argument(
        "--max-events",
        type=int,
        default=None,
        help="stop after this many events per sample",
    )
    parser.add_argument("--output-prefix", default="djr")
    parser.add_argument(
        "--exclude-pdg",
        type=lambda text: frozenset(abs(int(v)) for v in text.split(",")),
        default=None,
        help="comma-separated |pdg| to keep out of the clustering "
        "(default: the tops, leptons, photon and bosons that "
        "JetMatchingMadgraph excludes)",
    )
    parser.add_argument(
        "--format", default="pdf", help="plot file format (default %(default)s)"
    )
    parser.add_argument(
        "--no-plot", action="store_true", help="write the table but no plot"
    )
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)
    samples = [Sample(spec) for spec in args.sample]

    print(
        "clustering with the kT algorithm, R = %g, |eta| < %g"
        % (args.radius, args.eta_max)
    )
    histograms = [analyse(sample, args) for sample in samples]

    missing = [h.label for h, s in zip(histograms, samples) if s.cross_section is None]
    if missing and len(samples) > 1:
        print(
            "\nWARNING: no cross section for %s, so the samples are not on a\n"
            "         common normalisation and their sum is meaningless.\n"
            "         Pass it as LABEL:PATH:XSEC to check that the sum is smooth."
            % ", ".join(missing)
        )

    report_smoothness(histograms, args)
    write_table("%s_djr.dat" % args.output_prefix, histograms, args)
    if not args.no_plot:
        make_plots(args.output_prefix, histograms, args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
