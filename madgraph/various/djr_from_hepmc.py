"""Differential jet rates from a showered HepMC file, for validating MLM merging.

Reads the final state of a showered event file, reruns the kT jet algorithm on
it with the same parameters the jet-matching veto uses, and records the
clustering scale of every step. Reversed, those are the differential jet rates:

    DJR_{n->n+1}, written d01, d12, d23, ... - the scale at which an event
    stops being resolved as n jets and starts being resolved as n+1.

Why this is the plot to look at
-------------------------------
In kT-MLM the veto clusters the showered event with SlowJet (kT, radius
JetMatching:coneRadius, |eta| < JetMatching:etaJetMax, visible final-state
particles) and compares the resulting jets against the matrix-element partons
at JetMatching:qCut. Reconstructing the same clustering here puts the DJRs on
exactly the scale the veto acts on, so each multiplicity sample has to switch
off where the next one switches on:

  * d01 is filled below qCut by the 0-jet sample (its hardest jet can only come
    from the shower) and above qCut by the 1-jet sample (its hardest jet is a
    matrix-element parton),
  * d12 likewise separates the 1-jet and 2-jet samples, and so on.

Summed over samples the distribution has to be smooth across qCut. A step, a
gap or a bump there means the merging is not working: the samples are either
double counting or leaving a hole.

Because the clustering is redone here from the particle record, the result is
independent of the merging implementation being validated. In particular it
does not need the djrs.dat that the MG5aMC-PY8 interface writes, and it works
the same for events generated by madevent and by madspace/mg7.

Usage
-----
    djr_from_hepmc.py --sample 0j:wj0.hepmc:1234.5 \\
                      --sample 1j:wj1.hepmc:567.8 \\
                      --qcut 30 --output-prefix djr

Each --sample is LABEL:PATH[:CROSS_SECTION_IN_PB]. Without a cross section the
one recorded in the file is used, and failing that the sample is normalised to
unit area, which is enough to see the shapes line up but not to check that the
sum is smooth.
"""

from __future__ import absolute_import

import argparse
import gzip
import math
import os
import sys

import numpy as np


# Defaults matching the MG5aMC Pythia8 card (see JetMatching:* in banner.py).
DEFAULT_RADIUS = 1.0
DEFAULT_ETA_MAX = 1000.0
DEFAULT_N_DJR = 4

# Particles the jet matching keeps out of the clustering. This is the list
# JetMatchingMadgraph applies when it builds workEventJet, the event it both
# vetoes on and takes its own DJRs from:
#
#     // Original AG+Py6 algorithm explicitly excludes tops,
#     // leptons and photons.
#     if ((id >= ID_LEPMIN && id <= ID_LEPMAX) || id == ID_TOP
#       || id == ID_PHOTON || id == 23 || id == 24 || id == 25) ...
#
# i.e. charged leptons and neutrinos (11-16), the top, the photon and the
# electroweak bosons. Getting this wrong does not fail loudly, it just fills
# the rates with things the veto never looked at: for t tbar + jets the top
# decay products swamp d01 and d12 and the merging structure disappears.
NON_JET_PDGS = frozenset([11, 12, 13, 14, 15, 16, 6, 22, 23, 24, 25])

# workEventJet is built from the hardest subsystem plus ISR and FSR, with no
# resonance showers, so the shower has to be run with the resonances left
# undecayed for the reconstruction to see the same final state.


################################################################################
# reading the event file
################################################################################


def open_maybe_gzip(path):
    if path.endswith(".gz"):
        return gzip.open(path, "rt", errors="replace")
    return open(path, "r", errors="replace")


class HepMCFormatError(Exception):
    pass


def read_hepmc(path, max_events=None):
    """Yield (weight, pdg_ids, momenta) for each event in a HepMC file.

    momenta is an (n, 4) array of (px, py, pz, E) for the final-state particles
    only. Both the HepMC2 and the HepMC3 ascii formats are understood; they
    differ in the particle line by one leading field.

    This reads only what the clustering needs, and skips the vertex records
    entirely, which is what makes it fast enough to run over a full sample.
    """
    version = None
    with open_maybe_gzip(path) as stream:
        pdgs, momenta, weight = [], [], 1.0
        in_event = False
        for line in stream:
            if not line:
                continue
            code = line[0]

            if code == "H" or line.startswith("HepMC::"):
                if "Asciiv3" in line or "Version 3" in line:
                    version = 3
                elif "IO_GenEvent" in line or "Version 2" in line:
                    version = 2
                continue

            if code == "E":
                if in_event:
                    yield weight, np.array(pdgs, dtype=np.int64), _as_momenta(momenta)
                    if max_events is not None:
                        max_events -= 1
                        if max_events <= 0:
                            return
                pdgs, momenta = [], []
                in_event = True
                weight = _event_line_weight(line, version)
                continue

            if not in_event:
                continue

            if code == "W":
                # HepMC3 keeps the weights on their own line
                fields = line.split()
                if len(fields) > 1:
                    weight = float(fields[1])
                continue

            if code == "P":
                fields = line.split()
                # HepMC2: P barcode pdg px py pz E m status ...
                # HepMC3: P id  vtx  pdg px py pz E m status
                offset = 3 if _particle_line_is_v3(fields, version) else 2
                if len(fields) < offset + 7:
                    continue
                if int(fields[offset + 6]) != 1:
                    continue  # not a final-state particle
                pdgs.append(int(fields[offset]))
                momenta.append(
                    (
                        float(fields[offset + 1]),
                        float(fields[offset + 2]),
                        float(fields[offset + 3]),
                        float(fields[offset + 4]),
                    )
                )

        if in_event:
            yield weight, np.array(pdgs, dtype=np.int64), _as_momenta(momenta)


def _as_momenta(momenta):
    if not momenta:
        return np.zeros((0, 4))
    return np.array(momenta, dtype=float)


def _particle_line_is_v3(fields, version):
    if version == 3:
        return True
    if version == 2:
        return False
    # No usable header: HepMC3 particle lines carry one more leading integer
    # than HepMC2 ones, and the status is the last field either way.
    return len(fields) >= 10 and fields[9].lstrip("-").isdigit()


def _event_line_weight(line, version):
    """The event weight from an E line. HepMC3 puts weights on a W line
    instead, so this returns 1 there and the W handler overwrites it."""
    fields = line.split()
    if version == 3 or len(fields) < 12:
        return 1.0
    try:
        # E num nmpi scale aQCD aQED sig_id sig_vtx nvtx beam1 beam2 nrandom ...
        index = 11
        n_random = int(fields[index])
        index += 1 + n_random
        n_weights = int(fields[index])
        if n_weights < 1:
            return 1.0
        return float(fields[index + 1])
    except (ValueError, IndexError):
        return 1.0


def read_cross_section(path):
    """The cross section in pb recorded in the file, or None.

    HepMC writes a running estimate on every event, so the last one is the
    converged value for the sample.
    """
    value = None
    with open_maybe_gzip(path) as stream:
        for line in stream:
            if line.startswith("C "):
                fields = line.split()
                if len(fields) >= 2:
                    try:
                        value = float(fields[1])
                    except ValueError:
                        pass
    return value


################################################################################
# the kT clustering
################################################################################


def rapidity(pz, energy):
    """y = 0.5 log((E + pz) / (E - pz)), clipped so that a particle exactly
    along the beam does not produce an infinity."""
    numerator = np.maximum(energy + pz, 1e-12)
    denominator = np.maximum(energy - pz, 1e-12)
    return 0.5 * np.log(numerator / denominator)


def clustering_scales(momenta, radius=DEFAULT_RADIUS):
    """Run the hadron-collider kT algorithm and return sqrt(d) for every step.

    The measures are the standard ones, and the ones SlowJet uses with
    slowJetPower = 1:

        d_ij = min(pT_i^2, pT_j^2) * dR_ij^2 / R^2 ,   dR^2 = dy^2 + dphi^2
        d_iB = pT_i^2

    A step either combines the closest pair or promotes a cluster to a jet,
    whichever measure is smaller; the sequence therefore ends with the beam
    distances of the final jets, so the largest scale is the pT of the hardest
    jet. Values come back in the order the algorithm found them, i.e. smallest
    first.
    """
    n = len(momenta)
    if n == 0:
        return np.empty(0)

    px = momenta[:, 0].astype(float).copy()
    py = momenta[:, 1].astype(float).copy()
    pz = momenta[:, 2].astype(float).copy()
    energy = momenta[:, 3].astype(float).copy()

    pt2 = px * px + py * py
    y = rapidity(pz, energy)
    phi = np.arctan2(py, px)
    r2 = radius * radius

    # d_ij for every pair, with the diagonal and the lower triangle masked off
    # so that each pair appears once
    delta_y = y[:, None] - y[None, :]
    delta_phi = np.abs(phi[:, None] - phi[None, :])
    delta_phi = np.minimum(delta_phi, 2.0 * math.pi - delta_phi)
    dij = np.minimum(pt2[:, None], pt2[None, :]) * (
        delta_y**2 + delta_phi**2
    ) / r2
    dij[np.tril_indices(n)] = np.inf

    # Scanning the whole matrix at every step would make the clustering cubic
    # in the number of particles, which is minutes per thousand events for a
    # hadron-level record. Keeping the minimum of each row instead makes the
    # search linear; the rows that can be invalidated by a step are the ones
    # whose minimum pointed at a cluster that just changed.
    alive = np.ones(n, dtype=bool)
    beam = pt2.copy()
    row_min = dij.min(axis=1)
    row_arg = dij.argmin(axis=1)

    state = _ClusterState(dij, alive, beam, row_min, row_arg, pt2, y, phi, r2)

    scales = []
    for _ in range(n):
        pair_row = int(np.argmin(row_min))
        pair_distance = row_min[pair_row]
        beam_index = int(np.argmin(beam))
        beam_distance = beam[beam_index]

        if beam_distance <= pair_distance:
            scales.append(beam_distance)
            state.drop(beam_index)
            continue

        i, j = pair_row, int(row_arg[pair_row])
        scales.append(pair_distance)
        # E-scheme recombination: add the four-momenta
        px[i] += px[j]
        py[i] += py[j]
        pz[i] += pz[j]
        energy[i] += energy[j]
        state.drop(j)

        pt2[i] = px[i] * px[i] + py[i] * py[i]
        y[i] = 0.5 * math.log(
            max(energy[i] + pz[i], 1e-12) / max(energy[i] - pz[i], 1e-12)
        )
        phi[i] = math.atan2(py[i], px[i])
        beam[i] = pt2[i]
        state.refresh(i)

    return np.sqrt(np.array(scales))


class _ClusterState(object):
    """Bookkeeping for the cached row minima of the distance matrix."""

    def __init__(self, dij, alive, beam, row_min, row_arg, pt2, y, phi, r2):
        self.dij = dij
        self.alive = alive
        self.beam = beam
        self.row_min = row_min
        self.row_arg = row_arg
        self.pt2 = pt2
        self.y = y
        self.phi = phi
        self.r2 = r2

    def _recompute_row(self, r):
        self.row_min[r] = self.dij[r].min()
        self.row_arg[r] = self.dij[r].argmin()

    def _revalidate_rows_pointing_at(self, index):
        rows = np.where((self.row_arg == index) & self.alive)[0]
        for r in rows:
            self._recompute_row(int(r))

    def drop(self, index):
        """Take a cluster out of the event."""
        self.alive[index] = False
        self.beam[index] = np.inf
        self.dij[index, :] = np.inf
        self.dij[:, index] = np.inf
        self.row_min[index] = np.inf
        self.row_arg[index] = index
        self._revalidate_rows_pointing_at(index)

    def refresh(self, i):
        """Recompute every distance involving cluster i, whose momentum
        changed, and repair the row minima that depended on them."""
        others = np.where(self.alive)[0]
        others = others[others != i]
        if len(others):
            delta_y = self.y[i] - self.y[others]
            delta_phi = np.abs(self.phi[i] - self.phi[others])
            delta_phi = np.minimum(delta_phi, 2.0 * math.pi - delta_phi)
            values = (
                np.minimum(self.pt2[i], self.pt2[others])
                * (delta_y**2 + delta_phi**2)
                / self.r2
            )
            # keep the upper-triangle convention so each pair is stored once
            below = others < i
            self.dij[others[below], i] = values[below]
            self.dij[i, others[~below]] = values[~below]

        self._recompute_row(i)
        # every row above i now has a different entry in column i
        for r in np.where(self.alive)[0]:
            r = int(r)
            if r >= i:
                continue
            if self.row_arg[r] == i or self.dij[r, i] < self.row_min[r]:
                self._recompute_row(r)


def differential_jet_rates(momenta, radius=DEFAULT_RADIUS, count=DEFAULT_N_DJR):
    """The first `count` DJRs, largest first: d01, d12, d23, ...

    Entries beyond the number of clustering steps the event has come back as
    NaN and are simply not filled, which is what keeps a low-multiplicity
    sample from contributing a spurious entry at zero.
    """
    scales = clustering_scales(momenta, radius)
    result = np.full(count, np.nan)
    take = min(count, len(scales))
    if take:
        result[:take] = scales[::-1][:take]
    return result


def visible_final_state(pdgs, momenta, eta_max=DEFAULT_ETA_MAX, exclude=None):
    """The particles the matching would cluster: light partons inside the
    acceptance, with the tops, leptons, photons and bosons taken out."""
    if len(pdgs) == 0:
        return momenta
    excluded = NON_JET_PDGS if exclude is None else exclude
    keep = ~np.isin(np.abs(pdgs), list(excluded))
    if eta_max < 100.0:
        px, py, pz = momenta[:, 0], momenta[:, 1], momenta[:, 2]
        p = np.sqrt(px * px + py * py + pz * pz)
        # pseudorapidity, guarded for a particle exactly along the beam
        eta = 0.5 * np.log(np.maximum(p + pz, 1e-12) / np.maximum(p - pz, 1e-12))
        keep &= np.abs(eta) < eta_max
    return momenta[keep]


