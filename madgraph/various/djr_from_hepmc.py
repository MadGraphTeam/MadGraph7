class DJRHistograms(object):
    """log10(DJR/GeV) histograms for one sample, one per jet rate."""

    def __init__(self, label, count, bins, low, high):
        self.label = label
        self.count = count
        self.edges = np.linspace(low, high, bins + 1)
        self.values = np.zeros((count, bins))
        self.errors2 = np.zeros((count, bins))
        self.event_count = 0
        self.weight_sum = 0.0

    def fill(self, djrs, weight):
        self.event_count += 1
        self.weight_sum += weight
        for index, value in enumerate(djrs):
            if not np.isfinite(value) or value <= 0.0:
                continue
            bin_index = np.searchsorted(self.edges, math.log10(value)) - 1
            if 0 <= bin_index < self.values.shape[1]:
                self.values[index, bin_index] += weight
                self.errors2[index, bin_index] += weight * weight

    def normalise(self, cross_section):
        """Turn the weight sums into dsigma/dlog10(DJR) in pb.

        With a cross section the sample carries its physical normalisation, so
        the samples can be added; without one each is scaled to unit area,
        which shows the shapes but says nothing about the sum.
        """
        width = self.edges[1] - self.edges[0]
        if cross_section is None:
            scale = 1.0 / (self.weight_sum * width) if self.weight_sum else 0.0
        else:
            scale = cross_section / (self.weight_sum * width) if self.weight_sum else 0.0
        self.values *= scale
        self.errors2 *= scale * scale

    @property
    def errors(self):
        return np.sqrt(self.errors2)

    @property
    def centres(self):
        return 0.5 * (self.edges[:-1] + self.edges[1:])


