"""Chili with fixed beams (lepton colliders).

With fixed beams the incoming momenta add up to P = (sqrt(s), 0, 0, 0), and the
final state has no longitudinal freedom left. ChiliMapping(fixed_beams=True)
generates the first n - 2 momenta as chili does (pT, y, phi, with the exact
energy bound on y), and the last two as the two-body decay of
Q = P - sum p_i in the rest frame of Q, from 3n - 4 random numbers.
PhaseSpaceMapping takes it for chili with leptonic beams, whose momenta, on
their mass shells if they are massive, it builds itself. With dressed-lepton
beams the split of the luminosity samples x1 and x2, and chili builds the
final state for fixed beams in their partonic frame.

The forward map is a bijection onto the phase space with its density if it
gives the volume of rambo, if its inverse takes every rambo event into the unit
cube, and if the inverse gives back the random numbers and the inverse
Jacobian. With a density g = 1 / det of the inverse,
E_rambo[w g] over a region R is the fraction of chili events in R, a test of
the density everywhere.
"""

import math

import numpy as np
import pytest
from madspace_testing import to_numpy
from pytest import approx

import madspace as ms

# numpy inputs, which madspace runs on the CPU
pytestmark = pytest.mark.cpu_only

PSM = ms.PhaseSpaceMapping
SQRT_S = 1000.0

# outgoing masses, the heavy particle among the first n - 2 (generated by
# chili) and among the last two (the decay)
OUTGOING = {
    "2 massless": [0.0, 0.0],
    "2 t tbar": [173.0, 173.0],
    "3 massless": [0.0, 0.0, 0.0],
    "3 heavy first": [173.0, 0.0, 10.0],
    "3 heavy last": [0.0, 173.0, 10.0],
    "4 massless": [0.0, 0.0, 0.0, 0.0],
    "5 with W": [80.0, 0.0, 0.0, 0.0, 0.0],
}
BEAMS = {"massless beams": [0.0, 0.0], "W Z beams": [80.4, 91.2]}


def make(m_in, m_out, mode="chili", cuts=None):
    kwargs = {} if cuts is None else {"cuts": cuts}
    return PSM(
        list(m_in) + list(m_out),
        SQRT_S,
        leptonic=True,
        mode=getattr(PSM, mode),
        **kwargs,
    )


def jet_cuts(n_out, pt_min=30.0, eta_max=2.0):
    """pt and |eta| cuts on the outgoing particles, all jets"""
    O = ms.Observable
    pids = [11, -11] + [21] * n_out
    return ms.Cuts(
        [
            ms.CutItem(O(pids, O.obs_pt, [O.jet_pids]), min=pt_min),
            ms.CutItem(O(pids, O.obs_eta_abs, [O.jet_pids]), max=eta_max),
        ]
    )


def in_cuts(p, pt_min=30.0, eta_max=2.0):
    q = p[:, 2:]
    pt = np.hypot(q[..., 1], q[..., 2])
    with np.errstate(divide="ignore", invalid="ignore"):
        eta = np.arctanh(q[..., 3] / np.sqrt(pt**2 + q[..., 3] ** 2))
    return np.all((pt > pt_min) & (np.abs(eta) < eta_max), axis=1)


def forward(mapping, seed, n):
    r = np.random.default_rng(seed).random((n, mapping.random_dim()))
    p, x1, x2, det = map(to_numpy, mapping.map_forward([r], []))
    return r, p, np.broadcast_to(x1, (n,)), np.broadcast_to(x2, (n,)), det


def inverse(mapping, p, x1, x2):
    result = mapping.map_inverse(
        [p, np.ascontiguousarray(x1), np.ascontiguousarray(x2)], []
    )
    return to_numpy(result[0]), to_numpy(result[-1])


def mass2(p):
    return p[..., 0] ** 2 - p[..., 1] ** 2 - p[..., 2] ** 2 - p[..., 3] ** 2


def mean_and_error(w):
    return w.mean(), w.std() / math.sqrt(len(w))


def test_random_dim():
    for n in range(2, 6):
        args = (n, [math.inf] * n, [0.0] * n)
        fixed = ms.ChiliMapping(*args, fixed_beams=True)
        assert fixed.fixed_beams() and fixed.random_dim() == 3 * n - 4
        assert ms.ChiliMapping(*args).random_dim() == 3 * n - 2
        m_out = [0.0] * n
        assert make([0.0, 0.0], m_out).random_dim() == 3 * n - 4
        assert (
            make([0.0, 0.0], m_out).random_dim()
            == make([0.0, 0.0], m_out, "rambo").random_dim()
        )
    with pytest.raises(ValueError):
        ms.ChiliMapping(1, [math.inf], [0.0], fixed_beams=True)


@pytest.mark.parametrize("m_in", BEAMS.values(), ids=BEAMS.keys())
@pytest.mark.parametrize("m_out", OUTGOING.values(), ids=OUTGOING.keys())
def test_momenta(m_in, m_out):
    """The beams with their sum at rest, x1 = x2 = 1, every particle on its
    mass shell and momentum conservation."""
    _, p, x1, x2, det = forward(make(m_in, m_out), 1, 4000)
    ok = det > 0
    assert np.all(det >= 0) and ok.mean() > 0.3
    assert np.all(x1 == 1.0) and np.all(x2 == 1.0)
    p = p[ok]
    for leg, mass in enumerate(list(m_in) + list(m_out)):
        assert mass2(p[:, leg]) == approx(mass**2, abs=1e-10 * SQRT_S**2)
    assert np.all(p[:, :2, 1:3] == 0.0) and np.all(p[:, 0, 3] > 0.0)
    total = np.array([SQRT_S, 0.0, 0.0, 0.0])
    assert p[:, :2].sum(axis=1) == approx(
        np.broadcast_to(total, (len(p), 4)), abs=1e-12 * SQRT_S
    )
    assert p[:, 2:].sum(axis=1) == approx(
        np.broadcast_to(total, (len(p), 4)), abs=1e-10 * SQRT_S
    )


# without cuts chili samples four and more massless particles with weights of
# a variance too large for a test of the volume, so those have cuts below
VOLUME = {name: m_out for name, m_out in OUTGOING.items() if len(m_out) <= 3}


@pytest.mark.parametrize("m_out", VOLUME.values(), ids=VOLUME.keys())
def test_volume(m_out):
    """The phase-space volume of rambo, with a heavy particle among the first
    n - 2 too (with the bound acosh(sqrt(s) / (2 mT)) of hadronic chili on y
    it lost 7% of [173, 0, 10]). Two particles are the decay of P alone, with
    the two-body volume as a constant Jacobian."""
    n = 1000000
    w_chili = forward(make([0.0, 0.0], m_out), 2, n)[-1]
    if len(m_out) == 2:
        s, (m1, m2) = SQRT_S**2, m_out
        root = math.sqrt((s - (m1 + m2) ** 2) * (s - (m1 - m2) ** 2))
        assert w_chili == approx(root / s / (8.0 * math.pi), rel=1e-12)
        return
    w_rambo = forward(make([0.0, 0.0], m_out, "rambo"), 3, n)[-1]
    (a, error_a), (b, error_b) = mean_and_error(w_chili), mean_and_error(w_rambo)
    assert abs(a - b) < 5.0 * math.hypot(error_a, error_b)


@pytest.mark.parametrize("cuts", [False, True], ids=["no-cuts", "cuts"])
@pytest.mark.parametrize("m_in", BEAMS.values(), ids=BEAMS.keys())
@pytest.mark.parametrize("m_out", OUTGOING.values(), ids=OUTGOING.keys())
def test_round_trip(m_out, m_in, cuts):
    """The inverse gives back the random numbers and the inverse Jacobian,
    also at large rapidities."""
    mapping = make(m_in, m_out, cuts=jet_cuts(len(m_out)) if cuts else None)
    r, p, x1, x2, det = forward(mapping, 5, 4000)
    ok = det > 0
    r_inv, det_inv = inverse(mapping, p[ok], x1[ok], x2[ok])
    assert r_inv == approx(r[ok], abs=1e-10)
    assert det_inv * det[ok] == approx(1.0, rel=1e-10)


@pytest.mark.parametrize("cuts", [False, True], ids=["no-cuts", "cuts"])
@pytest.mark.parametrize("m_out", OUTGOING.values(), ids=OUTGOING.keys())
def test_covers_the_phase_space(m_out, cuts):
    """The inverse takes every rambo event into the unit cube, and with cuts,
    which keep the density g = 1 / det away from the soft and collinear
    regions, E_rambo[w g] over the region of the cuts is the fraction of chili
    events in it."""
    n = 100000
    kwargs = dict(cuts=jet_cuts(len(m_out))) if cuts else {}
    chili = make([0.0, 0.0], m_out, **kwargs)
    rambo = make([0.0, 0.0], m_out, "rambo", **kwargs)
    _, p, x1, x2, w = forward(rambo, 6, n)
    region = (w > 0) & (in_cuts(p) if cuts else True)
    r, g = inverse(chili, p[region], x1[region], x2[region])
    assert np.all((r >= 0.0) & (r <= 1.0))
    assert np.all(np.isfinite(g) & (g > 0.0))
    if not cuts:
        return
    lhs = np.zeros(n)
    lhs[region] = w[region] * g
    _, p_c, _, _, w_c = forward(chili, 7, n)
    rhs = ((w_c > 0) & in_cuts(p_c)).astype(float)
    (a, error_a), (b, error_b) = mean_and_error(lhs), mean_and_error(rhs)
    assert b > 0.05
    assert abs(a - b) < 5.0 * math.hypot(error_a, error_b)


def dressed(m_in, m_out, mode="chili", cuts=None):
    """beams with a dressed-lepton density: x1 and x2 from the split"""
    kwargs = {} if cuts is None else {"cuts": cuts}
    return PSM(
        list(m_in) + list(m_out),
        SQRT_S,
        leptonic=False,
        mode=getattr(PSM, mode),
        lepton_sampling_power=0.96,
        **kwargs,
    )


def forward_dressed(mapping, seed, n):
    r = np.random.default_rng(seed).random((n, mapping.random_dim()))
    return [to_numpy(out) for out in mapping.map_forward([r], [])]


@pytest.mark.parametrize("m_in", BEAMS.values(), ids=BEAMS.keys())
def test_dressed_lepton_beams(m_in):
    """The split draws x1, x2 and 1 - x first, the same as for rambo, and chili
    the final state of the partonic frame, boosted to the lab: momentum
    conservation, every particle on its mass shell, and the volume of
    rambo."""
    m_out = [80.4, 80.4, 0.0]
    chili, rambo = dressed(m_in, m_out), dressed(m_in, m_out, "rambo")
    assert chili.random_dim() == rambo.random_dim() == 3 * len(m_out) - 1
    n = 200000
    p, *fractions, det = forward_dressed(chili, 8, n)
    _, *fractions_rambo, det_rambo = forward_dressed(rambo, 8, n)
    for a, b in zip(fractions, fractions_rambo):
        assert np.array_equal(a, b)
    x1, x2 = fractions[:2]
    ok = det > 0
    assert ok.mean() > 0.5
    p, x1, x2 = p[ok], x1[ok], x2[ok]
    half = 0.5 * SQRT_S
    total = np.stack([half * (x1 + x2), 0.0 * x1, 0.0 * x1, half * (x1 - x2)], axis=1)
    assert p[:, :2].sum(axis=1) == approx(total, abs=1e-12 * SQRT_S)
    assert p[:, 2:].sum(axis=1) == approx(total, abs=1e-10 * SQRT_S)
    for leg, mass in enumerate(list(m_in) + m_out):
        assert mass2(p[:, leg]) == approx(mass**2, abs=1e-10 * SQRT_S**2)
    (a, error_a), (b, error_b) = mean_and_error(det), mean_and_error(det_rambo)
    assert abs(a - b) < 5.0 * math.hypot(error_a, error_b)


def test_dressed_lepton_beams_with_cuts():
    """The cuts hold in the lab, which the partonic frame of chili is boosted
    from: the volume they leave is that of rambo."""
    m_out = [80.4, 80.4, 0.0]
    volumes = []
    for mode, seed in [("chili", 9), ("rambo", 10)]:
        mapping = dressed([0.0, 0.0], m_out, mode, cuts=jet_cuts(len(m_out)))
        p, *_, det = forward_dressed(mapping, seed, 200000)
        volumes.append(mean_and_error(det * in_cuts(p)))
    (a, error_a), (b, error_b) = volumes
    assert abs(a - b) < 5.0 * math.hypot(error_a, error_b)
