      SUBROUTINE ML5_0_GET_NHEL(IDEN_STAR,NHEL_STAR)
C     CONSTANTS
C     
CF2PY INTENT(OUT) :: NHEL_STAR
CF2PY INTENT(OUT) :: IDEN_STAR
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=4)
      INTEGER                 NCOMB
      PARAMETER (             NCOMB=16)

      INTEGER NHEL(NEXTERNAL,NCOMB)
      COMMON/ML5_0_PROCESS_NHEL/NHEL
