      SUBROUTINE GET_NHEL(IDEN_STAR,NHEL_STAR)
C     CONSTANTS
C     
CF2PY INTENT(OUT) :: NHEL_STAR
CF2PY INTENT(OUT) :: IDEN_STAR
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=5)
      INTEGER                 NCOMB
      PARAMETER (             NCOMB=32)

      INTEGER NHEL(NEXTERNAL,NCOMB)
      COMMON/PROCESS_NHEL/NHEL
      INTEGER NHEL_STAR(NEXTERNAL,NCOMB)
      INTEGER IDEN,IDEN_STAR
      DATA IDEN/24/
      CALL FILL_NHEL()
      IDEN_STAR = IDEN
      NHEL_STAR = NHEL
      END

      SUBROUTINE GET_NHEL_IDX(FLAV_IDX_IN,IDEN_STAR,
     & NHEL_STAR)
C     Same as GET_NHEL, but reporting the denominator SMATRIX
C     ACTUALLY divides by for FLAV_IDX_IN, rather than the
C     static IDEN.
C     
C     The static IDEN is the averaging/symmetry factor of the
C     uncrossed *representative* flavor. SMATRIX never uses it
C     bare: it applies IDEN/BROKEN_SYM(FLAVOR) uncrossed
C     (BROKEN_SYM correcting the identical-particle count of the
C     representative to that of the actual flavor) and
C     GET_SPINCOL_CROSS*GET_IDENT_CROSS when crossed. A caller
C     that reads GET_NHEL and multiplies ANS by it to recover
C     the raw helicity/color sum -- the natural thing to do, and
C     what makes two crossings comparable -- is therefore wrong
C     for every crossed flavor and for every non-representative
C     one.
C     
C     NHEL_STAR is the helicity table of the process FLAV_IDX_IN
C     names, in its own leg order: column C is the code C that
C     SMATRIXHEL takes for it (the base table when uncrossed).
C     
C     GET_NHEL is deliberately left alone: its signature and its
C     value are what existing uncrossed callers expect.
      INTEGER GET_SPINCOL_CROSS
      INTEGER GET_IDENT_CROSS
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=5)
      INTEGER                 NCOMB
      PARAMETER (             NCOMB=32)
      INTEGER    NFLAV
      PARAMETER (NFLAV=1)
CF2PY INTENT(IN) :: FLAV_IDX_IN
CF2PY INTENT(OUT) :: NHEL_STAR
CF2PY INTENT(OUT) :: IDEN_STAR
      INTEGER FLAV_IDX_IN
      INTEGER NHEL_STAR(NEXTERNAL,NCOMB)
      INTEGER IDEN_STAR
      INTEGER NHI_FLAV, NHI_CROSS
      INTEGER FLAVOR(NEXTERNAL)
      INTEGER BROKEN_SYM

      CALL GET_NHEL(IDEN_STAR, NHEL_STAR)
C     An index naming no valid flavor gives a zero matrix
C     element; report a 0 denominator rather than a
C     plausible-looking one.
      IF (FLAV_IDX_IN .LT. 1) THEN
        IDEN_STAR = 0
        RETURN
      ENDIF
      NHI_FLAV = MOD(FLAV_IDX_IN-1, NFLAV) + 1
      NHI_CROSS = (FLAV_IDX_IN-1) / NFLAV
      CALL GET_FLAVOR(NHI_FLAV, FLAVOR)
C     Mirrors SMATRIX branch for branch: IDEN/BROKEN_SYM
C     uncrossed, GET_SPINCOL_CROSS*GET_IDENT_CROSS crossed.
C     Keeping the CROSS=0 branch on the old path (rather than
C     letting the crossed formula cover it) is what guarantees
C     no change for existing callers.
      IF (NHI_CROSS .EQ. 0) THEN
        IDEN_STAR = IDEN_STAR / BROKEN_SYM(FLAVOR)
      ELSE
        IDEN_STAR = GET_SPINCOL_CROSS(NHI_CROSS)
     &   * GET_IDENT_CROSS(NHI_CROSS, FLAVOR)
C       SMATRIXHEL takes the crossed process's own code
C       (CROSS_HELCODE): report that process's own table.
        CALL CROSS_NHEL_TABLE(FLAV_IDX_IN, NCOMB,
     &   NHEL_STAR)
      ENDIF
      RETURN
      END

      SUBROUTINE GET_AMP(P,NHEL,IC,FLAV_IDX,AMP)
      USE MODEL_OBJECT
C     
C     Process: e+ e- > a a a
C     
C     CONTRACT (this routine is pure: it decodes nothing).
C     
C     P(0:3,NEXTERNAL) : momenta, ALREADY crossed.
C     NHEL(NEXTERNAL)  : helicities, ALREADY crossed (permuted,
C     NOT negated:
C     helas uses nh=nhel*nsf, so the sign follows IC).
C     IC(NEXTERNAL)    : NSF/NSV flag per leg, ALREADY crossed
C     (-1 on a leg
C     the crossing moved across).
C     FLAV_IDX         : flavor index ALREADY reduced to
C     [1,NFLAV]; it must
C     NOT be an extended index carrying a crossing.
C     
C     When the crossing machinery is written out (see
C     GET_CROSS_PERM below; it is left out when
C     the process was generated with --use_crossing=False, in
C     which case FLAV_IDX is never extended), the callers inside
C     this file (SMATRIX via MATRIX, GET_ALL_INTER_CROSSED)
C     apply the crossing ONCE per entry point with
C     APPLY_CROSSING /
C     APPLY_CROSSING_TABLE and then call this
C     routine in their inner loop. An external (f2py) caller
C     holding an extended FLAV_IDX must call the public
C     APPLY_CROSSING itself first; passing the
C     extended index here would otherwise silently return the
C     UNCROSSED amplitude, so the range is checked below and
C     violations are reported and return AMP=0.
C     
CF2PY INTENT(OUT) :: AMP
CF2PY INTENT(IN) :: NHEL
CF2PY INTENT(IN) :: P(0:3,NEXTERNAL)
CF2PY INTENT(IN) :: IC
CF2PY INTENT(IN) :: FLAV_IDX

      USE ALOHA_OBJECT
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      INTEGER    NGRAPHS
      PARAMETER (NGRAPHS=6)
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=5)
      INTEGER    NWAVEFUNCS, NCOLOR
      PARAMETER (NWAVEFUNCS=9, NCOLOR=1)
      INTEGER    NFLAV
      PARAMETER (NFLAV=1)
      REAL*8     ZERO
      PARAMETER (ZERO=0D0)
C     
C     ARGUMENTS
C     
      REAL*8 P(0:3,NEXTERNAL)
      INTEGER NHEL(NEXTERNAL), IC(NEXTERNAL)
      INTEGER FLAV_IDX
      COMPLEX*16 AMP(NGRAPHS)
C     
C     LOCAL VARIABLES
C     
C     FLAVOR is rebuilt from FLAV_IDX below and is NOT permuted
C     by any crossing: each slot keeps its own flavor-group
C     position, which is what the mask indexes.
      INTEGER FLAVOR(NEXTERNAL)
      INTEGER AMP_I
      TYPE(ALOHA) W(NWAVEFUNCS)
      COMPLEX*16 DUM0,DUM1
      DATA DUM0, DUM1/(0D0, 0D0), (1D0, 0D0)/
      DOUBLE PRECISION BWCUTOFF
      DOUBLE PRECISION STANDALONE_BWCUTOFF
      COMMON/TO_STANDALONE_BWCUTOFF/STANDALONE_BWCUTOFF
C     Flavor table for the FLAV_IDX -> FLAVOR rebuild.
      INTEGER NMASK_FLAV
      PARAMETER (NMASK_FLAV=1)
      INTEGER MASK_J
      INTEGER FLAV_TABLE(NEXTERNAL, NMASK_FLAV)
      DATA FLAV_TABLE / 1, 1, 1, 1, 1 /
C     
C     GLOBAL VARIABLES
C     
      INCLUDE 'coupl.inc'

C     
C     
C     $-syntax propagators veto |m-M| < bwcutoff*Gamma. That has to be
C      the
C     window the events were generated with (run_card bwcutoff); a
C      caller
C     such as MadSpin or the reweighting sets it through SET_BWCUTOFF.
C     Zero (nothing set it) keeps the historical default of 15.
      IF (STANDALONE_BWCUTOFF.GT.0D0) THEN
        BWCUTOFF = STANDALONE_BWCUTOFF
      ELSE
        BWCUTOFF = 15D0
      ENDIF
C     Contract guard: an extended FLAV_IDX (one carrying a
C     crossing) reaching this routine would be silently
C     truncated to its flavor part and give the uncrossed
C     amplitude. Fail loudly and return zero instead.
      IF (FLAV_IDX.LT.1 .OR. FLAV_IDX.GT.NFLAV) THEN
        WRITE(*,*) 'ERROR: GET_AMP got FLAV_IDX', FLAV_IDX, 'NFLAV',
     $    NFLAV
        WRITE(*,*) 'GET_AMP needs a reduced index and crossed P/NHEL'
     $   //'/IC.'
        WRITE(*,*) 'Returning AMP=0.'
        DO AMP_I = 1, NGRAPHS
          AMP(AMP_I) = (0D0, 0D0)
        ENDDO
        RETURN
      ENDIF
C     Rebuild FLAVOR(NEXTERNAL) from the resolved flavor index.
      IF (FLAV_IDX .GE. 1 .AND. FLAV_IDX .LE. NMASK_FLAV) THEN
        DO MASK_J = 1, NEXTERNAL
          FLAVOR(MASK_J) = FLAV_TABLE(MASK_J, FLAV_IDX)
        ENDDO
      ELSE
        DO MASK_J = 1, NEXTERNAL
          FLAVOR(MASK_J) = FLAV_TABLE(MASK_J, 1)
        ENDDO
      ENDIF
      CALL OXXXXX(P(0,1),ZERO,NHEL(1),-1, FLAVOR(1),W(1))
      CALL IXXXXX(P(0,2),ZERO,NHEL(2),+1, FLAVOR(2),W(2))
      CALL VXXXXX(P(0,3),ZERO,NHEL(3),+1,W(3))
      CALL VXXXXX(P(0,4),ZERO,NHEL(4),+1,W(4))
      CALL VXXXXX(P(0,5),ZERO,NHEL(5),+1,W(5))
      CALL FVOXXX(W(1),W(3),MGVX12,ZERO,ZERO,W(6))
      CALL FVIXXX(W(2),W(4),MGVX12,ZERO,ZERO,W(7))
C     Amplitude(s) for diagram number 1
      CALL IOVXXX(W(7),W(6),W(5),MGVX12,AMP(1))
      CALL FVIXXX(W(2),W(5),MGVX12,ZERO,ZERO,W(8))
C     Amplitude(s) for diagram number 2
      CALL IOVXXX(W(8),W(6),W(4),MGVX12,AMP(2))
      CALL FVOXXX(W(1),W(4),MGVX12,ZERO,ZERO,W(6))
      CALL FVIXXX(W(2),W(3),MGVX12,ZERO,ZERO,W(9))
C     Amplitude(s) for diagram number 3
      CALL IOVXXX(W(9),W(6),W(5),MGVX12,AMP(3))
C     Amplitude(s) for diagram number 4
      CALL IOVXXX(W(8),W(6),W(3),MGVX12,AMP(4))
      CALL FVOXXX(W(1),W(5),MGVX12,ZERO,ZERO,W(6))
C     Amplitude(s) for diagram number 5
      CALL IOVXXX(W(9),W(6),W(4),MGVX12,AMP(5))
C     Amplitude(s) for diagram number 6
      CALL IOVXXX(W(7),W(6),W(3),MGVX12,AMP(6))

      END

      SUBROUTINE GET_JAMP(AMP,JAMP)
C     
C     Process: e+ e- > a a a
C     
CF2PY INTENT(OUT) :: JAMP
CF2PY INTENT(IN) :: AMP

      IMPLICIT NONE
C     
C     CONSTANTS
C     
      INTEGER    NGRAPHS
      PARAMETER (NGRAPHS=6)
      INTEGER    NCOLOR
      PARAMETER ( NCOLOR=1)
      COMPLEX*16 IMAG1
      PARAMETER (IMAG1=(0D0,1D0))
      COMPLEX*16 AMP(NGRAPHS), JAMP(NCOLOR)
      COMPLEX*16 TMP_JAMP(0)


      JAMP(1) = (-1.000000000000000D+00)*AMP(1)+(-1.000000000000000D
     $ +00)*AMP(2)+(-1.000000000000000D+00)*AMP(3)+(
     $ -1.000000000000000D+00)*AMP(4)+(-1.000000000000000D+00)*AMP(5)
     $ +(-1.000000000000000D+00)*AMP(6)
      END



      SUBROUTINE GET_MATRIX(JAMP,MATRIX)
C     
C     Process: e+ e- > a a a
C     
      IMPLICIT NONE
C     
C     CONSTANTS
C     
CF2PY INTENT(OUT) :: MATRIX
CF2PY INTENT(IN) :: JAMP


      INTEGER    NCOLOR
      PARAMETER (NCOLOR=1)
      REAL*8     ZERO,MATRIX
      PARAMETER (ZERO=0D0)
C     

C     LOCAL VARIABLES
C     
      INTEGER I,J,NJ,NB
      COMPLEX*16 ZTEMP,Z1,Z2,Z3,Z4

      INTEGER CF_INDEX
      INTEGER CF(NCOLOR*(NCOLOR+1)/2)
      INTEGER DENOM
      COMMON /COLOR_MATRIX/ CF,DENOM
      COMPLEX*16 JAMP(NCOLOR)
      COMPLEX*16 TMP_JAMP(0)
      COMPLEX*16 DUM0,DUM1
      DATA DUM0, DUM1/(0D0, 0D0), (1D0, 0D0)/
C     

C     COLOR DATA
C     
      CALL INIT_CF()

      MATRIX = 0.D0
      CF_INDEX = 0
C     Four accumulators, not one: with a single one every
C     term waits for the one before it to come out of the
C     adder, and that latency is what the loop spends its
C     time on. No compiler does this by itself, since it
C     changes the order the terms are summed in.
      DO I = 1, NCOLOR
        Z1 = (0.D0,0.D0)
        Z2 = (0.D0,0.D0)
        Z3 = (0.D0,0.D0)
        Z4 = (0.D0,0.D0)
        NJ = NCOLOR - I + 1
        NB = (NJ/4)*4
        DO J = 0, NB-4, 4
          Z1 = Z1 + CF(CF_INDEX+J+1)*JAMP(I+J)
          Z2 = Z2 + CF(CF_INDEX+J+2)*JAMP(I+J+1)
          Z3 = Z3 + CF(CF_INDEX+J+3)*JAMP(I+J+2)
          Z4 = Z4 + CF(CF_INDEX+J+4)*JAMP(I+J+3)
        ENDDO
        ZTEMP = (Z1+Z2)+(Z3+Z4)
        DO J = NB, NJ-1
          ZTEMP = ZTEMP + CF(CF_INDEX+J+1)*JAMP(I+J)
        ENDDO
        CF_INDEX = CF_INDEX + NJ
        MATRIX = MATRIX+ZTEMP*DCONJG(JAMP(I))/DENOM
      ENDDO
      END

      SUBROUTINE INIT_CF()
      RETURN
      END





      SUBROUTINE GET_INTER(JAMP_1,JAMP_2, INTER)

CF2PY INTENT(OUT) :: INTER
CF2PY INTENT(IN) :: JAMP_1
CF2PY INTENT(IN) :: JAMP_2

      INTEGER I,J
      INTEGER NCOLOR
      PARAMETER (NCOLOR=1)
      INTEGER CF_INDEX
      INTEGER CF(NCOLOR*(NCOLOR+1)/2)
      INTEGER DENOM, IDEN
      DATA IDEN/24/
      COMMON /COLOR_MATRIX/ CF,DENOM
      COMPLEX*16 JAMP_1(NCOLOR),JAMP_2(NCOLOR),INTER

C     COLOR DATA
C     
      CALL INIT_CF()

      INTER = (0.D0,0.D0)
      CF_INDEX = 0
      DO I = 1, NCOLOR
C       ZTEMP = DCONJG(JAMP_2(I))
        DO J=I, NCOLOR
          CF_INDEX = CF_INDEX +1
          INTER = INTER + CF(CF_INDEX) * (JAMP_1(J) * DCONJG(JAMP_2(I))
     $      +JAMP_1(I) * DCONJG(JAMP_2(J)))
        ENDDO
      ENDDO
      INTER = INTER/ (2D0*DENOM*IDEN)

      END



