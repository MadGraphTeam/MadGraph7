      DATA (NHEL(I,  24),I=1,5) / 1,-1, 1,-1,-1/
      DATA (NHEL(I,  25),I=1,5) / 1, 1,-1, 1, 1/
      DATA (NHEL(I,  26),I=1,5) / 1, 1,-1, 1,-1/
      DATA (NHEL(I,  27),I=1,5) / 1, 1,-1,-1, 1/
      DATA (NHEL(I,  28),I=1,5) / 1, 1,-1,-1,-1/
      DATA (NHEL(I,  29),I=1,5) / 1, 1, 1, 1, 1/
      DATA (NHEL(I,  30),I=1,5) / 1, 1, 1, 1,-1/
      DATA (NHEL(I,  31),I=1,5) / 1, 1, 1,-1, 1/
      DATA (NHEL(I,  32),I=1,5) / 1, 1, 1,-1,-1/
      LOGICAL GOODHEL(NCOMB,HEL_CONFIGS)
      DATA GOODHEL/THEL*.FALSE./
      INTEGER NTRY(HEL_CONFIGS)
      DATA NTRY/HEL_CONFIGS*0/
      INTEGER NFKSPROCESS
      COMMON/C_NFKSPROCESS/NFKSPROCESS
      INTEGER IDEN_FLAVOR(4)
      DATA IDEN_FLAVOR / 12, 12, 12, 12 /
C     ----------
C     BEGIN CODE
C     ----------
      FLAV_IDX=REAL_FLAVOR_INDEX_D(NFKSPROCESS)
      HEL_INDEX=NFKSPROCESS
      IF (FLAV_IDX.GE.1.AND.FLAV_IDX.LE.4) IDEN=IDEN_FLAVOR(FLAV_IDX)
      NTRY(HEL_INDEX)=NTRY(HEL_INDEX)+1
      DO I=0,NSQAMPSO
        ANS(I) = 0D0
      ENDDO
      DO IHEL=1,NCOMB
        IF (GOODHEL(IHEL,HEL_INDEX) .OR.
     $      NTRY(HEL_INDEX) .LT. 2) THEN
        IF (NTRY(HEL_INDEX).LT.2) THEN
C         for the first ps-point, check for helicities that give
C         identical matrix elements
          CALL MATRIX_2(P,NHEL(1,IHEL),FLAV_IDX,T)
          DO I=0,NSQAMPSO
            T_SAVE(IHEL,I,HEL_INDEX)=T(I)
          ENDDO
          T_IDENT(IHEL,HEL_INDEX)=-1
          DO I=1,IHEL-1
            IF (T(0).EQ.0D0) EXIT
            IF (T_SAVE(I,0,HEL_INDEX).EQ.0D0) CYCLE
            DO J = 0, NSQAMPSO
              IF (ABS(T(J)/T_SAVE(I,J,HEL_INDEX)-1D0)
     $                .GT. 1D-12) goto 444
            ENDDO
            T_IDENT(IHEL,HEL_INDEX) = I
 444        CONTINUE
          ENDDO
        ELSE
          IF (T_IDENT(IHEL,HEL_INDEX).GT.0) THEN
C           if two helicity states are identical, dont recompute
            DO I=0,NSQAMPSO
              T(I)=T_SAVE(T_IDENT(IHEL,HEL_INDEX),I,HEL_INDEX)
              T_SAVE(IHEL,I,HEL_INDEX)=T(I)
            ENDDO
          ELSE
            CALL MATRIX_2(P,NHEL(1,IHEL),FLAV_IDX,T)
            DO I=0,NSQAMPSO
              T_SAVE(IHEL,I,HEL_INDEX)=T(I)
            ENDDO
          ENDIF
        ENDIF
C       add to the sum of helicities
        DO I=1,NSQAMPSO  !keep loop from 1!!
          ANS(I)=ANS(I)+T(I)
        ENDDO
        IF (T(0) .NE. 0D0 .AND.
     $        .NOT. GOODHEL(IHEL,HEL_INDEX)) THEN
        GOODHEL(IHEL,HEL_INDEX)=.TRUE.
        ENDIF
        ENDIF
      ENDDO
      DO I=1,NSQAMPSO
        ANS(I)=ANS(I)/DBLE(IDEN)
        ANS(0)=ANS(0)+ANS(I)
      ENDDO
      END


