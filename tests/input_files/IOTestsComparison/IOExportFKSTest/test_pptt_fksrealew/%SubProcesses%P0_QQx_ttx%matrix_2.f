      SUBROUTINE MATRIX_2(P,NHEL,FLAV_IDX,RES)
C     
C     Generated by MadGraph7 v. %(version)s, %(date)s
C     By the MadGraph7 Development Team
C     Visit launchpad.net/madgraph5 and amcatnlo.web.cern.ch
C     
C     Returns amplitude squared summed/avg over colors
C     for the point with external lines W(0:6,NEXTERNAL)
C     
C     Process: a _anti_quark > t t~ _anti_quark [ real = QCD QED ]
C      QCD^2<=4 QED^2<=2
C     
      USE ALOHA_OBJECT
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      INTEGER    NGRAPHS
      PARAMETER (NGRAPHS=4)
      INTEGER    NWAVEFUNCS, NCOLOR
      PARAMETER (NWAVEFUNCS=8, NCOLOR=2)
      INTEGER NAMPSO, NSQAMPSO
      PARAMETER (NAMPSO=1, NSQAMPSO=1)
      REAL*8     ZERO
      PARAMETER (ZERO=0D0)
      COMPLEX*16 IMAG1
      PARAMETER (IMAG1=(0D0,1D0))
      INCLUDE 'nexternal.inc'
      INCLUDE 'coupl.inc'
C     
C     ARGUMENTS 
C     
      REAL*8 P(0:3,NEXTERNAL)
      INTEGER NHEL(NEXTERNAL),FLAV_IDX
      REAL*8 RES(0:NSQAMPSO)
C     
C     LOCAL VARIABLES 
C     
      INTEGER I,J,M,N
      INTEGER IC(NEXTERNAL)
      DATA IC /NEXTERNAL*1/
      INTEGER FLAVOR(NEXTERNAL)
      INTEGER CF(NCOLOR*(NCOLOR+1))
      INTEGER CF_INDEX, DENOM
      COMPLEX*16 ZTEMP, AMP(NGRAPHS), JAMP(NCOLOR,NAMPSO)
      TYPE(ALOHA) W(NWAVEFUNCS)
      COMPLEX*16 TMP_JAMP(3)
C     Flavor table for the FLAV_IDX -> FLAVOR rebuild.
      INTEGER NMASK_FLAV
      PARAMETER (NMASK_FLAV=4)
      INTEGER MASK_J
      INTEGER FLAV_TABLE(NEXTERNAL, NMASK_FLAV)
      DATA FLAV_TABLE / 1, 1, 1, 1, 1, 1, 2, 1, 1, 2, 1, 3, 1, 1, 3, 1
     $ , 4, 1, 1, 4 /
C     
C     FUNCTION
C     
      INTEGER SQSOINDEX2
C     
C     COLOR DATA
C     
      DATA DENOM/1/
      DATA (CF(I),I=  1,  2) /9,6/
C     1 T(2,4) T(3,5)
      DATA (CF(I),I=  3,  3) /9/
C     1 T(2,5) T(3,4)
C     ----------
C     BEGIN CODE
C     ----------
      JAMP(:,:) = (0D0,0D0)
      FLAVOR(:) = 1
C     Rebuild FLAVOR(NEXTERNAL) from the resolved flavor index.
      IF (FLAV_IDX .GE. 1 .AND. FLAV_IDX .LE. NMASK_FLAV) THEN
        DO MASK_J = 1, NEXTERNAL
          FLAVOR(MASK_J) = FLAV_TABLE(MASK_J, FLAV_IDX)
        ENDDO
      ELSE
        DO MASK_J = 1, NEXTERNAL
          FLAVOR(MASK_J) = FLAV_TABLE(MASK_J, 1)
        ENDDO
      ENDIF
      CALL VXXXXX(P(0,1),ZERO,NHEL(1),-1,W(1))
      CALL OXXXXX(P(0,2),ZERO,NHEL(2),-1, FLAVOR(2),W(2))
      CALL OXXXXX(P(0,3),MDL_MT,NHEL(3),+1, FLAVOR(3),W(3))
      CALL IXXXXX(P(0,4),MDL_MT,NHEL(4),-1, FLAVOR(4),W(4))
      CALL IXXXXX(P(0,5),ZERO,NHEL(5),-1, FLAVOR(5),W(5))
      CALL FFV1M_1(W(2),W(1),FLV_94,ZERO,ZERO,W(6))
      CALL FFV1P0_3(W(4),W(3),GC_11,ZERO,ZERO,W(7))
C     Amplitude(s) for diagram number 1
      CALL FFV1_0(W(5),W(6),W(7),GC_11,AMP(1))
      CALL FFV1_1(W(3),W(1),GC_2,MDL_MT,MDL_WT,W(6))
      CALL FFV1P0_3(W(5),W(2),GC_11,ZERO,ZERO,W(8))
C     Amplitude(s) for diagram number 2
      CALL FFV1_0(W(4),W(6),W(8),GC_11,AMP(2))
      CALL FFV1_2(W(4),W(1),GC_2,MDL_MT,MDL_WT,W(6))
