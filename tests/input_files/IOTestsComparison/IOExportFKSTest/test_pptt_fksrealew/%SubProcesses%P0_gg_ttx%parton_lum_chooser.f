      DOUBLE PRECISION FUNCTION DLUM_VEC(SECTOR)
      IMPLICIT NONE
      INTEGER SECTOR,NFKSPROCESS,PREVIOUS
      COMMON/C_NFKSPROCESS/NFKSPROCESS
      DOUBLE PRECISION DLUM
      EXTERNAL DLUM
      PREVIOUS=NFKSPROCESS
      NFKSPROCESS=SECTOR
      DLUM_VEC=DLUM()
      NFKSPROCESS=PREVIOUS
      END
