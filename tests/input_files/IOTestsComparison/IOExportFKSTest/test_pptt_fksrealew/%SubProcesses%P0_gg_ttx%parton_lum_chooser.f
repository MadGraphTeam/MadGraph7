      CASE(13)
        CALL DLUM_4(DLUM)
      CASE(14)
        CALL DLUM_4(DLUM)
      CASE(15)
        CALL DLUM_4(DLUM)
      CASE(16)
        CALL DLUM_4(DLUM)
      CASE(17)
        CALL DLUM_5(DLUM)
      CASE(18)
        CALL DLUM_5(DLUM)
      CASE(19)
        CALL DLUM_NATIVE_1_4(DLUM)
