     $          CF(CF_INDEX)*(JAMPH(2,J,M)*DCONJG(JAMPH(1,I,N))
     $         +JAMPH(2,I,M)*DCONJG(JAMPH(1,J,N)))
            ENDDO
          ENDDO
        ENDDO

      ENDDO
      ANS(2,:) = ANS(2,:)/(2D0*DENOM)
      IF (GLU_IJ.NE.0) NHEL(GLU_IJ) = BACK_HEL
      END

