      JAMP2(:,:) = 0.0
      JAMP2(0,0) = 2

      IDEN=IDEN_VALUES(NFKSPROCESS)
      FLAV_IDX=BORN_FLAVOR_INDEX_D(NFKSPROCESS)
      CALL BORN(P,NHEL,HELL,FLAV_IDX,.TRUE.,AMP2,JAMP2,ANS,BORNS,
