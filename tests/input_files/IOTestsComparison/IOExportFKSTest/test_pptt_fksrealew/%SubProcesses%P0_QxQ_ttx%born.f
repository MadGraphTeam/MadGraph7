      INCLUDE 'has_ewsudakov.inc'
      INCLUDE 'orders.inc'
      INCLUDE 'born_nhel.inc'
      INTEGER NAMPSO, NSQAMPSO
      PARAMETER (NAMPSO=2, NSQAMPSO=3)
