C         stop
C         endif
C         enddo
C         ret_saveamp(:,:) = saveamp(:,:)
C         endif
C         JAMPs contributing to orders QCD=2 QED=0
          JAMP(1,1) = (-1.666666666666667D-01)*AMP(2)
          JAMP(2,1) = (5.000000000000000D-01)*AMP(2)
C         JAMPs contributing to orders QCD=0 QED=2
          JAMP(1,2) = AMP(1)+AMP(3)
          DO M = 1, NAMPSO
            CF_INDEX = 0
            DO I = 1, NCOLOR
              ZTEMP = (0.D0,0.D0)
              DO J = I, NCOLOR
                CF_INDEX = CF_INDEX + 1
                ZTEMP = ZTEMP + CF(CF_INDEX)*JAMP(J,M)
              ENDDO
              DO N = 1, NAMPSO
                BORNS(2-(1+BACK_HEL*IHEL)/2,SQSOINDEXB(M,N))=BORNS(2
     $           -(1+BACK_HEL*IHEL)/2,SQSOINDEXB(M,N))+ZTEMP
     $           *DCONJG(JAMP(I,N))
              ENDDO
            ENDDO
          ENDDO
          DO I = 1, NGRAPHS
            AMP2(I)=AMP2(I)+AMP(I)*DCONJG(AMP(I))
          ENDDO
          DO J = 1,NAMPSO
            DO I = 1, NCOLOR
              JAMP2(I,J)=JAMP2(I,J)+JAMP(I,J)*DCONJG(JAMP(I,J))
              JAMPH(2-(1+BACK_HEL*IHEL)/2,I,J)=JAMP(I,J)
            ENDDO
          ENDDO
        ENDIF
      ENDDO
      BORNS(:,:) = BORNS(:,:)/DENOM
      DO I = 1, NSQAMPSO
        BORNS(1,0)=BORNS(1,0)+BORNS(1,I)
        BORNS(2,0)=BORNS(2,0)+BORNS(2,I)
        ANS(1,I) = BORNS(1,I) + BORNS(2,I)
      ENDDO
      DO M = 1, NAMPSO
        CF_INDEX = 0
        DO I = 1, NCOLOR
          ZTEMP = (0.D0,0.D0)
          DO J = I, NCOLOR
            CF_INDEX = CF_INDEX +1
            DO  N = 1, NAMPSO
