            CALL FFV1_0(W(4),W(3),W(5),GC_2,AMP(1))
            CALL FFV1P0_3(W(2),W(1),GC_11,ZERO,ZERO,W(5))
C           Amplitude(s) for diagram number 2
            CALL FFV1_0(W(4),W(3),W(5),GC_11,AMP(2))
            CALL FFV6_2M_3(W(2),W(1),FLV_96,FLV_97,MDL_MZ,MDL_WZ,W(5))
