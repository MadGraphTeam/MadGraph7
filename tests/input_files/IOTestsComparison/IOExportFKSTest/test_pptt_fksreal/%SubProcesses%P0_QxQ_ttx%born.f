      INTEGER NHEL(NEXTERNAL-1), HELL, FLAV_IDX
      LOGICAL FORCE_IJGLU_ZERO
      DOUBLE PRECISION AMP2(1), JAMP2(0:2,0:NAMPSO)
      COMPLEX*16 ANS(2,NSQAMPSO)
      INTEGER IVEC,IFKS
      INTEGER I,J,M,N,IHEL,BACK_HEL,GLU_IJ
      INTEGER IC(NEXTERNAL-1),NMO
