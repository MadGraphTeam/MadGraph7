      DOUBLE COMPLEX RET_SAVEAMP(NGRAPHS,MAX_BHEL)
      DOUBLE PRECISION SAVEMOM(NEXTERNAL-1,2)
      COMMON/TO_SAVEMOM/SAVEMOM
      INTEGER SKIP(24)
      COMMON/CBORN/SKIP
      LOGICAL CALCULATEDBORN
      COMMON/CCALCULATEDBORN/CALCULATEDBORN
      INTEGER CALCULATED_BORN_FLAVOR
      COMMON/CCALCULATEDBORNFLAVOR/CALCULATED_BORN_FLAVOR
      INTEGER NFKSPROCESS
      COMMON/C_NFKSPROCESS/NFKSPROCESS
      LOGICAL COND_IJ
      LOGICAL BORN_CACHE_OK
      INTEGER BORN_CACHE_NFKS
      COMMON /C_BORN_CACHE/ BORN_CACHE_OK, BORN_CACHE_NFKS
      COMPLEX*16 BORN_CACHE_ANS(2,0:NSQAMPSO)
      SAVE BORN_CACHE_ANS
      LOGICAL CHECK_BORN_AMPS, BORN_CHECKS_AMPS
      COMMON /C_BORN_AMPS_CHECK/ CHECK_BORN_AMPS, BORN_CHECKS_AMPS
      DOUBLE PRECISION SAVEMOM4(0:3,NEXTERNAL-1)
      DOUBLE COMPLEX SAVED_COUP(1)
      SAVE SAVEMOM4, SAVED_COUP
      INTEGER MAXQCDPOW
      PARAMETER (MAXQCDPOW=4)
      LOGICAL DO_GSCALE
      PARAMETER (DO_GSCALE=.TRUE.)
      DOUBLE PRECISION GSCALE_TOL
      PARAMETER (GSCALE_TOL=1D-12)
      DOUBLE PRECISION SAVED_G, RG, RPOW(0:MAXQCDPOW)
      LOGICAL COUP_CHANGED, GSCALED
      SAVE SAVED_G
      DATA SAVED_G /0D0/
      DOUBLE COMPLEX SAVEAMP(NGRAPHS,MAX_BHEL)
      COMMON /TO_SAVEAMP/ SAVEAMP
      DOUBLE PRECISION CACHE_AMP2(NGRAPHS), CACHE_JAMP2(0:2,0:NAMPSO)
      COMMON /TO_AMPS_BORN/ CACHE_AMP2, CACHE_JAMP2
      INCLUDE 'coupl.inc'
      IDEN=IDEN_VALUES(NFKSPROCESS)
      FLAV_IDX=BORN_FLAVOR_INDEX_D(NFKSPROCESS)
      IF (CALCULATEDBORN .AND.     CALCULATED_BORN_FLAVOR.NE.FLAV_IDX) CALCULATEDBORN=.FALSE.
      GLU_IJ = IJ_VALUES(NFKSPROCESS)
      IF (CALCULATEDBORN .AND. CHECK_BORN_AMPS) THEN
        COUP_CHANGED=.FALSE.
        IF (SAVED_COUP(1).NE.GC_11) COUP_CHANGED=.TRUE.
        DO J=1,NEXTERNAL-1
          DO I=0,3
            IF (P1(I,J).NE.SAVEMOM4(I,J)) CALCULATEDBORN=.FALSE.
          ENDDO
        ENDDO
        IF (CALCULATEDBORN .AND. COUP_CHANGED) THEN
          GSCALED=DO_GSCALE .AND. SAVED_G.NE.0D0
          IF (GSCALED) THEN
            RG=G/SAVED_G
            RPOW(0)=1D0
            DO I=1,MAXQCDPOW
              RPOW(I)=RPOW(I-1)*RG
            ENDDO
            IF (ABS(GC_11-SAVED_COUP(1)*RPOW(1)).GT.GSCALE_TOL        *ABS(GC_11)) GSCALED=.FALSE.
          ENDIF
          IF (GSCALED) THEN
            CALL BORN_GSCALE(RPOW,BORN_CACHE_ANS)
            SAVED_COUP(1)=GC_11
            SAVED_G=G
          ELSE
            CALCULATEDBORN=.FALSE.
          ENDIF
        ENDIF
      ENDIF
      CHECK_BORN_AMPS=.FALSE.
      IF (CALCULATEDBORN) THEN
        IF (ANY(P1.NE.SAVEMOM4)) CALCULATEDBORN=.FALSE.
      ENDIF
      IF (.NOT.CALCULATEDBORN) THEN
        BORN_CACHE_OK=.FALSE.
        SAVEMOM4(:,:)=P1(:,:)
        DO J=1,NEXTERNAL-1
          SAVEMOM(J,1)=P1(0,J)
          SAVEMOM(J,2)=P1(3,J)
        ENDDO
        SAVED_COUP(1)=GC_11
        SAVED_G=G
        SAVEAMP(:,:)=(0D0,0D0)
      ENDIF
      IF (CALCULATEDBORN.AND.BORN_CACHE_OK.AND.     NFKSPROCESS.EQ.BORN_CACHE_NFKS) THEN
      ANS(:,:)=BORN_CACHE_ANS(:,:)
      AMP2(:)=CACHE_AMP2(:)
      JAMP2(:,:)=CACHE_JAMP2(:,:)
      RET_SAVEAMP(:,:)=SAVEAMP(:,:)
      RETURN
      ENDIF
      IF(DO_TRY(NFKSPROCESS)) THEN
        CALL SBORN_SPLITORDERS_NTRY(P1,AMP2,JAMP2,ANS,RET_SAVEAMP    ,DO_TRY(NFKSPROCESS))
      ELSE
        DO JJ=1,NGRAPHS
          AMP2(JJ)=0D0
        ENDDO
        DO I=0,NAMPSO
          DO JJ=1,INT(JAMP2(0,0))
            JAMP2(JJ,I)=0D0
          ENDDO
        ENDDO
        IF (CALCULATEDBORN) THEN
          DO J=1,NEXTERNAL-1
            IF (SAVEMOM(J,1).NE.P1(0,J) .OR. SAVEMOM(J,2).NE.P1(3,J))         THEN
              CALCULATEDBORN=.FALSE.
              WRITE (*,*) 'momenta not the same in Born'
              STOP
            ENDIF
          ENDDO
        ENDIF
        IF (.NOT.CALCULATEDBORN) THEN
          DO J=1,NEXTERNAL-1
            SAVEMOM(J,1)=P1(0,J)
            SAVEMOM(J,2)=P1(3,J)
          ENDDO
          RET_SAVEAMP(:,:) = (0D0,0D0)
        ENDIF
        DO I=0,NSQAMPSO
          ANS(1,I) = 0D0
          ANS(2,I) = 0D0
        ENDDO
        DO IHEL=1,NCOMB
          COND_IJ=SKIP(NFKSPROCESS).EQ.0
          IF (.NOT.COND_IJ) COND_IJ=COND_IJ.OR.NHEL(GLU_IJ,IHEL)      .EQ.NHEL(GLU_IJ,1)
          IF (COND_IJ) THEN
            IF ((GOODHEL(IHEL,NFKSPROCESS) .OR. GOODHEL(IHEL        +SKIP(NFKSPROCESS),NFKSPROCESS)) ) THEN
              CALL BORN(P1,NHEL(1,IHEL),IHEL,FLAV_IDX,.FALSE.,AMP2,            JAMP2,T,borns,ret_saveamp)
              DO I=1,NSQAMPSO
                ANS(1,I)=ANS(1,I)+T(1,I)
                ANS(2,I)=ANS(2,I)+T(2,I)
              ENDDO
            ENDIF
          ENDIF
        ENDDO
        DO I=1,NSQAMPSO
          ANS(1,I)=ANS(1,I)/DBLE(IDEN)
          ANS(2,I)=ANS(2,I)/DBLE(IDEN)
          ANS(1,0)=ANS(1,0)+ANS(1,I)
          ANS(2,0)=ANS(2,0)+ANS(2,I)
        ENDDO
        CALCULATEDBORN=.TRUE.
        CALCULATED_BORN_FLAVOR=FLAV_IDX
      ENDIF
      CALCULATEDBORN=.TRUE.
      CALCULATED_BORN_FLAVOR=FLAV_IDX
      BORN_CACHE_ANS(:,:)=ANS(:,:)
      CACHE_AMP2(:)=AMP2(:)
      CACHE_JAMP2(:,:)=JAMP2(:,:)
      BORN_CACHE_NFKS=NFKSPROCESS
      BORN_CACHE_OK=.TRUE.
      RET_SAVEAMP(:,:)=SAVEAMP(:,:)
      END
      SUBROUTINE BORN_GSCALE(RPOW,CACHE_ANS)
      IMPLICIT NONE
      INCLUDE 'nexternal.inc'
      INCLUDE 'born_nhel.inc'
      INTEGER NAMPSO, NSQAMPSO
      PARAMETER (NAMPSO=1, NSQAMPSO=1)
      INTEGER    NGRAPHS
      PARAMETER (NGRAPHS=   1)
      INTEGER    NCOLOR, NCF
      PARAMETER (NCOLOR=2, NCF=NCOLOR*(NCOLOR+1)/2)
      INTEGER MAXQCDPOW
      PARAMETER (MAXQCDPOW=4)
      DOUBLE PRECISION RPOW(0:MAXQCDPOW)
      COMPLEX*16 CACHE_ANS(2,0:NSQAMPSO)
      INTEGER I,J,K
      INTEGER AMPQCD(NGRAPHS), AMPSOQCD(NAMPSO), SQSOQCD(NSQAMPSO)
      LOGICAL GSCALE_FAST
      DOUBLE COMPLEX SAVEAMP(NGRAPHS,MAX_BHEL)
      COMMON/TO_SAVEAMP/SAVEAMP
      DOUBLE PRECISION AMP2(NGRAPHS), JAMP2(0:NCOLOR,0:NAMPSO)
      COMMON/TO_AMPS_BORN/  AMP2,       JAMP2
      LOGICAL BORN_CACHE_OK
      INTEGER BORN_CACHE_NFKS
      COMMON /C_BORN_CACHE/ BORN_CACHE_OK, BORN_CACHE_NFKS
      DATA (AMPQCD(I),I=1,1) /2/
      DATA (AMPSOQCD(I),I=1,1) /2/
      DATA (SQSOQCD(I),I=1,1) /4/
      DATA GSCALE_FAST /.TRUE./
      DO I=1,NGRAPHS
        IF (AMPQCD(I).NE.0) SAVEAMP(I,:)=SAVEAMP(I,:)*RPOW(AMPQCD(I))
      ENDDO
      IF (.NOT.(BORN_CACHE_OK.AND.GSCALE_FAST)) THEN
        BORN_CACHE_OK=.FALSE.
        RETURN
      ENDIF
      DO I=1,NGRAPHS
        AMP2(I)=AMP2(I)*RPOW(2*AMPQCD(I))
      ENDDO
      DO J=1,NAMPSO
        DO I=1,NCOLOR
          JAMP2(I,J)=JAMP2(I,J)*RPOW(2*AMPSOQCD(J))
        ENDDO
      ENDDO
      CACHE_ANS(:,0)=(0D0,0D0)
      DO K=1,NSQAMPSO
        CACHE_ANS(:,K)=CACHE_ANS(:,K)*RPOW(SQSOQCD(K))
        CACHE_ANS(:,0)=CACHE_ANS(:,0)+CACHE_ANS(:,K)
      ENDDO
      END
