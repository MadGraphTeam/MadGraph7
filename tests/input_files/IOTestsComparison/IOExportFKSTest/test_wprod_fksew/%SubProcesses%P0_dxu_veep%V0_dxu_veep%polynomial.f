      SUBROUTINE UPDATE_WL_0_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
      USE POLYNOMIAL_CONSTANTS
      INTEGER I,J,K
      COMPLEX*16 A(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE)
      COMPLEX*16 B(MAXLWFSIZE,0:VERTEXMAXCOEFS-1,MAXLWFSIZE)
      COMPLEX*16 OUT(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE)
      INTEGER LCUT_SIZE,IN_SIZE,OUT_SIZE

      DO I=1,LCUT_SIZE
        DO K=0,4
          DO J=1,OUT_SIZE
            OUT(J,K,I)=(0.0D0,0.0D0)
          ENDDO
        ENDDO
        DO K=1,IN_SIZE
          DO J=1,OUT_SIZE
            OUT(J,0,I)=OUT(J,0,I)+A(K,0,I)*B(J,0,K)
            OUT(J,1,I)=OUT(J,1,I)+A(K,0,I)*B(J,1,K)
            OUT(J,2,I)=OUT(J,2,I)+A(K,0,I)*B(J,2,K)
            OUT(J,3,I)=OUT(J,3,I)+A(K,0,I)*B(J,3,K)
            OUT(J,4,I)=OUT(J,4,I)+A(K,0,I)*B(J,4,K)
          ENDDO
        ENDDO
      ENDDO
      END

      SUBROUTINE MP_UPDATE_WL_0_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
      USE POLYNOMIAL_CONSTANTS
      USE, INTRINSIC :: IEEE_ARITHMETIC
      INTEGER I,J,K
      COMPLEX*32 A(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE)
      COMPLEX*32 B(MAXLWFSIZE,0:VERTEXMAXCOEFS-1,MAXLWFSIZE)
      COMPLEX*32 OUT(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE)
      INTEGER LCUT_SIZE,IN_SIZE,OUT_SIZE
      TYPE(IEEE_ROUND_TYPE) WL_ROUNDING
      LOGICAL WL_NEAREST
      LOGICAL WL_SKIP(MAXLWFSIZE,MAXLWFSIZE)
      INTEGER WL_J,WL_K

      CALL IEEE_GET_ROUNDING_MODE(WL_ROUNDING)
      WL_NEAREST=WL_ROUNDING.EQ.IEEE_NEAREST
      IF(.NOT.WL_NEAREST.OR..NOT.ALL(WL_IS_FINITE(REAL(A(1:IN_SIZE,0:0
     $ ,1:LCUT_SIZE),KIND=16)))
     $ .OR..NOT.ALL(WL_IS_FINITE(AIMAG(A(1:IN_SIZE,0:0,1:LCUT_SIZE))))
     $ .OR..NOT.ALL(WL_IS_FINITE(REAL(B(1:OUT_SIZE,0:4,1:IN_SIZE)
     $ ,KIND=16))).OR..NOT.ALL(WL_IS_FINITE(AIMAG(B(1:OUT_SIZE,0:4
     $ ,1:IN_SIZE))))) THEN
        CALL MP_UPDATE_WL_0_1_DENSE(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
        RETURN
      ENDIF
      WL_SKIP=.FALSE.
      IF(WL_NEAREST) THEN
        DO WL_K=1,IN_SIZE
          IF(ALL(WL_IS_FINITE(REAL(A(WL_K,0:0,1:LCUT_SIZE),KIND=16)))
     $     .AND.ALL(WL_IS_FINITE(AIMAG(A(WL_K,0:0,1:LCUT_SIZE))))) THEN
            DO WL_J=1,OUT_SIZE
              IF(ALL(WL_IS_FINITE(REAL(B(WL_J,0:4,WL_K),KIND=16)))
     $         .AND.ALL(WL_IS_FINITE(AIMAG(B(WL_J,0:4,WL_K)))))
     $          WL_SKIP(WL_J,WL_K)=ALL(B(WL_J,0:4,WL_K).EQ.0)
            ENDDO
          ENDIF
        ENDDO
      ENDIF

      DO I=1,LCUT_SIZE
        DO K=0,4
          DO J=1,OUT_SIZE
            OUT(J,K,I)=CMPLX(0.0E0_16,0.0E0_16,KIND=16)
          ENDDO
        ENDDO
        DO K=1,IN_SIZE
          DO J=1,OUT_SIZE
            IF(WL_SKIP(J,K)) CYCLE
            OUT(J,0,I)=OUT(J,0,I)+A(K,0,I)*B(J,0,K)
            OUT(J,1,I)=OUT(J,1,I)+A(K,0,I)*B(J,1,K)
            OUT(J,2,I)=OUT(J,2,I)+A(K,0,I)*B(J,2,K)
            OUT(J,3,I)=OUT(J,3,I)+A(K,0,I)*B(J,3,K)
            OUT(J,4,I)=OUT(J,4,I)+A(K,0,I)*B(J,4,K)
          ENDDO
        ENDDO
      ENDDO
      CONTAINS
      ELEMENTAL LOGICAL FUNCTION WL_IS_FINITE(X)
      REAL*16, INTENT(IN) :: X
      INTEGER*8, PARAMETER :: ONE_WORDS(2)=TRANSFER(1.0_16,(/0_8,0_8/))
      INTEGER, PARAMETER :: HI=MERGE(1,2,ONE_WORDS(1).NE.0_8)
      WL_IS_FINITE=.FALSE.
      IF(STORAGE_SIZE(X).NE.128.OR.DIGITS(X).NE.113.OR.RADIX(X)
     $ .NE.2.OR.MAXEXPONENT(X).NE.16384) RETURN
      IF(ONE_WORDS(HI).NE.ISHFT(16383_8,48).OR.ONE_WORDS(3-HI).NE.0_8)
     $  RETURN
      ASSOCIATE(WORDS=>TRANSFER(X,ONE_WORDS))
      WL_IS_FINITE=IBITS(WORDS(HI),48,15).NE.32767_8
      END ASSOCIATE
      END FUNCTION

      END

