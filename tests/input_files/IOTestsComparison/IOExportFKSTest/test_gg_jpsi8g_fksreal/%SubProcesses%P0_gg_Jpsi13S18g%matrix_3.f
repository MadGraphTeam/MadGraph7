      DOUBLE PRECISION FUNCTION ONIA_AMP_R3FAC()
C     
C     The LDME factor of the bound states of ONIA_AMP_R3: for each
C      onium
C     <O_n> (m1+m2)/(2 m1 m2)/(N_[C] (2J+1)), N_[1] = 6, N_[8] = 8
C     (arXiv:2402.19221, eq. 2.9), with the LDMEs of the onia card. A
C     decaying onium has its decay LDME <O_H> (Block ldme_decay),
C      without
C     the 1/(2J+1): the average over its 2J+1 states is in IDEN.
C     
      IMPLICIT NONE
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=5)
      INTEGER    NONIA
      PARAMETER (NONIA=1)

      INTEGER MAPPING(6)
      INTEGER PAIRS(6)
      DATA (MAPPING(I),I=1,6)/1,2,3,3,4,5/
      DATA (PAIRS(I),I=1,6)/0,0,1,-1,0,0/

      INTEGER ONIA(NONIA), N_ONIA(NONIA), S_ONIA(NONIA), L_ONIA(NONIA)
     $ , J_ONIA(NONIA), C_ONIA(NONIA)
      DATA (ONIA(I),I=1,1)/3/
      DATA (N_ONIA(I),I=1,1)/1/
      DATA (S_ONIA(I),I=1,1)/1/
      DATA (L_ONIA(I),I=1,1)/0/
      DATA (J_ONIA(I),I=1,1)/1/
      DATA (C_ONIA(I),I=1,1)/8/

      INTEGER ONIA_IN(NONIA), JH2_ONIA(NONIA)
      DATA (ONIA_IN(I),I=1,1)/0/
      DATA (JH2_ONIA(I),I=1,1)/3/

      INTEGER UNCOUPLED_ONIA(NONIA)
      DATA (UNCOUPLED_ONIA(I),I=1,1)/0/
      REAL*8     ZERO
      PARAMETER (ZERO=0D0)
      INTEGER I, Q1, Q2
      REAL*8 LDME, NPOL, PMASS_ONIA(NEXTERNAL+NONIA)
      LOGICAL FIRSTTIME
      DATA FIRSTTIME/.TRUE./
      REAL*8 SAVED
      SAVE FIRSTTIME, SAVED
      INCLUDE 'coupl.inc'
      DOUBLE PRECISION LDME_9940003
      INTEGER NLDME
      PARAMETER (NLDME=1)
      INTEGER LDME_PDG(NLDME+1)
      DATA LDME_PDG/9940003,0/
      DOUBLE PRECISION LDME_VAL(NLDME+1)
      IF (FIRSTTIME) THEN
        CALL ONIA_AMP_R3READCARD(NLDME, LDME_PDG, LDME_VAL)
        LDME_9940003 = LDME_VAL(1)
        PMASS_ONIA(1)=ZERO
        PMASS_ONIA(2)=ZERO
        PMASS_ONIA(3)=ABS(MDL_MC)
        PMASS_ONIA(4)=ABS(MDL_MC)
        PMASS_ONIA(5)=ZERO
        PMASS_ONIA(6)=ZERO
        LDME = 1D0
        DO I = 1, NONIA
          Q1 = FINDLOC(PAIRS, I, DIM=1)
          Q2 = FINDLOC(PAIRS,-I, DIM=1)
          LDME = LDME*(PMASS_ONIA(Q1)+PMASS_ONIA(Q2))
     &      /(2D0*PMASS_ONIA(Q1)*PMASS_ONIA(Q2))
          IF (ONIA_IN(I).EQ.1) THEN
            NPOL = 1D0
          ELSE
            NPOL = 2D0*J_ONIA(I)+1D0
          ENDIF
          IF (C_ONIA(I).EQ.1) THEN
            LDME = LDME/6D0/NPOL
          ELSE IF (C_ONIA(I).EQ.8) THEN
            LDME = LDME/8D0/NPOL
          ENDIF
        ENDDO
C       perturbative (leptonium) LDMEs

        SAVED = LDME*LDME_9940003
        FIRSTTIME = .FALSE.
      ENDIF
      ONIA_AMP_R3FAC = SAVED
      END


