      SUBROUTINE ONIA_AMP_R1CG(L, LZ, S, SZ, J, JZ, CG)
C     <L L_z; S S_z | J J_z> for L, S <= 1 (as CLEBSCH_GORDAN of the
C     dual-number HELAS library, which the NLO output does not build)
      IMPLICIT NONE
      INTEGER L, LZ, S, SZ, J, JZ
      DOUBLE PRECISION CG
      IF (JZ.NE.LZ+SZ .OR. ABS(LZ).GT.L .OR. ABS(SZ).GT.S) THEN
        CG = 0D0
      ELSE IF (L.EQ.0 .OR. S.EQ.0) THEN
        CG = 1D0
      ELSE IF (J.EQ.2) THEN
        IF (LZ.EQ.0 .AND. SZ.EQ.0) THEN
          CG = DSQRT(2D0/3D0)
        ELSE IF (LZ.EQ.0 .OR. SZ.EQ.0) THEN
          CG = 1D0/DSQRT(2D0)
        ELSE IF (LZ.EQ.SZ) THEN
          CG = 1D0
        ELSE
          CG = 1D0/DSQRT(6D0)
        ENDIF
      ELSE IF (J.EQ.1) THEN
        IF (LZ.EQ.1 .OR. SZ.EQ.-1) THEN
          CG = 1D0/DSQRT(2D0)
        ELSE IF (LZ.EQ.-1 .OR. SZ.EQ.1) THEN
          CG = -1D0/DSQRT(2D0)
        ELSE
          CG = 0D0
        ENDIF
      ELSE IF (J.EQ.0) THEN
        IF (LZ.EQ.0 .AND. SZ.EQ.0) THEN
          CG = -1D0/DSQRT(3D0)
        ELSE
          CG = 1D0/DSQRT(3D0)
        ENDIF
      ELSE
        CG = 0D0
      ENDIF
      END


      DOUBLE PRECISION FUNCTION ONIA_AMP_R1FAC()
C     
C     The LDME factor of the bound states of ONIA_AMP_R1: for each
C      onium
C     <O_n> (m1+m2)/(2 m1 m2)/(N_[C] (2J+1)), N_[1] = 6, N_[8] = 8
C     (arXiv:2402.19221, eq. 2.9), with the LDMEs of the onia card.
C     
      IMPLICIT NONE
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=5)
      INTEGER    NONIA
      INTEGER    NPWAVE
      INTEGER    DER_ORDER
      PARAMETER (NONIA=1)
      PARAMETER (NPWAVE=1)
      PARAMETER (DER_ORDER=1)

      INTEGER MAPPING(6)
      INTEGER PAIRS(6)
      DATA (MAPPING(I),I=1,6)/1,2,3,3,4,5/
      DATA (PAIRS(I),I=1,6)/0,0,1,-1,0,0/

      INTEGER ONIA(NONIA), N_ONIA(NONIA), S_ONIA(NONIA), L_ONIA(NONIA)
     $ , J_ONIA(NONIA), C_ONIA(NONIA)
      DATA (ONIA(I),I=1,1)/3/
      DATA (N_ONIA(I),I=1,1)/1/
      DATA (S_ONIA(I),I=1,1)/1/
      DATA (L_ONIA(I),I=1,1)/1/
      DATA (J_ONIA(I),I=1,1)/0/
      DATA (C_ONIA(I),I=1,1)/1/

      INTEGER ONIA_IN(NONIA), JH2_ONIA(NONIA)
      DATA (ONIA_IN(I),I=1,1)/0/
      DATA (JH2_ONIA(I),I=1,1)/1/

      INTEGER UNCOUPLED_ONIA(NONIA)
      DATA (UNCOUPLED_ONIA(I),I=1,1)/0/
      REAL*8     ZERO
      PARAMETER (ZERO=0D0)
      INTEGER I, Q1, Q2
      REAL*8 LDME, PMASS_ONIA(NEXTERNAL+NONIA)
      LOGICAL FIRSTTIME
      DATA FIRSTTIME/.TRUE./
      REAL*8 SAVED
      SAVE FIRSTTIME, SAVED
      INCLUDE 'coupl.inc'
      DOUBLE PRECISION LDME_10441
      INTEGER NLDME
      PARAMETER (NLDME=1)
      INTEGER LDME_PDG(NLDME+1)
      DATA LDME_PDG/10441,0/
      DOUBLE PRECISION LDME_VAL(NLDME+1)
      IF (FIRSTTIME) THEN
        CALL ONIA_AMP_R1READCARD(NLDME, LDME_PDG, LDME_VAL)
        LDME_10441 = LDME_VAL(1)
        PMASS_ONIA(1)=ZERO
        PMASS_ONIA(2)=ZERO
        PMASS_ONIA(3)=ABS(MDL_MC)
        PMASS_ONIA(4)=ABS(MDL_MC)
        PMASS_ONIA(5)=ZERO
        PMASS_ONIA(6)=ZERO
        LDME = 1D0
        DO I = 1, NONIA
          Q1 = FINDLOC(PAIRS, I, DIM=1)
          Q2 = FINDLOC(PAIRS,-I, DIM=1)
          LDME = LDME*(PMASS_ONIA(Q1)+PMASS_ONIA(Q2))
     &      /(2D0*PMASS_ONIA(Q1)*PMASS_ONIA(Q2))
          IF (C_ONIA(I).EQ.1) THEN
            LDME = LDME/6D0/(2D0*J_ONIA(I)+1D0)
          ELSE IF (C_ONIA(I).EQ.8) THEN
            LDME = LDME/8D0/(2D0*J_ONIA(I)+1D0)
          ENDIF
        ENDDO
C       perturbative (leptonium) LDMEs

        SAVED = LDME*LDME_10441
        FIRSTTIME = .FALSE.
      ENDIF
      ONIA_AMP_R1FAC = SAVED
      END


      SUBROUTINE ONIA_AMP_R1READCARD(N, PDG, VAL)
C     
C     The LDMEs of Block ldme of the onia card for the codes PDG(1:N),
C      read
C     directly (no COMMON: the native Born providers keep private
C      copies of
C     the COMMON blocks of their sources).
C     
      IMPLICIT NONE
      INTEGER N, PDG(*)
      DOUBLE PRECISION VAL(*)
      CHARACTER*256 LINE
      CHARACTER*16 WORD, BNAME
      CHARACTER*40 FILES(4)
      DATA FILES /'onia_card.dat', '../onia_card.dat',
     &  '../../Cards/onia_card.dat', '../../../Cards/onia_card.dat'/
      INTEGER I, K, IUNIT, IOS, ID
      DOUBLE PRECISION X
      LOGICAL INBLOCK, FOUND(64)
      IF (N.EQ.0) RETURN
      IUNIT = 97
      DO K = 1, 4
        OPEN(UNIT=IUNIT, FILE=FILES(K), STATUS='OLD', IOSTAT=IOS)
        IF (IOS.EQ.0) GOTO 10
      ENDDO
      WRITE(*,*) 'Error: the onia card onia_card.dat was not found'
      STOP 1
 10   CONTINUE
      INBLOCK = .FALSE.
      DO I = 1, N
        FOUND(I) = .FALSE.
      ENDDO
 20   CONTINUE
      READ(IUNIT,'(A)',IOSTAT=IOS) LINE
      IF (IOS.NE.0) GOTO 30
      IF (INDEX(ADJUSTL(LINE),'#').EQ.1) GOTO 20
      WORD = ' '
      BNAME = ' '
      READ(LINE,*,IOSTAT=IOS) WORD, BNAME
      IF (WORD.EQ.'Block' .OR. WORD.EQ.'BLOCK' .OR. WORD.EQ.'block')
     $  THEN
        INBLOCK = BNAME.EQ.'ldme' .OR. BNAME.EQ.'LDME' .OR.
     $    BNAME.EQ.'Ldme'
        GOTO 20
      ENDIF
      IF (INBLOCK) THEN
        READ(LINE,*,IOSTAT=IOS) ID, X
        IF (IOS.EQ.0) THEN
          DO I = 1, N
            IF (PDG(I).EQ.ID) THEN
              VAL(I) = X
              FOUND(I) = .TRUE.
            ENDIF
          ENDDO
        ENDIF
      ENDIF
      GOTO 20
 30   CONTINUE
      CLOSE(IUNIT)
      DO I = 1, N
        IF (.NOT.FOUND(I)) THEN
          WRITE(*,*) 'Error: no LDME for ', PDG(I), ' in Block ldme'
     &      //' of the onia card'
          STOP 1
        ENDIF
      ENDDO
      END


