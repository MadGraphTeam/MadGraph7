      SUBROUTINE ONIA_SOFT_AMPPCG(L, LZ, S, SZ, J, JZ, CG)
C     <L L_z; S S_z | J J_z> for L, S <= 1 (as CLEBSCH_GORDAN of the
C     dual-number HELAS library, which the NLO output does not build)
      IMPLICIT NONE
      INTEGER L, LZ, S, SZ, J, JZ
      DOUBLE PRECISION CG
      IF (JZ.NE.LZ+SZ .OR. ABS(LZ).GT.L .OR. ABS(SZ).GT.S) THEN
        CG = 0D0
      ELSE IF (L.EQ.0 .OR. S.EQ.0) THEN
        CG = 1D0
      ELSE IF (J.EQ.2) THEN
        IF (LZ.EQ.0 .AND. SZ.EQ.0) THEN
          CG = DSQRT(2D0/3D0)
        ELSE IF (LZ.EQ.0 .OR. SZ.EQ.0) THEN
          CG = 1D0/DSQRT(2D0)
        ELSE IF (LZ.EQ.SZ) THEN
          CG = 1D0
        ELSE
          CG = 1D0/DSQRT(6D0)
        ENDIF
      ELSE IF (J.EQ.1) THEN
        IF (LZ.EQ.1 .OR. SZ.EQ.-1) THEN
          CG = 1D0/DSQRT(2D0)
        ELSE IF (LZ.EQ.-1 .OR. SZ.EQ.1) THEN
          CG = -1D0/DSQRT(2D0)
        ELSE
          CG = 0D0
        ENDIF
      ELSE IF (J.EQ.0) THEN
        IF (LZ.EQ.0 .AND. SZ.EQ.0) THEN
          CG = -1D0/DSQRT(3D0)
        ELSE
          CG = 1D0/DSQRT(3D0)
        ENDIF
      ELSE
        CG = 0D0
      ENDIF
      END


      DOUBLE PRECISION FUNCTION ONIA_SOFT_AMPPFAC()
C     
C     The LDME factor of the bound states of ONIA_SOFT_AMPP: for each
C      onium
C     <O_n> (m1+m2)/(2 m1 m2)/(N_[C] (2J+1)), N_[1] = 6, N_[8] = 8
C     (arXiv:2402.19221, eq. 2.9), with the LDMEs of the onia card. A
C     decaying onium has its decay LDME <O_H> (Block ldme_decay),
C      without
C     the 1/(2J+1): the average over its 2J+1 states is in IDEN.
C     
      IMPLICIT NONE
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=4)
      INTEGER    NONIA
      INTEGER    NPWAVE
      INTEGER    DER_ORDER
      PARAMETER (NONIA=1)
      PARAMETER (NPWAVE=1)
      PARAMETER (DER_ORDER=1)

      INTEGER MAPPING(5)
      INTEGER PAIRS(5)
      DATA (MAPPING(I),I=1,5)/1,2,3,3,4/
      DATA (PAIRS(I),I=1,5)/0,0,1,-1,0/

      INTEGER ONIA(NONIA), N_ONIA(NONIA), S_ONIA(NONIA), L_ONIA(NONIA)
     $ , J_ONIA(NONIA), C_ONIA(NONIA)
      DATA (ONIA(I),I=1,1)/3/
      DATA (N_ONIA(I),I=1,1)/1/
      DATA (S_ONIA(I),I=1,1)/1/
      DATA (L_ONIA(I),I=1,1)/1/
      DATA (J_ONIA(I),I=1,1)/0/
      DATA (C_ONIA(I),I=1,1)/1/

      INTEGER ONIA_IN(NONIA), JH2_ONIA(NONIA)
      DATA (ONIA_IN(I),I=1,1)/0/
      DATA (JH2_ONIA(I),I=1,1)/1/

      INTEGER UNCOUPLED_ONIA(NONIA)
      DATA (UNCOUPLED_ONIA(I),I=1,1)/0/
      REAL*8     ZERO
      PARAMETER (ZERO=0D0)
      INTEGER I, Q1, Q2
      REAL*8 LDME, NPOL, PMASS_ONIA(NEXTERNAL+NONIA)
      LOGICAL FIRSTTIME
      DATA FIRSTTIME/.TRUE./
      REAL*8 SAVED
      SAVE FIRSTTIME, SAVED
      INCLUDE 'coupl.inc'
      DOUBLE PRECISION LDME_10441
      INTEGER NLDME
      PARAMETER (NLDME=1)
      INTEGER LDME_PDG(NLDME+1)
      DATA LDME_PDG/10441,0/
      DOUBLE PRECISION LDME_VAL(NLDME+1)
      IF (FIRSTTIME) THEN
        CALL ONIA_SOFT_AMPPREADCARD(NLDME, LDME_PDG, LDME_VAL)
        LDME_10441 = LDME_VAL(1)
        PMASS_ONIA(1)=ZERO
        PMASS_ONIA(2)=ZERO
        PMASS_ONIA(3)=ABS(MDL_MC)
        PMASS_ONIA(4)=ABS(MDL_MC)
        PMASS_ONIA(5)=ZERO
        LDME = 1D0
        DO I = 1, NONIA
          Q1 = FINDLOC(PAIRS, I, DIM=1)
          Q2 = FINDLOC(PAIRS,-I, DIM=1)
          LDME = LDME*(PMASS_ONIA(Q1)+PMASS_ONIA(Q2))
     &      /(2D0*PMASS_ONIA(Q1)*PMASS_ONIA(Q2))
          IF (ONIA_IN(I).EQ.1) THEN
            NPOL = 1D0
          ELSE
            NPOL = 2D0*J_ONIA(I)+1D0
          ENDIF
          IF (C_ONIA(I).EQ.1) THEN
            LDME = LDME/6D0/NPOL
          ELSE IF (C_ONIA(I).EQ.8) THEN
            LDME = LDME/8D0/NPOL
          ENDIF
        ENDDO
C       perturbative (leptonium) LDMEs

        SAVED = LDME*LDME_10441
        FIRSTTIME = .FALSE.
      ENDIF
      ONIA_SOFT_AMPPFAC = SAVED
      END


      SUBROUTINE ONIA_SOFT_AMPPREADCARD(N, PDG, VAL)
C     
C     The LDMEs of the onia card for the codes PDG(1:N): Block ldme for
C     PDG > 0, Block ldme_decay for -PDG when PDG < 0 (a decaying
C      onium),
C     read directly (no COMMON: the native Born providers keep private
C     copies of the COMMON blocks of their sources).
C     
      IMPLICIT NONE
      INTEGER N, PDG(*)
      DOUBLE PRECISION VAL(*)
      CHARACTER*256 LINE
      CHARACTER*16 WORD, BNAME
      CHARACTER*40 FILES(4)
      DATA FILES /'onia_card.dat', '../onia_card.dat',
     &  '../../Cards/onia_card.dat', '../../../Cards/onia_card.dat'/
      INTEGER I, K, IUNIT, IOS, ID
      DOUBLE PRECISION X
      INTEGER INBLOCK
      LOGICAL FOUND(64)
      IF (N.EQ.0) RETURN
      IUNIT = 97
      DO K = 1, 4
        OPEN(UNIT=IUNIT, FILE=FILES(K), STATUS='OLD', IOSTAT=IOS)
        IF (IOS.EQ.0) GOTO 10
      ENDDO
      WRITE(*,*) 'Error: the onia card onia_card.dat was not found'
      STOP 1
 10   CONTINUE
      INBLOCK = 0
      DO I = 1, N
        FOUND(I) = .FALSE.
      ENDDO
 20   CONTINUE
      READ(IUNIT,'(A)',IOSTAT=IOS) LINE
      IF (IOS.NE.0) GOTO 30
      IF (INDEX(ADJUSTL(LINE),'#').EQ.1) GOTO 20
      WORD = ' '
      BNAME = ' '
      READ(LINE,*,IOSTAT=IOS) WORD, BNAME
      IF (WORD.EQ.'Block' .OR. WORD.EQ.'BLOCK' .OR. WORD.EQ.'block')
     $  THEN
        INBLOCK = 0
        IF (BNAME.EQ.'ldme' .OR. BNAME.EQ.'LDME' .OR. BNAME.EQ.'Ldme')
     &    INBLOCK = 1
        IF (BNAME.EQ.'ldme_decay' .OR. BNAME.EQ.'LDME_DECAY'
     &    .OR. BNAME.EQ.'Ldme_decay') INBLOCK = -1
        GOTO 20
      ENDIF
      IF (INBLOCK.NE.0) THEN
        READ(LINE,*,IOSTAT=IOS) ID, X
        IF (IOS.EQ.0) THEN
          DO I = 1, N
            IF (PDG(I).EQ.INBLOCK*ID) THEN
              VAL(I) = X
              FOUND(I) = .TRUE.
            ENDIF
          ENDDO
        ENDIF
      ENDIF
      GOTO 20
 30   CONTINUE
      CLOSE(IUNIT)
      DO I = 1, N
        IF (.NOT.FOUND(I)) THEN
          IF (PDG(I).GT.0) THEN
            WRITE(*,*) 'Error: no LDME for ', PDG(I), ' in Block ldme'
     &        //' of the onia card'
          ELSE
            WRITE(*,*) 'Error: no LDME for ', -PDG(I),
     &        ' in Block ldme_decay of the onia card'
          ENDIF
          STOP 1
        ENDIF
      ENDDO
      END


      SUBROUTINE ONIA_SOFT_AMPPM2(AMP,ABSAMP,M2,SCALE)
C     colour-summed square M2 of the projected amplitudes AMP of
C     one helicity of ONIA_SOFT_AMPP, and its bound SCALE from the
C      moduli
C     ABSAMP >= |AMP| of their terms (get_onia_flush)
      IMPLICIT NONE
      INTEGER NGRAPHS, NCOLOR
      PARAMETER (NGRAPHS=18, NCOLOR=2)
      COMPLEX*16 AMP(NGRAPHS)
      DOUBLE PRECISION ABSAMP(NGRAPHS)
      DOUBLE PRECISION M2, SCALE
      COMPLEX*16 JAMP(NCOLOR), A(NGRAPHS)
      DOUBLE PRECISION CF(NCOLOR,NCOLOR), K, ROWMAX
      INTEGER I, J, D
      LOGICAL FIRSTTIME
      DATA FIRSTTIME/.TRUE./
      SAVE FIRSTTIME, CF, K
      IF (FIRSTTIME) THEN
        CF(:,:) = 0D0
        CF(1,1) = 2.33333333333333348D+00
        CF(1,2) = -6.66666666666666630D-01
        CF(2,1) = -6.66666666666666630D-01
        CF(2,2) = 2.33333333333333348D+00
        ROWMAX = 0D0
        DO I = 1, NCOLOR
          ROWMAX = MAX(ROWMAX, SUM(ABS(CF(I,:))))
        ENDDO
C       sum_d |c e_d|^2: the colour flows of each diagram alone
        K = 0D0
        DO D = 1, NGRAPHS
          A(:) = (0D0,0D0)
          A(D) = (1D0,0D0)
          CALL ONIA_SOFT_AMPPJF(A,JAMP)
          K = K+SUM(ABS(JAMP(:))**2)
        ENDDO
        K = K*ROWMAX
        FIRSTTIME = .FALSE.
      ENDIF
      CALL ONIA_SOFT_AMPPJF(AMP,JAMP)
      M2 = 0D0
      DO I = 1, NCOLOR
        DO J = 1, NCOLOR
          M2 = M2+DBLE(DCONJG(JAMP(I))*CF(I,J)*JAMP(J))
        ENDDO
      ENDDO
      SCALE = K*SUM(ABSAMP(:)**2)
      END


