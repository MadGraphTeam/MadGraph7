              ENDDO
              DO MU = 0, 3
                DO NU = 0, 3
                  Z = (0D0,0D0)
                  DO IA = 1, NCOLP
                    DO IB = 1, NCOLD(A1,A2,IP)
                      Z = Z+DCONJG(JP(IA))*ZM(IA,IB,A1,A2,IP)
     &                  *W(MU,NU,IB)
                    ENDDO
                  ENDDO
                  VPAR(MU,NU,IP) = VPAR(MU,NU,IP)+Z
                ENDDO
              ENDDO
            ENDDO
          ENDDO
        ENDDO
      ENDDO
      FAC = ONIA_SOFT_AMPPFAC()/DBLE(IDEN)
      DO H = 1, NPQ
        VEC(:,:,H) = VEC(:,:,H)*ISV(H)
      ENDDO
      DO IP = 1, NPAIR
        DD(:,:,IP) = DD(:,:,IP)*ISV(IPAIR(1,IP))*ISV(IPAIR(2,IP))
        VPAR(:,:,IP) = VPAR(:,:,IP)*ISV(IPAIR(1,IP))*ISV(IPAIR(2,IP))
      ENDDO
      VEC(:,:,:) = VEC(:,:,:)*FAC
      TEN(:,:,:) = TEN(:,:,:)*FAC
      BAUX(:,:) = BAUX(:,:)*FAC
      DD(:,:,:) = DD(:,:,:)*FAC
      VPAR(:,:,:) = VPAR(:,:,:)*FAC
      PLAST(:,:) = P(:,:)
      VEC_S(:,:,:) = VEC(:,:,:)
      TEN_S(:,:,:) = TEN(:,:,:)
      BAUX_S(:,:) = BAUX(:,:)
      DD_S(:,:,:) = DD(:,:,:)
      VPAR_S(:,:,:) = VPAR(:,:,:)
      END


