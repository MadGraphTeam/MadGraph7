          PABS = 0D0
          DO IGS = 1, NGOOD
            PRJ = COEFS(IGS)
            DO I = 1, NONIA
              Q1 = FINDLOC(PAIRS, I, DIM=1)
              Q2 = FINDLOC(PAIRS,-I, DIM=1)
              PRJ = PRJ*PROJ_SAVED(I,NHEL_ONIA(Q1),NHEL_ONIA(Q2),IGS)
            ENDDO
            PROJ = PROJ+PRJ
            PABS = PABS+ABS(PRJ)
          ENDDO
          IF (PROJ.NE.(0D0,0D0)) THEN
            CALL VXXXXX(P_ONIA(0,1),ZERO,NHEL_ONIA(1),-1,W(1))
            CALL VXXXXX(P_ONIA(0,2),ZERO,NHEL_ONIA(2),-1,W(2))
            CALL OXXXXX(P_ONIA(0,3),ONIA_MS(3),NHEL_ONIA(3),+1,
     $        FLAVOR_ONIA(3),W(3))
            CALL IXXXXX(P_ONIA(0,4),ONIA_MS(4),NHEL_ONIA(4),-1,
     $        FLAVOR_ONIA(4),W(4))
            CALL VXXXXX(P_ONIA(0,5),ZERO,NHEL_ONIA(5),+1,W(5))
            CALL VVV1P0_1(W(1),W(2),GC_10,ZERO,ZERO,W(6))
            CALL FFV1P0_3(W(4),W(3),GC_11,ZERO,ZERO,W(7))
C           Amplitude(s) for diagram number 1
            CALL VVV1_0(W(6),W(7),W(5),GC_10,AMP(1))
            CALL FFV1_1(W(3),W(5),GC_11,ONIA_MS(3),ZERO,W(8))
C           Amplitude(s) for diagram number 2
            CALL FFV1_0(W(4),W(8),W(6),GC_11,AMP(2))
            CALL FFV1_2(W(4),W(5),GC_11,ONIA_MS(4),ZERO,W(9))
C           Amplitude(s) for diagram number 3
