        CF(2,6) = -3.33333333333333315D-01
        CF(3,1) = -3.33333333333333315D-01
        CF(3,2) = -3.33333333333333315D-01
        CF(3,3) = 3.16666666666666652D+00
        CF(3,4) = -3.33333333333333315D-01
        CF(3,5) = 6.66666666666666630D-01
