      SUBROUTINE ONIA_AMP_R6(P_IN,NHEL,AMP_OUT)
C     
C     Generated by MadGraph7 v. %(version)s, %(date)s
C     By the MadGraph7 Development Team
C     Visit launchpad.net/madgraph5 and amcatnlo.web.cern.ch
C     
C     Bound states at NLO (FKS, arXiv:2402.19221;
C      madgraph/fks/fks_onia.py),
C     with P waves: the projected amplitudes AMP_OUT(NGRAPHS) of the
C      diagrams
C     for the physical momenta P and helicities NHEL (J_z for an
C      onium). The
C     constituents of an onium of momentum K and mass M = m1+m2 have
C     k1 = m1/M K + q, k2 = m2/M K - q. A P wave is the derivative
C     eps*(L_z).d/dq at q = 0 of the spin-projected amplitude,
C      combined with
C     the spin S_z = J_z - L_z by Clebsch-Gordan coefficients (as the
C      dual
C     numbers of the LO templates). Here the derivative is taken
C      numerically
C     along three real directions e_a orthogonal to K (eps* = sum_a
C      c_a e_a),
C     with the seven-point stencil (error O(h**6), h = 1d-2 M): the
C      plain HELAS
C     library serves S and P waves, and the native Born providers of
C      the NLO
C     runtime need no dual-number library. The LDME and averages are
C      the
C     factor ONIA_AMP_R6FAC().
C     Process: g g > chic0(1|3P01) d d~ [ real = QCD QED ] QCD^2=8
C      QED^2=0
C     Process: g g > chic0(1|3P01) s s~ [ real = QCD QED ] QCD^2=8
C      QED^2=0
C     Process: g g > chic0(1|3P01) u u~ [ real = QCD QED ] QCD^2=8
C      QED^2=0
C     
      USE ALOHA_OBJECT
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      INTEGER    NGRAPHS
      PARAMETER (NGRAPHS=38)
      INTEGER    NWAVEFUNCS
      PARAMETER (NWAVEFUNCS=15)
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=5)
      REAL*8     ZERO
      PARAMETER (ZERO=0D0)
      COMPLEX*16 IMAG1
      PARAMETER (IMAG1=(0D0,1D0))
C     the step h = HREL*M of the derivative: its error is O((h/M)**6)
C     (q.p/K.p <= |q|/M for any momentum p, so h/M is the expansion
C     parameter), while its round-off grows as M/h near the soft limit
C      of
C     a real emission (on-shell constituents below). The five-point
C     stencil, O((h/M)**4) ~ 1d-6, was seen by the FKS limit tests.
      REAL*8     HREL
      PARAMETER (HREL=1D-2)
      INTEGER    NONIA
      INTEGER    NPWAVE
      INTEGER    DER_ORDER
      PARAMETER (NONIA=1)
      PARAMETER (NPWAVE=1)
      PARAMETER (DER_ORDER=1)

      INTEGER MAPPING(6)
      INTEGER PAIRS(6)
      DATA (MAPPING(I),I=1,6)/1,2,3,3,4,5/
      DATA (PAIRS(I),I=1,6)/0,0,1,-1,0,0/

      INTEGER ONIA(NONIA), N_ONIA(NONIA), S_ONIA(NONIA), L_ONIA(NONIA)
     $ , J_ONIA(NONIA), C_ONIA(NONIA)
      DATA (ONIA(I),I=1,1)/3/
      DATA (N_ONIA(I),I=1,1)/1/
      DATA (S_ONIA(I),I=1,1)/1/
      DATA (L_ONIA(I),I=1,1)/1/
      DATA (J_ONIA(I),I=1,1)/0/
      DATA (C_ONIA(I),I=1,1)/1/

      INTEGER ONIA_IN(NONIA), JH2_ONIA(NONIA)
      DATA (ONIA_IN(I),I=1,1)/0/
      DATA (JH2_ONIA(I),I=1,1)/1/

      INTEGER UNCOUPLED_ONIA(NONIA)
      DATA (UNCOUPLED_ONIA(I),I=1,1)/0/
C     
C     ARGUMENTS
C     
      REAL*8 P_IN(0:3,NEXTERNAL)
      INTEGER NHEL(NEXTERNAL)
      COMPLEX*16 AMP_OUT(NGRAPHS)
C     
C     LOCAL VARIABLES
C     
      INTEGER I, J, K, KP, QQ, Q1, Q2, MU, A, IPT, NPT, ISZ, NSZ
      INTEGER SZ(NONIA), NSZ_ONIA(NONIA), SZ_LIST(3,NONIA)
      INTEGER DIR(NONIA), STEP(NONIA)
      REAL*8 FRAC, NORM, CG, KDOTN, WEIGHT, QSQ
      REAL*8 Q(0:3,NONIA), E3(0:3,3,NONIA), H(NONIA)
      REAL*8 STENCIL(6), SWEIGHT(6)
      DATA STENCIL /-3D0, -2D0, -1D0, 1D0, 2D0, 3D0/
      DATA SWEIGHT /-1D0, 9D0, -45D0, 45D0, -9D0, 1D0/
      COMPLEX*16 AMP(NGRAPHS), PROJ
      REAL*8 PABS, P(0:3,NEXTERNAL), BETA(3), B2, GAMB, BP, FB
      TYPE(ALOHA) W(NWAVEFUNCS), EPS_L
      REAL*8 P_ONIA(0:3,NEXTERNAL+NONIA), ONIA_MS(NEXTERNAL+NONIA)
      REAL*8 PMASS_ONIA(NEXTERNAL+NONIA), PMASS_RESH(NEXTERNAL)
      INTEGER NHEL_ONIA(NEXTERNAL+NONIA), IC_ONIA(NEXTERNAL+NONIA)
      INTEGER FLAVOR_ONIA(NEXTERNAL+NONIA)
C     the S_z combinations with a non-zero Clebsch-Gordan weight
      INTEGER    NSZMAX
      PARAMETER (NSZMAX=3**NONIA)
      INTEGER NGOOD, IGS, SZS(NONIA,NSZMAX)
      REAL*8 CGS(NSZMAX)
      COMPLEX*16 CAS(3,NONIA,NSZMAX), COEFS(NSZMAX), PRJ
      COMPLEX*16 PROJ_SAVED(NONIA,-1:1,-1:1,NSZMAX)
      INTEGER HELQ(2)
      DATA HELQ/-1, 1/
      INCLUDE 'coupl.inc'

C     ----------
C     BEGIN CODE
C     ----------
C     A P-wave onium within rounding of rest (0 < |p| < 1d-6 E, e.g.
C      in the
C     rest frame of a decay): the spinors of its constituents and its
C     polarisation axes turn with a direction set by rounding, and the
C     derivative loses eps E/|p|. All momenta are boosted by its
C      velocity
C     and its 3-momentum is set to zero (as MadLoop's ONIA_PW_NEAR_REST
C     and onia_decay's tree level).
      P(:,:) = P_IN(:,:)
      DO I = 1, NONIA
        IF (L_ONIA(I).NE.1) CYCLE
        QQ = ONIA(I)
        PABS = SQRT(P(1,QQ)**2+P(2,QQ)**2+P(3,QQ)**2)
        IF (PABS.GT.0D0 .AND. PABS.LT.1D-6*P(0,QQ)) THEN
          BETA(1:3) = -P(1:3,QQ)/P(0,QQ)
          B2 = BETA(1)**2+BETA(2)**2+BETA(3)**2
          GAMB = 1D0/SQRT(1D0-B2)
          DO J = 1, NEXTERNAL
            BP = BETA(1)*P(1,J)+BETA(2)*P(2,J)+BETA(3)*P(3,J)
            FB = (GAMB-1D0)*BP/B2+GAMB*P(0,J)
            P(0,J) = GAMB*(P(0,J)+BP)
            P(1:3,J) = P(1:3,J)+FB*BETA(1:3)
          ENDDO
          P(1:3,QQ) = 0D0
        ENDIF
      ENDDO
      PMASS_ONIA(1)=ZERO
      PMASS_ONIA(2)=ZERO
      PMASS_ONIA(3)=ABS(MDL_MC)
      PMASS_ONIA(4)=ABS(MDL_MC)
      PMASS_ONIA(5)=ZERO
      PMASS_ONIA(6)=ZERO
      PMASS_RESH = 0D0
      DO I = 1, NEXTERNAL+NONIA
        PMASS_RESH(MAPPING(I)) = PMASS_RESH(MAPPING(I))+PMASS_ONIA(I)
      ENDDO
      DO I = 1, NEXTERNAL+NONIA
        NHEL_ONIA(I) = NHEL(MAPPING(I))
        IC_ONIA(I) = 1
        FLAVOR_ONIA(I) = 1
      ENDDO
C     for each onium: the S_z it can have, the colour norm, and for a P
C     wave the real directions orthogonal to K (rest-frame axes
C      boosted to
C     the frame of P)
      NORM = 1D0
      DO I = 1, NONIA
        QQ = ONIA(I)
        IF (C_ONIA(I).EQ.1) THEN
          NORM = NORM/3D0
        ELSE IF (C_ONIA(I).EQ.8) THEN
          NORM = NORM*2D0
        ENDIF
        NSZ_ONIA(I) = 0
        DO K = -S_ONIA(I), S_ONIA(I)
          IF (ABS(NHEL(QQ)-K).LE.L_ONIA(I)) THEN
            NSZ_ONIA(I) = NSZ_ONIA(I)+1
            SZ_LIST(NSZ_ONIA(I),I) = K
          ENDIF
        ENDDO
        H(I) = HREL*PMASS_RESH(QQ)
        IF (L_ONIA(I).EQ.1) THEN
          DO A = 1, 3
            KDOTN = P(A,QQ)
            E3(0,A,I) = KDOTN/PMASS_RESH(QQ)
            DO MU = 1, 3
              E3(MU,A,I) = P(MU,QQ)*KDOTN/(PMASS_RESH(QQ)*(P(0,QQ)
     &          +PMASS_RESH(QQ)))
            ENDDO
            E3(A,A,I) = E3(A,A,I)+1D0
          ENDDO
        ENDIF
      ENDDO
      AMP_OUT(:) = (0D0,0D0)

C     the combinations of S_z of the onia (ISZ codes them) with a
C      non-zero
C     Clebsch-Gordan weight, and for each P wave eps*(L_z) = sum_a
C      CA(a) e_a,
C     L_z = J_z - S_z. The diagrams do not depend on S_z: they are
C      evaluated
C     once per stencil point and constituent helicities, with the
C      projectors
C     summed over S_z.
      NSZ = 1
      DO I = 1, NONIA
        NSZ = NSZ*NSZ_ONIA(I)
      ENDDO
      NGOOD = 0
      DO ISZ = 1, NSZ
        K = ISZ-1
        CG = 1D0
        DO I = 1, NONIA
          SZ(I) = SZ_LIST(MOD(K,NSZ_ONIA(I))+1,I)
          K = K/NSZ_ONIA(I)
          CALL ONIA_AMP_R6CG(L_ONIA(I),NHEL(ONIA(I))-SZ(I),S_ONIA(I),
     &      SZ(I),J_ONIA(I),NHEL(ONIA(I)),WEIGHT)
          CG = CG*WEIGHT
        ENDDO
        IF (CG.EQ.0D0) CYCLE
        NGOOD = NGOOD+1
        CGS(NGOOD) = CG
        DO I = 1, NONIA
          SZS(I,NGOOD) = SZ(I)
          IF (L_ONIA(I).NE.1) CYCLE
          QQ = ONIA(I)
C         eps*(L_z) of an outgoing onium, eps(L_z) of a decaying one
          CALL VXXXXX(P(0,QQ),PMASS_RESH(QQ),NHEL(QQ)-SZ(I),
     &      1-2*ONIA_IN(I),EPS_L)
          DO A = 1, 3
            CAS(A,I,NGOOD) = -(EPS_L%W(1)*E3(0,A,I)
     &        -EPS_L%W(2)*E3(1,A,I)-EPS_L%W(3)*E3(2,A,I)
     &        -EPS_L%W(4)*E3(3,A,I))
          ENDDO
        ENDDO
      ENDDO
      IF (NGOOD.EQ.0) RETURN
C     the derivatives: the directions and stencil points of every P
C      wave
      NPT = 18**NPWAVE
      DO IPT = 1, NPT
        K = IPT-1
        DO I = 1, NONIA
          Q(:,I) = 0D0
          IF (L_ONIA(I).NE.1) CYCLE
          STEP(I) = MOD(K,6)+1
          K = K/6
          DIR(I) = MOD(K,3)+1
          K = K/3
          Q(:,I) = STENCIL(STEP(I))*H(I)*E3(:,DIR(I),I)
        ENDDO
        DO IGS = 1, NGOOD
          COEFS(IGS) = DCMPLX(CGS(IGS)*SQRT(NORM), 0D0)
          DO I = 1, NONIA
            IF (L_ONIA(I).NE.1) CYCLE
            COEFS(IGS) = COEFS(IGS)*CAS(DIR(I),I,IGS)
     &        *SWEIGHT(STEP(I))/(60D0*H(I))
          ENDDO
        ENDDO
C       the constituent momenta and spin projectors at these q:
C       k_i = m_i/M K +- q, which conserves momentum exactly, with
C       k_i**2 = m_i**2 + q**2. The constituents are given this mass,
C       ONIA_MS(i) = sqrt(m_i**2 + q**2), in their wave functions, in
C        the
C       spin projector and in the propagators of a constituent line
C        next
C       to the emission of one gluon (get_onia_kernel), so that such a
C       propagator is 2 k_i.k_g exactly near the soft limit of a real
C       emission. The shift is even in q and leaves the derivative
C       unchanged. (On-shell constituents with k_1 + k_2 /= K would
C        break
C       momentum conservation at O(h**2) instead, and with it the
C       propagators near the soft limit built from the other side of a
C       diagram.)
        DO I = 1, NEXTERNAL+NONIA
          ONIA_MS(I) = PMASS_ONIA(I)
          IF (PAIRS(I).NE.0) THEN
            J = FINDLOC(PAIRS,-PAIRS(I),DIM=1)
            KP = ABS(PAIRS(I))
            QSQ = Q(0,KP)**2-Q(1,KP)**2-Q(2,KP)**2-Q(3,KP)**2
            FRAC = PMASS_ONIA(I)/(PMASS_ONIA(I)+PMASS_ONIA(J))
            ONIA_MS(I) = SQRT(PMASS_ONIA(I)**2+QSQ)
            P_ONIA(:,I) = FRAC*P(:,MAPPING(I))
     &        +SIGN(1,PAIRS(I))*Q(:,KP)
          ELSE
            P_ONIA(:,I) = P(:,MAPPING(I))
          ENDIF
        ENDDO
        DO IGS = 1, NGOOD
          DO I = 1, NONIA
            QQ = ONIA(I)
            Q1 = FINDLOC(PAIRS, I, DIM=1)
            Q2 = FINDLOC(PAIRS,-I, DIM=1)
            DO J = 1, 2
              DO A = 1, 2
                IF (ONIA_IN(I).EQ.1) THEN
                  CALL ONIA_PROJ_IN(P_ONIA(:,Q1),ONIA_MS(Q1),HELQ(J),
     &              P_ONIA(:,Q2),ONIA_MS(Q2),HELQ(A),P(:,QQ),
     &              PMASS_RESH(QQ),SZS(I,IGS),S_ONIA(I),PROJ)
                ELSE
                  CALL ONIA_PROJ(P_ONIA(:,Q1),ONIA_MS(Q1),HELQ(J),
     &              P_ONIA(:,Q2),ONIA_MS(Q2),HELQ(A),P(:,QQ),
     &              PMASS_RESH(QQ),SZS(I,IGS),S_ONIA(I),PROJ)
                ENDIF
                PROJ_SAVED(I,HELQ(J),HELQ(A),IGS) = PROJ
              ENDDO
            ENDDO
          ENDDO
        ENDDO
        DO J = 1, 4**NONIA
          DO I = 1, NONIA
            Q1 = FINDLOC(PAIRS, I, DIM=1)
            Q2 = FINDLOC(PAIRS,-I, DIM=1)
            NHEL_ONIA(Q1) = HELQ(IBITS(J-1,2*I-2,1)+1)
            NHEL_ONIA(Q2) = HELQ(IBITS(J-1,2*I-1,1)+1)
          ENDDO
          PROJ = (0D0,0D0)
          PABS = 0D0
          DO IGS = 1, NGOOD
            PRJ = COEFS(IGS)
            DO I = 1, NONIA
              Q1 = FINDLOC(PAIRS, I, DIM=1)
              Q2 = FINDLOC(PAIRS,-I, DIM=1)
              PRJ = PRJ*PROJ_SAVED(I,NHEL_ONIA(Q1),NHEL_ONIA(Q2),IGS)
            ENDDO
            PROJ = PROJ+PRJ
            PABS = PABS+ABS(PRJ)
          ENDDO
          IF (PROJ.NE.(0D0,0D0)) THEN
            CALL VXXXXX(P_ONIA(0,1),ZERO,NHEL_ONIA(1),-1,W(1))
            CALL VXXXXX(P_ONIA(0,2),ZERO,NHEL_ONIA(2),-1,W(2))
            CALL OXXXXX(P_ONIA(0,3),ONIA_MS(3),NHEL_ONIA(3),+1,
     $        FLAVOR_ONIA(3),W(3))
            CALL IXXXXX(P_ONIA(0,4),ONIA_MS(4),NHEL_ONIA(4),-1,
     $        FLAVOR_ONIA(4),W(4))
            CALL OXXXXX(P_ONIA(0,5),ZERO,NHEL_ONIA(5),+1,
     $        FLAVOR_ONIA(5),W(5))
            CALL IXXXXX(P_ONIA(0,6),ZERO,NHEL_ONIA(6),-1,
     $        FLAVOR_ONIA(6),W(6))
            CALL VVV1P0_1(W(1),W(2),GC_10,ZERO,ZERO,W(7))
            CALL FFV1P0_3(W(4),W(3),GC_11,ZERO,ZERO,W(8))
            CALL FFV1_1(W(5),W(7),GC_11,ZERO,ZERO,W(9))
C           Amplitude(s) for diagram number 1
            CALL FFV1_0(W(6),W(9),W(8),GC_11,AMP(1))
            CALL FFV1_2(W(6),W(7),GC_11,ZERO,ZERO,W(9))
C           Amplitude(s) for diagram number 2
            CALL FFV1_0(W(9),W(5),W(8),GC_11,AMP(2))
            CALL FFV1P0_3(W(6),W(5),GC_11,ZERO,ZERO,W(9))
C           Amplitude(s) for diagram number 3
            CALL VVV1_0(W(7),W(8),W(9),GC_10,AMP(3))
            CALL FFV1_1(W(3),W(7),GC_11,MDL_MC,ZERO,W(10))
C           Amplitude(s) for diagram number 4
            CALL FFV1_0(W(4),W(10),W(9),GC_11,AMP(4))
            CALL FFV1_2(W(4),W(7),GC_11,MDL_MC,ZERO,W(10))
C           Amplitude(s) for diagram number 5
            CALL FFV1_0(W(10),W(3),W(9),GC_11,AMP(5))
            CALL FFV1_1(W(3),W(1),GC_11,ONIA_MS(3),ZERO,W(10))
            CALL FFV1_2(W(4),W(2),GC_11,ONIA_MS(4),ZERO,W(7))
C           Amplitude(s) for diagram number 6
            CALL FFV1_0(W(7),W(10),W(9),GC_11,AMP(6))
            CALL FFV1_1(W(5),W(2),GC_11,ZERO,ZERO,W(11))
            CALL FFV1P0_3(W(4),W(10),GC_11,ZERO,ZERO,W(12))
C           Amplitude(s) for diagram number 7
            CALL FFV1_0(W(6),W(11),W(12),GC_11,AMP(7))
            CALL FFV1_2(W(6),W(2),GC_11,ZERO,ZERO,W(13))
C           Amplitude(s) for diagram number 8
            CALL FFV1_0(W(13),W(5),W(12),GC_11,AMP(8))
            CALL FFV1_1(W(10),W(2),GC_11,MDL_MC,ZERO,W(14))
C           Amplitude(s) for diagram number 9
            CALL FFV1_0(W(4),W(14),W(9),GC_11,AMP(9))
C           Amplitude(s) for diagram number 10
            CALL VVV1_0(W(2),W(9),W(12),GC_10,AMP(10))
            CALL FFV1_2(W(4),W(1),GC_11,ONIA_MS(4),ZERO,W(12))
            CALL FFV1_1(W(3),W(2),GC_11,ONIA_MS(3),ZERO,W(14))
C           Amplitude(s) for diagram number 11
            CALL FFV1_0(W(12),W(14),W(9),GC_11,AMP(11))
            CALL FFV1P0_3(W(12),W(3),GC_11,ZERO,ZERO,W(10))
C           Amplitude(s) for diagram number 12
            CALL FFV1_0(W(6),W(11),W(10),GC_11,AMP(12))
C           Amplitude(s) for diagram number 13
            CALL FFV1_0(W(13),W(5),W(10),GC_11,AMP(13))
            CALL FFV1_2(W(12),W(2),GC_11,MDL_MC,ZERO,W(15))
C           Amplitude(s) for diagram number 14
            CALL FFV1_0(W(15),W(3),W(9),GC_11,AMP(14))
C           Amplitude(s) for diagram number 15
            CALL VVV1_0(W(2),W(9),W(10),GC_10,AMP(15))
            CALL FFV1_1(W(5),W(1),GC_11,ZERO,ZERO,W(10))
            CALL FFV1P0_3(W(6),W(10),GC_11,ZERO,ZERO,W(15))
C           Amplitude(s) for diagram number 16
            CALL FFV1_0(W(4),W(14),W(15),GC_11,AMP(16))
C           Amplitude(s) for diagram number 17
            CALL FFV1_0(W(7),W(3),W(15),GC_11,AMP(17))
C           Amplitude(s) for diagram number 18
            CALL FFV1_0(W(13),W(10),W(8),GC_11,AMP(18))
            CALL FFV1_1(W(10),W(2),GC_11,ZERO,ZERO,W(12))
C           Amplitude(s) for diagram number 19
            CALL FFV1_0(W(6),W(12),W(8),GC_11,AMP(19))
C           Amplitude(s) for diagram number 20
            CALL VVV1_0(W(2),W(8),W(15),GC_10,AMP(20))
            CALL FFV1_2(W(6),W(1),GC_11,ZERO,ZERO,W(15))
            CALL FFV1P0_3(W(15),W(5),GC_11,ZERO,ZERO,W(12))
C           Amplitude(s) for diagram number 21
            CALL FFV1_0(W(4),W(14),W(12),GC_11,AMP(21))
C           Amplitude(s) for diagram number 22
            CALL FFV1_0(W(7),W(3),W(12),GC_11,AMP(22))
C           Amplitude(s) for diagram number 23
            CALL FFV1_0(W(15),W(11),W(8),GC_11,AMP(23))
            CALL FFV1_2(W(15),W(2),GC_11,ZERO,ZERO,W(10))
C           Amplitude(s) for diagram number 24
            CALL FFV1_0(W(10),W(5),W(8),GC_11,AMP(24))
C           Amplitude(s) for diagram number 25
            CALL VVV1_0(W(2),W(8),W(12),GC_10,AMP(25))
            CALL FFV1_1(W(14),W(1),GC_11,MDL_MC,ZERO,W(12))
C           Amplitude(s) for diagram number 26
            CALL FFV1_0(W(4),W(12),W(9),GC_11,AMP(26))
            CALL VVV1P0_1(W(1),W(9),GC_10,ZERO,ZERO,W(12))
C           Amplitude(s) for diagram number 27
            CALL FFV1_0(W(4),W(14),W(12),GC_11,AMP(27))
            CALL FFV1_2(W(7),W(1),GC_11,MDL_MC,ZERO,W(14))
C           Amplitude(s) for diagram number 28
            CALL FFV1_0(W(14),W(3),W(9),GC_11,AMP(28))
C           Amplitude(s) for diagram number 29
            CALL FFV1_0(W(7),W(3),W(12),GC_11,AMP(29))
            CALL FFV1_1(W(11),W(1),GC_11,ZERO,ZERO,W(7))
C           Amplitude(s) for diagram number 30
            CALL FFV1_0(W(6),W(7),W(8),GC_11,AMP(30))
            CALL VVV1P0_1(W(1),W(8),GC_10,ZERO,ZERO,W(7))
C           Amplitude(s) for diagram number 31
            CALL FFV1_0(W(6),W(11),W(7),GC_11,AMP(31))
            CALL FFV1_2(W(13),W(1),GC_11,ZERO,ZERO,W(11))
C           Amplitude(s) for diagram number 32
            CALL FFV1_0(W(11),W(5),W(8),GC_11,AMP(32))
C           Amplitude(s) for diagram number 33
            CALL FFV1_0(W(13),W(5),W(7),GC_11,AMP(33))
C           Amplitude(s) for diagram number 34
            CALL VVVV1_0(W(1),W(2),W(8),W(9),GC_12,AMP(34))
            CALL VVVV3_0(W(1),W(2),W(8),W(9),GC_12,AMP(35))
            CALL VVVV4_0(W(1),W(2),W(8),W(9),GC_12,AMP(36))
C           Amplitude(s) for diagram number 35
            CALL VVV1_0(W(2),W(9),W(7),GC_10,AMP(37))
C           Amplitude(s) for diagram number 36
            CALL VVV1_0(W(2),W(8),W(12),GC_10,AMP(38))
            AMP_OUT(:) = AMP_OUT(:)+AMP(:)*PROJ

          ENDIF
        ENDDO
      ENDDO

      END


      SUBROUTINE ONIA_AMP_R6CG(L, LZ, S, SZ, J, JZ, CG)
C     <L L_z; S S_z | J J_z> for L, S <= 1 (as CLEBSCH_GORDAN of the
C     dual-number HELAS library, which the NLO output does not build)
      IMPLICIT NONE
      INTEGER L, LZ, S, SZ, J, JZ
      DOUBLE PRECISION CG
      IF (JZ.NE.LZ+SZ .OR. ABS(LZ).GT.L .OR. ABS(SZ).GT.S) THEN
        CG = 0D0
      ELSE IF (L.EQ.0 .OR. S.EQ.0) THEN
        CG = 1D0
      ELSE IF (J.EQ.2) THEN
        IF (LZ.EQ.0 .AND. SZ.EQ.0) THEN
          CG = DSQRT(2D0/3D0)
        ELSE IF (LZ.EQ.0 .OR. SZ.EQ.0) THEN
          CG = 1D0/DSQRT(2D0)
        ELSE IF (LZ.EQ.SZ) THEN
          CG = 1D0
        ELSE
          CG = 1D0/DSQRT(6D0)
        ENDIF
      ELSE IF (J.EQ.1) THEN
        IF (LZ.EQ.1 .OR. SZ.EQ.-1) THEN
          CG = 1D0/DSQRT(2D0)
        ELSE IF (LZ.EQ.-1 .OR. SZ.EQ.1) THEN
          CG = -1D0/DSQRT(2D0)
        ELSE
          CG = 0D0
        ENDIF
      ELSE IF (J.EQ.0) THEN
        IF (LZ.EQ.0 .AND. SZ.EQ.0) THEN
          CG = -1D0/DSQRT(3D0)
        ELSE
          CG = 1D0/DSQRT(3D0)
        ENDIF
      ELSE
        CG = 0D0
      ENDIF
      END


      DOUBLE PRECISION FUNCTION ONIA_AMP_R6FAC()
C     
C     The LDME factor of the bound states of ONIA_AMP_R6: for each
C      onium
C     <O_n> (m1+m2)/(2 m1 m2)/(N_[C] (2J+1)), N_[1] = 6, N_[8] = 8
C     (arXiv:2402.19221, eq. 2.9), with the LDMEs of the onia card. A
C     decaying onium has its decay LDME <O_H> (Block ldme_decay),
C      without
C     the 1/(2J+1): the average over its 2J+1 states is in IDEN.
C     
      IMPLICIT NONE
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=5)
      INTEGER    NONIA
      INTEGER    NPWAVE
      INTEGER    DER_ORDER
      PARAMETER (NONIA=1)
      PARAMETER (NPWAVE=1)
      PARAMETER (DER_ORDER=1)

      INTEGER MAPPING(6)
      INTEGER PAIRS(6)
      DATA (MAPPING(I),I=1,6)/1,2,3,3,4,5/
      DATA (PAIRS(I),I=1,6)/0,0,1,-1,0,0/

      INTEGER ONIA(NONIA), N_ONIA(NONIA), S_ONIA(NONIA), L_ONIA(NONIA)
     $ , J_ONIA(NONIA), C_ONIA(NONIA)
      DATA (ONIA(I),I=1,1)/3/
      DATA (N_ONIA(I),I=1,1)/1/
      DATA (S_ONIA(I),I=1,1)/1/
      DATA (L_ONIA(I),I=1,1)/1/
      DATA (J_ONIA(I),I=1,1)/0/
      DATA (C_ONIA(I),I=1,1)/1/

      INTEGER ONIA_IN(NONIA), JH2_ONIA(NONIA)
      DATA (ONIA_IN(I),I=1,1)/0/
      DATA (JH2_ONIA(I),I=1,1)/1/

      INTEGER UNCOUPLED_ONIA(NONIA)
      DATA (UNCOUPLED_ONIA(I),I=1,1)/0/
      REAL*8     ZERO
      PARAMETER (ZERO=0D0)
      INTEGER I, Q1, Q2
      REAL*8 LDME, NPOL, PMASS_ONIA(NEXTERNAL+NONIA)
      LOGICAL FIRSTTIME
      DATA FIRSTTIME/.TRUE./
      REAL*8 SAVED
      SAVE FIRSTTIME, SAVED
      INCLUDE 'coupl.inc'
      DOUBLE PRECISION LDME_10441
      INTEGER NLDME
      PARAMETER (NLDME=1)
      INTEGER LDME_PDG(NLDME+1)
      DATA LDME_PDG/10441,0/
      DOUBLE PRECISION LDME_VAL(NLDME+1)
      IF (FIRSTTIME) THEN
        CALL ONIA_AMP_R6READCARD(NLDME, LDME_PDG, LDME_VAL)
        LDME_10441 = LDME_VAL(1)
        PMASS_ONIA(1)=ZERO
        PMASS_ONIA(2)=ZERO
        PMASS_ONIA(3)=ABS(MDL_MC)
        PMASS_ONIA(4)=ABS(MDL_MC)
        PMASS_ONIA(5)=ZERO
        PMASS_ONIA(6)=ZERO
        LDME = 1D0
        DO I = 1, NONIA
          Q1 = FINDLOC(PAIRS, I, DIM=1)
          Q2 = FINDLOC(PAIRS,-I, DIM=1)
          LDME = LDME*(PMASS_ONIA(Q1)+PMASS_ONIA(Q2))
     &      /(2D0*PMASS_ONIA(Q1)*PMASS_ONIA(Q2))
          IF (ONIA_IN(I).EQ.1) THEN
            NPOL = 1D0
          ELSE
            NPOL = 2D0*J_ONIA(I)+1D0
          ENDIF
          IF (C_ONIA(I).EQ.1) THEN
            LDME = LDME/6D0/NPOL
          ELSE IF (C_ONIA(I).EQ.8) THEN
            LDME = LDME/8D0/NPOL
          ENDIF
        ENDDO
C       perturbative (leptonium) LDMEs

        SAVED = LDME*LDME_10441
        FIRSTTIME = .FALSE.
      ENDIF
      ONIA_AMP_R6FAC = SAVED
      END


      SUBROUTINE ONIA_AMP_R6READCARD(N, PDG, VAL)
C     
C     The LDMEs of the onia card for the codes PDG(1:N): Block ldme for
C     PDG > 0, Block ldme_decay for -PDG when PDG < 0 (a decaying
C      onium),
C     read directly (no COMMON: the native Born providers keep private
C     copies of the COMMON blocks of their sources).
C     
      IMPLICIT NONE
      INTEGER N, PDG(*)
      DOUBLE PRECISION VAL(*)
      CHARACTER*256 LINE
      CHARACTER*16 WORD, BNAME
      CHARACTER*40 FILES(4)
      DATA FILES /'onia_card.dat', '../onia_card.dat',
     &  '../../Cards/onia_card.dat', '../../../Cards/onia_card.dat'/
      INTEGER I, K, IUNIT, IOS, ID
      DOUBLE PRECISION X
      INTEGER INBLOCK
      LOGICAL FOUND(64)
      IF (N.EQ.0) RETURN
      IUNIT = 97
      DO K = 1, 4
        OPEN(UNIT=IUNIT, FILE=FILES(K), STATUS='OLD', IOSTAT=IOS)
        IF (IOS.EQ.0) GOTO 10
      ENDDO
      WRITE(*,*) 'Error: the onia card onia_card.dat was not found'
      STOP 1
 10   CONTINUE
      INBLOCK = 0
      DO I = 1, N
        FOUND(I) = .FALSE.
      ENDDO
 20   CONTINUE
      READ(IUNIT,'(A)',IOSTAT=IOS) LINE
      IF (IOS.NE.0) GOTO 30
      IF (INDEX(ADJUSTL(LINE),'#').EQ.1) GOTO 20
      WORD = ' '
      BNAME = ' '
      READ(LINE,*,IOSTAT=IOS) WORD, BNAME
      IF (WORD.EQ.'Block' .OR. WORD.EQ.'BLOCK' .OR. WORD.EQ.'block')
     $  THEN
        INBLOCK = 0
        IF (BNAME.EQ.'ldme' .OR. BNAME.EQ.'LDME' .OR. BNAME.EQ.'Ldme')
     &    INBLOCK = 1
        IF (BNAME.EQ.'ldme_decay' .OR. BNAME.EQ.'LDME_DECAY'
     &    .OR. BNAME.EQ.'Ldme_decay') INBLOCK = -1
        GOTO 20
      ENDIF
      IF (INBLOCK.NE.0) THEN
        READ(LINE,*,IOSTAT=IOS) ID, X
        IF (IOS.EQ.0) THEN
          DO I = 1, N
            IF (PDG(I).EQ.INBLOCK*ID) THEN
              VAL(I) = X
              FOUND(I) = .TRUE.
            ENDIF
          ENDDO
        ENDIF
      ENDIF
      GOTO 20
 30   CONTINUE
      CLOSE(IUNIT)
      DO I = 1, N
        IF (.NOT.FOUND(I)) THEN
          IF (PDG(I).GT.0) THEN
            WRITE(*,*) 'Error: no LDME for ', PDG(I), ' in Block ldme'
     &        //' of the onia card'
          ELSE
            WRITE(*,*) 'Error: no LDME for ', -PDG(I),
     &        ' in Block ldme_decay of the onia card'
          ENDIF
          STOP 1
        ENDIF
      ENDDO
      END

