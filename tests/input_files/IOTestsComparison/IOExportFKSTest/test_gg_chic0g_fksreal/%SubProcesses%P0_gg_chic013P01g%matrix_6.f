      SUBROUTINE SMATRIX6(P,ANS_SUMMED)
C     
C     Generated by MadGraph7 v. %(version)s, %(date)s
C     By the MadGraph7 Development Team
C     Visit launchpad.net/madgraph5 and amcatnlo.web.cern.ch
C     
C     
C     Return the sum of the split orders which are required in
C      orders.inc (NLO_ORDERS)
C     
C     
C     Process: g g > chic0(1|3P01) d d~ [ real = QCD QED ] QCD^2=8
C      QED^2=0
C     Process: g g > chic0(1|3P01) s s~ [ real = QCD QED ] QCD^2=8
C      QED^2=0
C     Process: g g > chic0(1|3P01) u u~ [ real = QCD QED ] QCD^2=8
C      QED^2=0
C     
C     
C     CONSTANTS
C     
      IMPLICIT NONE
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=5)
      INTEGER NSQAMPSO
      PARAMETER (NSQAMPSO=1)
C     
C     ARGUMENTS 
C     
      REAL*8 P(0:3,NEXTERNAL), ANS_SUMMED
C     
C     VARIABLES
C     
      INTEGER I,J
      REAL*8 ANS(0:NSQAMPSO)
      LOGICAL KEEP_ORDER(NSQAMPSO), FIRSTTIME
      INCLUDE 'orders.inc'
      DATA KEEP_ORDER / NSQAMPSO*.TRUE. /
      DATA FIRSTTIME / .TRUE. /
      INTEGER AMP_ORDERS(NSPLITORDERS)
      DOUBLE PRECISION ANS_MAX, TINY
      PARAMETER (TINY = 1D-12)
      DOUBLE PRECISION       WGT_ME_BORN,WGT_ME_REAL
      COMMON /C_WGT_ME_TREE/ WGT_ME_BORN,WGT_ME_REAL
C     
C     FUNCTIONS
C     
      INTEGER GETORDPOWFROMINDEX6
      INTEGER ORDERS_TO_AMP_SPLIT_POS
C     
C     BEGIN CODE
C     

C     look for orders which match the nlo order constraint 

      IF (FIRSTTIME) THEN
        DO I = 1, NSQAMPSO
          DO J = 1, NSPLITORDERS
            IF(GETORDPOWFROMINDEX6(J, I) .GT. NLO_ORDERS(J)) THEN
              KEEP_ORDER(I) = .FALSE.
              EXIT
            ENDIF
          ENDDO
          IF (KEEP_ORDER(I)) THEN
            WRITE(*,*) 'REAL 6: keeping split order ', I
          ELSE
            WRITE(*,*) 'REAL 6: not keeping split order ', I
          ENDIF
        ENDDO
        FIRSTTIME = .FALSE.
      ENDIF

      CALL SMATRIX6_SPLITORDERS(P,ANS)
      ANS_SUMMED = 0D0
      ANS_MAX = 0D0

C     reset the amp_split array
      AMP_SPLIT(1:AMP_SPLIT_SIZE) = 0D0

      DO I = 1, NSQAMPSO
        ANS_MAX = MAX(DABS(ANS(I)),ANS_MAX)
      ENDDO

      DO I = 1, NSQAMPSO
        IF (KEEP_ORDER(I)) THEN
          ANS_SUMMED = ANS_SUMMED + ANS(I)
C         keep track of the separate pieces corresponding to different
C          coupling combinations
          DO J = 1, NSPLITORDERS
            AMP_ORDERS(J) = GETORDPOWFROMINDEX6(J, I)
          ENDDO
          IF (ABS(ANS(I)).GT.ANS_MAX*TINY)
     $      AMP_SPLIT(ORDERS_TO_AMP_SPLIT_POS(AMP_ORDERS)) = ANS(I)
        ENDIF
      ENDDO

C     avoid fake non-zeros
      IF (DABS(ANS_SUMMED).LT.TINY*ANS_MAX) ANS_SUMMED=0D0

      WGT_ME_REAL = ANS_SUMMED

      END



      SUBROUTINE SMATRIX6_SPLITORDERS(P,ANS)
      USE MC_BORN_TYPES,ONLY:BORNMODELSTATE,BORN_HELICITY_STATE_EQUAL
      IMPLICIT NONE
      TYPE(BORNMODELSTATE),SAVE::HELICITY_MODEL_STATE
     $ ,HELICITY_CURRENT_STATE
      INCLUDE 'nexternal.inc'
      INTEGER     NCOMB
      PARAMETER ( NCOMB=16)
      INTEGER NSQAMPSO
      PARAMETER (NSQAMPSO=1)
      REAL*8 P(0:3,NEXTERNAL),ANS(0:NSQAMPSO)
      INTEGER IHEL,IDEN,I
      REAL*8 T(0:NSQAMPSO)
      INTEGER NHEL(NEXTERNAL,NCOMB)
      DATA (NHEL(I,   1),I=1,5) /-1,-1, 0,-1, 1/
      DATA (NHEL(I,   2),I=1,5) /-1,-1, 0,-1,-1/
      DATA (NHEL(I,   3),I=1,5) /-1,-1, 0, 1, 1/
      DATA (NHEL(I,   4),I=1,5) /-1,-1, 0, 1,-1/
      DATA (NHEL(I,   5),I=1,5) /-1, 1, 0,-1, 1/
      DATA (NHEL(I,   6),I=1,5) /-1, 1, 0,-1,-1/
      DATA (NHEL(I,   7),I=1,5) /-1, 1, 0, 1, 1/
      DATA (NHEL(I,   8),I=1,5) /-1, 1, 0, 1,-1/
      DATA (NHEL(I,   9),I=1,5) / 1,-1, 0,-1, 1/
      DATA (NHEL(I,  10),I=1,5) / 1,-1, 0,-1,-1/
      DATA (NHEL(I,  11),I=1,5) / 1,-1, 0, 1, 1/
      DATA (NHEL(I,  12),I=1,5) / 1,-1, 0, 1,-1/
      DATA (NHEL(I,  13),I=1,5) / 1, 1, 0,-1, 1/
      DATA (NHEL(I,  14),I=1,5) / 1, 1, 0,-1,-1/
      DATA (NHEL(I,  15),I=1,5) / 1, 1, 0, 1, 1/
      DATA (NHEL(I,  16),I=1,5) / 1, 1, 0, 1,-1/
      LOGICAL GOODHEL(NCOMB)
      DATA GOODHEL/NCOMB*.FALSE./
      INTEGER NTRY
      DATA NTRY/0/
      INCLUDE 'real_matrix_weights.inc'
      DOUBLE PRECISION ONIA_AMP_R6FAC
      EXTERNAL ONIA_AMP_R6FAC
      DATA IDEN/256/
      CALL MC_CAPTURE_MODEL_STATE(HELICITY_CURRENT_STATE)
      IF(.NOT.BORN_HELICITY_STATE_EQUAL(HELICITY_MODEL_STATE
     $ ,HELICITY_CURRENT_STATE))THEN
        NTRY=0
        GOODHEL=.FALSE.
        HELICITY_MODEL_STATE%CONFIGURATION_EPOCH=HELICITY_CURRENT_STATE
     $%CONFIGURATION_EPOCH
        HELICITY_MODEL_STATE%REAL_VALUES=HELICITY_CURRENT_STATE%REAL_VA
     $LUES
        HELICITY_MODEL_STATE%COMPLEX_VALUES=HELICITY_CURRENT_STATE%COMP
     $LEX_VALUES
      ENDIF
      NTRY=NTRY+1
      IF (GET_REAL_DIAGRAM_WEIGHTS) REAL_AMP2(:)=0D0
      DO I=0,NSQAMPSO
        ANS(I) = 0D0
      ENDDO
      DO IHEL=1,NCOMB
        IF (GOODHEL(IHEL) .OR. NTRY .LT. 2) THEN
          CALL MATRIX_6(P ,NHEL(1,IHEL),T)
          DO I=1,NSQAMPSO  !keep loop from 1!!
            ANS(I)=ANS(I)+T(I)
          ENDDO
          IF (MAXVAL(ABS(T(1:NSQAMPSO))).NE.0D0 .AND. .NOT.
     $      GOODHEL(IHEL)) THEN
            GOODHEL(IHEL)=.TRUE.
          ENDIF
        ENDIF
      ENDDO
      IF (NTRY.LT.2 .AND. GET_REAL_DIAGRAM_WEIGHTS) THEN
        REAL_AMP2(:)=0D0
        DO IHEL=1,NCOMB
          IF (GOODHEL(IHEL)) THEN
            CALL MATRIX_6(P ,NHEL(1,IHEL),T)
          ENDIF
        ENDDO
      ENDIF
      DO I=1,NSQAMPSO
        ANS(I)=ANS(I)/DBLE(IDEN)
        ANS(0)=ANS(0)+ANS(I)
      ENDDO
      END


