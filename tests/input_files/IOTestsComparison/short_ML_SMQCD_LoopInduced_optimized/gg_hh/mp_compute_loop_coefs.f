      SUBROUTINE ML5_0_MP_COMPUTE_LOOP_COEFS(PS,ANSDP)
C     
C     Generated by MadGraph5_aMC@NLO v. %(version)s, %(date)s
C     By the MadGraph5_aMC@NLO Development Team
C     Visit launchpad.net/madgraph5 and amcatnlo.web.cern.ch
C     
C     Returns amplitude squared summed/avg over colors
C     and helicities for the point in phase space P(0:3,NEXTERNAL)
C     and external lines W(0:6,NEXTERNAL)
C     
C     Process: g g > h h QCD<=2 QED<=2 [ sqrvirt = QCD ]
C     
C     Modules
C     
      USE ML5_0_POLYNOMIAL_CONSTANTS
      USE ALOHA_OBJECT
C     
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      CHARACTER*64 PARAMFILENAME
      PARAMETER ( PARAMFILENAME='MadLoopParams.dat')
      INTEGER    NLOOPS, NLOOPGROUPS, NCTAMPS
      PARAMETER (NLOOPS=16, NLOOPGROUPS=16, NCTAMPS=4)
      INTEGER    NLOOPAMPS
      PARAMETER (NLOOPAMPS=20)
      INTEGER    NCOLORROWS
      PARAMETER (NCOLORROWS=NLOOPAMPS)
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=4)
      INTEGER    NWAVEFUNCS,NLOOPWAVEFUNCS
      PARAMETER (NWAVEFUNCS=5,NLOOPWAVEFUNCS=40)
      INTEGER    NCOMB
      PARAMETER (NCOMB=4)
      REAL*16    ZERO
      PARAMETER (ZERO=0E0_16)
      COMPLEX*32 IMAG1
      PARAMETER (IMAG1=(0E0_16,1E0_16))
      COMPLEX*32 DP_IMAG1
      PARAMETER (DP_IMAG1=(0D0,1D0))
C     These are constants related to the split orders
      INTEGER    NSO, NSQUAREDSO, NAMPSO
      PARAMETER (NSO=0, NSQUAREDSO=0, NAMPSO=0)

C     The variables below are just used in the context of a JAMP
C      consistency check turned off by default.
      LOGICAL DIRECT_ME_COMPUTATION, ME_COMPUTATION_FROM_JAMP
      REAL*8 RES_FROM_JAMP(0:3,0:NSQUAREDSO)
      COMMON/ML5_0_DOUBLECHECK_JAMP/RES_FROM_JAMP
     $ ,DIRECT_ME_COMPUTATION,ME_COMPUTATION_FROM_JAMP

C     
C     ARGUMENTS 
C     
      REAL*16 PS(0:3,NEXTERNAL)
      REAL*8 ANSDP(3,0:NSQUAREDSO)
C     
C     LOCAL VARIABLES 
C     
      LOGICAL DPW_COPIED
      LOGICAL COMPUTE_INTEGRAND_IN_QP
      INTEGER I,J,K,H,HEL_MULT,ITEMP
      REAL*16 TEMP2(3)
      REAL*8 DP_TEMP2(3)
      COMPLEX*32 CTEMP
      COMPLEX*16 DP_CTEMP

      INTEGER NHEL(NEXTERNAL), IC(NEXTERNAL)
      REAL*16 MP_P(0:3,NEXTERNAL)
      REAL*8 P(0:3,NEXTERNAL)

      DATA IC/NEXTERNAL*1/
      REAL*16 ANS(3,0:NSQUAREDSO)
      REAL*8 BUFFRES(0:3,0:NSQUAREDSO)
      COMPLEX*32 COEFS(MAXLWFSIZE,0:VERTEXMAXCOEFS-1,MAXLWFSIZE)
      COMPLEX*32 CFTOT
      COMPLEX*16 DP_CFTOT
C     
C     FUNCTIONS
C     
      LOGICAL ML5_0_IS_HEL_SELECTED
      INTEGER ML5_0_ML5SOINDEX_FOR_BORN_AMP
      INTEGER ML5_0_ML5SOINDEX_FOR_LOOP_AMP
      INTEGER ML5_0_ML5SQSOINDEX
C     
C     GLOBAL VARIABLES
C     

      INCLUDE 'mp_coupl_same_name.inc'

      INCLUDE 'MadLoopParams.inc'

      LOGICAL CHECKPHASE, HELDOUBLECHECKED
      COMMON/ML5_0_INIT/CHECKPHASE, HELDOUBLECHECKED

      INTEGER HELOFFSET
      INTEGER GOODHEL(NCOMB)
      LOGICAL GOODAMP(NSQUAREDSO,NLOOPGROUPS)
      COMMON/ML5_0_FILTERS/GOODAMP,GOODHEL,HELOFFSET

      INTEGER HELPICKED
      COMMON/ML5_0_HELCHOICE/HELPICKED

      INTEGER USERHEL
      COMMON/ML5_0_USERCHOICE/USERHEL

      INTEGER SQSO_TARGET
      COMMON/ML5_0_SOCHOICE/SQSO_TARGET

      LOGICAL UVCT_REQ_SO_DONE,MP_UVCT_REQ_SO_DONE,CT_REQ_SO_DONE
     $ ,MP_CT_REQ_SO_DONE,LOOP_REQ_SO_DONE,MP_LOOP_REQ_SO_DONE
     $ ,CTCALL_REQ_SO_DONE,FILTER_SO
      COMMON/ML5_0_SO_REQS/UVCT_REQ_SO_DONE,MP_UVCT_REQ_SO_DONE
     $ ,CT_REQ_SO_DONE,MP_CT_REQ_SO_DONE,LOOP_REQ_SO_DONE
     $ ,MP_LOOP_REQ_SO_DONE,CTCALL_REQ_SO_DONE,FILTER_SO

      TYPE(MP_ALOHA) W(NWAVEFUNCS)
      COMMON/ML5_0_MP_W/W

      TYPE(ALOHA) DPW(NWAVEFUNCS)
      COMMON/ML5_0_W/DPW

      COMPLEX*32 WL(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE,
     $ -1:NLOOPWAVEFUNCS)
      COMPLEX*32 PL(0:3,-1:NLOOPWAVEFUNCS)
      COMMON/ML5_0_MP_WL/WL,PL

      COMPLEX*16 DP_WL(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE,
     $ -1:NLOOPWAVEFUNCS)
      COMPLEX*16 DP_PL(0:3,-1:NLOOPWAVEFUNCS)
      COMMON/ML5_0_WL/DP_WL,DP_PL

      COMPLEX*32 LOOPCOEFS(0:LOOPMAXCOEFS-1,NLOOPGROUPS)
      COMMON/ML5_0_MP_LCOEFS/LOOPCOEFS

      COMPLEX*16 DP_LOOPCOEFS(0:LOOPMAXCOEFS-1,NLOOPGROUPS)
      COMMON/ML5_0_LCOEFS/DP_LOOPCOEFS

C     This flag is used to prevent the re-computation of the OpenLoop
C      coefficients when changing the CTMode for the stability test.
      LOGICAL SKIP_LOOPNUM_COEFS_CONSTRUCTION
      COMMON/ML5_0_SKIP_COEFS/SKIP_LOOPNUM_COEFS_CONSTRUCTION

      COMPLEX*32 AMPL(3,NLOOPAMPS)
      COMMON/ML5_0_MP_AMPL/AMPL

      COMPLEX*16 DP_AMPL(3,NLOOPAMPS)
      COMMON/ML5_0_AMPL/DP_AMPL

      COMPLEX*16 LOOPRES(3,NSQUAREDSO,NLOOPGROUPS)
      LOGICAL S(NSQUAREDSO,NLOOPGROUPS)
      COMMON/ML5_0_LOOPRES/LOOPRES,S

      INTEGER I_SO
      COMMON/ML5_0_I_SO/I_SO

      INTEGER CF_D(NCOLORROWS,NLOOPAMPS)
      INTEGER CF_N(NCOLORROWS,NLOOPAMPS)
      COMMON/ML5_0_CF/CF_D,CF_N

      INTEGER HELC(NEXTERNAL,NCOMB)
      COMMON/ML5_0_HELCONFIGS/HELC

      LOGICAL MP_DONE_ONCE
      COMMON/ML5_0_MP_DONE_ONCE/MP_DONE_ONCE

      INTEGER LIBINDEX
      COMMON/ML5_0_I_LIB/LIBINDEX

C     This array specify potential special requirements on the
C      helicities to
C     consider. POLARIZATIONS(0,0) is -1 if there is not such
C      requirement.
      INTEGER POLARIZATIONS(0:NEXTERNAL,0:5)
      COMMON/ML5_0_BEAM_POL/POLARIZATIONS

C     ----------
C     BEGIN CODE
C     ----------

C     Decide whether to really compute the integrand in quadruple
C      precision or to fake it and copy the double precision
C      computation in the quadruple precision variables.
      COMPUTE_INTEGRAND_IN_QP = ((MLREDUCTIONLIB(LIBINDEX)
     $ .EQ.6.AND.USEQPINTEGRANDFORNINJA) .OR. (MLREDUCTIONLIB(LIBINDEX)
     $ .EQ.1.AND.USEQPINTEGRANDFORCUTTOOLS))

C     To be on the safe side, we always update the MP params here.
C     It can be redundant as this routine can be called a couple of
C      times for the same PS point during the stability checks.
C     But it is really not time consuming and I would rather be safe.
      CALL MP_UPDATE_AS_PARAM()

      MP_DONE_ONCE = .TRUE.

C     AS A SAFETY MEASURE WE FIRST COPY HERE THE PS POINT
      DO I=1,NEXTERNAL
        DO J=0,3
          MP_P(J,I)=PS(J,I)
          P(J,I) = REAL(PS(J,I),KIND=8)
        ENDDO
      ENDDO

      DO I=0,3
        PL(I,-1)=CMPLX(ZERO,ZERO,KIND=16)
        PL(I,0)=CMPLX(ZERO,ZERO,KIND=16)
        IF (.NOT.COMPUTE_INTEGRAND_IN_QP) THEN
          DP_PL(I,-1)=DCMPLX(0.0D0,0.0D0)
          DP_PL(I,0)=DCMPLX(0.0D0,0.0D0)
        ENDIF
      ENDDO

      IF (.NOT.SKIP_LOOPNUM_COEFS_CONSTRUCTION) THEN
        DO I=1,MAXLWFSIZE
          DO J=0,LOOPMAXCOEFS-1
            DO K=1,MAXLWFSIZE
              WL(I,J,K,-1)=(ZERO,ZERO)
              DP_WL(I,J,K,-1)=(0.0D0,0.0D0)
              IF (I.EQ.K.AND.J.EQ.0) THEN
                WL(I,J,K,0)=(1.0E0_16,ZERO)
              ELSE
                WL(I,J,K,0)=(ZERO,ZERO)
              ENDIF
              IF (.NOT.COMPUTE_INTEGRAND_IN_QP) THEN
                IF (I.EQ.K.AND.J.EQ.0) THEN
                  DP_WL(I,J,K,0)=(1.0D0,0.0D0)
                ELSE
                  DP_WL(I,J,K,0)=(0.0D0,0.0D0)
                ENDIF
              ENDIF
            ENDDO
          ENDDO
        ENDDO

C       This is the chare conjugate version of the unit 4-currents in
C        the canonical cartesian basis.
C       This, for now, is only defined for 4-fermionic currents.
        WL(1,0,2,-1) = (-1.0E0_16,ZERO)
        WL(2,0,1,-1) = (1.0E0_16,ZERO)
        WL(3,0,4,-1) = (1.0E0_16,ZERO)
        WL(4,0,3,-1) = (-1.0E0_16,ZERO)
        DP_WL(1,0,2,-1) = DCMPLX(-1.0D0,0.0D0)
        DP_WL(2,0,1,-1) = DCMPLX(1.0D0,0.0D0)
        DP_WL(3,0,4,-1) = DCMPLX(1.0D0,0.0D0)
        DP_WL(4,0,3,-1) = DCMPLX(-1.0D0,0.0D0)


        DO K=1, 3
          DO I=1,NLOOPAMPS
            AMPL(K,I)=(ZERO,ZERO)
            IF (.NOT.COMPUTE_INTEGRAND_IN_QP) THEN
              DP_AMPL(K,I)=(0.0D0,0.0D0)
            ENDIF
          ENDDO
        ENDDO

      ENDIF



      DO K=1,3
        DO J=0,NSQUAREDSO
          ANSDP(K,J)=0.0D0
          ANS(K,J)=ZERO
        ENDDO
      ENDDO

      DPW_COPIED = .FALSE.
      DO H=1,NCOMB
        IF ((HELPICKED.EQ.H).OR.((HELPICKED.EQ.-1)
     $   .AND.(CHECKPHASE.OR.(.NOT.HELDOUBLECHECKED).OR.(GOODHEL(H)
     $   .GT.-HELOFFSET.AND.GOODHEL(H).NE.0)))) THEN

C         Handle the possible requirement of specific polarizations
          IF ((.NOT.CHECKPHASE)
     $     .AND.HELDOUBLECHECKED.AND.POLARIZATIONS(0,0)
     $     .EQ.0.AND.(.NOT.ML5_0_IS_HEL_SELECTED(H))) THEN
            CYCLE
          ENDIF

          DO I=1,NEXTERNAL
            NHEL(I)=HELC(I,H)
          ENDDO

          IF (COMPUTE_INTEGRAND_IN_QP) THEN
            MP_UVCT_REQ_SO_DONE=.FALSE.
            MP_CT_REQ_SO_DONE=.FALSE.
            MP_LOOP_REQ_SO_DONE=.FALSE.
          ELSE
            UVCT_REQ_SO_DONE=.FALSE.
            CT_REQ_SO_DONE=.FALSE.
            LOOP_REQ_SO_DONE=.FALSE.
          ENDIF

          IF (.NOT.CHECKPHASE.AND.HELDOUBLECHECKED.AND.HELPICKED.EQ.-1)
     $      THEN
            HEL_MULT=GOODHEL(H)
          ELSE
            HEL_MULT=1
          ENDIF

          CTCALL_REQ_SO_DONE=.FALSE.

C         The coefficient were already computed previously with
C          another CTMode, so we can skip them
          IF (SKIP_LOOPNUM_COEFS_CONSTRUCTION) THEN
            GOTO 4000
          ENDIF

          DO I=1,NLOOPGROUPS
            DO J=0,LOOPMAXCOEFS-1
              LOOPCOEFS(J,I)=(ZERO,ZERO)
              IF (.NOT.COMPUTE_INTEGRAND_IN_QP) THEN
                DP_LOOPCOEFS(J,I)=(0.0D0,0.0D0)
              ENDIF
            ENDDO
          ENDDO

          DO K=1, 3
            DO I=1,NLOOPAMPS
              AMPL(K,I)=(ZERO,ZERO)
              IF (.NOT.COMPUTE_INTEGRAND_IN_QP) THEN
                DP_AMPL(K,I)=(0.0D0,0.0D0)
              ENDIF
            ENDDO
          ENDDO

          IF (COMPUTE_INTEGRAND_IN_QP) THEN
            CALL ML5_0_MP_HELAS_CALLS_AMPB_1(MP_P,NHEL,H,IC)
            CONTINUE
          ELSE
            CALL ML5_0_HELAS_CALLS_AMPB_1(P,NHEL,H,IC)
            CONTINUE
          ENDIF

 2000     CONTINUE
          MP_CT_REQ_SO_DONE=.TRUE.

          IF (COMPUTE_INTEGRAND_IN_QP) THEN

            CONTINUE
          ELSE

            CONTINUE
          ENDIF

          IF (.NOT.COMPUTE_INTEGRAND_IN_QP) THEN
C           Copy back to the quantities computed in DP in the QP
C            containers (but only those needed)
            DO I=1,NCTAMPS
              DO K=1,3
                AMPL(K,I)=CMPLX(DP_AMPL(K,I),KIND=16)
              ENDDO
            ENDDO
            DO I=1,NWAVEFUNCS
              DO J=1,SIZE(W(I)%W)
                W(I)%W(J)=CMPLX(DPW(I)%W(J),KIND=16)
              ENDDO
              W(I)%P = DPW(I)%P
              W(I)%FLV_INDEX = DPW(I)%FLV_INDEX
            ENDDO
          ENDIF

 3000     CONTINUE
          MP_UVCT_REQ_SO_DONE=.TRUE.


          IF (COMPUTE_INTEGRAND_IN_QP) THEN

            CALL ML5_0_MP_COEF_CONSTRUCTION_1(MP_P,NHEL,H,IC)

          ELSE

            CALL ML5_0_COEF_CONSTRUCTION_1(P,NHEL,H,IC)

C           Copy back to the coefficients computed in DP in the QP
C            containers
            DO I=0,LOOPMAXCOEFS-1
              DO K=1,NLOOPGROUPS
                LOOPCOEFS(I,K)=CMPLX(DP_LOOPCOEFS(I,K),KIND=16)
              ENDDO
            ENDDO
          ENDIF

 4000     CONTINUE
          MP_LOOP_REQ_SO_DONE=.TRUE.

          IF (COMPUTE_INTEGRAND_IN_QP) THEN

C           Copy the multiple precision CT amplitudes computed to the
C            AMPL double precision array for its use later if
C            necessary (i.e. color flows for example.)
            DO I=1,NCTAMPS
              DO K=1,3
                DP_AMPL(K,I)=CMPLX(AMPL(K,I),KIND=8)
              ENDDO
            ENDDO

          ENDIF

C         Copy the qp wfs to the dp ones as they are used to setup the
C          CT calls.
C         This needs to be done once since only the momenta of these
C          WF matters.
          IF(.NOT.DPW_COPIED.AND.COMPUTE_INTEGRAND_IN_QP) THEN
            DO I=1,NWAVEFUNCS
              DO J=1,SIZE(W(I)%W)
                DPW(I)%W(J)=CMPLX(W(I)%W(J),KIND=8)
              ENDDO
              DPW(I)%P = W(I)%P
              DPW(I)%FLV_INDEX = W(I)%FLV_INDEX
            ENDDO
            DPW_COPIED=.TRUE.
          ENDIF

          DO I=1,NSQUAREDSO
            DO J=1,NLOOPGROUPS
              S(I,J)=.TRUE.
            ENDDO
          ENDDO

C         We need a dummy argument for the squared order index to
C          conform to the 
C         structure that the call to the LOOP* subroutine takes for
C          processes with Born diagrams.
          I_SO=1
          CALL ML5_0_LOOP_CT_CALLS_1(P,NHEL,H,IC)
 5000     CONTINUE
          CTCALL_REQ_SO_DONE=.TRUE.

C         Copy the loop amplitudes computed (whose final result was
C          stored in a double
C         precision variable) to the AMPL multiple precision array.
          DO I=NCTAMPS+1,NLOOPAMPS
            DO K=1,3
              AMPL(K,I)=CMPLX(DP_AMPL(K,I),KIND=16)
            ENDDO
          ENDDO

          IF (DIRECT_ME_COMPUTATION) THEN
            DO I=1,NLOOPAMPS
              DO J=1,NLOOPAMPS

                IF (COMPUTE_INTEGRAND_IN_QP) THEN

                  CFTOT=CMPLX(CF_N(I,J)/REAL(ABS(CF_D(I,J)),KIND=16)
     $             ,0.0E0_16,KIND=16)
                  IF(CF_D(I,J).LT.0) CFTOT=CFTOT*IMAG1
                  ITEMP =
     $              ML5_0_ML5SQSOINDEX(ML5_0_ML5SOINDEX_FOR_LOOP_AMP(I)
     $             ,ML5_0_ML5SOINDEX_FOR_LOOP_AMP(J))
                  TEMP2(1) = HEL_MULT*REAL(CFTOT*AMPL(1,I)
     $             *CONJG(AMPL(1,J)),KIND=16)
C                 Computing the quantities below is not strictly
C                  necessary since the result should be finite
C                 It is however a good cross-check.
                  TEMP2(2) = HEL_MULT*REAL(CFTOT*(AMPL(2,I)
     $             *CONJG(AMPL(1,J)) + AMPL(1,I)*CONJG(AMPL(2,J)))
     $             ,KIND=16)
                  TEMP2(3) = HEL_MULT*REAL(CFTOT*(AMPL(3,I)
     $             *CONJG(AMPL(1,J)) + AMPL(1,I)*CONJG(AMPL(3,J))
     $             +AMPL(2,I)*CONJG(AMPL(2,J))),KIND=16)

                ELSE

                  DP_CFTOT=CMPLX(CF_N(I,J)/REAL(ABS(CF_D(I,J)),KIND=8)
     $             ,0.0D0,KIND=8)
                  IF(CF_D(I,J).LT.0) DP_CFTOT=DP_CFTOT*DP_IMAG1
                  ITEMP =
     $              ML5_0_ML5SQSOINDEX(ML5_0_ML5SOINDEX_FOR_LOOP_AMP(I)
     $             ,ML5_0_ML5SOINDEX_FOR_LOOP_AMP(J))
                  DP_TEMP2(1) = HEL_MULT*REAL(DP_CFTOT*DP_AMPL(1,I)
     $             *DCONJG(DP_AMPL(1,J)),KIND=8)
C                 Computing the quantities below is not strictly
C                  necessary since the result should be finite
C                 It is however a good cross-check.
                  DP_TEMP2(2) = HEL_MULT*REAL(DP_CFTOT*(DP_AMPL(2,I)
     $             *DCONJG(DP_AMPL(1,J)) + DP_AMPL(1,I)
     $             *DCONJG(DP_AMPL(2,J))),KIND=8)
                  DP_TEMP2(3) = HEL_MULT*REAL(DP_CFTOT*(DP_AMPL(3,I)
     $             *DCONJG(DP_AMPL(1,J)) + DP_AMPL(1,I)
     $             *DCONJG(DP_AMPL(3,J))+DP_AMPL(2,I)*DCONJG(DP_AMPL(2
     $             ,J))),KIND=8)

                ENDIF

C               To mimic the structure of the non loop-induced
C                processes, we add here the squared counterterm
C                contribution directly the result ANS and put the loop
C                contributions in the LOOPRES array which will be
C                added to ANS later
                IF (I.LE.NCTAMPS) THEN
                  IF (.NOT.FILTER_SO.OR.SQSO_TARGET.EQ.ITEMP) THEN
                    DO K=1,3
                      IF (COMPUTE_INTEGRAND_IN_QP) THEN
                        ANS(K,ITEMP)=ANS(K,ITEMP)+TEMP2(K)
                        ANS(K,0)=ANS(K,0)+TEMP2(K)
                      ELSE
                        ANSDP(K,ITEMP)=ANSDP(K,ITEMP)+DP_TEMP2(K)
                        ANSDP(K,0)=ANSDP(K,0)+DP_TEMP2(K)
                      ENDIF
                    ENDDO
                  ENDIF
                ELSE
                  DO K=1,3
C                   This LOOPRES array entries will be added to the
C                    main result ANS(*,*) later in the loop_matrix.f
C                    file. It is in double precision however, so the
C                    cast of the temporary variable TEMP2 is necessary.
                    IF (COMPUTE_INTEGRAND_IN_QP) THEN
                      LOOPRES(K,ITEMP,I-NCTAMPS)=LOOPRES(K,ITEMP,I
     $                 -NCTAMPS)+DBLE(TEMP2(K))
                    ELSE
                      LOOPRES(K,ITEMP,I-NCTAMPS)=LOOPRES(K,ITEMP,I
     $                 -NCTAMPS)+DP_TEMP2(K)
                    ENDIF
C                   During the evaluation of the AMPL, we had stored
C                    the stability in S(1,*) so we now copy over this
C                    flag to the relevant contributing Squared orders.
                    S(ITEMP,I-NCTAMPS)=S(1,I-NCTAMPS)
                  ENDDO
                ENDIF
              ENDDO
            ENDDO

          ENDIF




C         We should compute the color flow either if it contributes to
C          the final result (i.e. not used just for the filtering), or
C          if the computation is only done from the color flows
          IF (((.NOT.DIRECT_ME_COMPUTATION)
     $     .AND.ME_COMPUTATION_FROM_JAMP)
     $     .OR.((H.EQ.USERHEL.OR.USERHEL.EQ.-1).AND.(POLARIZATIONS(0,0)
     $     .EQ.-1.OR.ML5_0_IS_HEL_SELECTED(H)))) THEN
C           The cumulative quantities must only be computed if that
C            helicity contributes according to user request (second
C            argument of the subroutine below).
            CALL ML5_0_COMPUTE_COLOR_FLOWS(HEL_MULT)
            IF(ME_COMPUTATION_FROM_JAMP) THEN
              CALL ML5_0_COMPUTE_RES_FROM_JAMP(BUFFRES,HEL_MULT)
              IF(((.NOT.DIRECT_ME_COMPUTATION)
     $         .AND.ME_COMPUTATION_FROM_JAMP)) THEN
C               If the computation from the color flow is the only
C                form of computation, we directly update the answer.
                DO K=1,3
                  DO I=0,NSQUAREDSO
                    IF (COMPUTE_INTEGRAND_IN_QP) THEN
                      ANS(K,I)=ANS(K,I)+REAL(BUFFRES(K,I),KIND=16)
                    ELSE
                      ANSDP(K,I)=ANSDP(K,I)+BUFFRES(K,I)
                    ENDIF
                  ENDDO
                ENDDO
C               In this case, we temporarily store the compute Born ME
C                in RES_FROM_JAMP(0,I), which will be used to set
C                ANS(0,I) just after the call to this subroutine in
C                loop_matrix.f
                DO I=0,NSQUAREDSO
                  RES_FROM_JAMP(0,I)=RES_FROM_JAMP(0,I)+BUFFRES(0,I)
                ENDDO
C               When setting up the loop filter, it is important to
C                set the quantitied LOOPRES.
C               Notice that you may have a more powerful filter with
C                the direct computation mode because it can filter
C                vanishing loop contributions for a particular squared
C                split order only
C               The quantity LOOPRES defined below is not physical,'
C               //' but it's ok since it is only intended for the loop
C                filtering.
C               In principle it is no longer necessary to compute the
C                quantity below once the loop filter is setup, but it
C                takes a negligible amount of time compare to the quad
C                prec computations. 
                DO J=1,NLOOPGROUPS
                  DO I=1,NSQUAREDSO
                    DO K=1,3
                      LOOPRES(K,I,J)=LOOPRES(K,I,J)+DP_AMPL(K,NCTAMPS
     $                 +J)
                    ENDDO
                  ENDDO
                ENDDO
C               The if statement below is not strictly necessary but
C                makes it clear when it is executed.
              ELSEIF(H.EQ.USERHEL.OR.USERHEL.EQ.-1) THEN
C               Make sure that that no polarization constraint filters
C                out this helicity
                IF (POLARIZATIONS(0,0).EQ.
     $           -1.OR.ML5_0_IS_HEL_SELECTED(H)) THEN
C                 If both computational method is used, then we must
C                  just update RES_FROM_JAMP
                  DO K=0,3
                    DO I=0,NSQUAREDSO
                      RES_FROM_JAMP(K,I)=RES_FROM_JAMP(K,I)+BUFFRES(K
     $                 ,I)
                    ENDDO
                  ENDDO
                ENDIF
              ENDIF
              IF (H.EQ.USERHEL.OR.USERHEL.EQ.-1) THEN
C               Make sure that that no polarization constraint filters
C                out this helicity
                IF (POLARIZATIONS(0,0).EQ.
     $           -1.OR.ML5_0_IS_HEL_SELECTED(H)) THEN
                  CALL
     $              ML5_0_COMPUTE_COLOR_FLOWS_DERIVED_QUANTITIES(HEL_MU
     $LT)
                ENDIF
              ENDIF
            ENDIF
          ENDIF

        ENDIF
      ENDDO


