          DO J = I, NCOLOR
            CF_INDEX = CF_INDEX +1
            ZTEMP = ZTEMP + CF(CF_INDEX)*JAMP(J,M)
          ENDDO
          DO N = 1, NAMPSO
            RES(SQSOINDEX(M,N)) = RES(SQSOINDEX(M,N)) + REAL(ZTEMP
     $       *DCONJG(JAMP(I,N)))
          ENDDO
        ENDDO
      ENDDO
      RES(:) = RES(:)/DENOM
      END

      SUBROUTINE GET_INTER(JAMP_1,JAMP_2, INTER)
      IMPLICIT NONE
CF2PY INTENT(OUT) :: INTER(NSQAMPSO)
CF2PY INTENT(IN) :: JAMP_1(NCOLOR,NAMPSO)
CF2PY INTENT(IN) :: JAMP_2(NCOLOR,NAMPSO)

      INTEGER NAMPSO, NSQAMPSO
      PARAMETER (NAMPSO=1, NSQAMPSO=1)
      INTEGER SQSOINDEX

      INTEGER I,J,M,N
      INTEGER NCOLOR
      PARAMETER (NCOLOR=6)
      INTEGER CF_INDEX
      INTEGER CF(NCOLOR*(NCOLOR+1)/2)
      INTEGER DENOM, IDEN
      DATA IDEN/144/
      COMMON /COLOR_MATRIX/ CF,DENOM
      COMPLEX*16 JAMP_1(NCOLOR,NAMPSO),JAMP_2(NCOLOR,NAMPSO),ZTEMP
     $ ,INTER(NSQAMPSO)
C     
C     COLOR DATA
C     

      INTER(:) = 0.D0
      DO M = 1, NAMPSO
        CF_INDEX= 0
        DO I = 1, NCOLOR
          DO J = I, NCOLOR
            CF_INDEX = CF_INDEX +1
            DO N = 1, NAMPSO
              INTER(SQSOINDEX(M,N)) =
     $            INTER(SQSOINDEX(M,N)) +
     $            CF(CF_INDEX)*(DCONJG(JAMP_2(I,N))*
     $            JAMP_1(J,M)+DCONJG(JAMP_2(J,N))*JAMP_1(I,M))
            ENDDO
          ENDDO
        ENDDO
      ENDDO
      INTER(:) = INTER(:)/(2D0*DENOM*IDEN)
      RETURN
      END

      SUBROUTINE  GET_DENSITY(P, POS, N_CHANGING, ALLOW_HEL, N_COMB,
     $  FLAVOR, ALPHAS, MU_R2, INTER_SUM)
C     P momenta
C     NHEL base of helicity that are not changing
C     POS(N_CHNGING): position of the changing helicity
C     n_changing: number of changing helicity
C     ALLOW_HEL(NCOMB, N_CHANGING): combination of helicity to
C      consider (all jamp computed)
C     INTER((NCOMB*NCOMB+1)/2i,NSQAMPSO) : all interference term (not
C      the symmetric one)
      USE MODEL_OBJECT
      IMPLICIT NONE
CF2PY INTENT(IN) :: P(0:3,6)
CF2PY INTENT(IN) :: POS(N_CHANGING)
CF2PY INTENT(IN) :: N_CHANGING
CF2PY INTENT(IN) :: ALLOW_HEL(N_CHANGING*N_COMB)
CF2PY INTENT(IN) :: N_COMB
CF2PY INTENT(IN) :: FLAVOR(6)
CF2PY INTENT(IN) :: ALPHAS
CF2PY INTENT(OUT) :: INTER_SUM(N_COMB*(N_COMB+1)/2)
C     

      INTEGER NB_NHEL
      INTEGER NAMPSO, NSQAMPSO
      PARAMETER (NB_NHEL=64)
      PARAMETER (NAMPSO=1, NSQAMPSO=1)
C     
C     ARGUMENTS
C     
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=6)
      REAL*8 P(0:3,NEXTERNAL)
      INTEGER THISNHEL(NEXTERNAL)
      INTEGER N_CHANGING, N_COMB
      INTEGER NINTER
      INTEGER POS(*)
      INTEGER ALLOW_HEL(*)
      INTEGER FLAVOR(NEXTERNAL)
      DOUBLE COMPLEX, ALLOCATABLE :: TMP_INTER(:,:)
      DOUBLE PRECISION ALPHAS, MU_R2
      DOUBLE COMPLEX INTER_SUM(*)
      INTEGER    NINITIAL
      PARAMETER (NINITIAL=2)
C     LOCAL
      INTEGER I,IHEL,IPART,JJ
      INTEGER J
      DOUBLE PRECISION PI
      DOUBLE PRECISION POLFACT
C     
C     GLOBAL
C     
      LOGICAL CHOSEN_SO_CONFIGS(NSQAMPSO)
      COMMON/CHOSEN_BORN_SQSO/CHOSEN_SO_CONFIGS
C     beam polarisation, filled from python through PY_SET_BEAMPOL.
C     Same common block and convention as the v1 MadSpin path
C     (matrix_standalone_msP_v4.inc / msF).
      DOUBLE PRECISION BEAMPOL(2)
      COMMON/TO_BEAMPOL/BEAMPOL

      INTEGER NHEL(NEXTERNAL,NB_NHEL),NTRY
C     put in common block to expose this variable to python interface
      COMMON/PROCESS_NHEL/NHEL
C     
C     include coupling definition to update the value of alphas
C     
      INCLUDE 'coupl.inc'

      NINTER = N_COMB*(N_COMB+1)/2
      ALLOCATE(TMP_INTER(NSQAMPSO, NINTER))
      TMP_INTER(:,:) = (0D0, 0D0)

      DO I = 1,  N_COMB*(N_COMB+1)/2
        INTER_SUM(I) = 0D0
      ENDDO

      IF (ALPHAS.NE.0D0) THEN
        PI = 3.141592653589793D0
        G = 2* DSQRT(ALPHAS*PI)
        CALL UPDATE_AS_PARAM()
      ENDIF
C     The NHEL table is materialized at runtime (see FILL_NHEL),
C     so it has to be filled here too: a caller reaching the
C     density matrix before any SMATRIX evaluation would
C     otherwise read a table of zeros.
      CALL FILL_NHEL()

      DO IHEL =1, NB_NHEL
        THISNHEL(:) = NHEL(:, IHEL)
        DO IPART=1,N_CHANGING
          IF(THISNHEL(POS(IPART)).NE.ALLOW_HEL(IPART)) GOTO 10  !BYPASS COMPUTATION FOR HELICITY
        ENDDO
        TMP_INTER(:,:) = 0
        CALL  GET_ALL_INTER(P, THISNHEL, POS, N_CHANGING, ALLOW_HEL,
     $    N_COMB, FLAVOR, TMP_INTER)
C       Support for polarised beam: reweight the initial-state helicity
C       sum exactly as SMATRIX_PROD does in the v1 path. Skipped unless
C       the process has two incoming legs -- the same shared library
C       also holds the 1 -> N decay matrix elements, whose leg 1 is the
C       decaying resonance and not a beam.
        POLFACT = 1D0
        IF (NINITIAL.EQ.2) THEN
          DO JJ=1,NINITIAL
C           |BEAMPOL| runs from 1 (unpolarised) to 2 (fully
C           polarised), so anything at or below 1 means "no
C           polarisation" -- including the zero-filled common
C           block of an output whose link line does not pull
C           in BLOCK DATA BEAMPOL_DEFAULT.
            IF (ABS(BEAMPOL(JJ)).LE.1D0) CYCLE
            IF (THISNHEL(JJ).EQ.INT(SIGN(1D0,BEAMPOL(JJ)))) THEN
              POLFACT = POLFACT*ABS(BEAMPOL(JJ))
            ELSE
              POLFACT = POLFACT*(2D0-ABS(BEAMPOL(JJ)))
            ENDIF
          ENDDO
        ENDIF
        DO J =1, NSQAMPSO
          IF (CHOSEN_SO_CONFIGS(J)) THEN
            DO I = 1, N_COMB*(N_COMB+1)/2
              INTER_SUM(I) = INTER_SUM(I) + POLFACT*TMP_INTER(J,I)
            ENDDO
          ENDIF
        ENDDO
 10   ENDDO
      RETURN
      DEALLOCATE(TMP_INTER)
      END



      SUBROUTINE  GET_ALL_INTER(P, NHEL, POS, N_CHANGING, ALLOW_HEL,
     $  N_COMB, FLAVOR, INTER)
C     P momenta
C     NHEL base of helicity that are not changing
C     POS(N_CHNGING): position of the changing helicity
C     n_changing: number of changing helicity
C     ALLOW_HEL(NCOMB, N_CHANGING): combination of helicity to
C      consider (all jamp computed)
C     INTER(NSO, (NCOMB*NCOMB+1)/2): all interference term (not the
C      symmetric one)
      IMPLICIT NONE
CF2PY INTENT(IN) :: P(0:3,6)
CF2PY INTENT(IN) :: NHEL(6)
CF2PY INTENT(IN) :: POS(N_CHANGING)
CF2PY INTENT(IN) :: N_CHANGING
CF2PY INTENT(IN) :: ALLOW_HEL(N_CHANGING*N_COMB)
CF2PY INTENT(IN) :: N_COMB
CF2PY INTENT(IN) :: FLAVOR(6)
CF2PY INTENT(OUT) :: INTER(NSQAMPSO,NCOMB*(NCOMB+1)/2)
C     
C     
C     ARGUMENTS
C     
      INTEGER NAMPSO, NSQAMPSO
      PARAMETER (NAMPSO=1, NSQAMPSO=1)
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=6)
      REAL*8 P(0:3,NEXTERNAL)
      INTEGER NHEL(NEXTERNAL)
      INTEGER N_CHANGING, N_COMB
      INTEGER POS(*)
      INTEGER ALLOW_HEL(*)
      INTEGER FLAVOR(NEXTERNAL)
      DOUBLE COMPLEX INTER(NSQAMPSO,*)
C     
C     Intermediate array
C     
      INTEGER    NGRAPHS
      PARAMETER (NGRAPHS=42)
      INTEGER    NCOLOR
      PARAMETER (NCOLOR=6)
      INTEGER IC(NEXTERNAL)

      DOUBLE COMPLEX AMP(NGRAPHS)
      DOUBLE COMPLEX, ALLOCATABLE:: JAMP(:,:,:)
      INTEGER, SAVE :: S_NCOMB = -1
C     
C     LOCAL
C     
      INTEGER I,J,SOL,N
      INTEGER FLAV_IDX
      INTEGER GET_FLAVOR_INDEX
      INTEGER BROKEN_SYM
      DOUBLE PRECISION RESCALE

C     ----------
C     BEGIN CODE
C     ----------
      IF (ALLOCATED(JAMP).AND. N_COMB.NE.S_NCOMB)THEN
        DEALLOCATE(JAMP)
      ENDIF
      IF (.NOT.ALLOCATED(JAMP))THEN
        ALLOCATE(JAMP(NCOLOR, NAMPSO, N_COMB))
        S_NCOMB=N_COMB
      ENDIF
      IC(:)=1
      FLAV_IDX = GET_FLAVOR_INDEX(FLAVOR)
      DO I = 1, N_COMB
        DO N = 1, N_CHANGING
          NHEL(POS(N)) = ALLOW_HEL((I-1)*N_CHANGING+N)
        ENDDO
        CALL GET_AMP(P,NHEL,IC,FLAV_IDX,AMP)
        CALL GET_JAMP(AMP,JAMP(1,1,I))
      ENDDO

C     GET_INTER only sees JAMPs, so it normalises with the bare
C     static IDEN and cannot apply any flavor dependent factor.
C     SMATRIX does ANS/IDEN*BROKEN_SYM(FLAVOR); the density
C     matrix must use the same normalisation or the sum of its
C     diagonal stops matching SMATRIX.
      RESCALE = DBLE(BROKEN_SYM(FLAVOR))
      SOL = 0
      DO I = 1, N_COMB
        DO J= I, N_COMB
          SOL = SOL +1
          CALL GET_INTER(JAMP(1,1,I), JAMP(1,1,J), INTER(1,SOL))
          INTER(:,SOL) = INTER(:,SOL) * RESCALE
        ENDDO
      ENDDO


      RETURN
      END


      SUBROUTINE GET_ALL_INTER_SUMSO(P, NHEL, POS,
     & N_CHANGING, ALLOW_HEL, N_COMB, FLAVOR, INTER)
C     GET_ALL_INTER summed over the chosen squared split
C     orders, as GET_DENSITY sums them: one INTER per pair of
C     helicity combinations, the shape the f2py dispatch
C     (py_get_all_inter) allocates.
      IMPLICIT NONE
      INTEGER NSQAMPSO
      PARAMETER (NSQAMPSO=1)
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=6)
      REAL*8 P(0:3,NEXTERNAL)
      INTEGER NHEL(NEXTERNAL)
      INTEGER N_CHANGING, N_COMB
      INTEGER POS(*)
      INTEGER ALLOW_HEL(*)
      INTEGER FLAVOR(NEXTERNAL)
      DOUBLE COMPLEX INTER(*)
      INTEGER I, J, NINTER
      DOUBLE COMPLEX, ALLOCATABLE :: TMP_INTER(:,:)
      LOGICAL CHOSEN_SO_CONFIGS(NSQAMPSO)
      COMMON/CHOSEN_BORN_SQSO/CHOSEN_SO_CONFIGS

      NINTER = N_COMB*(N_COMB+1)/2
      ALLOCATE(TMP_INTER(NSQAMPSO, NINTER))
      TMP_INTER(:,:) = (0D0, 0D0)
      CALL GET_ALL_INTER(P, NHEL, POS, N_CHANGING,
     & ALLOW_HEL, N_COMB, FLAVOR, TMP_INTER)
      DO I = 1, NINTER
        INTER(I) = (0D0, 0D0)
        DO J = 1, NSQAMPSO
          IF (CHOSEN_SO_CONFIGS(J)) INTER(I) = INTER(I) + TMP_INTER(J
     $     ,I)
        ENDDO
      ENDDO
      DEALLOCATE(TMP_INTER)
      RETURN
      END




