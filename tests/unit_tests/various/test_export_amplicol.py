class TestGenerationInProcess(unittest.TestCase):
    """The artifacts are generated by amplicol_generation in this process."""

    def run_export(self, generate, **kwargs):
        tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, tmp)
        os.makedirs(os.path.join(tmp, 'SubProcesses'))
        with mock.patch.object(export_amplicol, 'check_pyamplicol',
                               return_value={'version': '0', 'source_hash': 'h'}), \
                mock.patch.object(export_amplicol, 'model_job', return_value={}), \
                mock.patch.object(export_amplicol, 'clustering_model', return_value={}), \
                mock.patch('madgraph.iolibs.amplicol_generation.generate', generate):
            return export_amplicol.export_amplicol_processes(tmp, [], None, **kwargs)

    def test_the_job_is_passed_to_generate(self):
        jobs = []
        entries = self.run_export(lambda job: jobs.append(job) or [])
        self.assertEqual(entries, [])
        self.assertEqual(jobs, [{'model': {}, 'processes': [], 'flavor_unions': True}])

    def test_flavor_unions_can_be_turned_off(self):
        jobs = []
        self.run_export(lambda job: jobs.append(job) or [], flavor_unions=False)
        self.assertFalse(jobs[0]['flavor_unions'])

    def test_flavor_union_crossing_is_in_the_job_only_when_set(self):
        jobs = []
        self.run_export(lambda job: jobs.append(job) or [], flavor_union_crossing=True)
        self.assertEqual(jobs, [{'model': {}, 'processes': [], 'flavor_unions': True,
                                 'flavor_union_crossing': True}])

    def test_selector_only_is_in_the_job_only_when_set(self):
        jobs = []
        self.run_export(lambda job: jobs.append(job) or [], selector_only_full_colour=True)
        self.assertEqual(jobs, [{'model': {}, 'processes': [], 'flavor_unions': True,
                                 'selector_only_full_colour': True}])

    def test_selector_only_sets_the_generation_option(self):
        from madgraph.iolibs import amplicol_generation
        configs = []
        config_module = mock.Mock(resolve_config=lambda value: configs.append(value) or value)
        pyamplicol = mock.Mock()
        process = {'multiparticles': {}, 'orders': {'QED': 0}, 'expression': 'p p > j j'}
        with mock.patch.dict(sys.modules, {'pyamplicol': pyamplicol,
                                           'pyamplicol.config': config_module}):
            amplicol_generation.generate_artifact(pyamplicol, '/tmp/a', 'full', process, None)
            amplicol_generation.generate_artifact(pyamplicol, '/tmp/a', 'full', process, None,
                                                  selector_only_full_colour=True)
        self.assertNotIn('selector_only_full_colour', configs[0]['generation'])
        self.assertTrue(configs[1]['generation']['selector_only_full_colour'])
        self.assertEqual(configs[1]['generation']['relation_discovery'], {'mode': 'off'})

    def test_flavor_union_crossing_needs_unions(self):
        jobs = []
        self.run_export(lambda job: jobs.append(job) or [], flavor_unions=False,
                        flavor_union_crossing=True)
        self.assertEqual(jobs, [{'model': {}, 'processes': [], 'flavor_unions': False}])

    def test_flavor_union_crossing_sets_the_process_option(self):
        from madgraph.iolibs import amplicol_generation
        configs = []
        config_module = mock.Mock(resolve_config=lambda value: configs.append(value) or value)
        pyamplicol = mock.Mock()
        process = {'multiparticles': {}, 'orders': {'QED': 0}, 'expression': 'p p > j j'}
        with mock.patch.dict(sys.modules, {'pyamplicol': pyamplicol,
                                           'pyamplicol.config': config_module}):
            amplicol_generation.generate_artifact(pyamplicol, '/tmp/a', 'lc', process, None)
            amplicol_generation.generate_artifact(pyamplicol, '/tmp/a', 'lc', process, None,
                                                  flavor_union_crossing=True)
        self.assertNotIn('flavor_union_crossing', configs[0]['process'])
        self.assertTrue(configs[1]['process']['flavor_union_crossing'])
        self.assertTrue(configs[1]['process']['flavor_unions'])

    def test_flavor_unions_apply_to_both_colour_artifacts(self):
        from madgraph.iolibs import amplicol_generation
        configs = []
        config_module = mock.Mock(resolve_config=lambda value: configs.append(value) or value)
        pyamplicol = mock.Mock()
        process = {'multiparticles': {}, 'orders': {'QED': 0}, 'expression': 'p p > j j'}
        with mock.patch.dict(sys.modules, {'pyamplicol': pyamplicol,
                                           'pyamplicol.config': config_module}):
            for accuracy, unions in (('lc', False), ('lc', True), ('full', False),
                                     ('full', True)):
                amplicol_generation.generate_artifact(
                    pyamplicol, '/tmp/a', accuracy, process, None, flavor_unions=unions)
        self.assertEqual([c['process'].get('flavor_unions', False) for c in configs],
                         [False, True, False, True])
        self.assertTrue(all(c['process']['flavor_blind_strict'] for c in configs))

    def test_failure_raises(self):
        def fail(job):
            raise RuntimeError('boom')
        with self.assertRaisesRegex(madgraph.InvalidCmd, 'boom'):
            self.run_export(fail)

    def test_sys_path_is_restored(self):
        before = list(sys.path)

        def change(job):
            sys.path.insert(0, '/pyamplicol/install')
            return []
        self.run_export(change)
        self.assertEqual(sys.path, before)


class TestConcurrentArtifacts(unittest.TestCase):
    """With a license the full-colour artifact is generated in a child process
    while this one generates the leading-colour one."""

    def run_generate(self, licensed, unions=True, crossing=None, selector=None,
                     selectors=None):
        from madgraph.iolibs import amplicol_generation
        calls = []
        licensing = mock.Mock(_cpu_budget=lambda: 5)
        licensing.detect_symbolica_license.return_value = mock.Mock(licensed=licensed)
        pyamplicol = mock.Mock(licensing=licensing, __file__='pyamplicol')
        reweight = mock.Mock()
        reweight.write_reweight_provider.side_effect = lambda *args, **kwargs: (
            calls.append(('reweight',)) or ['p0'])
        children = []

        class Child(object):
            def __init__(self, artifact, accuracy, process, model, workers,
                         flavor_unions=False, flavor_union_crossing=None,
                         selector_only_full_colour=None):
                children.append(self)
                if selectors is not None:
                    selectors.append((accuracy, selector_only_full_colour))
                calls.append(('child', os.path.basename(artifact), workers, flavor_unions,
                              flavor_union_crossing))

            def wait(self):
                calls.append(('wait',))

        modules = {'pyamplicol': pyamplicol, 'pyamplicol.licensing': licensing,
                   'pyamplicol.artifacts': mock.Mock(umami_reweight=reweight),
                   'pyamplicol.artifacts.umami_reweight': reweight}
        job = {'model': {'cache': '/m'}, 'processes': [{'path': '/a'}],
               'flavor_unions': unions}
        if crossing is not None:
            job['flavor_union_crossing'] = crossing
        if selector is not None:
            job['selector_only_full_colour'] = selector

        def generate_artifact(p, artifact, accuracy, *args, **kwargs):
            if selectors is not None:
                selectors.append((accuracy, kwargs.get('selector_only_full_colour')))
            calls.append((os.path.basename(artifact), kwargs.get('workers'),
                          kwargs.get('flavor_unions'), kwargs.get('flavor_union_crossing')))
        with mock.patch.dict(sys.modules, modules), \
                mock.patch.object(amplicol_generation, 'model_source'), \
                mock.patch.object(amplicol_generation, 'ArtifactProcess', Child), \
                mock.patch.object(amplicol_generation, 'generate_artifact',
                                  generate_artifact):
            self.assertEqual(amplicol_generation.generate(job), [['p0']])
        return calls

    def test_full_colour_in_a_child_process(self):
        self.assertEqual(self.run_generate(True), [
            ('child', 'full', 2, True, False), ('lc', 3, True, False), ('wait',),
            ('reweight',)])

    def test_restricted_mode_generates_one_artifact_at_a_time(self):
        self.assertEqual(self.run_generate(False),
                         [('lc', None, True, False), ('full', None, True, False),
                          ('reweight',)])

    def test_unions_off_reach_both_artifacts(self):
        self.assertEqual(self.run_generate(True, unions=False), [
            ('child', 'full', 2, False, False), ('lc', 3, False, False), ('wait',),
            ('reweight',)])

    def test_crossing_reaches_only_the_leading_colour_artifact(self):
        # full colour keeps its side-aware unions on both paths
        self.assertEqual(self.run_generate(True, crossing=True), [
            ('child', 'full', 2, True, False), ('lc', 3, True, True), ('wait',),
            ('reweight',)])
        self.assertEqual(self.run_generate(False, crossing=True),
                         [('lc', None, True, True), ('full', None, True, False),
                          ('reweight',)])

    def test_selector_only_reaches_only_the_full_colour_artifact(self):
        for licensed in (True, False):
            selectors = []
            self.run_generate(licensed, selectors=selectors)
            self.assertEqual(sorted(selectors), [('full', False), ('lc', False)])
            selectors = []
            self.run_generate(licensed, selector=True, selectors=selectors)
            self.assertEqual(sorted(selectors), [('full', True), ('lc', False)])

    def test_generate_child_passes_selector_only(self):
        from madgraph.iolibs import amplicol_generation
        calls, jobs = [], []
        with mock.patch('subprocess.Popen',
                        lambda args, **kwargs: jobs.append(json.loads(args[-1]))):
            amplicol_generation.ArtifactProcess('/a/full', 'full', {}, '/m', 2).log.close()
            amplicol_generation.ArtifactProcess('/a/full', 'full', {}, '/m', 2,
                                                selector_only_full_colour=True).log.close()
        self.assertFalse(jobs[0]['selector_only_full_colour'])
        self.assertTrue(jobs[1]['selector_only_full_colour'])
        with mock.patch.dict(sys.modules, {'pyamplicol': mock.Mock()}), \
                mock.patch.object(amplicol_generation, 'generate_artifact',
                                  lambda *args, **kwargs: calls.append(kwargs)):
            for job in jobs:
                amplicol_generation.generate_child(job)
        self.assertEqual(calls, [
            {'workers': 2, 'flavor_unions': True, 'flavor_union_crossing': False},
            {'workers': 2, 'flavor_unions': True, 'flavor_union_crossing': False,
             'selector_only_full_colour': True}])

    def test_generate_child_passes_flavor_unions(self):
        from madgraph.iolibs import amplicol_generation
        calls = []
        with mock.patch.dict(sys.modules, {'pyamplicol': mock.Mock()}), \
                mock.patch.object(amplicol_generation, 'generate_artifact',
                                  lambda *args, **kwargs: calls.append(kwargs)):
            amplicol_generation.generate_child({
                'artifact': '/a/full', 'accuracy': 'full', 'process': {},
                'model': '/m', 'workers': 2, 'flavor_unions': True})
        self.assertEqual(calls, [{'workers': 2, 'flavor_unions': True,
                                  'flavor_union_crossing': False}])

    def test_generate_child_passes_flavor_union_crossing(self):
        from madgraph.iolibs import amplicol_generation
        calls, jobs = [], []
        with mock.patch('subprocess.Popen',
                        lambda args, **kwargs: jobs.append(json.loads(args[-1]))):
            amplicol_generation.ArtifactProcess('/a/lc', 'lc', {}, '/m', 2,
                                                flavor_union_crossing=True).log.close()
        self.assertTrue(jobs[0]['flavor_union_crossing'])
        with mock.patch.dict(sys.modules, {'pyamplicol': mock.Mock()}), \
                mock.patch.object(amplicol_generation, 'generate_artifact',
                                  lambda *args, **kwargs: calls.append(kwargs)):
            amplicol_generation.generate_child(jobs[0])
        self.assertEqual(calls, [{'workers': 2, 'flavor_unions': True,
                                  'flavor_union_crossing': True}])

    def test_flavor_unions_default_on_without_the_argument(self):
        from madgraph.iolibs import amplicol_generation
        configs, jobs = [], []
        config_module = mock.Mock(resolve_config=lambda value: configs.append(value) or value)
        process = {'multiparticles': {}, 'orders': {'QED': 0}, 'expression': 'p p > j j'}
        with mock.patch.dict(sys.modules, {'pyamplicol': mock.Mock(),
                                           'pyamplicol.config': config_module}):
            amplicol_generation.generate_artifact(mock.Mock(), '/tmp/a', 'lc', process, None)
        with mock.patch('subprocess.Popen',
                        lambda args, **kwargs: jobs.append(json.loads(args[-1]))):
            amplicol_generation.ArtifactProcess('/a/full', 'full', {}, '/m', 1).log.close()
        self.assertTrue(configs[0]['process']['flavor_unions'])
        self.assertNotIn('flavor_union_crossing', configs[0]['process'])
        self.assertTrue(jobs[0]['flavor_unions'])
        self.assertFalse(jobs[0]['flavor_union_crossing'])

    def test_a_failing_child_raises_with_its_output(self):
        from madgraph.iolibs import amplicol_generation
        with mock.patch.object(amplicol_generation, '_CHILD',
                               'import sys; print("boom"); sys.exit(3)'):
            child = amplicol_generation.ArtifactProcess('/a/full', 'full', {}, '/m', 1)
            with self.assertRaisesRegex(RuntimeError, '(?s)exit code 3.*boom'):
                child.wait()


class TestExporterOptions(unittest.TestCase):
    """The MG options amplicol_flavor_unions/_crossing and
    amplicol_selector_only_full_colour as ProcessExporterMG7 passes them to
    export_amplicol_processes."""

    def exported(self, options):
        import madgraph.iolibs.export_cpp as export_cpp
        exporter = object.__new__(export_cpp.ProcessExporterMG7)
        cmd = mock.Mock(_curr_proc_defs=None, _curr_amplicol_defs=['p p > j j'],
                        _curr_amps=[], _curr_model=None, _multiparticles={},
                        use_rawinput=False, options=options)
        exporter.pass_information_from_cmd(cmd)
        exporter.dir_path, exporter.process_info = '/tmp/x', []
        calls = []
        with mock.patch.object(export_amplicol, 'export_amplicol_processes',
                               lambda *args, **kwargs: calls.append(kwargs) or []):
            exporter.export_amplicol()
        return calls[0]

    def test_crossing_is_on_by_default(self):
        import madgraph.interface.madgraph_interface as interface
        defaults = dict(interface.MadGraphCmd.options_madgraph)
        self.assertIs(defaults['amplicol_flavor_union_crossing'], True)
        for options in ({}, defaults):
            kwargs = self.exported(options)
            self.assertTrue(kwargs['flavor_unions'])
            self.assertTrue(kwargs['flavor_union_crossing'])

    def test_selector_only_is_off_by_default(self):
        import madgraph.interface.madgraph_interface as interface
        defaults = dict(interface.MadGraphCmd.options_madgraph)
        self.assertIs(defaults['amplicol_selector_only_full_colour'], False)
        for options in ({}, defaults):
            self.assertFalse(self.exported(options)['selector_only_full_colour'])

    def test_selector_only_follows_the_option(self):
        kwargs = self.exported({'amplicol_selector_only_full_colour': True})
        self.assertTrue(kwargs['selector_only_full_colour'])
        self.assertTrue(kwargs['flavor_union_crossing'])

    def test_crossing_follows_the_option(self):
        kwargs = self.exported({'amplicol_flavor_union_crossing': False})
        self.assertFalse(kwargs['flavor_union_crossing'])


class TestCheckPyamplicol(unittest.TestCase):

    def test_stale_install_is_an_error(self):
        from madgraph.mg7 import bootstrap
        with mock.patch.object(bootstrap, 'ensure_pyamplicol'), \
                mock.patch.object(bootstrap, 'check_pyamplicol_source_hash',
                                  side_effect=RuntimeError('mismatch')):
            with self.assertRaisesRegex(madgraph.InvalidCmd, 'mismatch'):
                export_amplicol.check_pyamplicol()

    def test_check_script_rejects_another_pyamplicol(self):
        tmp = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, tmp)
        export_amplicol.write_rusticol_config(
            tmp, {'version': '0.0.0', 'source_hash': 'stale'})
        result = subprocess.run([os.path.join(tmp, 'check-pyamplicol')],
                                capture_output=True, text=True)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('generated with pyamplicol 0.0.0', result.stderr)


class FakeModel(dict):
    """The attributes of a restricted MG model that model_job reads."""

    def __init__(self, path, name):
        super().__init__(name=name, version_tag=path + '##0')

    def get(self, key):
        import madgraph.core.base_objects as base_objects
        if key in ('modelpath', 'restrict_name'):
            return base_objects.Model.get(self, key)
        return self[key]


