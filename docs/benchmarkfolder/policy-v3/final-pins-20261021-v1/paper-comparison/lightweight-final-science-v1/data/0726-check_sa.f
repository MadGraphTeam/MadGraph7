      PROGRAM DP_STABILITY_DRIVER
      USE, INTRINSIC :: IEEE_ARITHMETIC
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      INTEGER NEXTERNAL
      PARAMETER(NEXTERNAL=5)
      INCLUDE 'coupl.inc'
      INCLUDE 'MadLoopParams.inc'
      INTEGER NDIM,NSO,NP,I,J,K,T,MODE,HEL,EXPECTED,IOS,WARM
      INTEGER HCODE,TCODE,UCODE,CODE
      REAL*8,ALLOCATABLE :: POINTS(:,:,:),ANS(:,:),ACC(:)
      REAL*8 P(0:3,NEXTERNAL),TOTAL(0:3),MUPOINT,ELAPSED
      INTEGER*8 COUNTS(18),CLOCK0,CLOCK1,RATE
      TYPE(IEEE_ROUND_TYPE) ROUNDING
      COMMON/ML5_0_DPSTAB_COUNTS/COUNTS
      REAL*8 INTERNAL_ACC(0:1)
      COMMON/ML5_0_ACC/INTERNAL_ACC,HCODE,TCODE,UCODE
      LOGICAL FPE_DP,FPE_QP,CHECKPHASE,HELDOUBLECHECKED,FLAG
      COMMON/ML5_0_FPE_IN_REDUCTION/FPE_DP,FPE_QP
      COMMON/ML5_0_INIT/CHECKPHASE,HELDOUBLECHECKED
      LOGICAL NRS_RETRY_MODE,NRS_RETRY_USED
      COMMON/ML5_0_NRS_RETRY_FLAGS/NRS_RETRY_MODE,NRS_RETRY_USED
      CHARACTER*1024 ARG
      CALL GET_COMMAND_ARGUMENT(1,ARG)
      OPEN(73,FILE=TRIM(ARG),STATUS='OLD')
      READ(73,*) NP
      IF(NP.LE.0) STOP 1
      ALLOCATE(POINTS(0:3,NEXTERNAL,NP))
      DO K=1,NP
        DO I=1,NEXTERNAL
          READ(73,*) POINTS(:,I,K)
        ENDDO
      ENDDO
      CLOSE(73)
      CALL GET_COMMAND_ARGUMENT(2,ARG)
      READ(ARG,*) EXPECTED
      CALL GET_COMMAND_ARGUMENT(3,ARG)
      READ(ARG,*) HEL
      CALL GET_COMMAND_ARGUMENT(4,ARG)
      OPEN(74,FILE=TRIM(ARG),STATUS='NEW')
      CALL SETPARA('param_card.dat')
      CALL ML5_0_GET_ANSWER_DIMENSION(NDIM)
      CALL ML5_0_GET_NSQSO_LOOP(NSO)
      IF(NSO.NE.1) STOP 2
      ALLOCATE(ANS(0:3,0:NDIM),ACC(0:NSO))
      CALL ML5_0_FORCE_STABILITY_CHECK(.FALSE.)
      CALL IEEE_GET_ROUNDING_MODE(ROUNDING)
      WRITE(74,*) 'DPSD_HEADER',1,NP,NDIM,NSO,HEL,EXPECTED,
     $ MERGE(1,0,ROUNDING.EQ.IEEE_NEAREST)
      FLUSH(74)
      IF(ROUNDING.NE.IEEE_NEAREST) STOP 10
C     Initialization uses forced DP too. It is outside the observations.
C DPSTAB_CUSTODY_BEGIN
      CALL ML5_0_DPSTAB_WARM_RESET()
C DPSTAB_CUSTODY_END
      WARM=0
      CALL SYSTEM_CLOCK(CLOCK0,RATE)
      DO K=1,1000+NP
        P=POINTS(:,:,1+MOD(K-1,NP))
        TOTAL=P(:,1)+P(:,2)
        MU_R=SQRT(ABS(TOTAL(0)**2-SUM(TOTAL(1:3)**2)))
        CALL UPDATE_AS_PARAM()
        COUNTS=0
        FPE_DP=.FALSE.
        FPE_QP=.FALSE.
        NRS_RETRY_MODE=.FALSE.
        NRS_RETRY_USED=.FALSE.
        CALL ML5_0_SLOOPMATRIXHEL(P,HEL,ANS)
C DPSTAB_CUSTODY_BEGIN
        CALL ML5_0_DPSTAB_WARM_CAPTURE(COUNTS,
     $    FPE_DP,FPE_QP,NRS_RETRY_MODE,NRS_RETRY_USED)
C DPSTAB_CUSTODY_END
        IF(.NOT.CHECKPHASE.AND.HELDOUBLECHECKED) THEN
          WARM=WARM+1
        ELSE
          WARM=0
        ENDIF
        IF(WARM.GE.NP) EXIT
      ENDDO
      IF(WARM.LT.NP) STOP 3
      IF(MLREDUCTIONLIB(1).NE.EXPECTED) STOP 4
      IF(MLREDUCTIONLIB(2).NE.0) STOP 5
      IF(CTMODERUN.NE.1.OR.CTMODEINIT.NE.1) STOP 6
      IF(.NOT.COLLIERCOMPUTEUVPOLES) STOP 7
      IF(.NOT.COLLIERCOMPUTEIRPOLES) STOP 8
      IF(COLLIERGLOBALCACHE.NE.0) STOP 9
      CALL SYSTEM_CLOCK(CLOCK1)
      WRITE(74,*) 'WARM',K,DBLE(CLOCK1-CLOCK0)/DBLE(RATE)
      FLUSH(74)
C DPSTAB_CUSTODY_BEGIN
      CALL ML5_0_DPSTAB_WARM_WRITE()
      CALL ML5_0_DPSTAB_CUSTODY_CHECKPOINT(1)
C DPSTAB_CUSTODY_END
      CALL SYSTEM_CLOCK(CLOCK0)
      DO K=1,NP
        DO T=1,3
          P=POINTS(:,:,K)
          MODE=1
          IF(T.EQ.2) MODE=2
          IF(T.EQ.3) THEN
            DO I=1,NEXTERNAL
              P(1,I)=-POINTS(2,I,K)
              P(2,I)= POINTS(1,I,K)
            ENDDO
          ENDIF
          CTMODERUN=MODE
          COUNTS=0
          FPE_DP=.FALSE.
          FPE_QP=.FALSE.
          NRS_RETRY_MODE=.FALSE.
          NRS_RETRY_USED=.FALSE.
          CALL IEEE_SET_FLAG(IEEE_INVALID,.FALSE.)
          CALL IEEE_SET_FLAG(IEEE_DIVIDE_BY_ZERO,.FALSE.)
          CALL IEEE_SET_FLAG(IEEE_OVERFLOW,.FALSE.)
          ANS=IEEE_VALUE(0D0,IEEE_QUIET_NAN)
          WRITE(74,*) 'BEGIN',K,T
          FLUSH(74)
          TOTAL=P(:,1)+P(:,2)
          MU_R=SQRT(ABS(TOTAL(0)**2-SUM(TOTAL(1:3)**2)))
          CALL UPDATE_AS_PARAM()
          CALL ML5_0_CLEAR_CACHES()
          CALL ML5_0_SLOOPMATRIXHEL(P,HEL,ANS)
          CODE=100*HCODE+10*TCODE+UCODE
          CALL IEEE_GET_ROUNDING_MODE(ROUNDING)
          CALL IEEE_GET_FLAG(IEEE_INVALID,FLAG)
          COUNTS(16)=MERGE(1,0,FLAG)
          CALL IEEE_GET_FLAG(IEEE_DIVIDE_BY_ZERO,FLAG)
          COUNTS(17)=MERGE(1,0,FLAG)
          CALL IEEE_GET_FLAG(IEEE_OVERFLOW,FLAG)
          COUNTS(18)=MERGE(1,0,FLAG)
          WRITE(74,*) 'OBS',K,T,MODE,CODE,
     $      MERGE(1,0,FPE_DP),MERGE(1,0,FPE_QP),
     $      MERGE(1,0,ROUNDING.EQ.IEEE_NEAREST),COUNTS
          DO J=0,NSO
            WRITE(74,'(A,3I8,5ES26.17E3)') 'ROW',K,T,J,
     $        ANS(:,J),INTERNAL_ACC(J)
          ENDDO
          WRITE(74,*) 'ENDOBS',K,T
          FLUSH(74)
        ENDDO
      ENDDO
      CALL SYSTEM_CLOCK(CLOCK1)
      ELAPSED=DBLE(CLOCK1-CLOCK0)/DBLE(RATE)
      CALL ML5_0_EXIT_MADLOOP()
C DPSTAB_CUSTODY_BEGIN
      CALL ML5_0_DPSTAB_CUSTODY_CHECKPOINT(2)
C DPSTAB_CUSTODY_END
      WRITE(74,*) 'DONE',3*NP,ELAPSED
      CLOSE(74)
      END

C     Observer only: it never writes STABLE, RES, LIB, or MODE.
      SUBROUTINE ML5_0_DPSTAB_CAPTURE(STABLE,RES,LIB,MODE)
      USE, INTRINSIC :: IEEE_ARITHMETIC
      IMPLICIT NONE
      LOGICAL STABLE,BAD,FPE_DP,FPE_QP
      LOGICAL NRS_RETRY_MODE,NRS_RETRY_USED
      COMPLEX*16 RES(3)
      INTEGER LIB,MODE,I
      INTEGER*8 COUNTS(18)
      COMMON/ML5_0_DPSTAB_COUNTS/COUNTS
      COMMON/ML5_0_FPE_IN_REDUCTION/FPE_DP,FPE_QP
      COMMON/ML5_0_NRS_RETRY_FLAGS/NRS_RETRY_MODE,NRS_RETRY_USED
      COUNTS(1)=COUNTS(1)+1
      IF(.NOT.STABLE) COUNTS(2)=COUNTS(2)+1
      BAD=.FALSE.
      DO I=1,3
        BAD=BAD.OR..NOT.IEEE_IS_FINITE(DBLE(RES(I)))
        BAD=BAD.OR..NOT.IEEE_IS_FINITE(AIMAG(RES(I)))
      ENDDO
      IF(BAD) COUNTS(3)=COUNTS(3)+1
      IF(MODE.GE.4) COUNTS(4)=COUNTS(4)+1
      IF(LIB.GE.1.AND.LIB.LE.8) COUNTS(4+LIB)=
     $  COUNTS(4+LIB)+1
      IF(FPE_DP) COUNTS(13)=COUNTS(13)+1
      IF(FPE_QP) COUNTS(14)=COUNTS(14)+1
      IF(LIB.EQ.8.AND.NRS_RETRY_MODE) COUNTS(15)=COUNTS(15)+1
      END
C DPSTAB_CUSTODY_BEGIN

      SUBROUTINE ML5_0_DPSTAB_CUSTODY_CHECKPOINT(PHASE)
      USE, INTRINSIC :: ISO_C_BINDING, ONLY: C_INT
      IMPLICIT NONE
      INTEGER PHASE
      INTERFACE
        SUBROUTINE DPSTAB_CUSTODY_C(PHASE) BIND(C,
     $   NAME='dpstab_custody_checkpoint')
          IMPORT C_INT
          INTEGER(C_INT), VALUE :: PHASE
        END SUBROUTINE
      END INTERFACE
      CALL DPSTAB_CUSTODY_C(INT(PHASE,C_INT))
      END

      SUBROUTINE ML5_0_DPSTAB_WARM_RESET()
      IMPLICIT NONE
      INTEGER*8 WARM_COUNTS(20)
      COMMON/ML5_0_DPSTAB_WARM_STATE/WARM_COUNTS
      SAVE /ML5_0_DPSTAB_WARM_STATE/
      WARM_COUNTS=0
      END

      SUBROUTINE ML5_0_DPSTAB_WARM_CAPTURE(COUNTS,
     $ FPE_DP,FPE_QP,RETRY_MODE,RETRY_USED)
      IMPLICIT NONE
      INTEGER*8, INTENT(IN) :: COUNTS(18)
      LOGICAL, INTENT(IN) :: FPE_DP,FPE_QP
      LOGICAL, INTENT(IN) :: RETRY_MODE,RETRY_USED
      INTEGER*8 WARM_COUNTS(20)
      COMMON/ML5_0_DPSTAB_WARM_STATE/WARM_COUNTS
      SAVE /ML5_0_DPSTAB_WARM_STATE/
      WARM_COUNTS(1)=WARM_COUNTS(1)+1
      WARM_COUNTS(2:16)=WARM_COUNTS(2:16)+COUNTS(1:15)
      WARM_COUNTS(17)=WARM_COUNTS(17)+MERGE(1,0,FPE_DP)
      WARM_COUNTS(18)=WARM_COUNTS(18)+MERGE(1,0,FPE_QP)
      WARM_COUNTS(19)=WARM_COUNTS(19)+MERGE(1,0,RETRY_MODE)
      WARM_COUNTS(20)=WARM_COUNTS(20)+MERGE(1,0,RETRY_USED)
      END

      SUBROUTINE ML5_0_DPSTAB_WARM_WRITE()
      IMPLICIT NONE
      INTEGER*8 WARM_COUNTS(20)
      COMMON/ML5_0_DPSTAB_WARM_STATE/WARM_COUNTS
      SAVE /ML5_0_DPSTAB_WARM_STATE/
      WRITE(74,'(A,20(1X,I0))') 'WARMDIAG',WARM_COUNTS
      FLUSH(74)
      END
C DPSTAB_CUSTODY_END
