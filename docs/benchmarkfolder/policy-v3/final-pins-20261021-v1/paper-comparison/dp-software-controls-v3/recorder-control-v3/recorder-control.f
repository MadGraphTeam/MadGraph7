      PROGRAM RECORDER_CONTROL
      USE, INTRINSIC :: IEEE_ARITHMETIC
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      INTEGER*8 COUNTS(18)
      COMMON/DPT_DPSTAB_COUNTS/COUNTS
      COMPLEX*16 RES(3),SAVED(3)
      LOGICAL STABLE,FPE_DP,FPE_QP,FLAG
      COMMON/DPT_FPE_IN_REDUCTION/FPE_DP,FPE_QP
      LOGICAL NRS_RETRY_MODE,NRS_RETRY_USED
      COMMON/DPT_NRS_RETRY_FLAGS/NRS_RETRY_MODE,NRS_RETRY_USED
      INTEGER LIB,I
      DO I=1,4
        LIB=1
        IF(I.EQ.2) LIB=6
        IF(I.EQ.3) LIB=7
        IF(I.EQ.4) LIB=8
        COUNTS=0
        FPE_DP=.FALSE.
        FPE_QP=.FALSE.
        NRS_RETRY_MODE=.FALSE.
        NRS_RETRY_USED=.FALSE.
        RES=(0D0,0D0)
        SAVED=RES
        STABLE=.FALSE.
        CALL DPT_DPSTAB_CAPTURE(STABLE,RES,LIB,1)
        IF(COUNTS(2).NE.1) STOP 1
        IF(STABLE.OR.ANY(RES.NE.SAVED)) STOP 2
        STABLE=.TRUE.
        CALL DPT_DPSTAB_CAPTURE(STABLE,RES,LIB,2)
        IF(COUNTS(2).NE.1) STOP 3
        IF(COUNTS(4+LIB).NE.2) STOP 4
        IF(.NOT.STABLE.OR.ANY(RES.NE.SAVED)) STOP 5
        RES(1)=CMPLX(IEEE_VALUE(0D0,IEEE_QUIET_NAN),0D0,8)
        CALL DPT_DPSTAB_CAPTURE(STABLE,RES,LIB,1)
        IF(COUNTS(3).NE.1) STOP 6
        CALL DPT_DPSTAB_CAPTURE(STABLE,SAVED,LIB,4)
        IF(COUNTS(4).NE.1) STOP 7
        FPE_DP=.TRUE.
        CALL DPT_DPSTAB_CAPTURE(STABLE,SAVED,LIB,1)
        IF(COUNTS(13).NE.1) STOP 8
        NRS_RETRY_MODE=.TRUE.
        CALL DPT_DPSTAB_CAPTURE(STABLE,SAVED,LIB,1)
        IF(LIB.EQ.8.AND.COUNTS(15).NE.1) STOP 9
        IF(LIB.NE.8.AND.COUNTS(15).NE.0) STOP 10
        COUNTS(16:18)=0
        CALL IEEE_SET_FLAG(IEEE_INVALID,.TRUE.)
        CALL IEEE_SET_FLAG(IEEE_DIVIDE_BY_ZERO,.TRUE.)
        CALL IEEE_SET_FLAG(IEEE_OVERFLOW,.TRUE.)
        CALL DPT_DPSTAB_CAPTURE(STABLE,SAVED,LIB,1)
        CALL IEEE_GET_FLAG(IEEE_INVALID,FLAG)
        COUNTS(16)=MERGE(1,0,FLAG)
        CALL IEEE_GET_FLAG(IEEE_DIVIDE_BY_ZERO,FLAG)
        COUNTS(17)=MERGE(1,0,FLAG)
        CALL IEEE_GET_FLAG(IEEE_OVERFLOW,FLAG)
        COUNTS(18)=MERGE(1,0,FLAG)
        IF(ANY(COUNTS(16:18).NE.1)) STOP 11
        CALL IEEE_SET_FLAG(IEEE_INVALID,.FALSE.)
        CALL IEEE_SET_FLAG(IEEE_DIVIDE_BY_ZERO,.FALSE.)
        CALL IEEE_SET_FLAG(IEEE_OVERFLOW,.FALSE.)
      ENDDO
      WRITE(*,*) 'DPSTAB_RECORDER_CONTROLS_PASS'
      END
C     Observer only: it never writes STABLE, RES, LIB, or MODE.
      SUBROUTINE DPT_DPSTAB_CAPTURE(STABLE,RES,LIB,MODE)
      USE, INTRINSIC :: IEEE_ARITHMETIC
      IMPLICIT NONE
      LOGICAL STABLE,BAD,FPE_DP,FPE_QP
      LOGICAL NRS_RETRY_MODE,NRS_RETRY_USED
      COMPLEX*16 RES(3)
      INTEGER LIB,MODE,I
      INTEGER*8 COUNTS(18)
      COMMON/DPT_DPSTAB_COUNTS/COUNTS
      COMMON/DPT_FPE_IN_REDUCTION/FPE_DP,FPE_QP
      COMMON/DPT_NRS_RETRY_FLAGS/NRS_RETRY_MODE,NRS_RETRY_USED
      COUNTS(1)=COUNTS(1)+1
      IF(.NOT.STABLE) COUNTS(2)=COUNTS(2)+1
      BAD=.FALSE.
      DO I=1,3
        BAD=BAD.OR..NOT.IEEE_IS_FINITE(DBLE(RES(I)))
        BAD=BAD.OR..NOT.IEEE_IS_FINITE(AIMAG(RES(I)))
      ENDDO
      IF(BAD) COUNTS(3)=COUNTS(3)+1
      IF(MODE.GE.4) COUNTS(4)=COUNTS(4)+1
      IF(LIB.GE.1.AND.LIB.LE.8) COUNTS(4+LIB)=
     $  COUNTS(4+LIB)+1
      IF(FPE_DP) COUNTS(13)=COUNTS(13)+1
      IF(FPE_QP) COUNTS(14)=COUNTS(14)+1
      IF(LIB.EQ.8.AND.NRS_RETRY_MODE) COUNTS(15)=COUNTS(15)+1
      END
