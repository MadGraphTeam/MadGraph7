      SUBROUTINE MP_ML5_0_TERMINAL_WL_3_0(A,LCUT_SIZE,B,IN_SIZE
     $ ,OUT_SIZE,OUT,WL_ENTRY_INEXACT)
      USE ML5_0_POLYNOMIAL_CONSTANTS
      USE, INTRINSIC :: IEEE_ARITHMETIC
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      INTEGER I,J,K
      COMPLEX*32 A(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE)
      COMPLEX*32 B(MAXLWFSIZE,0:VERTEXMAXCOEFS-1,MAXLWFSIZE)
      COMPLEX*32 OUT(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE)
      INTEGER LCUT_SIZE,IN_SIZE,OUT_SIZE
      TYPE(IEEE_ROUND_TYPE) WL_ROUNDING
      LOGICAL WL_NEAREST
      LOGICAL WL_SKIP(MAXLWFSIZE,MAXLWFSIZE)
      INTEGER WL_J,WL_K
      LOGICAL WL_ALREADY,WL_HALT,WL_ENTRY_INEXACT

      CALL IEEE_GET_ROUNDING_MODE(WL_ROUNDING)
      WL_NEAREST=WL_ROUNDING.EQ.IEEE_NEAREST
      WL_ALREADY=WL_ENTRY_INEXACT
      WL_HALT=.TRUE.
      IF(IEEE_SUPPORT_HALTING(IEEE_INEXACT)) CALL
     $  IEEE_GET_HALTING_MODE(IEEE_INEXACT,WL_HALT)
      IF(.NOT.WL_NEAREST.OR..NOT.WL_ALREADY.OR.WL_HALT.OR.LCUT_SIZE.GT.
     $OUT_SIZE.OR.MAXLWFSIZE.GT.16.OR.35.GT.65536.OR.1.GT.65536.OR..NOT
     $.ALL(WL_BOUNDED(REAL(A(1:IN_SIZE,0:34,1:LCUT_SIZE),KIND=16)))
     $ .OR..NOT.ALL(WL_BOUNDED(AIMAG(A(1:IN_SIZE,0:34,1:LCUT_SIZE))))
     $ .OR..NOT.ALL(WL_BOUNDED(REAL(B(1:OUT_SIZE,0:0,1:IN_SIZE)
     $ ,KIND=16))).OR..NOT.ALL(WL_BOUNDED(AIMAG(B(1:OUT_SIZE,0:0
     $ ,1:IN_SIZE))))) THEN
        CALL MP_ML5_0_UPDATE_WL_3_0(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
        RETURN
      ENDIF
      WL_SKIP=.FALSE.
