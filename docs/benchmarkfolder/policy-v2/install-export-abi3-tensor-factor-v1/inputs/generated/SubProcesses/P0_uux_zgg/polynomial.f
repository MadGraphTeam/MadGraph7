     $ ,KIND=16))).OR..NOT.ALL(WL_BOUNDED(AIMAG(B(1:OUT_SIZE,0:4
     $ ,1:IN_SIZE))))) THEN
        CALL MP_ML5_0_UPDATE_WL_3_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
        RETURN
      ENDIF
      WL_AZERO(1:IN_SIZE,0:34,1:LCUT_SIZE)=.FALSE.
