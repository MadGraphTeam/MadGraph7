        CALL MP_ML5_0_UPDATE_WL_2_1_DENSE(A,LCUT_SIZE,B,IN_SIZE
     $   ,OUT_SIZE,OUT)
        RETURN
      ENDIF
      WL_AZERO(1:IN_SIZE,0:14,1:LCUT_SIZE)=.FALSE.
      IF(WL_NEAREST) THEN
