      SUBROUTINE MP_ML5_0_UPDATE_WL_3_1_FACTOR_FFV1L2_1(A,LCUT_SIZE,B
     $ ,IN_SIZE,OUT_SIZE,OUT,WL_ENTRY_INEXACT)
      USE ML5_0_POLYNOMIAL_CONSTANTS
