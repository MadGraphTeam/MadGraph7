     $ .NE.2.OR.MAXEXPONENT(X).NE.16384) RETURN
      IF(ONE_WORDS(HI).NE.ISHFT(16383_8,48).OR.ONE_WORDS(3-HI).NE.0_8)
     $  RETURN
