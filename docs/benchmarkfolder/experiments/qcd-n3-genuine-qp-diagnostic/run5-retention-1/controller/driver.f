      PROGRAM QCD_N3_GENUINE_QP
      USE QG_OBSERVER
      IMPLICIT NONE
      INCLUDE 'MadLoopParams.inc'
      REAL*8 POINTS(0:3,5,3),P(0:3,5),TOTAL(0:3)
      REAL*8 ANS(0:3,0:1),ACC(0:1)
      INTEGER BACKEND,MODE,OBSERVED,I,J,K,CODE,IOS,NPTS,RC
      INTEGER POINTIDS(3),WARMCOUNT,NDIM,NSO
      CHARACTER*32 ARG
      DATA POINTIDS/1,93,39/
      CALL GET_COMMAND_ARGUMENT(1,ARG)
      READ(ARG,*,IOSTAT=IOS) BACKEND
      IF(IOS.NE.0) STOP 81
      CALL GET_COMMAND_ARGUMENT(2,ARG)
      READ(ARG,*,IOSTAT=IOS) MODE
      IF(IOS.NE.0) STOP 81
      CALL GET_COMMAND_ARGUMENT(3,ARG)
      READ(ARG,*,IOSTAT=IOS) OBSERVED
      IF(IOS.NE.0) STOP 81
      IF(BACKEND.NE.1.AND.BACKEND.NE.6.AND.BACKEND.NE.8
     $ .AND.BACKEND.NE.9) STOP 81
      IF(MODE.NE.4.AND.MODE.NE.5) STOP 81
      IF(OBSERVED.NE.0.AND.OBSERVED.NE.1) STOP 81
      IF(DIGITS(0.0_16).NE.113.OR.STORAGE_SIZE(0.0_16).NE.128)
     $ STOP 81
      RC=QG_SETUP(OBSERVED)
      IF(RC.NE.0) STOP 81
      CALL SETPARA('nominal/param_card.dat')
      CALL ML5_0_GET_ANSWER_DIMENSION(NDIM)
      CALL ML5_0_GET_NSQSO_LOOP(NSO)
      IF(NDIM.NE.1.OR.NSO.NE.1) STOP 81
      OPEN(73,FILE='points.dat',STATUS='OLD',ACTION='READ')
      READ(73,*) NPTS
      IF(NPTS.NE.3) STOP 81
      DO K=1,3
        DO I=1,5
          READ(73,*) POINTS(:,I,K)
        ENDDO
      ENDDO
      CLOSE(73)
C     Original policy bootstrap. No forced fake failure or threshold edit.
      CALL ML5_0_FORCE_STABILITY_CHECK(.TRUE.)
      CALL PHYSICAL(0,1,1)
      WARMCOUNT=0
      DO K=1,8
        CALL PHYSICAL(K,1,1)
        IF(.NOT.WARM_STATUS(CODE)) CALL FAILED(82)
        IF(MOD(CODE,100)/10.EQ.1.OR.MOD(CODE,100)/10.EQ.2) THEN
          WARMCOUNT=K
          EXIT
        ENDIF
      ENDDO
      IF(WARMCOUNT.EQ.0) CALL FAILED(82)
      IF(MLREDUCTIONLIB(1).NE.BACKEND.OR.
     $ ANY(MLREDUCTIONLIB(2:10).NE.0)) CALL FAILED(83)
      IF(CTMODERUN.NE.-1.OR.CTMODEINIT.NE.1) CALL FAILED(83)
      IF(.NOT.USEQPINTEGRANDFORCUTTOOLS.OR.
     $ .NOT.USEQPINTEGRANDFORNINJA.OR.
     $ .NOT.USEQPINTEGRANDFORNINJARS.OR.
     $ .NOT.USEQPINTEGRANDFORTIRUST) CALL FAILED(83)
      IF(MLSTABTHRES.NE.1D-6.OR.IMPROVEPSPOINT.NE.2.OR.
     $ LOOPPOLEMODE.NE.0.OR..NOT.TIRUSTCOMPUTEFINITE)
     $ CALL FAILED(83)
C     Fixed modes are unchecked diagnostics. Preserve their return120.
      CTMODERUN=MODE
      CALL ML5_0_FORCE_STABILITY_CHECK(.FALSE.)
      DO K=1,3
        CALL PHYSICAL(100+K,K,POINTIDS(K))
      ENDDO
      CALL ML5_0_EXIT_MADLOOP()
      CALL QG_CALL(-2)
      CALL EMIT(9,0,INT([BACKEND,MODE,OBSERVED,WARMCOUNT,
     $ DIGITS(0.0_16),STORAGE_SIZE(0.0_16)],C_INT64_T),
     $ ALWAYS=.TRUE.,LEAN=.TRUE.)
      RC=QG_FLUSH()
      IF(RC.NE.0) STOP 84
      WRITE(*,*) 'QG_DONE',BACKEND,MODE,OBSERVED,WARMCOUNT
      CONTAINS
      LOGICAL FUNCTION WARM_STATUS(V)
      INTEGER V,H,T,U
      H=V/100
      T=MOD(V,100)/10
      U=MOD(V,10)
      WARM_STATUS=(T.EQ.1.OR.T.EQ.2.OR.T.EQ.3).AND.
     $ ((H.EQ.2.AND.U.EQ.BACKEND).OR.
     $ (H.EQ.3.AND.((BACKEND.EQ.1.AND.U.EQ.9).OR.
     $ (BACKEND.EQ.6.AND.U.EQ.2).OR.
     $ (BACKEND.EQ.8.AND.U.EQ.8).OR.
     $ (BACKEND.EQ.9.AND.U.EQ.3))).OR.
     $ (T.EQ.3.AND.H.EQ.1.AND.U.EQ.BACKEND))
      END FUNCTION
      SUBROUTINE FAILED(REASON)
      INTEGER REASON
      RC=QG_FLUSH()
      WRITE(*,*) 'QG_FAILED',REASON,RC
      STOP 85
      END SUBROUTINE
      SUBROUTINE POLICY_STATE(VALUES)
      INTEGER(C_INT64_T) VALUES(5)
      VALUES=INT([CTMODERUN,
     $ MERGE(1,0,USEQPINTEGRANDFORCUTTOOLS),
     $ MERGE(1,0,USEQPINTEGRANDFORNINJA),
     $ MERGE(1,0,USEQPINTEGRANDFORNINJARS),
     $ MERGE(1,0,USEQPINTEGRANDFORTIRUST)],C_INT64_T)
      END SUBROUTINE
      SUBROUTINE PHYSICAL(CALL_ID,INDEX,POINT_ID)
      INTEGER CALL_ID,INDEX,POINT_ID
      INTEGER(C_INT64_T) POLICY(11)
      P=POINTS(:,:,INDEX)
      TOTAL=P(:,1)+P(:,2)
      DS(1)=SQRT(ABS(TOTAL(0)**2-SUM(TOTAL(1:3)**2)))
      CALL UPDATE_AS_PARAM()
      ANS=0D0
      ACC=-1D0
      CODE=-999
      CALL QG_CALL(CALL_ID)
      POLICY(1:6)=INT([BACKEND,MODE,POINT_ID,CALL_ID,
     $ DIGITS(0.0_16),STORAGE_SIZE(0.0_16)],C_INT64_T)
C     Branch before reading parameters initialized by the first call.
      IF(CALL_ID.EQ.0) THEN
        POLICY(7:11)=-1
      ELSE
        CALL POLICY_STATE(POLICY(7:11))
      ENDIF
      CALL EMIT(1,0,[TRANSFER(P,[0_C_INT64_T],20),POLICY],
     $ ALWAYS=.TRUE.)
      CALL ML5_0_SLOOPMATRIX_THRES(P,ANS,-1D0,ACC,CODE)
      CALL POLICY_STATE(POLICY(7:11))
      CALL EMIT(1,1,[TRANSFER(P,[0_C_INT64_T],20),POLICY,
     $ TRANSFER(ANS,[0_C_INT64_T],8),
     $ TRANSFER(ACC,[0_C_INT64_T],2),INT(CODE,C_INT64_T)],
     $ ALWAYS=.TRUE.)
      IF(QG_HEALTH().NE.0) CALL FAILED(86)
      END SUBROUTINE
      END
