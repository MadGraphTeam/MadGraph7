      SUBROUTINE ML5_0_BORN_WITH_C_RESCUE(P,HEL,FLAV_IDX,ANS,
     $ RESCUED,OK,C_READY,C,PC)
      USE, INTRINSIC :: IEEE_ARITHMETIC
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      REAL*8 P(0:3,5),ANS(0:1)
      REAL*16 C(0:3,5),ANSQ(0:1)
      REAL*8 PC(0:3,5)
      REAL*16 MP_PS(0:3,5),MP_P(0:3,5)
      COMMON/ML5_0_MP_PSPOINT/MP_PS,MP_P
      INTEGER HEL,FLAV_IDX,I,USERHEL
      LOGICAL RESCUED,OK,C_READY,RAISED(SIZE(IEEE_ALL))
      LOGICAL INVALID,DIVZERO,OVERFLOW
      LOGICAL HELRESET
      TYPE(IEEE_STATUS_TYPE) ENTRY_STATUS
      INTEGER RESCUE_COUNT,FAIL_COUNT
      COMMON/ML5_0_HELUSERCHOICE/USERHEL
      COMMON/ML5_0_HELRESET/HELRESET
      COMMON/AUDIT_BORN_RESCUE_COUNTS/RESCUE_COUNT,FAIL_COUNT
      DATA RESCUE_COUNT,FAIL_COUNT/0,0/

C     This snapshot changes no caller flags, rounding mode or halting policy.
C     Enabled caller traps remain enabled and may abort the original DP call.
      C_READY=.FALSE.
      CALL IEEE_GET_STATUS(ENTRY_STATUS)
      CALL ML5_0_SMATRIXHEL_SPLITORDERS(P,HEL,FLAV_IDX,ANS)
      RESCUED=.FALSE.
      OK=ALL(IEEE_IS_FINITE(ANS))
      IF(OK) RETURN

      RESCUED=.TRUE.
      RESCUE_COUNT=RESCUE_COUNT+1
C     The failed DP result must not train the original helicity cache.
      HELRESET=.TRUE.
C     Discard exceptions from the failed DP evaluation, preserving entry state.
      CALL IEEE_SET_STATUS(ENTRY_STATUS)
      CALL IEEE_SET_FLAG(IEEE_ALL,.FALSE.)
C     Prepare exactly the coordinates returned by the actual host setter.
C     It may retain its input after a repair failure; this is not a
C     certificate that shell/conservation repair succeeded.
      CALL ML5_0_SET_MP_PS(P)
      C=MP_PS
      OK=ALL(IEEE_IS_FINITE(C))
      IF(OK) THEN
C       Check the DP trial copy within the same IEEE rescue interval.
        PC=REAL(C,KIND=8)
        OK=ALL(IEEE_IS_FINITE(PC))
      ENDIF
      CALL IEEE_GET_FLAG(IEEE_INVALID,INVALID)
      CALL IEEE_GET_FLAG(IEEE_DIVIDE_BY_ZERO,DIVZERO)
      CALL IEEE_GET_FLAG(IEEE_OVERFLOW,OVERFLOW)
      OK=OK.AND..NOT.(INVALID.OR.DIVZERO.OR.OVERFLOW)
      IF(OK) THEN
        USERHEL=HEL
        CALL AUDIT_QP_SMATRIX_SPLITORDERS(C,FLAV_IDX,ANSQ)
        USERHEL=-1
        OK=ALL(IEEE_IS_FINITE(ANSQ))
        IF(OK) ANS=REAL(ANSQ,KIND=8)
      ENDIF
      OK=OK.AND.ALL(IEEE_IS_FINITE(ANS))
      CALL IEEE_GET_FLAG(IEEE_INVALID,INVALID)
      CALL IEEE_GET_FLAG(IEEE_DIVIDE_BY_ZERO,DIVZERO)
      CALL IEEE_GET_FLAG(IEEE_OVERFLOW,OVERFLOW)
      OK=OK.AND..NOT.(INVALID.OR.DIVZERO.OR.OVERFLOW)
      CALL IEEE_GET_FLAG(IEEE_ALL,RAISED)
C     Merge only new QP flags into the caller's original IEEE environment.
      CALL IEEE_SET_STATUS(ENTRY_STATUS)
      DO I=1,SIZE(IEEE_ALL)
        IF(RAISED(I)) CALL IEEE_SET_FLAG(IEEE_ALL(I),.TRUE.)
      ENDDO
C     A current-call handoff, not a checked amplitude certificate.
      C_READY=OK
      IF(.NOT.OK) THEN
        FAIL_COUNT=FAIL_COUNT+1
        ANS=IEEE_VALUE(0D0,IEEE_QUIET_NAN)
      ENDIF
      END

      SUBROUTINE AUDIT_QP_MATRIX(P,NHEL,IC,FLAV_IDX,RES)
      IMPLICIT NONE
      REAL*16 P(0:3,5),RES(1)
      INTEGER NHEL(5),IC(5),FLAV_IDX
      COMPLEX*32 AMP(8),JAMP(2,1)
      INCLUDE 'coupl.inc'
      CALL AUDIT_QP_GET_AMP(P,NHEL,IC,FLAV_IDX,AMP,
     $ REAL(MDL_MZ,KIND=16),CMPLX(GC_4,KIND=16),
     $ CMPLX(GC_5,KIND=16),CMPLX(GC_22,KIND=16),
     $ CMPLX(GC_23,KIND=16))
      CALL AUDIT_QP_GET_JAMP(AMP,JAMP)
      CALL AUDIT_QP_GET_MATRIX(JAMP,RES)
      END

      SUBROUTINE AUDIT_QP_SMATRIX_SPLITORDERS(P, FLAV_IDX, ANS)
C     
C     Generated by MadGraph7 v. 0.2.1, 2026-09-24
C     By the MadGraph7 Development Team
C     Visit launchpad.net/madgraph5 and amcatnlo.web.cern.ch
C     
C     MadGraph StandAlone Version
C     
C     Returns amplitude squared summed/avg over colors
C     and helicities
C     for the point in phase space P(0:3,NEXTERNAL)
C     
C     Process: u u~ > z g g [ virt = QCD ]
C     
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=5)
      INTEGER    NINITIAL
      PARAMETER (NINITIAL=2)
      INTEGER NPOLENTRIES
      PARAMETER (NPOLENTRIES=(NEXTERNAL+1)*6)
      INTEGER                 NCOMB
      PARAMETER (             NCOMB=48)
      INTEGER NSQAMPSO
      PARAMETER (NSQAMPSO=1)
      INTEGER HELAVGFACTOR
      PARAMETER (HELAVGFACTOR=4)
      LOGICAL CHOSEN_SO_CONFIGS(NSQAMPSO)
      COMMON/ML5_0_CHOSEN_BORN_SQSO/CHOSEN_SO_CONFIGS
C     
C     ARGUMENTS
C     
      REAL*16 P(0:3,NEXTERNAL),ANS(0:NSQAMPSO)
C     FLAV_IDX (the dummy argument) is declared with NFLAV below.
C     
C     LOCAL VARIABLES
C     
      INTEGER FLAVOR(NEXTERNAL)
      REAL*16 T(NSQAMPSO), BUFF
      INTEGER IHEL,IDEN, I, J, JJ
C     beam polarisation, see the same block in matrix_standalone_v4.inc
      DOUBLE PRECISION BEAMPOL(2)
      COMMON/TO_BEAMPOL/BEAMPOL
C     For a 1>N process, them BEAMTWO_HELAVGFACTOR would be set to 1.
      INTEGER BEAMS_HELAVGFACTOR(2)
      DATA (BEAMS_HELAVGFACTOR(I),I=1,2)/2,2/
      INTEGER JC(NEXTERNAL)
      INTEGER NFLAV
      PARAMETER (NFLAV=1)
      INTEGER FLAV_IDX
      DATA IDEN/72/
C     
C     GLOBAL VARIABLES
C     
      INTEGER NHEL(NEXTERNAL,NCOMB)
      COMMON/ML5_0_PROCESS_NHEL/NHEL

      INTEGER USERHEL
      COMMON/ML5_0_HELUSERCHOICE/USERHEL

      INTEGER POLARIZATIONS(0:NEXTERNAL,0:5)
      COMMON/ML5_0_BORN_BEAM_POL/POLARIZATIONS

C     
C     FUNCTIONS
C     
      LOGICAL ML5_0_IS_BORN_HEL_SELECTED
      INTEGER ML5_0_BROKEN_SYM

C     Sum every requested, selected helicity on each rare rescue.
C     No learning cache: failed DP evaluations cannot train QP selection.
      IF (FLAV_IDX.LT.1 .OR. FLAV_IDX.GT.NFLAV) THEN
        ANS(:) = 0Q0
        RETURN
      ENDIF
      CALL ML5_0_GET_FLAVOR(FLAV_IDX, FLAVOR)
      JC=1
      ANS=0Q0
      DO IHEL=1,NCOMB
        IF (USERHEL.EQ.-1.OR.USERHEL.EQ.IHEL) THEN
            IF(POLARIZATIONS(0,0).NE.
     $       -1.AND.(.NOT.ML5_0_IS_BORN_HEL_SELECTED(IHEL))) THEN
              CYCLE
            ENDIF
            CALL AUDIT_QP_MATRIX(P ,NHEL(1,IHEL),JC(1),FLAV_IDX, T)
C           Support for polarised beam, see matrix_standalone_v4.inc
            IF (NINITIAL.EQ.2) THEN
              DO JJ=1,NINITIAL
                IF (ABS(BEAMPOL(JJ)).LE.1Q0) CYCLE
                IF (NHEL(JJ,IHEL).EQ.INT(SIGN(1D0,BEAMPOL(JJ)))) THEN
                  DO I=1,NSQAMPSO
                    T(I)=T(I)*ABS(BEAMPOL(JJ))
                  ENDDO
                ELSE
                  DO I=1,NSQAMPSO
                    T(I)=T(I)*(2Q0-ABS(BEAMPOL(JJ)))
                  ENDDO
                ENDIF
              ENDDO
            ENDIF
            BUFF=0Q0
            DO I=1,NSQAMPSO
              IF(POLARIZATIONS(0,0).EQ.
     $         -1.OR.ML5_0_IS_BORN_HEL_SELECTED(IHEL)) THEN
                ANS(I)=ANS(I)+T(I)
              ENDIF
              BUFF=BUFF+T(I)
            ENDDO
        ENDIF
      ENDDO
      ANS(0)=0.0Q0
      DO I=1,NSQAMPSO
        ANS(I)=ANS(I)/DBLE(IDEN)*ML5_0_BROKEN_SYM(FLAVOR)
        IF (CHOSEN_SO_CONFIGS(I)) THEN
          ANS(0)=ANS(0)+ANS(I)
        ENDIF
      ENDDO
      IF(USERHEL.NE.-1) THEN
        DO I=0,NSQAMPSO
          ANS(I)=ANS(I)*HELAVGFACTOR
        ENDDO
      ELSE
        DO J=1,NINITIAL
          IF (POLARIZATIONS(J,0).NE.-1) THEN
            DO I=0,NSQAMPSO
              ANS(I)=ANS(I)*BEAMS_HELAVGFACTOR(J)
              ANS(I)=ANS(I)/POLARIZATIONS(J,0)
            ENDDO
          ENDIF
        ENDDO
      ENDIF
      END


      SUBROUTINE AUDIT_QP_GET_AMP(P,NHEL,IC,FLAV_IDX,AMP,MDL_MZ,GC_4,GC_5,GC_22,GC_23)
      USE MODEL_OBJECT
C     
C     Process: u u~ > z g g [ virt = QCD ]
C     
CF2PY INTENT(OUT) :: AMP
CF2PY INTENT(IN) :: NHEL
CF2PY INTENT(IN) :: P(0:3,NEXTERNAL)
CF2PY INTENT(IN) :: IC
CF2PY INTENT(IN) :: FLAV_IDX

      USE ALOHA_OBJECT
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      INTEGER    NGRAPHS
      PARAMETER (NGRAPHS=8)
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=5)
      INTEGER    NWAVEFUNCS, NCOLOR
      PARAMETER (NWAVEFUNCS=10, NCOLOR=2)
      REAL*16     ZERO
      PARAMETER (ZERO=0Q0)
C     
C     ARGUMENTS
C     
      REAL*16 P(0:3,NEXTERNAL)
      INTEGER NHEL(NEXTERNAL), IC(NEXTERNAL)
      INTEGER FLAV_IDX
      INTEGER FLAVOR(NEXTERNAL)
C     
C     LOCAL VARIABLES
C     
      COMPLEX*32 AMP(NGRAPHS)
      TYPE(MP_ALOHA) W(NWAVEFUNCS)
      COMPLEX*32 DUM0,DUM1
      DATA DUM0, DUM1/(0Q0, 0Q0), (1Q0, 0Q0)/
      REAL*16 BWCUTOFF
C     Flavor table for the FLAV_IDX -> FLAVOR rebuild.
      INTEGER NMASK_FLAV
      PARAMETER (NMASK_FLAV=1)
      INTEGER MASK_J
      INTEGER FLAV_TABLE(NEXTERNAL, NMASK_FLAV)
      DATA FLAV_TABLE / 1, 1, 1, 1, 1 /
C     
C     GLOBAL VARIABLES
C     
      REAL*16 MDL_MZ
      COMPLEX*32 GC_4,GC_5,GC_22,GC_23

C     
C     
      BWCUTOFF=15  ! use if $ syntax is defined in the process
C     Rebuild FLAVOR(NEXTERNAL) from the resolved flavor index.
      IF (FLAV_IDX .GE. 1 .AND. FLAV_IDX .LE. NMASK_FLAV) THEN
        DO MASK_J = 1, NEXTERNAL
          FLAVOR(MASK_J) = FLAV_TABLE(MASK_J, FLAV_IDX)
        ENDDO
      ELSE
        DO MASK_J = 1, NEXTERNAL
          FLAVOR(MASK_J) = FLAV_TABLE(MASK_J, 1)
        ENDDO
      ENDIF
      CALL MP_IXXXXX(P(0,1),ZERO,NHEL(1),+1, FLAVOR(1),W(1))
      CALL MP_OXXXXX(P(0,2),ZERO,NHEL(2),-1, FLAVOR(2),W(2))
      CALL MP_VXXXXX(P(0,3),MDL_MZ,NHEL(3),+1,W(3))
      CALL MP_VXXXXX(P(0,4),ZERO,NHEL(4),+1,W(4))
      CALL MP_VXXXXX(P(0,5),ZERO,NHEL(5),+1,W(5))
      CALL MP_FFV2_5_2(W(1),W(3),GC_22,GC_23,ZERO,ZERO,W(6))
      CALL MP_FFV1_1(W(2),W(4),GC_5,ZERO,ZERO,W(7))
C     Amplitude(s) for diagram number 1
      CALL MP_FFV1_0(W(6),W(7),W(5),GC_5,AMP(1))
      CALL MP_FFV1_1(W(2),W(5),GC_5,ZERO,ZERO,W(8))
C     Amplitude(s) for diagram number 2
      CALL MP_FFV1_0(W(6),W(8),W(4),GC_5,AMP(2))
      CALL MP_VVV1P0_1(W(4),W(5),GC_4,ZERO,ZERO,W(9))
C     Amplitude(s) for diagram number 3
      CALL MP_FFV1_0(W(6),W(2),W(9),GC_5,AMP(3))
      CALL MP_FFV1_2(W(1),W(4),GC_5,ZERO,ZERO,W(6))
      CALL MP_FFV2_5_1(W(2),W(3),GC_22,GC_23,ZERO,ZERO,W(10))
C     Amplitude(s) for diagram number 4
      CALL MP_FFV1_0(W(6),W(10),W(5),GC_5,AMP(4))
C     Amplitude(s) for diagram number 5
      CALL MP_FFV2_5_0(W(6),W(8),W(3),GC_22,GC_23,AMP(5))
      CALL MP_FFV1_2(W(1),W(5),GC_5,ZERO,ZERO,W(6))
C     Amplitude(s) for diagram number 6
      CALL MP_FFV1_0(W(6),W(10),W(4),GC_5,AMP(6))
C     Amplitude(s) for diagram number 7
      CALL MP_FFV2_5_0(W(6),W(7),W(3),GC_22,GC_23,AMP(7))
C     Amplitude(s) for diagram number 8
      CALL MP_FFV1_0(W(1),W(10),W(9),GC_5,AMP(8))

      END


