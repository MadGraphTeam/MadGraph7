C     Materialized private standalone tensor diagnostic; no partial
C      amplitude.
      PROGRAM RANK6_POLE_COMPLEMENT
      USE MTIRUST
      USE COLLIER, ONLY: GETERRFLAG_CLL,GETACCFLAG_CLL
      USE, INTRINSIC :: ISO_C_BINDING, ONLY:C_INT64_T
      IMPLICIT NONE
      INCLUDE 'coupl.inc'
      INCLUDE 'MadLoopParams.inc'
      INTEGER ORIGINAL_NC,MODEL
      PARAMETER(ORIGINAL_NC=70,MODEL=0)
      INTEGER I,J,K,F,N,R,NC,A,B,CT,MODE,FINITE,CACHE,BUDGET,CLR
      INTEGER NSTEPS,STEP,IOS,STATUS,FLAG0,ROUND0,FLAG1,ROUND1
      INTEGER CERR,CACC,ID,SQSO,RR,CACHED,COUNTS(3),HEALTH
      INTEGER RP_HEALTH,GEN0,GEN1
      INTEGER*8 CPRE(9),QPRE(6),CPOST(9),QPOST(6)
      REAL*8 P(0:3,6),PL(0:3,6),PL0(0:3,6,7),PDEN(0:3,5)
      REAL*8 BASEMU(7),TOTAL(0:3),MU0
      REAL*16 QPL(0:3,6)
      COMPLEX*16 M2(6),M20(6,7),CO(0:ORIGINAL_NC-1,3)
      COMPLEX*16 CD(0:209,3),CE(0:209,3)
      COMPLEX*32 CQ(0:209,3)
      LOGICAL STABLE,CTINIT,TIRINIT,GOLEMINIT,SAMURAIINIT
      LOGICAL NINJAINIT,COLLIERINIT,MUST_INIT_EVENT
      INTEGER COLLIER_CACHE_ACTIVE,NCALLS_IN_CACHE(4),NCOLLIERCALLS(4)
      COMMON/REDUCTIONCODEINIT/CTINIT,TIRINIT,GOLEMINIT,SAMURAIINIT,
     $ NINJAINIT,COLLIERINIT
      COMMON/CAP6_LOOP/ID,SQSO,RR
      COMMON/CAP6_COLLIER_CACHE_STATUS/COLLIER_CACHE_ACTIVE,
     $ NCALLS_IN_CACHE,NCOLLIERCALLS,MUST_INIT_EVENT
      OPEN(71,FILE='records.txt',STATUS='NEW')
      WRITE(71,*) 'HEADER',1,MODEL,ORIGINAL_NC
      CALL RP_OPEN()
      CALL SETPARA('nominal/param_card.dat')
      CALL DEFAULTPARAM()
      OPEN(72,FILE='point.dat',STATUS='OLD')
      READ(72,*) I
      DO J=1,6
        READ(72,*) P(:,J)
      ENDDO
      CLOSE(72)
      TOTAL=P(:,1)+P(:,2)
      MU_R=SQRT(ABS(TOTAL(0)**2-SUM(TOTAL(1:3)**2)))
      MU0=MU_R
      CALL UPDATE_AS_PARAM()
      MLREDUCTIONLIB=0
      MLREDUCTIONLIB(1)=9
      TIRUSTGLOBALCACHE=0
      TIRUSTCOMPUTEFINITE=.TRUE.
      LOOPPOLEMODE=0
      CTINIT=.TRUE.
      TIRINIT=.TRUE.
      GOLEMINIT=.TRUE.
      SAMURAIINIT=.TRUE.
      NINJAINIT=.TRUE.
      COLLIERINIT=.TRUE.
      PL0=0
      M20=0
      BASEMU=MU0
      COUNTS=0
      DO K=1,2
        A=900+K
        CALL RP_BEGIN(A)
        CALL RP_CAPTURE_GROUP(P,K)
        CALL RP_CAPTURE(PL,M2,CO,STABLE,CACHED)
        WRITE(71,*) 'CAPTURE',A,K,MERGE(1,0,STABLE),CACHED
        CALL DUMP_INPUT('PI','MI',6,REAL(PL,KIND=16),M2)
        CQ=0
        CQ(0:ORIGINAL_NC-1,:)=CO
        CALL DUMP_VALUES(ORIGINAL_NC,CQ)
        WRITE(71,*) 'CAPTURE_END',A
        CALL RP_FLUSH()
        IF(K.EQ.1) THEN
          PL0(:,:,1+MODEL)=PL
          M20(:,1+MODEL)=M2
          PL0(:,:,3+MODEL)=PL
          M20(:,3+MODEL)=M2
        ELSE
          PL0(:,:,5)=PL
          M20(:,5)=M2
        ENDIF
      ENDDO
      IF(MODEL.EQ.0) THEN
        M20(3,5)=CMPLX(MDL_MZ**2,-MDL_MZ*2.498770D0,KIND=8)
        PL0(:,1,6)=(/2D0,0D0,0D0,2D0/)
        PL0(:,2,6)=-PL0(:,1,6)
        BASEMU(6)=2D0
        PL0(:,:,7)=PL0(:,:,3)
        M20(:,7)=M20(:,3)
        BASEMU(7)=2D0*MU0
      ENDIF
      COLLIERGLOBALCACHE=0
      COLLIERUSEINTERNALSTABILITYTEST=.FALSE.
      COLLIERCOMPUTEUVPOLES=.TRUE.
      COLLIERCOMPUTEIRPOLES=.TRUE.
      COLLIERCANOUTPUT=.FALSE.
      COLLIER_CACHE_ACTIVE=0
      NCALLS_IN_CACHE=-1
      NCOLLIERCALLS=0
      ID=1
      SQSO=1
      OPEN(72,FILE='schedule.dat',STATUS='OLD')
      READ(72,*) NSTEPS
      DO STEP=1,NSTEPS
        READ(72,*) A,F,B,CT,MODE,FINITE,CACHE,BUDGET,CLR,N,R
        IF(F.LT.101.OR.F.GT.107.OR.R.GT.6.OR.N.GT.6) STOP 11
        NC=(R+1)*(R+2)*(R+3)*(R+4)/24
C       Fresh copies are mandatory: SWITCH_ORDER modifies its
C        arguments.
        PL=PL0(:,:,F-100)
        M2=M20(:,F-100)
        QPL=REAL(PL,KIND=16)
        MU_R=BASEMU(F-100)
        CALL UPDATE_AS_PARAM()
        LOOPPOLEMODE=MODE
        TIRUSTCOMPUTEFINITE=FINITE.EQ.1
        TIRUSTGLOBALCACHE=CACHE
        TIRUSTCACHEMAXBYTES=BUDGET
        CALL TIRUST_SET_CACHE_BUDGET(INT(BUDGET,C_INT64_T),STATUS)
        IF(STATUS.NE.0) STOP 12
        IF(CLR.EQ.1) THEN
          CALL TIRUST_CLEAR_CACHE(STATUS)
          IF(STATUS.NE.0) STOP 13
        ENDIF
        CALL GET_STATS(CPRE,QPRE)
        WRITE(71,*) 'CASE',A,F,B,CT,MODE,FINITE,CACHE,BUDGET,CLR,N,R,NC
        WRITE(71,'(A,1X,Z16.16)') 'SCALE',TRANSFER(MU_R,0_8)
        CALL DUMP_INPUT('PI','MI',N,QPL,M2)
        WRITE(71,*) 'CACHE_PRE',CPRE,QPRE
        CALL RP_BEGIN(A)
        CALL RP_STATE(FLAG0,ROUND0)
        CQ=0
        CD=0
        CE=0
        CO=0
        STABLE=.FALSE.
        CERR=0
        CACC=0
        IF(B.EQ.9) THEN
          IF(F.EQ.101.OR.F.EQ.102) THEN
            IF(CT.EQ.1) THEN
              CALL ML5_0_TIRUST_TENSOR_DIAGNOSTIC(CT,N,R,PL(:,1:N)
     $         ,M2(1:N),CO,STABLE)
              CQ(0:NC-1,:)=CO(0:NC-1,:)
              QPL=REAL(PL,KIND=16)
            ELSE
              CALL RP_ORIGINAL_MP(CT,N,R,QPL(:,1:N),M2(1:N),CQ,STABLE)
            ENDIF
          ELSE IF(CT.LT.4) THEN
            CALL CAP6_TIRUST_TENSOR_DIAGNOSTIC(CT,N,R,PL(:,1:N),M2(1:N)
     $       ,CD,STABLE)
            CQ=CD
            QPL=REAL(PL,KIND=16)
          ELSE
            CALL CAP6_MP_TIRUST_TENSOR_DIAGNOSTIC(CT,N,R,QPL(:,1:N)
     $       ,M2(1:N),CQ,STABLE)
          ENDIF
        ELSE IF(B.EQ.7) THEN
          PDEN=0
          DO J=1,N-1
            IF(J.GT.1) PDEN(:,J)=PDEN(:,J-1)
            PDEN(:,J)=PDEN(:,J)+PL(:,J)
          ENDDO
          MUST_INIT_EVENT=.TRUE.
          RR=R
          CALL CAP6_COLLIERLOOP(CT,N,R,PL(:,1:N),PDEN(:,1:N-1),M2(1:N)
     $     ,CD,CE)
          CALL GETERRFLAG_CLL(CERR)
          CALL GETACCFLAG_CLL(CACC)
          STABLE=CERR.EQ.0.AND.CACC.GE.-1
          CQ=CD
          QPL=REAL(PL,KIND=16)
        ELSE
          STOP 14
        ENDIF
        CALL RP_STATE(FLAG1,ROUND1)
        WRITE(71,*) 'STATE',FLAG0,ROUND0,FLAG1,ROUND1,MERGE(1,0,STABLE)
     $   ,CERR,CACC
        CALL DUMP_INPUT('PO','MO',N,QPL,M2)
        CALL DUMP_VALUES(NC,CQ)
        CALL RP_FLUSH()
        CALL GET_STATS(CPOST,QPOST)
        WRITE(71,*) 'CACHE_POST',CPOST,QPOST
        HEALTH=RP_HEALTH()
        WRITE(71,*) 'END',A,HEALTH
        FLUSH(71)
        IF(HEALTH.NE.0) STOP 15
      ENDDO
      READ(72,*,IOSTAT=IOS) I
      IF(IOS.GE.0) STOP 16
      CLOSE(72)
      CALL TIRUST_CLEAR_CACHE(STATUS)
      IF(STATUS.NE.0) STOP 18
      CALL GET_STATS(CPOST,QPOST)
      GEN0=TIRUST_CONTEXT_GENERATION()
      CALL TIRUST_FINALIZE(STATUS)
      GEN1=TIRUST_CONTEXT_GENERATION()
      WRITE(71,*) 'FINAL',STATUS,GEN0,GEN1,CPOST,QPOST
      CALL RP_CLOSE()
      WRITE(71,*) 'DONE',RP_HEALTH()
      CLOSE(71)
      CONTAINS
      SUBROUTINE GET_STATS(C,Q)
      INTEGER*8 C(9),Q(6)
      INTEGER S1,S2
      CALL TIRUST_CACHE_STATISTICS(C,S1)
      CALL TIRUST_QP_CACHE_STATISTICS(Q,S2)
      IF(S1.NE.0.OR.S2.NE.0) STOP 17
      END SUBROUTINE
      SUBROUTINE DUMP_INPUT(PTAG,MTAG,NN,PP,MM)
      CHARACTER*(*) PTAG,MTAG
      INTEGER NN,L
      REAL*16 PP(0:3,NN)
      COMPLEX*16 MM(NN)
      DO L=1,NN
        WRITE(71,'(A,1X,I3,8(1X,Z16.16))') PTAG,L,TRANSFER(PP(:,L),(
     $   /0_8/))
        WRITE(71,'(A,1X,I3,4(1X,Z16.16))') MTAG,L,TRANSFER(CMPLX(MM(L)
     $   ,KIND=16),(/0_8/))
      ENDDO
      END SUBROUTINE
      SUBROUTINE DUMP_VALUES(NN,VV)
      INTEGER NN,L,SLOT
      COMPLEX*32 VV(0:209,3)
      DO L=0,NN-1
        DO SLOT=1,3
          WRITE(71,'(A,2I5,4(1X,Z16.16),2(1X,ES46.35E4))') 'V',L,SLOT,
     $      TRANSFER(VV(L,SLOT),(/0_8/)),REAL(VV(L,SLOT),KIND=16),AIMAG(VV(L,SLOT))
        ENDDO
      ENDDO
      END SUBROUTINE
      END

      SUBROUTINE RP_ORIGINAL_MP(CT,N,R,P,M,C,STABLE)
      IMPLICIT NONE
      INTEGER CT,N,R
      REAL*16 P(0:3,N)
      COMPLEX*16 M(N)
      COMPLEX*32 C(0:209,3),ORIGINAL(0:69,3)
      LOGICAL STABLE
      CALL ML5_0_MP_TIRUST_TENSOR_DIAGNOSTIC(CT,N,R,P,M,ORIGINAL
     $ ,STABLE)
      C=0
      C(0:69,:)=ORIGINAL
      END

      SUBROUTINE RP_CAPTURE_GROUP(P,K)
      USE ALOHA_OBJECT
      IMPLICIT NONE
      INCLUDE 'coupl.inc'
      INTEGER K,NHEL(6),FLAVOR(6),I
      REAL*8 P(0:3,6),ZERO,LSCALE
      PARAMETER(ZERO=0D0)
      TYPE(ALOHA) W(155)
      COMMON/ML5_0_W/W
      COMPLEX*16 LOOPCOEFS(0:69,1,1218)
      COMMON/ML5_0_LCOEFS/LOOPCOEFS
      LOGICAL CHECKPHASE,HELDOUBLECHECKED,GOODAMP(1,1218)
      INTEGER GOODHEL(64),HELOFFSET,LIBINDEX,CTMODE
      COMMON/ML5_0_INIT/CHECKPHASE,HELDOUBLECHECKED
      COMMON/ML5_0_FILTERS/GOODAMP,GOODHEL,HELOFFSET
      COMMON/ML5_0_CT/LSCALE,CTMODE
      COMMON/ML5_0_I_LIB/LIBINDEX
      CHECKPHASE=.TRUE.
      HELDOUBLECHECKED=.FALSE.
      GOODAMP=.TRUE.
      GOODHEL=1
      HELOFFSET=0
      CTMODE=1
      LIBINDEX=1
      LSCALE=MU_R
      LOOPCOEFS=0
      FLAVOR=1
      NHEL=1
      CALL OXXXXX(P(0,1),ZERO,NHEL(1),-1, FLAVOR(1),W(1))
      CALL IXXXXX(P(0,2),ZERO,NHEL(2),+1, FLAVOR(2),W(2))
      CALL IXXXXX(P(0,3),ZERO,NHEL(3),-1, FLAVOR(3),W(3))
      CALL OXXXXX(P(0,4),ZERO,NHEL(4),+1, FLAVOR(4),W(4))
      CALL VXXXXX(P(0,5),ZERO,NHEL(5),+1,W(5))
      CALL VXXXXX(P(0,6),ZERO,NHEL(6),+1,W(6))
      IF(K.EQ.1) THEN
        LOOPCOEFS(0,1,269)=1D0
        CALL ML5_0_LOOP_6(1,2,4,6,5,3,DCMPLX(ZERO),DCMPLX(ZERO)
     $   ,DCMPLX(ZERO),DCMPLX(ZERO),DCMPLX(ZERO),DCMPLX(ZERO),4,1,269)
      ENDIF
      IF(K.EQ.2) THEN
        LOOPCOEFS(0,1,270)=1D0
        CALL ML5_0_LOOP_6(1,2,4,6,5,3,DCMPLX(ZERO),DCMPLX(MDL_MZ)
     $   ,DCMPLX(ZERO),DCMPLX(ZERO),DCMPLX(ZERO),DCMPLX(ZERO),4,1,270)
      ENDIF
      END

