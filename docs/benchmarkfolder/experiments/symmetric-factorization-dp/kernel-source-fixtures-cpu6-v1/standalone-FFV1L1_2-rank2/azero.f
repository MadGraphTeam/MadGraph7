      SUBROUTINE TEST_UPDATE_WL_2_1_AZERO(A,LCUT_SIZE,B,IN_SIZE
     $ ,OUT_SIZE,OUT,WL_ENTRY_INEXACT)
      USE TEST_POLYNOMIAL_CONSTANTS
      USE, INTRINSIC :: IEEE_ARITHMETIC
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      LOGICAL WL_ENTRY_INEXACT
      TYPE(IEEE_ROUND_TYPE) WL_ROUNDING
      LOGICAL HALT_FLAGS(SIZE(IEEE_ALL))
      INTEGER HALT_INDEX,R
      INTEGER I,J,K,L,M
      COMPLEX*16 U(4,0:14,MAXLWFSIZE)
      COMPLEX*16 A(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE)
      COMPLEX*16 B(MAXLWFSIZE,0:VERTEXMAXCOEFS-1,MAXLWFSIZE)
      COMPLEX*16 OUT(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE)
      INTEGER LCUT_SIZE,IN_SIZE,OUT_SIZE
      INTEGER NEW_POSITION
      COMPLEX*16 UPDATER_COEF

C     Experimental binary64 derivative-row factorization
      IF(.NOT.WL_ENTRY_INEXACT.OR.IN_SIZE.NE.4.OR.OUT_SIZE.NE.4.OR.MAXL
     $WFSIZE.NE.4.OR.LCUT_SIZE.LT.0.OR.LCUT_SIZE.GT.4) THEN
        CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
        RETURN
      ENDIF
      DO HALT_INDEX=1,SIZE(IEEE_ALL)
        IF(.NOT.IEEE_SUPPORT_HALTING(IEEE_ALL(HALT_INDEX))) THEN
          CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
          RETURN
        ENDIF
      ENDDO
      CALL IEEE_GET_HALTING_MODE(IEEE_ALL,HALT_FLAGS)
      IF(ANY(HALT_FLAGS)) THEN
        CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
        RETURN
      ENDIF
      CALL IEEE_GET_ROUNDING_MODE(WL_ROUNDING)
      IF(WL_ROUNDING.NE.IEEE_NEAREST) THEN
        CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
        RETURN
      ENDIF
      IF(.NOT.ALL(FACTOR_BOUNDED(REAL(A(1:IN_SIZE,0:14,1:LCUT_SIZE)
     $ ,KIND=8))).OR..NOT.ALL(FACTOR_BOUNDED(AIMAG(A(1:IN_SIZE,0:14
     $ ,1:LCUT_SIZE)))).OR..NOT.ALL(FACTOR_BOUNDED(REAL(B(1:OUT_SIZE
     $ ,0:4,1:IN_SIZE),KIND=8)))
     $ .OR..NOT.ALL(FACTOR_BOUNDED(AIMAG(B(1:OUT_SIZE,0:4,1:IN_SIZE))))
     $ ) THEN
        CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
        RETURN
      ENDIF
      DO K=1,4
        IF(B(1,2,K).NE.(-B(2,1,K))) THEN
          CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(2,2,K).NE.(-B(1,1,K))) THEN
          CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(3,2,K).NE.B(4,1,K)) THEN
          CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(4,2,K).NE.B(3,1,K)) THEN
          CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(1,3,K).NE.CMPLX(-AIMAG(B(2,1,K)),REAL(B(2,1,K),KIND=8)
     $   ,KIND=8)) THEN
          CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(2,3,K).NE.CMPLX(AIMAG(B(1,1,K)),-REAL(B(1,1,K),KIND=8)
     $   ,KIND=8)) THEN
          CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(3,3,K).NE.CMPLX(AIMAG(B(4,1,K)),-REAL(B(4,1,K),KIND=8)
     $   ,KIND=8)) THEN
          CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(4,3,K).NE.CMPLX(-AIMAG(B(3,1,K)),REAL(B(3,1,K),KIND=8)
     $   ,KIND=8)) THEN
          CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(1,4,K).NE.(-B(1,1,K))) THEN
          CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(2,4,K).NE.B(2,1,K)) THEN
          CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(3,4,K).NE.B(3,1,K)) THEN
          CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(4,4,K).NE.(-B(4,1,K))) THEN
          CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
          RETURN
        ENDIF
      ENDDO
C     FACTOR_FAST_PATH
      OUT(:,:,:)=(0.0D0,0.0D0)
      DO J=1,OUT_SIZE
        DO M=0,4
          DO K=1,IN_SIZE
            UPDATER_COEF = B(J,M,K)
            IF (UPDATER_COEF.EQ.(0.0D0,0.0D0)) CYCLE
            DO I=1,LCUT_SIZE
              DO L=0,14
                IF(A(K,L,I).EQ.(0.0D0,0.0D0)) CYCLE
                NEW_POSITION = COMB_COEF_POS(L,M)
                OUT(J,NEW_POSITION,I)=OUT(J,NEW_POSITION,I) + A(K,L,I)
     $           *UPDATER_COEF
              ENDDO
            ENDDO
          ENDDO
        ENDDO
      ENDDO

      CONTAINS
      ELEMENTAL LOGICAL FUNCTION FACTOR_BOUNDED(X)
      REAL*8, INTENT(IN) :: X
      INTEGER*8, PARAMETER :: ONE(1)=TRANSFER(1.0_8,(/0_8/))
      FACTOR_BOUNDED=.FALSE.
      IF(STORAGE_SIZE(X).NE.64.OR.DIGITS(X).NE.53.OR.RADIX(X)
     $ .NE.2.OR.MAXEXPONENT(X).NE.1024) RETURN
      IF(ONE(1).NE.ISHFT(1023_8,52)) RETURN
      ASSOCIATE(WORDS=>TRANSFER(X,ONE))
      FACTOR_BOUNDED=IBITS(WORDS(1),52,11).GE.823_8.AND.IBITS(WORDS(1)
     $ ,52,11).LE.1223_8
      IF(IBCLR(WORDS(1),63).EQ.0_8) FACTOR_BOUNDED=.TRUE.
      END ASSOCIATE
      END FUNCTION
      END

