      SUBROUTINE ML5_0_LOOP_3_PROVENANCE(W1, W2, W3, M1, M2, M3,  RANK
     $ , SQUAREDSOINDEX, LOOPNUM,GP_ROUTE,GP_ENV,GP_FRESH)
      USE ALOHA_OBJECT
      USE ML5_0_INVARIANT_BOUNDS, ONLY: IK, ROUTE_MATCHES,
     $ EXTERNAL_SLOTS_FOR_ROUTE,BUILD_CHORD_BOUNDS,ENVIRONMENT_UNCHANGED,
     $ PRODUCER_KIND_OK,GEOMETRY_WINDOW_SOURCE_OK
      USE, INTRINSIC :: ISO_C_BINDING, ONLY: C_INT64_T
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=3)
      INTEGER    NLOOPLINE
      PARAMETER (NLOOPLINE=3)
      INTEGER    NWAVEFUNCS
      PARAMETER (NWAVEFUNCS=3)
      INTEGER    NLOOPGROUPS
      PARAMETER (NLOOPGROUPS=1)
      INTEGER    NCOMB
      PARAMETER (NCOMB=12)
C     These are constants related to the split orders
      INTEGER    NSQUAREDSO
      PARAMETER (NSQUAREDSO=0)
C     
C     ARGUMENTS 
C     
      INTEGER W1, W2, W3
      COMPLEX*16 M1, M2, M3

      INTEGER RANK, LSYMFACT
      INTEGER LOOPNUM, SQUAREDSOINDEX
C     
C     LOCAL VARIABLES 
C     
      REAL*8 PL(0:3,NLOOPLINE)
      REAL*16 MP_PL(0:3,NLOOPLINE)
      COMPLEX*16 M2L(NLOOPLINE)
      INTEGER PAIRING(NLOOPLINE),WE(3)
      INTEGER I, J, K, TEMP,I_LIB
      LOGICAL COMPLEX_MASS,DOING_QP
C     
C     GLOBAL VARIABLES
C     
      INCLUDE 'MadLoopParams.inc'
      INTEGER ID,SQSOINDEX,R
      COMMON/ML5_0_LOOP/ID,SQSOINDEX,R

      LOGICAL CHECKPHASE, HELDOUBLECHECKED
      COMMON/ML5_0_INIT/CHECKPHASE, HELDOUBLECHECKED

      INTEGER HELOFFSET
      INTEGER GOODHEL(NCOMB)
      LOGICAL GOODAMP(NSQUAREDSO,NLOOPGROUPS)
      COMMON/ML5_0_FILTERS/GOODAMP,GOODHEL,HELOFFSET

      COMPLEX*16 LOOPRES(3,NSQUAREDSO,NLOOPGROUPS)
      LOGICAL S(NSQUAREDSO,NLOOPGROUPS)
      COMMON/ML5_0_LOOPRES/LOOPRES,S


      TYPE(ALOHA) W(NWAVEFUNCS)
      COMMON/ML5_0_W/W
      TYPE(MP_ALOHA) MP_W(NWAVEFUNCS)
      COMMON/ML5_0_MP_W/MP_W

      REAL*8 LSCALE
      INTEGER CTMODE
      COMMON/ML5_0_CT/LSCALE,CTMODE
      INTEGER LIBINDEX
      COMMON/ML5_0_I_LIB/LIBINDEX

      INTEGER GP_ROUTE,GP_SLOTS(NEXTERNAL),GP_WIDTH,GP_E,GP_MU
      INTEGER GP_CHORD(0:3,NLOOPLINE),GP_CLASS(NLOOPLINE,NLOOPLINE)
      INTEGER(C_INT64_T) GP_ENV,GP_PAIR64(2)
      INTEGER(IK) GP_EXTERNAL(2,0:3,NEXTERNAL),GP_PAIR128(2)
      LOGICAL GP_FRESH,GP_OK,GP_HAVE(NLOOPLINE),GP_ENV_OK
      WE(1)=W1
      WE(2)=W2
      WE(3)=W3
      DO I=1,NLOOPLINE
        PAIRING(I)=1
      ENDDO

      GP_WIDTH=64
      IF(CTMODE.GE.4) GP_WIDTH=128
      GP_EXTERNAL=0_IK
      CALL EXTERNAL_SLOTS_FOR_ROUTE(GP_ROUTE,CTMODE,GP_SLOTS,GP_OK)
      GP_ENV_OK=ENVIRONMENT_UNCHANGED(GP_ENV)
      GP_OK=GP_OK.AND.GP_FRESH.AND.GP_ENV_OK
      GP_OK=GP_OK.AND.GEOMETRY_WINDOW_SOURCE_OK(CTMODE,GP_WIDTH)
      GP_OK=GP_OK.AND.ROUTE_MATCHES(GP_ROUTE,NLOOPLINE,SIZE(WE),WE
     $ ,PAIRING)
      GP_OK=GP_OK.AND.PRODUCER_KIND_OK(CTMODE,GP_WIDTH,GP_FRESH)
      IF(GP_OK) THEN
        DO GP_E=1,NEXTERNAL
          IF(GP_SLOTS(GP_E).LT.1.OR.GP_SLOTS(GP_E).GT.NWAVEFUNCS)
     $      GP_OK=.FALSE.
        ENDDO
      ENDIF
      IF(GP_OK) THEN
        DO GP_E=1,NEXTERNAL
          DO GP_MU=0,3
            IF(GP_WIDTH.EQ.128) THEN
              GP_PAIR128=TRANSFER(MP_W(GP_SLOTS(GP_E))%P(GP_MU)
     $         ,GP_PAIR128)
              GP_EXTERNAL(:,GP_MU,GP_E)=GP_PAIR128
            ELSE
              GP_PAIR64=TRANSFER(W(GP_SLOTS(GP_E))%P(GP_MU),GP_PAIR64)
              GP_EXTERNAL(:,GP_MU,GP_E)=IAND(INT(GP_PAIR64,IK)
     $         ,INT(Z'FFFFFFFFFFFFFFFF',IK))
            ENDIF
          ENDDO
        ENDDO
      ENDIF
      CALL BUILD_CHORD_BOUNDS(GP_ROUTE,CTMODE,GP_WIDTH,NLOOPLINE,
     $ GP_EXTERNAL,GP_OK,GP_CHORD,GP_CLASS,GP_HAVE)
      CALL ML5_0_LOOP_3_PROVENANCE_DISPATCH(W1, W2, W3, M1, M2, M3,
     $  RANK,SQUAREDSOINDEX,LOOPNUM,GP_CHORD,GP_CLASS,GP_HAVE,GP_ENV)
      END
