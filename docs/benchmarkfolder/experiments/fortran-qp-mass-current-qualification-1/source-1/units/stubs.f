      SUBROUTINE QPMUNIT_MP_TIRUST_LOOP_QPMASS(N,PL,M2L,
     $ RANK,RES,STABLE)
      USE UNIT_MASS_RECORDS
      IMPLICIT NONE
      INTEGER N,RANK,I
      REAL*16 PL(0:3,N)
      COMPLEX*32 M2L(N)
      COMPLEX*16 RES(3)
      LOGICAL STABLE
      IF(N.NE.3.OR.RANK.NE.2) STOP 94
      IF(CURRENT_MODE.NE.4.AND.CURRENT_MODE.NE.5) STOP 95
      QP_CALLS=QP_CALLS+1
      DO I=1,N
        CALL DUMP_QP('MASS2',CURRENT_MODE,I,M2L(I))
      ENDDO
      DO I=1,3
        RES(I)=CMPLX(DBLE(10*CURRENT_MODE+I),-DBLE(I),KIND=8)
      ENDDO
      STABLE=.TRUE.
      END

