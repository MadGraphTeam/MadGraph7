C     PRIVATE SOURCE-ONLY ONE-POINT DRIVER. NOT NATIVE-QUALIFIED.
C     Args: bootstrap measurement mode point trace-enabled fifo.
C     One ordinary bootstrap OUTER call, then one measurement maximum.
C     Diagnostic policy: FORCE_STABILITY_CHECK FALSE prevents the
C     wrapper's forced second amplitude call. No extra bootstrap/retry.
C     LoopPoleMode=0 temporarily enables the full sum and restores INIT
C     flags after each call. Restored flags are not a readiness gate.
      PROGRAM KTRACE_MADLOOP_WORKER
      IMPLICIT NONE
      INTEGER NEXTERNAL,NSQSO_BORN
      PARAMETER(NEXTERNAL=5,NSQSO_BORN=1)
      INCLUDE 'coupl.inc'
      REAL*8, ALLOCATABLE :: ANS(:,:),ACC(:)
      REAL*8 BOOT(0:3,NEXTERNAL),POINT(0:3,NEXTERNAL)
      REAL*8 P(0:3,NEXTERNAL),TOTAL(0:3),COLD,ELAPSED
      INTEGER NDIM,NSO,MODE,POINT_ID,TRACE_ON,CODE,BOOT_CODE
      INTEGER IOS,SEQUENCE,NLOOPS,BOOT_CALL
      INTEGER*8 T0,T1,RATE
      LOGICAL BOOT_RESTORED,MEASURE_RESTORED,IGNORED_RESTORED,DID_RUN
      CHARACTER*1024 ARG
      CHARACTER*16 COMMAND

      IF(COMMAND_ARGUMENT_COUNT().NE.6) STOP 21
      CALL GET_COMMAND_ARGUMENT(1,ARG)
      CALL KTRACE_READ_POINT(TRIM(ARG),NEXTERNAL,BOOT)
      CALL GET_COMMAND_ARGUMENT(2,ARG)
      CALL KTRACE_READ_POINT(TRIM(ARG),NEXTERNAL,POINT)
      CALL GET_COMMAND_ARGUMENT(3,ARG)
      IF(TRIM(ARG).NE.'1'.AND.TRIM(ARG).NE.'4') STOP 21
      READ(ARG,*) MODE
      CALL GET_COMMAND_ARGUMENT(4,ARG)
      IF(LEN_TRIM(ARG).EQ.0) STOP 21
      IF(VERIFY(TRIM(ARG),'0123456789').NE.0) STOP 21
      READ(ARG,*,IOSTAT=IOS) POINT_ID
      IF(IOS.NE.0) STOP 21
      IF(POINT_ID.LT.1) STOP 21
      CALL GET_COMMAND_ARGUMENT(5,ARG)
      IF(TRIM(ARG).NE.'0'.AND.TRIM(ARG).NE.'1') STOP 21
      READ(ARG,*) TRACE_ON
      CALL GET_COMMAND_ARGUMENT(6,ARG)
      OPEN(74,FILE=TRIM(ARG),STATUS='OLD',ACTION='WRITE')

      CALL SETPARA('param_card.dat')
      CALL ML5_0_GET_ANSWER_DIMENSION(NDIM)
      CALL ML5_0_GET_NSQSO_LOOP(NSO)
      IF(NDIM.NE.MAX(NSO,NSQSO_BORN)) STOP 22
      OPEN(73,FILE='dimensions.dat',STATUS='REPLACE')
      WRITE(73,*) NDIM,NSO,NSQSO_BORN
      CLOSE(73)
      ALLOCATE(ANS(0:3,0:NDIM),ACC(0:NSO))
      OPEN(75,FILE='bootstrap-values.dat',STATUS='REPLACE')
      WRITE(75,'(A)')
     $ '# call point order code Born finite single double accuracy'
      OPEN(76,FILE='trace.dat',STATUS='REPLACE')
      OPEN(77,FILE='driver-state.dat',STATUS='REPLACE')
      WRITE(77,'(A)')
     $ '# STATE stage phase call point requested-mode code'
      WRITE(77,'(A)') '# then actual-mode (-999 before/unknown return)'
      WRITE(77,'(A)') '# then CHECKPHASE HELDOUBLECHECKED FPEdp FPEqp'
      WRITE(77,'(A)') '# as 0/1 and four exact native logical words'
      WRITE(77,'(A)') '# INIT flags are restored, not effective state'
      OPEN(78,FILE='driver-bits.dat',STATUS='REPLACE')
      WRITE(78,'(A)') '# phase call point order code then ANS(0:3),ACC'
      WRITE(78,'(A)') '# five exact IEEE-binary64 words per row'
      OPEN(79,FILE='qualification.dat',STATUS='REPLACE')
      WRITE(79,'(A)') 'NATIVE_QUALIFICATION_PENDING'
      WRITE(79,'(A)') 'RESTORED_STATE_IS_NOT_EFFECTIVE_CALL_STATE'
      CALL KTRACE_DRIVER_CONTROL(.FALSE.,76,0)
C     The diagnostic policy avoids a forced second call. Pole mode zero
C     retains MadLoop's existing temporary full-sum bypass unchanged.
      CALL ML5_0_FORCE_STABILITY_CHECK(.FALSE.)
      CALL SYSTEM_CLOCK(T0,RATE)
      IF(RATE.LE.0) STOP 23
      BOOT_CALL=1
         P=BOOT
         TOTAL=P(:,1)+P(:,2)
         MU_R=SQRT(ABS(TOTAL(0)**2-SUM(TOTAL(1:3)**2)))
         CALL UPDATE_AS_PARAM()
         ANS=0D0
         ACC=-1D0
         CODE=-987654321
         CALL KTRACE_DRIVER_STATE(77,0,BOOT_CALL,1,MODE,'B',CODE,
     $        IGNORED_RESTORED)
         CALL ML5_0_SLOOPMATRIX_THRES(P,ANS,-1D0,ACC,CODE)
         BOOT_CODE=CODE
         CALL KTRACE_DRIVER_STATE(77,0,BOOT_CALL,1,MODE,'A',CODE,
     $        BOOT_RESTORED)
         CALL KTRACE_DRIVER_VALUES(75,78,0,BOOT_CALL,1,NDIM,NSO,
     $        CODE,ANS,ACC)
         CALL KTRACE_DRIVER_CARD(MODE)
         WRITE(79,'(A,4I12)') 'BOOTSTRAP_RESTORED_STATE ',
     $        BOOT_CALL,BOOT_CODE,MERGE(1,0,BOOT_RESTORED),MODE
         FLUSH(79)
      CALL SYSTEM_CLOCK(T1)
      COLD=DBLE(T1-T0)/DBLE(RATE)
      CLOSE(75)
      WRITE(74,'(A,5I12,ES26.17E3)') 'READY ',1,1,
     $ NDIM,NSO,NSQSO_BORN,COLD
      FLUSH(74)
      DID_RUN=.FALSE.

 100  CONTINUE
      READ(5,*,IOSTAT=IOS) COMMAND,SEQUENCE,NLOOPS
      IF(IOS.LT.0) GOTO 900
      IF(IOS.NE.0) GOTO 800
      IF(TRIM(COMMAND).EQ.'STOP') GOTO 900
      IF(TRIM(COMMAND).NE.'RUN') GOTO 800
      IF(DID_RUN.OR.SEQUENCE.NE.1.OR.NLOOPS.NE.1) GOTO 800
      DID_RUN=.TRUE.
      CALL KTRACE_DRIVER_CARD(MODE)
      P=POINT
      TOTAL=P(:,1)+P(:,2)
      MU_R=SQRT(ABS(TOTAL(0)**2-SUM(TOTAL(1:3)**2)))
      CALL UPDATE_AS_PARAM()
      ANS=0D0
      ACC=-1D0
      CODE=-987654321
      CALL KTRACE_DRIVER_STATE(77,1,2,POINT_ID,MODE,'B',CODE,
     $ IGNORED_RESTORED)
      CALL KTRACE_DRIVER_CONTROL(TRACE_ON.EQ.1,76,POINT_ID)
      CALL SYSTEM_CLOCK(T0)
      CALL ML5_0_SLOOPMATRIX_THRES(P,ANS,-1D0,ACC,CODE)
      CALL SYSTEM_CLOCK(T1)
      CALL KTRACE_DRIVER_CONTROL(.FALSE.,76,0)
      ELAPSED=DBLE(T1-T0)/DBLE(RATE)
      CALL KTRACE_DRIVER_STATE(77,1,2,POINT_ID,MODE,'A',CODE,
     $ MEASURE_RESTORED)
      OPEN(73,FILE='values.dat',STATUS='REPLACE')
C     values.dat preserves the retained Worker's single-point row index.
C     driver-bits.dat records the saved scientific point ID separately.
      CALL KTRACE_DRIVER_VALUES(73,78,1,2,POINT_ID,NDIM,NSO,
     $ CODE,ANS,ACC)
      CLOSE(73)
      WRITE(79,'(A,3I12)') 'MEASUREMENT_RESTORED_STATE ',CODE,
     $ MERGE(1,0,MEASURE_RESTORED),MODE
      WRITE(79,'(A)') 'STATUS_ALONE_IS_NOT_NUMERICAL_VALIDATION'
      FLUSH(79)
      OPEN(73,FILE='timing.dat',STATUS='REPLACE')
      WRITE(73,'(2ES26.17E3)') COLD,ELAPSED
      CLOSE(73)
      OPEN(73,FILE='timed_status.dat',STATUS='REPLACE')
      WRITE(73,'(I12,1X,I20)') CODE,1_8
      CLOSE(73)
      WRITE(74,'(A,2I12)') 'DONE ',SEQUENCE,NLOOPS
      FLUSH(74)
      GOTO 100

 800  CONTINUE
      WRITE(74,'(A)') 'ERROR invalid-command'
      FLUSH(74)
      CALL KTRACE_DRIVER_CONTROL(.FALSE.,76,0)
      CALL ML5_0_EXIT_MADLOOP()
      STOP 28
 900  CONTINUE
      CALL KTRACE_DRIVER_CONTROL(.FALSE.,76,0)
      CALL ML5_0_EXIT_MADLOOP()
      WRITE(74,'(A)') 'BYE'
      FLUSH(74)
      CLOSE(74)
      CLOSE(76)
      CLOSE(77)
      CLOSE(78)
      CLOSE(79)
      END

      SUBROUTINE KTRACE_DRIVER_CONTROL(ENABLED,LUN,POINT)
      IMPLICIT NONE
      LOGICAL ENABLED
      INTEGER LUN,POINT
C     Instrumented: CALL ML5_0_PRIVATE_KTRACE_SET(LUN,POINT,ENABLED)
C     Unmodified: CONTINUE. Neither branch evaluates an amplitude.
      CONTINUE
      END

      SUBROUTINE KTRACE_DRIVER_CARD(MODE)
      IMPLICIT NONE
      INTEGER MODE
      INCLUDE 'MadLoopParams.inc'
      IF(CTMODEINIT.NE.1.OR.CTMODERUN.NE.MODE.OR.
     $ MLReductionLib(1).NE.9.OR.MLReductionLib(2).NE.0)
     $ STOP 24
      IF(LoopPoleMode.NE.0) STOP 24
      IF(.NOT.UseQPIntegrandForTIRust) STOP 24
      IF(.NOT.TIRustComputeFinite.OR.TIRustGlobalCache.NE.0)
     $ STOP 24
      END

      SUBROUTINE KTRACE_DRIVER_STATE(LUN,PHASE,CALL_INDEX,POINT,
     $ MODE,STAGE,CODE,RESTORED_READY)
      IMPLICIT NONE
      INTEGER LUN,PHASE,CALL_INDEX,POINT,MODE,CODE,ACTUAL_MODE
      CHARACTER*1 STAGE
      LOGICAL RESTORED_READY,CHECKPHASE,HELDOUBLECHECKED
      LOGICAL FPE_IN_DP_REDUCTION,FPE_IN_QP_REDUCTION
      REAL*8 LSCALE
      INTEGER CTMODE
      COMMON/ML5_0_CT/LSCALE,CTMODE
      COMMON/ML5_0_INIT/CHECKPHASE,HELDOUBLECHECKED
      COMMON/ML5_0_FPE_IN_REDUCTION/FPE_IN_DP_REDUCTION,
     $ FPE_IN_QP_REDUCTION
C     These four logicals have DATA initialization in the pinned matrix.
C     Read only: do not reset them or touch potentially failed tensors.
      IF(STORAGE_SIZE(CHECKPHASE).NE.32) STOP 25
      IF(STORAGE_SIZE(HELDOUBLECHECKED).NE.32) STOP 25
      IF(STORAGE_SIZE(FPE_IN_DP_REDUCTION).NE.32) STOP 25
      IF(STORAGE_SIZE(FPE_IN_QP_REDUCTION).NE.32) STOP 25
      RESTORED_READY=.NOT.CHECKPHASE.AND.HELDOUBLECHECKED
      ACTUAL_MODE=-999
C     The admitted pole-mode-zero full-sum path assigns CTMODE before
C     returning an unchecked fixed-mode code. INIT has then been restored.
C     Never read CTMODE before a call or after an unknown return code.
      IF(STAGE.EQ.'A'.AND.(CODE.EQ.110.OR.CODE.EQ.120))
     $ ACTUAL_MODE=CTMODE
      WRITE(LUN,'(A,1X,A,6I12,4I3,4(1X,Z8.8))')
     $ 'STATE',STAGE,PHASE,CALL_INDEX,POINT,MODE,CODE,ACTUAL_MODE,
     $ MERGE(1,0,CHECKPHASE),MERGE(1,0,HELDOUBLECHECKED),
     $ MERGE(1,0,FPE_IN_DP_REDUCTION),MERGE(1,0,FPE_IN_QP_REDUCTION),
     $ TRANSFER(CHECKPHASE,0),TRANSFER(HELDOUBLECHECKED,0),
     $ TRANSFER(FPE_IN_DP_REDUCTION,0),TRANSFER(FPE_IN_QP_REDUCTION,0)
      FLUSH(LUN)
      END

      SUBROUTINE KTRACE_DRIVER_VALUES(LUN,BITS,PHASE,CALL_INDEX,
     $ POINT,NDIM,NSO,CODE,ANS,ACC)
      IMPLICIT NONE
      INTEGER LUN,BITS,PHASE,CALL_INDEX,POINT,NDIM,NSO,CODE,J
      REAL*8 ANS(0:3,0:NDIM),ACC(0:NSO),ESTIMATE
      IF(STORAGE_SIZE(ANS(0,0)).NE.64) STOP 25
      DO J=0,NDIM
         ESTIMATE=ACC(0)
         IF(J.LE.NSO) ESTIMATE=ACC(J)
         IF(PHASE.EQ.0) THEN
            WRITE(LUN,'(4I12,5ES26.17E3)') CALL_INDEX,1,J,CODE,
     $           ANS(:,J),ESTIMATE
         ELSE
            WRITE(LUN,'(3I8,5ES26.17E3)') 1,J,CODE,ANS(:,J),ESTIMATE
         ENDIF
         WRITE(BITS,'(5I12,5(1X,Z16.16))') PHASE,CALL_INDEX,POINT,J,
     $        CODE,
     $        TRANSFER(ANS(:,J),0_8,4),TRANSFER(ESTIMATE,0_8)
      ENDDO
      FLUSH(LUN)
      FLUSH(BITS)
      END

      SUBROUTINE KTRACE_READ_POINT(PATH,NEXTERNAL,P)
      USE, INTRINSIC :: ISO_FORTRAN_ENV, ONLY: IOSTAT_END,
     $ IOSTAT_EOR
      IMPLICIT NONE
      CHARACTER*(*) PATH
      INTEGER NEXTERNAL,IOS,NREAD,I,J,NTOKENS
      REAL*8 P(0:3,NEXTERNAL)
      CHARACTER*1024 LINE
      LOGICAL IN_TOKEN
      INTEGER*8 WORD,EXP_MASK
      PARAMETER(EXP_MASK=INT(Z'7FF0000000000000',8))
      OPEN(73,FILE=PATH,STATUS='OLD',ACTION='READ',IOSTAT=IOS)
      IF(IOS.NE.0) STOP 26
      READ(73,'(A)',ADVANCE='NO',SIZE=NREAD,IOSTAT=IOS) LINE
      IF(IOS.NE.IOSTAT_EOR) STOP 26
      IF(TRIM(ADJUSTL(LINE)).NE.'1') STOP 26
      DO I=1,NEXTERNAL
         READ(73,'(A)',ADVANCE='NO',SIZE=NREAD,IOSTAT=IOS) LINE
         IF(IOS.NE.IOSTAT_EOR) STOP 26
C        Pinned point files use four whitespace-separated finite numbers.
C        Reject commas, repeat/slash syntax and ignored extra tokens.
         NTOKENS=0
         IN_TOKEN=.FALSE.
         DO J=1,LEN_TRIM(LINE)
            IF(LINE(J:J).EQ.' '.OR.LINE(J:J).EQ.ACHAR(9)) THEN
               IN_TOKEN=.FALSE.
            ELSE
               IF(VERIFY(LINE(J:J),'0123456789+-.EeDd').NE.0)
     $              STOP 26
               IF(.NOT.IN_TOKEN) NTOKENS=NTOKENS+1
               IN_TOKEN=.TRUE.
            ENDIF
         ENDDO
         IF(NTOKENS.NE.4) STOP 26
         READ(LINE,*,IOSTAT=IOS) P(:,I)
         IF(IOS.NE.0) STOP 26
         DO J=0,3
            WORD=TRANSFER(P(J,I),0_8)
            IF(IAND(WORD,EXP_MASK).EQ.EXP_MASK) STOP 26
         ENDDO
      ENDDO
 200  CONTINUE
      READ(73,'(A)',ADVANCE='NO',SIZE=NREAD,IOSTAT=IOS) LINE
      IF(IOS.EQ.IOSTAT_END) THEN
         CLOSE(73)
         RETURN
      ENDIF
      IF(IOS.NE.IOSTAT_EOR) STOP 26
      IF(LEN_TRIM(LINE).NE.0) STOP 26
      GOTO 200
      END
