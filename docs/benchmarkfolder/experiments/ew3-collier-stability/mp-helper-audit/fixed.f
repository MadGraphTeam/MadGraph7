        COMPLEX*32 FUNCTION FIX_MP_GRREGLOG(LOGSW,EXPR1_IN,EXPR2_IN)
        IMPLICIT NONE
        COMPLEX*32 TWOPII
        PARAMETER (TWOPII=2.0E0_16
     $   *3.14159265358979323846264338327950288E0_16*(0.0E0_16
     $   ,1.0E0_16))
        COMPLEX*32 EXPR1_IN,EXPR2_IN
        COMPLEX*32 EXPR1,EXPR2
        REAL*16 LOGSW
        REAL*16 IMAGEXPR
        LOGICAL FIRSTSHEET
        EXPR1=EXPR1_IN
        EXPR2=EXPR2_IN
        IF(ABS(IMAGPART(EXPR1)).EQ.0.0E0_16)THEN
          EXPR1=CMPLX(REAL(EXPR1,KIND=16),0.0E0_16,KIND=16)
        ENDIF
        IF(ABS(REAL(EXPR1,KIND=16)).EQ.0.0E0_16)THEN
          EXPR1=CMPLX(0.0E0_16,IMAGPART(EXPR1),KIND=16)
        ENDIF
        IF(ABS(IMAGPART(EXPR2)).EQ.0.0E0_16)THEN
          EXPR2=CMPLX(REAL(EXPR2,KIND=16),0.0E0_16,KIND=16)
        ENDIF
        IF(ABS(REAL(EXPR2,KIND=16)).EQ.0.0E0_16)THEN
          EXPR2=CMPLX(0.0E0_16,IMAGPART(EXPR2),KIND=16)
        ENDIF
        IF(EXPR1.EQ.(0.0E0_16,0.0E0_16))THEN
          FIX_MP_GRREGLOG=(0.0E0_16,0.0E0_16)
        ELSE
          IMAGEXPR=IMAGPART(EXPR1)*IMAGPART(EXPR2)
          FIRSTSHEET=IMAGEXPR.GE.0.0E0_16
          FIRSTSHEET=FIRSTSHEET.OR.REAL(EXPR1,KIND=16).GE.0.0E0_16
          FIRSTSHEET=FIRSTSHEET.OR.REAL(EXPR2,KIND=16).GE.0.0E0_16
          IF(FIRSTSHEET)THEN
            FIX_MP_GRREGLOG=LOG(EXPR1)
          ELSE
            IF(IMAGPART(EXPR1).GT.0.0E0_16)THEN
              FIX_MP_GRREGLOG=LOG(EXPR1) - LOGSW*TWOPII
            ELSE
              FIX_MP_GRREGLOG=LOG(EXPR1) + LOGSW*TWOPII
            ENDIF
          ENDIF
        ENDIF
        END

