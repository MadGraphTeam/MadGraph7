      PROGRAM BENCHMARK_MADLOOP
      IMPLICIT NONE
      INTEGER TEST_SCENARIO,TEST_REBUILDS,TEST_DP,TEST_QP
      COMMON/ML5_0_RETRY_TEST/TEST_SCENARIO,TEST_REBUILDS,
     $ TEST_DP,TEST_QP
      LOGICAL NRS_RETRY_MODE,NRS_RETRY_USED
      INTEGER NRS_RETRY_COUNT,NRS_RETRY_PASS,NRS_RETRY_FAIL
      INTEGER NRS_RETRY_HARD_SKIP
      REAL*8 NRS_NATIVE_ACC,NRS_COMP_ACC
      COMMON/ML5_0_NRS_RETRY_FLAGS/NRS_RETRY_MODE,NRS_RETRY_USED
      COMMON/ML5_0_NRS_RETRY_STATS/NRS_RETRY_COUNT,NRS_RETRY_PASS,
     $ NRS_RETRY_FAIL,NRS_RETRY_HARD_SKIP
      COMMON/ML5_0_NRS_RETRY_ACC/NRS_NATIVE_ACC,NRS_COMP_ACC
      INTEGER NEXTERNAL
      PARAMETER(NEXTERNAL=3)
      INCLUDE 'coupl.inc'
      INTEGER NSQSO_BORN
      PARAMETER(NSQSO_BORN=1)
      REAL*8 ZERO
      PARAMETER(ZERO=0D0)
      REAL*8 PMASS(NEXTERNAL)
      REAL*8, ALLOCATABLE :: POINTS(:,:,:),ANS(:,:),ACC(:)
      REAL*8, ALLOCATABLE :: VALUES(:,:,:),ACCURACIES(:,:)
      INTEGER, ALLOCATABLE :: CODES(:)
      REAL*8 P(0:3,NEXTERNAL),TOTAL(0:3),COLD,ELAPSED
      INTEGER NPOINTS,NDIM,NSO,I,J,K,L,NLOOPS,CODE
      INTEGER TENS,WARM_POINTS
      INTEGER*8 TIMED_CODES(0:499)
      INTEGER*8 T0,T1,RATE
      CHARACTER*1024 ARG
      INTEGER SCENARIOS(6),IDX
      DATA SCENARIOS/1,0,3,0,2,0/

      TEST_SCENARIO=0
      CALL SETPARA('param_card.dat')
      INCLUDE 'pmass.inc'
      CALL ML5_0_GET_ANSWER_DIMENSION(NDIM)
      CALL ML5_0_GET_NSQSO_LOOP(NSO)
      OPEN(73,FILE='dimensions.dat',STATUS='REPLACE')
      WRITE(73,*) NDIM,NSO,NSQSO_BORN
      CLOSE(73)
      CALL GET_COMMAND_ARGUMENT(1,ARG)
      IF(TRIM(ARG).EQ.'--masses') THEN
         OPEN(73,FILE='masses.dat',STATUS='REPLACE')
         WRITE(73,'(ES26.17E3)') PMASS
         CLOSE(73)
         STOP
      ENDIF
      OPEN(73,FILE=TRIM(ARG),STATUS='OLD')
      READ(73,*) NPOINTS
      IF(NPOINTS.LE.0) STOP 1
      ALLOCATE(POINTS(0:3,NEXTERNAL,NPOINTS))
      DO K=1,NPOINTS
         DO I=1,NEXTERNAL
            READ(73,*) POINTS(:,I,K)
         ENDDO
      ENDDO
      CLOSE(73)
      CALL GET_COMMAND_ARGUMENT(2,ARG)
      READ(ARG,*) NLOOPS
      IF(NLOOPS.LE.0) STOP 2
      ALLOCATE(ANS(0:3,0:NDIM),ACC(0:NSO))
      ALLOCATE(VALUES(0:3,0:NDIM,NPOINTS))
      ALLOCATE(ACCURACIES(0:NSO,NPOINTS),CODES(NPOINTS))
      ANS=0D0
      VALUES=0D0
      TIMED_CODES=0
      CALL ML5_0_FORCE_STABILITY_CHECK(.TRUE.)
      P=POINTS(:,:,1)
      TOTAL=P(:,1)+P(:,2)
      MU_R=SQRT(ABS(TOTAL(0)**2-SUM(TOTAL(1:3)**2)))
      CALL UPDATE_AS_PARAM()
      CALL SYSTEM_CLOCK(T0,RATE)
      CALL ML5_0_SLOOPMATRIX_THRES(P,ANS,-1D0,ACC,CODE)
C     Wait for a full warm pass after helicity initialization finishes.
      WARM_POINTS=0
      DO K=1,1000+NPOINTS
         P=POINTS(:,:,1+MOD(K-1,NPOINTS))
         TOTAL=P(:,1)+P(:,2)
         MU_R=SQRT(ABS(TOTAL(0)**2-SUM(TOTAL(1:3)**2)))
         CALL UPDATE_AS_PARAM()
         CALL ML5_0_SLOOPMATRIX_THRES(P,ANS,-1D0,ACC,CODE)
         TENS=MOD(CODE,100)/10
         IF(TENS.EQ.1.OR.TENS.EQ.2) THEN
            WARM_POINTS=WARM_POINTS+1
         ELSE
            WARM_POINTS=0
         ENDIF
         IF(WARM_POINTS.GE.NPOINTS) EXIT
      ENDDO
      IF(WARM_POINTS.LT.NPOINTS) STOP 3
      CALL SYSTEM_CLOCK(T1)
      COLD=DBLE(T1-T0)/DBLE(RATE)
      OPEN(74,FILE='mock-flow.dat',STATUS='REPLACE')
      DO IDX=1,6
        TEST_SCENARIO=SCENARIOS(IDX)
        P=POINTS(:,:,1)
        TOTAL=P(:,1)+P(:,2)
        MU_R=SQRT(ABS(TOTAL(0)**2-SUM(TOTAL(1:3)**2)))
        CALL UPDATE_AS_PARAM()
        CALL ML5_0_SLOOPMATRIX_THRES(P,ANS,-1D0,ACC,CODE)
        WRITE(74,'(9I8,2L3,2ES26.17E3)') TEST_SCENARIO,CODE,
     $   NRS_RETRY_COUNT,NRS_RETRY_PASS,NRS_RETRY_FAIL,
     $   NRS_RETRY_HARD_SKIP,TEST_REBUILDS,TEST_DP,TEST_QP,
     $   NRS_RETRY_MODE,NRS_RETRY_USED,NRS_NATIVE_ACC,NRS_COMP_ACC
        IF(NRS_RETRY_MODE) STOP 91
      ENDDO
      CLOSE(74)
      END
