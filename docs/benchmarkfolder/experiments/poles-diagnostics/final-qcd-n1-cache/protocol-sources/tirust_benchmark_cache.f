C     Generated-adapter cache diagnostic. Never contracts an amplitude.
      PROGRAM TIRUST_CACHE_DIAGNOSTIC
      USE MTIRUST, ONLY: TIRUST_CACHE_STATISTICS,
     $ TIRUST_QP_CACHE_STATISTICS,TIRUST_CONTEXT_GENERATION,
     $ TIRUST_SET_CACHE_BUDGET,TIRUST_SUCCESS
      USE, INTRINSIC :: ISO_C_BINDING, ONLY: C_INT64_T
      IMPLICIT NONE
      INCLUDE 'coupl.inc'
      INCLUDE 'MadLoopParams.inc'
      INCLUDE 'loop_max_coefs.inc'
      INTEGER N,R,NC,I,J,NRECORDS,ID,CTMODE,MODE,FINITE
      INTEGER CACHE,CONTROL,GENBEFORE,GENAFTER,STATUS
      INTEGER(C_INT64_T) BUDGET,BEFORE(9),AFTER(9),QB(6),QA(6)
      REAL*8 SHIFTS(0:3,6),PL0(0:3,6),PL(0:3,6),MU2,MR,MI
      REAL*16 QPL(0:3,6),RESULT(6)
      COMPLEX*16 MASSES0(6),MASSES(6),COEFS(0:LOOPMAXCOEFS-1,3)
      COMPLEX*32 QCOEFS(0:LOOPMAXCOEFS-1,3)
      LOGICAL STABLE
      CHARACTER*1024 ARG
      CALL SETPARA('param_card.dat')
      CALL DEFAULTPARAM()
      MLReductionLib=0
      MLReductionLib(1)=9
      CALL GET_COMMAND_ARGUMENT(1,ARG)
      OPEN(71,FILE=TRIM(ARG),STATUS='OLD')
      OPEN(72,FILE='cache-values.dat',STATUS='REPLACE')
      READ(71,*) N,R,MU2,NRECORDS
      IF(N.LT.1.OR.N.GT.6.OR.R.LT.0.OR.R.GT.6) STOP 2
      NC=(R+1)*(R+2)*(R+3)*(R+4)/24
      IF(NC.GT.LOOPMAXCOEFS) STOP 3
      DO I=1,N
        READ(71,*) SHIFTS(:,I)
      ENDDO
      DO I=1,N
        READ(71,*) MR,MI
        MASSES0(I)=CMPLX(MR,MI,KIND=8)
      ENDDO
      PL0=0D0
      DO I=1,N-1
        PL0(:,I)=SHIFTS(:,I+1)-SHIFTS(:,I)
      ENDDO
      PL0(:,N)=SHIFTS(:,1)-SHIFTS(:,N)
      MU_R=SQRT(MU2)
      CALL UPDATE_AS_PARAM()
      DO ID=1,NRECORDS
        READ(71,*) CTMODE,MODE,FINITE,CACHE,BUDGET,CONTROL
        LoopPoleMode=MODE
        TIRustComputeFinite=FINITE.EQ.1
        TIRustGlobalCache=CACHE
        TIRustCacheMaxBytes=BUDGET
        IF(CONTROL.EQ.1) CALL @PREFIX@CLEAR_TIRUST_CACHE()
        IF(CONTROL.EQ.2) CALL @PREFIX@FINALIZE_TIRUST()
        IF(CONTROL.EQ.3) THEN
          CALL TIRUST_SET_CACHE_BUDGET(BUDGET,STATUS)
          IF(STATUS.NE.TIRUST_SUCCESS) STOP 4
        ENDIF
        GENBEFORE=TIRUST_CONTEXT_GENERATION()
C       Statistics access initializes a context. Avoid it after finalization
C       so that this call tests the generated adapter's reinitialization.
        BEFORE=0
        QB=0
        IF(GENBEFORE.NE.-1) THEN
          CALL TIRUST_CACHE_STATISTICS(BEFORE,STATUS)
          IF(STATUS.NE.TIRUST_SUCCESS) STOP 5
          CALL TIRUST_QP_CACHE_STATISTICS(QB,STATUS)
          IF(STATUS.NE.TIRUST_SUCCESS) STOP 6
        ENDIF
        PL=PL0
        QPL=REAL(PL0,KIND=16)
        MASSES=MASSES0
        COEFS=0
        QCOEFS=0
        IF(CTMODE.EQ.1.OR.CTMODE.EQ.2) THEN
          CALL @PREFIX@TIRUST_TENSOR_DIAGNOSTIC(CTMODE,N,R,PL,MASSES,COEFS,STABLE)
          QCOEFS=COEFS
        ELSE IF(CTMODE.EQ.4.OR.CTMODE.EQ.5) THEN
          CALL @PREFIX@MP_TIRUST_TENSOR_DIAGNOSTIC(CTMODE,N,R,QPL,MASSES,QCOEFS,STABLE)
        ELSE
          STOP 7
        ENDIF
        GENAFTER=TIRUST_CONTEXT_GENERATION()
        CALL TIRUST_CACHE_STATISTICS(AFTER,STATUS)
        IF(STATUS.NE.TIRUST_SUCCESS) STOP 8
        CALL TIRUST_QP_CACHE_STATISTICS(QA,STATUS)
        IF(STATUS.NE.TIRUST_SUCCESS) STOP 9
        WRITE(72,'(A,8I14,L3,2I14)') 'F ',ID,CTMODE,MODE,FINITE,CACHE,BUDGET,CONTROL,NC,STABLE,GENBEFORE,GENAFTER
        WRITE(72,'(A,16I20)') 'B ',ID,BEFORE,QB
        WRITE(72,'(A,16I20)') 'A ',ID,AFTER,QA
        IF(STABLE) THEN
          DO I=0,NC-1
            DO J=1,3
              RESULT(2*J-1)=REAL(QCOEFS(I,J),KIND=16)
              RESULT(2*J)=AIMAG(QCOEFS(I,J))
            ENDDO
            WRITE(72,'(A,2I8,6ES46.35E4)') 'C ',ID,I,RESULT
          ENDDO
        ENDIF
        FLUSH(72)
      ENDDO
      CLOSE(71)
      CLOSE(72)
      CALL @PREFIX@FINALIZE_TIRUST()
      END
