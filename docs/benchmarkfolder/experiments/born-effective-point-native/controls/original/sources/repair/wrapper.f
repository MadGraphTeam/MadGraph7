      SUBROUTINE RX_MP_IMPROVE_PS_POINT_PRECISION_CHECKED(KEEP_OFFSHELL
     $_MASS, P, ERR_PRIMARY, ERR_ALTERNATE, OUTCOME, ADOPTED)
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=5)
C     
C     ARGUMENTS 
C     
      REAL*16 P(0:3,NEXTERNAL)
      LOGICAL KEEP_OFFSHELL_MASS(NEXTERNAL)
C     CHECKED-REPORT-BEGIN DECLARATIONS
      INTEGER ERR_PRIMARY, ERR_ALTERNATE, OUTCOME
      LOGICAL ADOPTED
C     CHECKED-REPORT-END DECLARATIONS
C     
C     LOCAL VARIABLES 
C     
      INTEGER I,J
      INTEGER ERRCODE,ERRCODETMP
      REAL*16 NEWP(0:3,NEXTERNAL)
C     
C     FUNCTIONS
C     
      LOGICAL RX_MP_IS_PHYSICAL
C     
C     SAVED VARIABLES
C     
      INCLUDE 'MadLoopParams.inc'
C     
C     SAVED VARIABLES
C     
      INTEGER WARNED
      DATA WARNED/0/

      LOGICAL TOLD_SUPPRESS
      DATA TOLD_SUPPRESS/.FALSE./
C     ----------
C     BEGIN CODE
C     ----------

C     ERROR CODES CONVENTION
C     
C     1         ::  Nonphysical PS point input
C     100-1000  ::  Error in the original method for restoring
C      precision
C     1000-9999 ::  Error when restoring precision ala PSMC
C     
C     CHECKED-REPORT-BEGIN INITIAL_STATE
      ADOPTED=.FALSE.
      OUTCOME=0
C     CHECKED-REPORT-END INITIAL_STATE
      ERRCODETMP=0
      ERRCODE=0

      DO J=1,NEXTERNAL
        DO I=0,3
          NEWP(I,J)=P(I,J)
        ENDDO
      ENDDO

C     CHECKED-REPORT-BEGIN SUPPORTED_METHOD
C     The legacy >2 branch invokes no numerical repair method.
C     The checked entry must not certify that no-op as a repair.
      IF (IMPROVEPSPOINT.GT.2) THEN
        OUTCOME=-3
        GOTO 102
      ENDIF
C     CHECKED-REPORT-END SUPPORTED_METHOD
C     Check the sanity of the original PS point
      IF (.NOT.RX_MP_IS_PHYSICAL(NEWP,WARNED)) THEN
        ERRCODE = 1
C       CHECKED-REPORT-BEGIN INPUT_REJECTED
        OUTCOME=-1
C       CHECKED-REPORT-END INPUT_REJECTED
        WRITE(*,*) 'ERROR:: The input PS point is not precise enough.'
        GOTO 100
      ENDIF

C     Now restore the precision
      IF (IMPROVEPSPOINT.EQ.1) THEN
        CALL RX_MP_PSMC_IMPROVE_PS_POINT_PRECISION(NEWP,ERRCODE,WARNED)
      ELSEIF((IMPROVEPSPOINT.EQ.2).OR.(IMPROVEPSPOINT.LE.0)) THEN
        CALL RX_MP_ORIG_IMPROVE_PS_POINT_PRECISION(NEWP,ERRCODE,WARNED)
      ENDIF
C     CHECKED-REPORT-BEGIN PRIMARY_COMPLETED
      OUTCOME=1
C     CHECKED-REPORT-END PRIMARY_COMPLETED
      IF (ERRCODE.NE.0) THEN
        IF (WARNED.LT.20) THEN
          WRITE(*,*) 'INFO:: Attempting to rescue the precision'
     $     //' improvement with an alternative method.'
          WARNED=WARNED+1
        ENDIF
        IF (IMPROVEPSPOINT.EQ.1) THEN
          CALL RX_MP_ORIG_IMPROVE_PS_POINT_PRECISION(NEWP,ERRCODETMP
     $     ,WARNED)
        ELSEIF((IMPROVEPSPOINT.EQ.2).OR.(IMPROVEPSPOINT.LE.0)) THEN
          CALL RX_MP_PSMC_IMPROVE_PS_POINT_PRECISION(NEWP,ERRCODETMP
     $     ,WARNED)
        ENDIF
C       CHECKED-REPORT-BEGIN ALTERNATE_COMPLETED
        OUTCOME=-2
        IF (ERRCODETMP.EQ.0) OUTCOME=2
C       CHECKED-REPORT-END ALTERNATE_COMPLETED
        IF (ERRCODETMP.NE.0) GOTO 100
      ENDIF

C     Report to the user or update the PS point.

      GOTO 101
 100  CONTINUE
      IF (WARNED.LT.20) THEN
        WRITE(*,*) 'WARNING:: This PS point could not be improved.'
     $   //' Error code = ',ERRCODE,ERRCODETMP
        CALL RX_MP_WRITE_MOM(P)
        WARNED = WARNED +1
      ENDIF
      GOTO 102
 101  CONTINUE
      DO J=1,NEXTERNAL
        DO I=0,3
          P(I,J)=NEWP(I,J)
        ENDDO
      ENDDO
C     CHECKED-REPORT-BEGIN ADOPTED
      ADOPTED=.TRUE.
C     CHECKED-REPORT-END ADOPTED
 102  CONTINUE
C     CHECKED-REPORT-BEGIN RETURN_ERRORS
      ERR_PRIMARY=ERRCODE
      ERR_ALTERNATE=ERRCODETMP
C     CHECKED-REPORT-END RETURN_ERRORS

      IF (WARNED.GE.20.AND..NOT.TOLD_SUPPRESS) THEN
        WRITE(*,*) 'INFO:: Further warnings from the improve_ps'
     $   //' routine will now be suppressed.'
        TOLD_SUPPRESS=.TRUE.
      ENDIF

      END

C     CHECKED PREPARATION: algorithm outcome only, not an admission
C      certificate.
C     The caller owns finite/IEEE/conversion/Born checks before
C      publishing C128.
      SUBROUTINE RX_PREPARE_MP_PS_CHECKED(P_USER,C128,ERR_PRIMARY
     $ ,ERR_ALTERNATE,OUTCOME,ADOPTED)
      IMPLICIT NONE
      INTEGER NEXTERNAL
      PARAMETER (NEXTERNAL=5)
      REAL*8 P_USER(0:3,NEXTERNAL)
      REAL*16 C128(0:3,NEXTERNAL)
      INTEGER ERR_PRIMARY,ERR_ALTERNATE,OUTCOME
      LOGICAL ADOPTED
      REAL*16 P_LOCAL(0:3,NEXTERNAL)
      LOGICAL KEEP_OFFSHELL_MASS(NEXTERNAL)
      INTEGER I,J

      KEEP_OFFSHELL_MASS(1)=.FALSE.
      KEEP_OFFSHELL_MASS(2)=.FALSE.
      KEEP_OFFSHELL_MASS(3)=.FALSE.
      KEEP_OFFSHELL_MASS(4)=.FALSE.
      KEEP_OFFSHELL_MASS(5)=.FALSE.
      DO I=1,NEXTERNAL
        DO J=0,3
          P_LOCAL(J,I)=P_USER(J,I)
        ENDDO
      ENDDO
      CALL RX_MP_IMPROVE_PS_POINT_PRECISION_CHECKED(KEEP_OFFSHELL_MASS
     $ ,P_LOCAL,ERR_PRIMARY,ERR_ALTERNATE,OUTCOME,ADOPTED)
      IF (.NOT.ADOPTED) RETURN
      DO I=1,NEXTERNAL
        DO J=0,3
          C128(J,I)=P_LOCAL(J,I)
        ENDDO
      ENDDO
      END


