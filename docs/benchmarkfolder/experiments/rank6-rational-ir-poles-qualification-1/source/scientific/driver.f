C     Synthetic triangle tensor diagnostic only; no amplitude call.
      PROGRAM RANK6_IR_TRIANGLE
      USE MTIRUST
      USE,INTRINSIC::ISO_C_BINDING,ONLY:C_INT64_T
      IMPLICIT NONE
      INCLUDE 'coupl.inc'
      INCLUDE 'MadLoopParams.inc'
      INTEGER I,J,K,A,F,B,CT,MODE,FINITE,CACHE,BUDGET,CLR,N,R,NC
      INTEGER NSTEPS,STEP,IOS,STATUS,FLAG0,ROUND0,FLAG1,ROUND1
      INTEGER GEN0,GEN1,RP_HEALTH
      INTEGER*8 CPRE(9),QPRE(6),CPOST(9),QPOST(6)
      REAL*8 PL(0:3,3),PL0(0:3,3)
      REAL*16 QPL(0:3,3)
      COMPLEX*16 M2(3),CD(0:209,3)
      COMPLEX*32 CQ(0:209,3)
      LOGICAL STABLE
      CHARACTER*512 MESSAGE
      IF(DIGITS(1.0_16).NE.113) STOP 19
      OPEN(71,FILE='records.txt',STATUS='NEW')
      OPEN(73,FILE='errors.txt',STATUS='NEW')
      WRITE(71,*) 'HEADER',2,0,210
      CALL RP_OPEN()
      CALL RP_STATE(FLAG0,ROUND0)
      WRITE(71,*) 'INITIAL_IEEE',FLAG0,ROUND0
      CALL SETPARA('nominal/param_card.dat')
      CALL DEFAULTPARAM()
      MU_R=2D0
      CALL UPDATE_AS_PARAM()
      CALL RP_STATE(FLAG0,ROUND0)
      WRITE(71,*) 'MODEL_IEEE',FLAG0,ROUND0
      MLREDUCTIONLIB=0
      MLREDUCTIONLIB(1)=9
      TIRUSTGLOBALCACHE=0
      TIRUSTCOMPUTEFINITE=.TRUE.
      LOOPPOLEMODE=0
      CALL TIRUST_REGISTER_PLAN(2,6,STATUS)
      IF(STATUS.NE.0) STOP 20
      CALL TIRUST_REGISTER_PLAN(3,6,STATUS)
      IF(STATUS.NE.0) STOP 20
      PL0(:,1)=(/3D0,1D0,2D0,2D0/)
      PL0(:,2)=(/-3D0,1D0,-2D0,-2D0/)
      PL0(:,3)=(/0D0,-2D0,0D0,0D0/)
      OPEN(72,FILE='schedule.dat',STATUS='OLD')
      READ(72,*) NSTEPS
      IF(NSTEPS.NE.24) STOP 21
      DO STEP=1,NSTEPS
        READ(72,*) A,F,B,CT,MODE,FINITE,CACHE,BUDGET,CLR,N,R
        IF(B.NE.9.OR.R.NE.6) STOP 22
        IF(.NOT.((F.EQ.110.AND.N.EQ.3).OR.
     $   (F.EQ.111.AND.N.EQ.2))) STOP 25
        IF((CT.NE.1.AND.CT.NE.4).OR.CACHE.NE.0.OR.CLR.NE.1) STOP 23
        IF(MODE.LT.0.OR.MODE.GT.2.OR.FINITE.LT.0.OR.FINITE.GT.1) STOP 24
        NC=210
C       Always reset input arrays: adapters may reorder their arguments.
        PL=PL0
        IF(F.EQ.111) THEN
          PL(:,2)=-PL(:,1)
          PL(:,3)=0
        ENDIF
        QPL=REAL(PL,KIND=16)
        M2=CMPLX(0D0,0D0,KIND=8)
        MU_R=2D0
        LOOPPOLEMODE=MODE
        TIRUSTCOMPUTEFINITE=FINITE.EQ.1
        TIRUSTGLOBALCACHE=CACHE
        TIRUSTCACHEMAXBYTES=BUDGET
        CALL TIRUST_SET_CACHE_BUDGET(INT(BUDGET,C_INT64_T),STATUS)
        IF(STATUS.NE.0) STOP 12
        CALL TIRUST_CLEAR_CACHE(STATUS)
        IF(STATUS.NE.0) STOP 13
        CALL GET_STATS(CPRE,QPRE)
        WRITE(71,*) 'CASE',A,F,B,CT,MODE,FINITE,CACHE,BUDGET,CLR,N,R,NC
        WRITE(71,'(A,1X,Z16.16)') 'SCALE',TRANSFER(MU_R,0_8)
        CALL DUMP_INPUT('PI','MI',N,QPL,M2)
        WRITE(71,*) 'CACHE_PRE',CPRE,QPRE
        CALL RP_BEGIN(A)
        CALL RP_STATE(FLAG0,ROUND0)
        CQ=0
        CD=0
        STABLE=.FALSE.
        IF(CT.EQ.1) THEN
          CALL CAP6_TIRUST_TENSOR_DIAGNOSTIC(CT,N,R,PL,M2,CD,STABLE)
          CQ=CD
          QPL=REAL(PL,KIND=16)
        ELSE
          CALL CAP6_MP_TIRUST_TENSOR_DIAGNOSTIC(CT,N,R,QPL,M2,CQ,STABLE)
        ENDIF
        CALL RP_STATE(FLAG1,ROUND1)
        CALL TIRUST_ERROR_MESSAGE(MESSAGE)
        WRITE(73,'(A,2(1X,I0),512(1X,Z2.2))') 'ERROR',A,
     $   LEN_TRIM(MESSAGE),(IACHAR(MESSAGE(K:K)),K=1,512)
        FLUSH(73)
        WRITE(71,*) 'STATE',FLAG0,ROUND0,FLAG1,ROUND1,
     $   MERGE(1,0,STABLE),0,0
        CALL DUMP_INPUT('PO','MO',N,QPL,M2)
        CALL DUMP_VALUES(NC,CQ)
        CALL RP_FLUSH()
        CALL GET_STATS(CPOST,QPOST)
        WRITE(71,*) 'CACHE_POST',CPOST,QPOST
        WRITE(71,*) 'END',A,RP_HEALTH()
        FLUSH(71)
        IF(RP_HEALTH().NE.0) STOP 15
      ENDDO
      READ(72,*,IOSTAT=IOS) I
      IF(IOS.GE.0) STOP 16
      CLOSE(72)
      CLOSE(73)
      CALL TIRUST_CLEAR_CACHE(STATUS)
      IF(STATUS.NE.0) STOP 18
      CALL GET_STATS(CPOST,QPOST)
      GEN0=TIRUST_CONTEXT_GENERATION()
      CALL TIRUST_FINALIZE(STATUS)
      GEN1=TIRUST_CONTEXT_GENERATION()
      WRITE(71,*) 'FINAL',STATUS,GEN0,GEN1,CPOST,QPOST
      CALL RP_CLOSE()
      WRITE(71,*) 'DONE',RP_HEALTH()
      CLOSE(71)
      CONTAINS
      SUBROUTINE GET_STATS(C,Q)
      INTEGER*8 C(9),Q(6)
      INTEGER S1,S2
      CALL TIRUST_CACHE_STATISTICS(C,S1)
      CALL TIRUST_QP_CACHE_STATISTICS(Q,S2)
      IF(S1.NE.0.OR.S2.NE.0) STOP 17
      END SUBROUTINE
      SUBROUTINE DUMP_INPUT(PTAG,MTAG,NN,PP,MM)
      CHARACTER*(*) PTAG,MTAG
      INTEGER NN,L
      REAL*16 PP(0:3,NN)
      COMPLEX*16 MM(NN)
      DO L=1,NN
        WRITE(71,'(A,1X,I3,8(1X,Z16.16))') PTAG,L,
     $   TRANSFER(PP(:,L),(/0_8/))
        WRITE(71,'(A,1X,I3,4(1X,Z16.16))') MTAG,L,
     $   TRANSFER(CMPLX(MM(L),KIND=16),(/0_8/))
      ENDDO
      END SUBROUTINE
      SUBROUTINE DUMP_VALUES(NN,VV)
      INTEGER NN,L,SLOT
      COMPLEX*32 VV(0:209,3)
      DO L=0,NN-1
        DO SLOT=1,3
          WRITE(71,'(A,2I5,4(1X,Z16.16),2(1X,ES46.35E4))') 'V',L,SLOT,
     $     TRANSFER(VV(L,SLOT),(/0_8/)),REAL(VV(L,SLOT),KIND=16),
     $     AIMAG(VV(L,SLOT))
        ENDDO
      ENDDO
      END SUBROUTINE
      END
