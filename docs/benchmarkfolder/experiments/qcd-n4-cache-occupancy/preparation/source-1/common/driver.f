C     Private bounded diagnostic: exactly bootstrap0 and point1, then exit.
      PROGRAM CACHE_OCCUPANCY_POINT
      USE CACHE_OCCUPANCY_OBSERVER
      USE, INTRINSIC :: ISO_C_BINDING, ONLY: C_INT64_T
      IMPLICIT NONE
      INTEGER NEXTERNAL
      PARAMETER(NEXTERNAL=6)
      INCLUDE 'coupl.inc'
      REAL*8 P(0:3,NEXTERNAL),POINT(0:3,NEXTERNAL),TOTAL(0:3)
      REAL*8 ANS(0:3,0:1),ACC(0:1)
      INTEGER(C_INT64_T) INPUTS(25,0:1),OUTPUTS(8,0:1)
      INTEGER(C_INT64_T) INPUTS_AFTER(25,0:1)
      INTEGER(C_INT64_T) ACCURACIES(2,0:1),STATES(22,0:1)
      INTEGER CODES(0:1),I,K,COUNT,IOS,NDIM,NSO,UNIT
      CHARACTER*1024 ARG
      CALL OCC_SETUP()
      CALL SETPARA('param_card.dat')
      CALL ML5_0_GET_ANSWER_DIMENSION(NDIM)
      CALL ML5_0_GET_NSQSO_LOOP(NSO)
      IF(NDIM.NE.1.OR.NSO.NE.1) STOP 84
      CALL GET_COMMAND_ARGUMENT(1,ARG)
      OPEN(NEWUNIT=UNIT,FILE=TRIM(ARG),STATUS='OLD',ACTION='READ')
      READ(UNIT,*) COUNT
      IF(COUNT.NE.1) STOP 85
      DO I=1,NEXTERNAL
        READ(UNIT,*) POINT(:,I)
      ENDDO
      READ(UNIT,*,IOSTAT=IOS) ARG
      IF(IOS.GE.0) STOP 85
      CLOSE(UNIT)
      CALL ML5_0_FORCE_STABILITY_CHECK(.TRUE.)
      DO K=0,1
        P=POINT
        TOTAL=P(:,1)+P(:,2)
        MU_R=SQRT(ABS(TOTAL(0)**2-SUM(TOTAL(1:3)**2)))
        CALL UPDATE_AS_PARAM()
        ANS=0D0
        ACC=-1D0
        CALL OCC_BEGIN(K)
        INPUTS(:,K)=[TRANSFER(P,[0_C_INT64_T],24),
     $   TRANSFER(MU_R,0_C_INT64_T)]
        CALL OCC_STATE(STATES(1:11,K))
        CALL ML5_0_SLOOPMATRIX_THRES(P,ANS,-1D0,ACC,CODES(K))
        CALL OCC_STATE(STATES(12:22,K))
        INPUTS_AFTER(:,K)=[TRANSFER(P,[0_C_INT64_T],24),
     $   TRANSFER(MU_R,0_C_INT64_T)]
        OUTPUTS(:,K)=TRANSFER(ANS,[0_C_INT64_T],8)
        ACCURACIES(:,K)=TRANSFER(ACC,[0_C_INT64_T],2)
      ENDDO
      CALL OCC_BEGIN(2)
      CALL ML5_0_EXIT_MADLOOP()
C     All formatting and observer flushing occurs after numerical calls.
      OPEN(NEWUNIT=UNIT,FILE='public.txt',STATUS='NEW',ACTION='WRITE')
      WRITE(UNIT,'(A)') 'OCC_PUBLIC 1'
      DO K=0,1
        WRITE(UNIT,'(A,2(1X,I0))') 'CALL',K,CODES(K)
        WRITE(UNIT,'(A,*(1X,Z16.16))') 'INPUT',INPUTS(:,K)
        WRITE(UNIT,'(A,*(1X,Z16.16))') 'INPUT_AFTER',INPUTS_AFTER(:,K)
        WRITE(UNIT,'(A,*(1X,Z16.16))') 'ANS',OUTPUTS(:,K)
        WRITE(UNIT,'(A,*(1X,Z16.16))') 'ACC',ACCURACIES(:,K)
        WRITE(UNIT,'(A,*(1X,I0))') 'STATE',STATES(:,K)
      ENDDO
      CLOSE(UNIT)
      CALL OCC_FLUSH()
      END
