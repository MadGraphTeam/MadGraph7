      PROGRAM BORN_KINEMATICS_CONSISTENCY
      USE, INTRINSIC :: IEEE_ARITHMETIC
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      INCLUDE 'coupl.inc'
      INCLUDE 'mp_coupl.inc'
      INCLUDE 'MadLoopParams.inc'
      REAL*8 P(0:3,5),BEAMPOL(2)
      REAL*16 B(0:3,5),MP_PS(0:3,5),MP_P(0:3,5),ANS(0:1)
      REAL*16 MDP(5),MQP(5)
      INTEGER I,J,K,N,V,USERHEL,POLARIZATIONS(0:5,0:5)
      INTEGER*8 WORDS(2)
      LOGICAL ENTRY_FLAGS(SIZE(IEEE_ALL)),EXIT_FLAGS(SIZE(IEEE_ALL))
      LOGICAL TRAPS(3),TRAPS_AFTER(3),OK
      LOGICAL BADFLAGS(3)
      TYPE(IEEE_STATUS_TYPE) ENTRY_STATUS,OP_STATUS
      TYPE(IEEE_ROUND_TYPE) ROUND_BEFORE,ROUND_AFTER
      CHARACTER*512 CARD,POINTS,MLCARD
      COMMON/TO_BEAMPOL/BEAMPOL
      COMMON/ML5_0_HELUSERCHOICE/USERHEL
      COMMON/ML5_0_BORN_BEAM_POL/POLARIZATIONS
      COMMON/ML5_0_MP_PSPOINT/MP_PS,MP_P
      CALL IEEE_GET_STATUS(ENTRY_STATUS)
      CALL IEEE_GET_ROUNDING_MODE(ROUND_BEFORE)
      CALL IEEE_GET_HALTING_MODE(IEEE_INVALID,TRAPS(1))
      CALL IEEE_GET_HALTING_MODE(IEEE_DIVIDE_BY_ZERO,TRAPS(2))
      CALL IEEE_GET_HALTING_MODE(IEEE_OVERFLOW,TRAPS(3))
      CALL GET_COMMAND_ARGUMENT(1,CARD)
      CALL GET_COMMAND_ARGUMENT(2,POINTS)
      CALL GET_COMMAND_ARGUMENT(3,MLCARD)
      CALL SETPARA(TRIM(CARD))
      CALL MADLOOPPARAMREADER(MLCARD,.FALSE.)
      BEAMPOL=0D0
      POLARIZATIONS=-1
      USERHEL=-1
      WRITE(*,'(A,1X,I4,3(1X,L1))') 'POLICY',IMPROVEPSPOINT,TRAPS
      OPEN(17,FILE=TRIM(POINTS),STATUS='OLD')
      READ(17,*) N
      IF(N.NE.2) STOP 11
      DO K=1,N
        DO I=1,5
          READ(17,*) P(:,I)
        ENDDO
        MU_R=SQRT(ABS((P(0,1)+P(0,2))**2-
     $    SUM((P(1:3,1)+P(1:3,2))**2)))
        CALL UPDATE_AS_PARAM()
        B=REAL(P,KIND=16)
        CALL IEEE_GET_STATUS(OP_STATUS)
        CALL IEEE_GET_FLAG(IEEE_ALL,ENTRY_FLAGS)
C       Exact extracted historical SET_MP_PS, including its repair call.
        CALL ML5_0_SET_MP_PS(P)
        CALL IEEE_GET_FLAG(IEEE_ALL,EXIT_FLAGS)
        CALL IEEE_GET_FLAG(IEEE_INVALID,BADFLAGS(1))
        CALL IEEE_GET_FLAG(IEEE_DIVIDE_BY_ZERO,BADFLAGS(2))
        CALL IEEE_GET_FLAG(IEEE_OVERFLOW,BADFLAGS(3))
        CALL IEEE_SET_STATUS(OP_STATUS)
        WRITE(*,'(A,1X,I3,*(1X,L1))') 'REPAIR_FLAGS',K,
     $    ENTRY_FLAGS,EXIT_FLAGS
        WRITE(*,'(A,1X,I3,3(1X,L1))') 'REPAIR_BADFLAGS',K,BADFLAGS
        IF(ANY(TRANSFER(MP_PS,[0_8],40).NE.
     $    TRANSFER(MP_P,[0_8],40))) STOP 12
        MDP=0Q0
        MQP=0Q0
        MDP(3)=REAL(MDL_MZ,KIND=16)
        MQP(3)=MP__MDL_MZ
        DO I=1,5
          CALL PRINT_Q('MASS_DP',K,I,0,MDP(I))
          CALL PRINT_Q('MASS_MP',K,I,0,MQP(I))
          CALL PRINT_Q('SQUARE_DP',K,I,0,
     $      REAL(REAL(MDP(I),KIND=8)**2,KIND=16))
          CALL PRINT_Q('SQUARE_MP',K,I,0,MQP(I)**2)
          DO J=0,3
            CALL PRINT_Q('B_COORD',K,I,J,B(J,I))
            CALL PRINT_Q('C_COORD',K,I,J,MP_PS(J,I))
          ENDDO
        ENDDO
        CALL PRINT_Q('G_DP',K,0,0,REAL(G,KIND=16))
        CALL PRINT_Q('MU_DP',K,0,0,REAL(MU_R,KIND=16))
        CALL PRINT_Q('MZ_MP_REPAIR',K,0,0,MP__MDL_MZ)
        CALL MP_UPDATE_AS_PARAM()
        CALL PRINT_Q('MZ_MP_NUMERATOR',K,0,0,MP__MDL_MZ)
        CALL PRINT_Q('G_MP_NUMERATOR',K,0,0,MP__G)
        DO V=1,2
          CALL IEEE_GET_STATUS(OP_STATUS)
          CALL IEEE_GET_FLAG(IEEE_ALL,ENTRY_FLAGS)
          IF(V.EQ.1) THEN
            CALL AUDIT_QP_SMATRIX_SPLITORDERS(B,1,ANS)
          ELSE
            CALL AUDIT_QP_SMATRIX_SPLITORDERS(MP_PS,1,ANS)
          ENDIF
          CALL IEEE_GET_FLAG(IEEE_ALL,EXIT_FLAGS)
          CALL IEEE_GET_FLAG(IEEE_INVALID,BADFLAGS(1))
          CALL IEEE_GET_FLAG(IEEE_DIVIDE_BY_ZERO,BADFLAGS(2))
          CALL IEEE_GET_FLAG(IEEE_OVERFLOW,BADFLAGS(3))
          OK=ALL(IEEE_IS_FINITE(ANS))
          CALL IEEE_SET_STATUS(OP_STATUS)
          WRITE(*,'(A,2(1X,I3),1X,L1,*(1X,L1))')
     $      'BORN_FLAGS',K,V,OK,ENTRY_FLAGS,EXIT_FLAGS
          WRITE(*,'(A,2(1X,I3),3(1X,L1))')
     $      'BORN_BADFLAGS',K,V,BADFLAGS
          IF(.NOT.OK) STOP 13
          DO J=0,1
            IF(V.EQ.1) THEN
              CALL PRINT_Q('B_BORN',K,J,0,ANS(J))
            ELSE
              CALL PRINT_Q('C_BORN',K,J,0,ANS(J))
            ENDIF
          ENDDO
        ENDDO
      ENDDO
      CLOSE(17)
      CALL IEEE_SET_STATUS(ENTRY_STATUS)
      CALL IEEE_GET_ROUNDING_MODE(ROUND_AFTER)
      CALL IEEE_GET_HALTING_MODE(IEEE_INVALID,TRAPS_AFTER(1))
      CALL IEEE_GET_HALTING_MODE(IEEE_DIVIDE_BY_ZERO,TRAPS_AFTER(2))
      CALL IEEE_GET_HALTING_MODE(IEEE_OVERFLOW,TRAPS_AFTER(3))
      IF(ANY(TRAPS.NEQV.TRAPS_AFTER)) STOP 14
      IF(ROUND_BEFORE.NE.ROUND_AFTER) STOP 15
      WRITE(*,'(A,3(1X,L1))') 'CONSISTENCY_COMPLETE',TRAPS_AFTER
      END

      SUBROUTINE PRINT_Q(LABEL,POINT,I,J,VALUE)
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      CHARACTER*(*) LABEL
      INTEGER POINT,I,J
      REAL*16 VALUE
      INTEGER*8 WORDS(2)
      TYPE(IEEE_STATUS_TYPE) STATUS
      CALL IEEE_GET_STATUS(STATUS)
      WORDS=TRANSFER(VALUE,WORDS)
C     The pinned x86_64 platform stores the low word first; retain the
C     complete IEEE binary128 bit pattern plus 36 significant decimals.
      WRITE(*,'(A,3(1X,I3),1X,Z16.16,Z16.16,1X,ES46.35E4)')
     $  LABEL,POINT,I,J,WORDS(2),WORDS(1),VALUE
      CALL IEEE_SET_STATUS(STATUS)
      END
