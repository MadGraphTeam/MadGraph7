C     Fixed-form snapshots use the actual generated COMMON declarations.
      SUBROUTINE EW_MASS_UPDATE_SNAPSHOT(PS,GENUINE_QP)
      USE EW_MASS_OBSERVER
      IMPLICIT NONE
      REAL*16 PS(0:3,5)
      LOGICAL GENUINE_QP
      INCLUDE 'coupl.inc'
      INCLUDE 'mp_coupl.inc'
      IF(.NOT.OBS_ACTIVE()) RETURN
      CALL OBS_STATUS('MODEL_UPDATE',1)
      CALL OBS_BOOLEAN('GENUINE_QP_INTEGRAND',GENUINE_QP)
      CALL OBS_R16('CONSUMED_MP_PS',20,PS(0,1))
      CALL OBS_R8('MODEL_MDL_MT',1,(/MDL_MT/))
      CALL OBS_R8('MODEL_MDL_MZ',1,(/MDL_MZ/))
      CALL OBS_R8('MODEL_MDL_MW',1,(/MDL_MW/))
      CALL OBS_R8('MODEL_MDL_MH',1,(/MDL_MH/))
      CALL OBS_R16('MODEL_MP__MDL_MT',1,(/MP__MDL_MT/))
      CALL OBS_R16('MODEL_MP__MDL_MZ',1,(/MP__MDL_MZ/))
      CALL OBS_R16('MODEL_MP__MDL_MW',1,(/MP__MDL_MW/))
      CALL OBS_R16('MODEL_MP__MDL_MH',1,(/MP__MDL_MH/))
      CALL OBS_R8('MODEL_MU_R',1,(/MU_R/))
      CALL OBS_C32('MODEL_MP__MU_R',1,(/MP__MU_R/))
      CALL OBS_C16('MODEL_GAL',2,GAL(1))
      CALL OBS_C32('MODEL_MP__GAL',2,MP__GAL(1))
      END

      SUBROUTINE EW_MASS_GROUP_SNAPSHOT(ID,SQSO,RANK)
      USE EW_MASS_OBSERVER
      USE ML5_0_POLYNOMIAL_CONSTANTS, ONLY: NCOEF_R
      IMPLICIT NONE
      INTEGER ID,SQSO,RANK
      INCLUDE 'loop_max_coefs.inc'
      REAL*16 MP_PS(0:3,5),MP_P(0:3,5)
      COMMON/ML5_0_MP_PSPOINT/MP_PS,MP_P
      COMPLEX*32 LOOPCOEFS(0:LOOPMAXCOEFS-1,1,200)
      COMMON/ML5_0_MP_LCOEFS/LOOPCOEFS
      IF(.NOT.OBS_ACTIVE()) RETURN
      CALL OBS_R16('REPAIRED_MP_PS',20,MP_PS(0,1))
      CALL OBS_R16('CURRENT_MP_P',20,MP_P(0,1))
      CALL OBS_C32('NUMERATOR_COEFS',NCOEF_R(RANK),
     $ LOOPCOEFS(0,SQSO,ID))
      END

      SUBROUTINE EW_MASS_POINT_END(P,ANS,ACC,CODE)
      USE EW_MASS_OBSERVER
      IMPLICIT NONE
      REAL*8 P(0:3,5),ANS(0:3,0:1),ACC(0:1)
      INTEGER CODE
      LOGICAL FPE_DP,FPE_QP
      COMMON/ML5_0_FPE_IN_REDUCTION/FPE_DP,FPE_QP
      CALL OBS_R8('RETURN_P',20,P(0,1))
      CALL OBS_R8('AMPLITUDE',8,ANS(0,0))
      CALL OBS_R8('ACCURACY',2,ACC(0))
      CALL OBS_STATUS('PUBLIC_STATUS',CODE)
      CALL OBS_BOOLEAN('FPE_DP_END',FPE_DP)
      CALL OBS_BOOLEAN('FPE_QP_END',FPE_QP)
      CALL OBS_END()
      END

      SUBROUTINE EW_MASS_POINT_BEGIN(K,P)
      USE EW_MASS_OBSERVER
      IMPLICIT NONE
      INTEGER K
      REAL*8 P(0:3,5)
      LOGICAL FPE_DP,FPE_QP
      COMMON/ML5_0_FPE_IN_REDUCTION/FPE_DP,FPE_QP
      CALL OBS_BEGIN(K)
      CALL OBS_R8('INPUT_P',20,P(0,1))
      CALL OBS_BOOLEAN('FPE_DP_BEGIN',FPE_DP)
      CALL OBS_BOOLEAN('FPE_QP_BEGIN',FPE_QP)
      END
