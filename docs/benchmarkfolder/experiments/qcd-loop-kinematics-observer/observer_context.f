C     Private read-only hooks. All real/complex payloads are copied as bits.
C     No snapshot spans a physical calculation or backend invocation.
      SUBROUTINE QO_CAPTURE_CONTEXT()
      USE QCD_KINEMATICS_OBSERVER
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      INCLUDE 'coupl.inc'
      INCLUDE 'mp_coupl.inc'
      REAL*16 MP_PS(0:3,5),MP_P(0:3,5)
      COMMON/ML5_0_MP_PSPOINT/MP_PS,MP_P
      TYPE(IEEE_STATUS_TYPE) SAVED
      IF(.NOT.QO_SCOPE_ACTIVE()) RETURN
      CALL IEEE_GET_STATUS(SAVED)
      CALL QO_PUT('CONTEXT_MP_PS',0,0,
     $ TRANSFER(MP_PS,(/0_8/),40))
      CALL QO_PUT('CONTEXT_MP_P',0,0,
     $ TRANSFER(MP_P,(/0_8/),40))
      CALL QO_PUT('CONTEXT_MZ_DP',0,0,
     $ TRANSFER(MDL_MZ,(/0_8/),1))
      CALL QO_PUT('CONTEXT_MT_DP',0,0,
     $ TRANSFER(MDL_MT,(/0_8/),1))
      CALL QO_PUT('CONTEXT_MB_DP',0,0,
     $ TRANSFER(MDL_MB,(/0_8/),1))
      CALL QO_PUT('CONTEXT_MZ_MP',0,0,
     $ TRANSFER(MP__MDL_MZ,(/0_8/),2))
      CALL QO_PUT('CONTEXT_MT_MP',0,0,
     $ TRANSFER(MP__MDL_MT,(/0_8/),2))
      CALL QO_PUT('CONTEXT_MB_MP',0,0,
     $ TRANSFER(MP__MDL_MB,(/0_8/),2))
      CALL QO_PUT('CONTEXT_G_DP',0,0,TRANSFER(G,(/0_8/),1))
      CALL QO_PUT('CONTEXT_G_MP',0,0,TRANSFER(MP__G,(/0_8/),2))
      CALL QO_PUT('CONTEXT_MU_DP',0,0,TRANSFER(MU_R,(/0_8/),1))
      CALL QO_PUT('CONTEXT_MU_MP',0,0,
     $ TRANSFER(MP__MU_R,(/0_8/),4))
      CALL QO_PUT('CONTEXT_GC4_DP',0,0,TRANSFER(GC_4,(/0_8/),2))
      CALL QO_PUT('CONTEXT_GC5_DP',0,0,TRANSFER(GC_5,(/0_8/),2))
      CALL QO_PUT('CONTEXT_GC22_DP',0,0,
     $ TRANSFER(GC_22,(/0_8/),2))
      CALL QO_PUT('CONTEXT_GC23_DP',0,0,
     $ TRANSFER(GC_23,(/0_8/),2))
      CALL QO_PUT('CONTEXT_GC4_MP',0,0,
     $ TRANSFER(MP__GC_4,(/0_8/),4))
      CALL QO_PUT('CONTEXT_GC5_MP',0,0,
     $ TRANSFER(MP__GC_5,(/0_8/),4))
      CALL QO_PUT('CONTEXT_GC22_MP',0,0,
     $ TRANSFER(MP__GC_22,(/0_8/),4))
      CALL QO_PUT('CONTEXT_GC23_MP',0,0,
     $ TRANSFER(MP__GC_23,(/0_8/),4))
      CALL IEEE_SET_STATUS(SAVED)
      END

      SUBROUTINE QO_ERROR_TIRUST()
      USE QCD_KINEMATICS_OBSERVER
      USE MTIRUST, ONLY: TIRUST_ERROR_MESSAGE
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      CHARACTER*2048 MESSAGE
      TYPE(IEEE_STATUS_TYPE) SAVED
      IF(.NOT.QO_SCOPE_ACTIVE()) RETURN
      CALL IEEE_GET_STATUS(SAVED)
      CALL TIRUST_ERROR_MESSAGE(MESSAGE)
      CALL QO_ERROR(MESSAGE)
      CALL IEEE_SET_STATUS(SAVED)
      END

