      SUBROUTINE QO_HEALTH_REPORT(SEQ)
      USE QCD_KINEMATICS_OBSERVER
      USE, INTRINSIC :: ISO_FORTRAN_ENV, ONLY: INT64
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      INTEGER SEQ,IOS
      INTEGER(INT64) FAULTS,IO_FAILURES
      TYPE(IEEE_STATUS_TYPE) SAVED
      CALL IEEE_GET_STATUS(SAVED)
      CALL QO_GET_HEALTH(FAULTS,IO_FAILURES)
      WRITE(*,'(A,3(1X,I0))',IOSTAT=IOS)
     $ 'QO_HEALTH',SEQ,FAULTS,IO_FAILURES
      IF(IOS.EQ.0) FLUSH(6,IOSTAT=IOS)
      CALL IEEE_SET_STATUS(SAVED)
      END
