      SUBROUTINE INIT_CONTEXT(MODE,INTERNAL)
      USE, INTRINSIC :: IEEE_ARITHMETIC
      IMPLICIT NONE
      INTEGER MODE
      COMPLEX*32 INTERNAL
      INCLUDE 'mp_coupl.inc'
      INCLUDE 'MadLoopParams.inc'
      OSTHRES=1.0D-8
      IF(MODE.EQ.4) OSTHRES=-1.0D0
      MP__MDL_MZ=2.0E0_16
      IF(MODE.EQ.1) MP__MDL_MZ=2.0E0_16+2.0E0_16**(-111)
      IF(MODE.EQ.2) MP__MDL_MZ=-2.0E0_16
      IF(MODE.EQ.3) MP__MDL_MZ=IEEE_VALUE(0.0E0_16,
     $ IEEE_QUIET_NAN)
      MP__CMASS_MDL_MZ=CMPLX(2.0E0_16,-0.125E0_16,KIND=16)
      INTERNAL=MP__CMASS_MDL_MZ**2
      END
