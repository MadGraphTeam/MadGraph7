      PROGRAM AUDIT_BORN
      USE, INTRINSIC :: IEEE_ARITHMETIC
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      INCLUDE 'coupl.inc'
      INTEGER NHEL(5,48),IC(5),FLAVOR(5),IDEN,I,J,H,K,N,V
      INTEGER ML5_0_BROKEN_SYM
      REAL*8 P(0:3,5),ORIG(0:3,5),ANS,BEAMPOL(2),QDP(0:3)
      REAL*16 PQ(0:3,5),AMPRES(1),BORN,Q(0:3),D,MDLQ
      REAL*16 DENQ,ERR
      COMPLEX*32 AMP(8),JAMP(2,1),GC4Q,GC5Q,GC22Q,GC23Q
      LOGICAL BAD,INVALID,DIVZERO,OVERFLOW
      CHARACTER*1024 CARD,POINTS
      COMMON/TO_BEAMPOL/BEAMPOL
      CALL GET_COMMAND_ARGUMENT(1,CARD)
      CALL GET_COMMAND_ARGUMENT(2,POINTS)
      CALL SETPARA(TRIM(CARD))
      BEAMPOL=0D0
      IC=1
      FLAVOR=1
      CALL ML5_0_GET_NHEL(IDEN,NHEL)
      OPEN(17,FILE=TRIM(POINTS),STATUS='OLD')
      READ(17,*) N
      DO K=1,N
        DO I=1,5
          READ(17,*) ORIG(:,I)
        ENDDO
        MU_R=SQRT(ABS((ORIG(0,1)+ORIG(0,2))**2-
     $    SUM((ORIG(1:3,1)+ORIG(1:3,2))**2)))
        CALL UPDATE_AS_PARAM()
        MDLQ=REAL(MDL_MZ,KIND=16)
        GC4Q=CMPLX(GC_4,KIND=16)
        GC5Q=CMPLX(GC_5,KIND=16)
        GC22Q=CMPLX(GC_22,KIND=16)
        GC23Q=CMPLX(GC_23,KIND=16)
        CALL IEEE_SET_FLAG(IEEE_ALL,.FALSE.)
        CALL ML5_0_SMATRIX(ORIG,1,ANS)
        CALL IEEE_GET_FLAG(IEEE_INVALID,INVALID)
        CALL IEEE_GET_FLAG(IEEE_DIVIDE_BY_ZERO,DIVZERO)
        CALL IEEE_GET_FLAG(IEEE_OVERFLOW,OVERFLOW)
        WRITE(*,'(A,1X,I2,1X,ES46.35E4,3(1X,L1))')
     $    'DP_BORN',K,ANS,INVALID,DIVZERO,OVERFLOW
        DO V=0,2
          P=ORIG
          IF(V.EQ.1) THEN
            P(:,4)=ORIG(:,5)
            P(:,5)=ORIG(:,4)
          ELSE IF(V.EQ.2) THEN
            P(1,:)=ORIG(2,:)
            P(2,:)=ORIG(3,:)
            P(3,:)=ORIG(1,:)
          ENDIF
          PQ=REAL(P,KIND=16)
          QDP=P(:,1)-P(:,4)
          Q=PQ(:,1)-PQ(:,4)
          D=REAL(QDP(0)**2-QDP(1)**2-QDP(2)**2-
     $      QDP(3)**2,KIND=16)
          DENQ=Q(0)**2-Q(1)**2-Q(2)**2-Q(3)**2
          WRITE(*,'(A,2(1X,I2),3(1X,ES46.35E4))')
     $      'DENOM',K,V,D,DENQ,Q(0)-Q(3)
          CALL IEEE_SET_FLAG(IEEE_ALL,.FALSE.)
          BORN=0Q0
          BAD=.FALSE.
          DO H=1,48
            CALL AUDIT_QP_GET_AMP(PQ,NHEL(:,H),IC,1,AMP,
     $        MDLQ,GC4Q,GC5Q,GC22Q,GC23Q)
            CALL AUDIT_QP_GET_JAMP(AMP,JAMP)
            CALL AUDIT_QP_GET_MATRIX(JAMP,AMPRES)
            BAD=BAD.OR.(.NOT.IEEE_IS_FINITE(AMPRES(1)))
            BORN=BORN+AMPRES(1)
          ENDDO
          BORN=BORN/REAL(IDEN,KIND=16)*
     $      REAL(ML5_0_BROKEN_SYM(FLAVOR),KIND=16)
          CALL IEEE_GET_FLAG(IEEE_INVALID,INVALID)
          CALL IEEE_GET_FLAG(IEEE_DIVIDE_BY_ZERO,DIVZERO)
          CALL IEEE_GET_FLAG(IEEE_OVERFLOW,OVERFLOW)
          WRITE(*,'(A,2(1X,I2),1X,ES46.35E4,4(1X,L1))')
     $      'QP_BORN',K,V,BORN,BAD,INVALID,DIVZERO,OVERFLOW
        ENDDO
      ENDDO
      CLOSE(17)
      END
