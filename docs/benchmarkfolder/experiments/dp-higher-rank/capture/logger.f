
      SUBROUTINE DP_HIGHER_CAPTURE(A,B,R)
      USE ML5_0_POLYNOMIAL_CONSTANTS
      USE,INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      INTEGER R,COUNTS(2),SLOT
      SAVE COUNTS
      DATA COUNTS /0,0/
      COMPLEX*16 A(4,0:LOOPMAXCOEFS-1,4)
      COMPLEX*16 B(4,0:VERTEXMAXCOEFS-1,4)
      LOGICAL FLAGS(SIZE(IEEE_ALL)),HALTS(SIZE(IEEE_ALL))
      CHARACTER*64 NAME
      SLOT=R-1
      IF(COUNTS(SLOT).GE.2) RETURN
      CALL IEEE_GET_FLAG(IEEE_ALL,FLAGS)
      CALL IEEE_GET_HALTING_MODE(IEEE_ALL,HALTS)
      COUNTS(SLOT)=COUNTS(SLOT)+1
      WRITE(NAME,'(A,I1,A,I1,A)') 'capture-r',R,'-',
     $ COUNTS(SLOT),'.txt'
      OPEN(83,FILE=TRIM(NAME),STATUS='REPLACE')
      WRITE(83,*) R,LOOPMAXCOEFS,VERTEXMAXCOEFS
      WRITE(83,*) FLAGS
      WRITE(83,*) HALTS
      WRITE(83,'(Z16.16)') TRANSFER(A,(/0_8/),SIZE(A)*2)
      WRITE(83,'(Z16.16)') TRANSFER(B,(/0_8/),SIZE(B)*2)
      CLOSE(83)
      CALL IEEE_SET_FLAG(IEEE_ALL,FLAGS)
      IF(ALL(COUNTS.EQ.2)) STOP 77
      END
