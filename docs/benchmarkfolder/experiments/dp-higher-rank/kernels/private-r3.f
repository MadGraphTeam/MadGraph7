      SUBROUTINE TEST_DP_TERMINAL_WL_3_1(A,LCUT_SIZE,B,IN_SIZE
     $ ,OUT_SIZE,OUT,WL_ENTRY_INEXACT)
      USE TEST_POLYNOMIAL_CONSTANTS
      USE, INTRINSIC :: IEEE_ARITHMETIC
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      INTEGER I,J,K,L,M,WL_H
      LOGICAL WL_ENTRY_INEXACT,WL_HALTING(SIZE(IEEE_ALL))
      TYPE(IEEE_ROUND_TYPE) WL_ROUNDING
      COMPLEX*16 A(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE)
      COMPLEX*16 B(MAXLWFSIZE,0:VERTEXMAXCOEFS-1,MAXLWFSIZE)
      COMPLEX*16 OUT(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE)
      INTEGER LCUT_SIZE,IN_SIZE,OUT_SIZE
      INTEGER NEW_POSITION
      COMPLEX*16 UPDATER_COEF

C     Welcome to the computational heart of MadLoop...
C     Private diagonal arithmetic requires the rendered consumer proof.
      IF(.NOT.WL_ENTRY_INEXACT) GOTO 900
      IF(MAXLWFSIZE.NE.4.OR.LCUT_SIZE.NE.4.OR.IN_SIZE.NE.4.OR.OUT_SIZE.
     $NE.4) GOTO 900
      CALL IEEE_GET_ROUNDING_MODE(WL_ROUNDING)
      IF(WL_ROUNDING.NE.IEEE_NEAREST) GOTO 900
      DO WL_H=1,SIZE(IEEE_ALL)
        IF(.NOT.IEEE_SUPPORT_HALTING(IEEE_ALL(WL_H))) GOTO 900
      ENDDO
      CALL IEEE_GET_HALTING_MODE(IEEE_ALL,WL_HALTING)
      IF(ANY(WL_HALTING)) GOTO 900
      IF(.NOT.ALL(WL_DP_BOUNDED(REAL(A(:,0:34,:),KIND=8)))) GOTO 900
      IF(.NOT.ALL(WL_DP_BOUNDED(AIMAG(A(:,0:34,:))))) GOTO 900
      IF(.NOT.ALL(WL_DP_BOUNDED(REAL(B(:,0:4,:),KIND=8)))) GOTO 900
      IF(.NOT.ALL(WL_DP_BOUNDED(AIMAG(B(:,0:4,:))))) GOTO 900
C     DP_TERMINAL_FAST_PATH
      OUT(:,:,:)=(0.0D0,0.0D0)
      DO J=1,OUT_SIZE
        DO M=0,4
          DO K=1,IN_SIZE
            UPDATER_COEF = B(J,M,K)
            IF (UPDATER_COEF.EQ.(0.0D0,0.0D0)) CYCLE
            DO I=J,J
              DO L=0,34
                NEW_POSITION = COMB_COEF_POS(L,M)
                OUT(J,NEW_POSITION,I)=OUT(J,NEW_POSITION,I) + A(K,L,I)
     $           *UPDATER_COEF
              ENDDO
            ENDDO
          ENDDO
        ENDDO
      ENDDO

      RETURN
 900  CONTINUE
      CALL TEST_UPDATE_WL_3_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
      CONTAINS
      ELEMENTAL LOGICAL FUNCTION WL_DP_BOUNDED(X)
      REAL*8, INTENT(IN) :: X
      INTEGER*8, PARAMETER :: ONE_WORDS(1)=TRANSFER(1.0_8,(/0_8/))
      WL_DP_BOUNDED=.FALSE.
      IF(STORAGE_SIZE(X).NE.64.OR.DIGITS(X).NE.53.OR.RADIX(X)
     $ .NE.2.OR.MAXEXPONENT(X).NE.1024) RETURN
      IF(ONE_WORDS(1).NE.ISHFT(1023_8,52)) RETURN
      ASSOCIATE(WORDS=>TRANSFER(X,ONE_WORDS))
      IF(IBCLR(WORDS(1),63).EQ.0_8) THEN
        WL_DP_BOUNDED=.TRUE.
      ELSE
        WL_DP_BOUNDED=IBITS(WORDS(1),52,11).GE.623_8.AND.IBITS(WORDS(1)
     $   ,52,11).LE.1423_8
      ENDIF
      END ASSOCIATE
      END FUNCTION
      END
