C     Read-only logging hooks for an isolated historical generated process.
      BLOCK DATA EW_TRACE_STATE
      IMPLICIT NONE
      INTEGER POINTNUM,CALLNO,SEEN(200)
      LOGICAL ACTIVE,OPENED
      COMMON/EW_TRACE_CONTROL/POINTNUM,CALLNO,SEEN,ACTIVE,OPENED
      DATA POINTNUM,CALLNO/0,0/,SEEN/200*0/
      DATA ACTIVE,OPENED/.FALSE.,.FALSE./
      END

      SUBROUTINE EW_TRACE_BEGIN(K)
      IMPLICIT NONE
      INTEGER K,POINTNUM,CALLNO,SEEN(200)
      LOGICAL ACTIVE,OPENED
      COMMON/EW_TRACE_CONTROL/POINTNUM,CALLNO,SEEN,ACTIVE,OPENED
      IF(.NOT.OPENED) THEN
        OPEN(915,FILE='ew-tensor-trace.dat',STATUS='REPLACE')
        OPENED=.TRUE.
      ENDIF
      POINTNUM=K
      CALLNO=0
      SEEN=0
      ACTIVE=.TRUE.
      WRITE(915,*) 'BEGIN',K
      FLUSH(915)
      END

      SUBROUTINE EW_TRACE_TENSOR(CTMODE,N,RANK,SHIFTS,S,MASSES,
     $ SCALE,LD,NC,RAW,STATUS)
      USE MTIRUST, ONLY: TIRUST_ERROR_MESSAGE
      IMPLICIT NONE
      INTEGER CTMODE,N,RANK,LD,NC,STATUS,I,J,K
      REAL*16 SHIFTS(0:3,N),S(N,N),SCALE
      COMPLEX*32 MASSES(N),RAW(LD,4)
      INTEGER ID,SQSOINDEX,R
      COMMON/ML5_0_LOOP/ID,SQSOINDEX,R
      INTEGER POINTNUM,CALLNO,SEEN(200)
      LOGICAL ACTIVE,OPENED
      COMMON/EW_TRACE_CONTROL/POINTNUM,CALLNO,SEEN,ACTIVE,OPENED
      CHARACTER*2048 ERROR
      IF(.NOT.ACTIVE) RETURN
      CALLNO=CALLNO+1
      WRITE(915,*) 'CALL',POINTNUM,CALLNO,ID,SQSOINDEX,CTMODE,
     $ N,RANK,STATUS
      IF(STATUS.NE.0) THEN
        CALL TIRUST_ERROR_MESSAGE(ERROR)
        WRITE(915,'(A,A)') 'ERROR ',TRIM(ERROR)
      ENDIF
      IF(ID.LT.1.OR.ID.GT.200) STOP 91
      IF(SEEN(ID).EQ.0) THEN
        WRITE(915,'(A,ES45.35E4)') 'SCALE ',SCALE
        DO I=1,N
          WRITE(915,'(A,I4,4ES45.35E4)') 'SHIFT ',I,SHIFTS(:,I)
          WRITE(915,'(A,I4,2ES45.35E4)') 'MASS ',I,MASSES(I)
          DO J=1,N
            WRITE(915,'(A,2I4,ES45.35E4)') 'S ',I,J,S(I,J)
          ENDDO
        ENDDO
C       Native failure leaves RAW undefined: never inspect it then.
        IF(STATUS.EQ.0) THEN
          DO K=1,4
            DO I=1,NC
              WRITE(915,'(A,2I4,2ES45.35E4)') 'RAW ',I,K,RAW(I,K)
            ENDDO
          ENDDO
        ENDIF
        SEEN(ID)=1
      ENDIF
      FLUSH(915)
      END

      SUBROUTINE EW_TRACE_END(P,ANS,ACC,CODE)
      IMPLICIT NONE
      REAL*8 P(0:3,5),ANS(0:3,0:1),ACC(0:1)
      INTEGER CODE,I,J
      REAL*16 MP_PS(0:3,5),MP_P(0:3,5)
      COMMON/ML5_0_MP_PSPOINT/MP_PS,MP_P
      LOGICAL FPE_DP,FPE_QP
      COMMON/ML5_0_FPE_IN_REDUCTION/FPE_DP,FPE_QP
      INTEGER POINTNUM,CALLNO,SEEN(200)
      LOGICAL ACTIVE,OPENED
      COMMON/EW_TRACE_CONTROL/POINTNUM,CALLNO,SEEN,ACTIVE,OPENED
      INCLUDE 'coupl.inc'
      INCLUDE 'mp_coupl.inc'
      WRITE(915,*) 'END',POINTNUM,CALLNO,CODE,FPE_DP,FPE_QP
      DO I=1,5
        WRITE(915,'(A,I4,4ES45.35E4)') 'P ',I,REAL(P(:,I),16)
        WRITE(915,'(A,I4,4ES45.35E4)') 'MP_PS ',I,MP_PS(:,I)
        WRITE(915,'(A,I4,4ES45.35E4)') 'MP_P ',I,MP_P(:,I)
      ENDDO
      DO J=0,1
        WRITE(915,'(A,I4,5ES45.35E4)') 'ANS ',J,
     $   REAL(ANS(:,J),16),REAL(ACC(J),16)
      ENDDO
      WRITE(915,'(A,2ES45.35E4)') 'GAL ',GAL(1)
      WRITE(915,'(A,2ES45.35E4)') 'MP_GAL ',MP__GAL(1)
      WRITE(915,'(A,2ES45.35E4)') 'MT ',REAL(MDL_MT,16),MP__MDL_MT
      ACTIVE=.FALSE.
      FLUSH(915)
      END
