#!/usr/bin/env python3
"""Create the portable text-only inventory after all experiment writers stop."""
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parent
target = root / "evidence-index.json"
files = {}
for path in sorted(root.rglob("*")):
    if not path.is_file() or path == target:
        continue
    if path.is_symlink() or "__pycache__" in path.parts or path.suffix == ".pyc":
        raise ValueError("Unexpected symlink or generated bytecode: " + str(path))
    content = path.read_bytes()
    if b"\0" in content or content.startswith((b"\x7fELF", b"MZ", b"!<arch>\n", b"\x1f\x8b", b"PK\x03\x04")):
        raise ValueError("Unexpected binary evidence: " + str(path))
    content.decode("utf-8")
    files[path.relative_to(root).as_posix()] = {
        "sha256": hashlib.sha256(content).hexdigest(), "bytes": len(content)}
target.write_text(json.dumps({"scope": "Portable physical-stress evidence only; original numerical executables and libraries remain outside the package.",
                              "files": files}, indent=2, sort_keys=True) + "\n")
print(len(files))
