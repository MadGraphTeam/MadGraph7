      SUBROUTINE TEST_TERMINAL_WL_2_1_FACTOR(A,LCUT_SIZE,B,IN_SIZE
     $ ,OUT_SIZE,OUT,WL_ENTRY_INEXACT)
      USE TEST_POLYNOMIAL_CONSTANTS
      USE, INTRINSIC :: IEEE_ARITHMETIC
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      INTEGER I,J,K,L,M,R,HALT_INDEX
      COMPLEX*32 U(4,0:14,MAXLWFSIZE)
      LOGICAL, PARAMETER :: NEEDED(4,4)=RESHAPE((/.TRUE.,.TRUE.
     $ ,.FALSE.,.FALSE.,.TRUE.,.TRUE.,.FALSE.,.FALSE.,.FALSE.,.FALSE.
     $ ,.TRUE.,.TRUE.,.FALSE.,.FALSE.,.TRUE.,.TRUE./),(/4,4/))
      LOGICAL HALT_FLAGS(SIZE(IEEE_ALL))
      COMPLEX*32 A(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE)
      COMPLEX*32 B(MAXLWFSIZE,0:VERTEXMAXCOEFS-1,MAXLWFSIZE)
      COMPLEX*32 OUT(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE)
      INTEGER LCUT_SIZE,IN_SIZE,OUT_SIZE
      TYPE(IEEE_ROUND_TYPE) WL_ROUNDING
      LOGICAL WL_NEAREST
      LOGICAL WL_SKIP_ZERO
      LOGICAL WL_AZERO(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE)
      INTEGER WL_I,WL_K,WL_L
      LOGICAL WL_ALREADY,WL_HALT,WL_ENTRY_INEXACT
      INTEGER NEW_POSITION
      COMPLEX*32 UPDATER_COEF

C     Experimental derivative-row factorization; changed rounding
      IF(.NOT.WL_ENTRY_INEXACT.OR.IN_SIZE.NE.4.OR.OUT_SIZE.NE.4.OR.MAXL
     $WFSIZE.NE.4.OR.LCUT_SIZE.LT.0.OR.LCUT_SIZE.GT.4) THEN
        CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $   ,WL_ENTRY_INEXACT)
        RETURN
      ENDIF
      DO HALT_INDEX=1,SIZE(IEEE_ALL)
        IF(.NOT.IEEE_SUPPORT_HALTING(IEEE_ALL(HALT_INDEX))) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      CALL IEEE_GET_HALTING_MODE(IEEE_ALL,HALT_FLAGS)
      IF(ANY(HALT_FLAGS)) THEN
        CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $   ,WL_ENTRY_INEXACT)
        RETURN
      ENDIF
      IF(.NOT.ALL(GATHER_BOUNDED(REAL(A(1:IN_SIZE,0:14,1:LCUT_SIZE)
     $ ,KIND=16))).OR..NOT.ALL(GATHER_BOUNDED(AIMAG(A(1:IN_SIZE,0:14
     $ ,1:LCUT_SIZE)))).OR..NOT.ALL(GATHER_BOUNDED(REAL(B(1:OUT_SIZE
     $ ,0:4,1:IN_SIZE),KIND=16)))
     $ .OR..NOT.ALL(GATHER_BOUNDED(AIMAG(B(1:OUT_SIZE,0:4,1:IN_SIZE))))
     $ ) THEN
        CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $   ,WL_ENTRY_INEXACT)
        RETURN
      ENDIF

      CALL IEEE_GET_ROUNDING_MODE(WL_ROUNDING)
      WL_NEAREST=WL_ROUNDING.EQ.IEEE_NEAREST
      WL_ALREADY=WL_ENTRY_INEXACT
      WL_HALT=.TRUE.
      IF(IEEE_SUPPORT_HALTING(IEEE_INEXACT)) CALL
     $  IEEE_GET_HALTING_MODE(IEEE_INEXACT,WL_HALT)
      IF(.NOT.WL_NEAREST.OR..NOT.WL_ALREADY.OR.WL_HALT.OR.LCUT_SIZE.GT.
     $OUT_SIZE.OR.MAXLWFSIZE.GT.16.OR.15.GT.65536.OR.5.GT.65536.OR..NOT
     $.ALL(WL_BOUNDED(REAL(A(1:IN_SIZE,0:14,1:LCUT_SIZE),KIND=16)))
     $ .OR..NOT.ALL(WL_BOUNDED(AIMAG(A(1:IN_SIZE,0:14,1:LCUT_SIZE))))
     $ .OR..NOT.ALL(WL_BOUNDED(REAL(B(1:OUT_SIZE,0:4,1:IN_SIZE)
     $ ,KIND=16))).OR..NOT.ALL(WL_BOUNDED(AIMAG(B(1:OUT_SIZE,0:4
     $ ,1:IN_SIZE))))) THEN
        CALL TEST_UPDATE_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT)
        RETURN
      ENDIF
      WL_AZERO(1:IN_SIZE,0:14,1:LCUT_SIZE)=.FALSE.
      IF(WL_NEAREST) THEN
        DO WL_K=1,IN_SIZE
          DO WL_I=1,LCUT_SIZE
            DO WL_L=0,14
              IF(WL_IS_FINITE(REAL(A(WL_K,WL_L,WL_I),KIND=16))
     $         .AND.WL_IS_FINITE(AIMAG(A(WL_K,WL_L,WL_I))))
     $          WL_AZERO(WL_K,WL_L,WL_I)=A(WL_K,WL_L,WL_I).EQ.0
            ENDDO
          ENDDO
        ENDDO
      ENDIF

      DO K=1,4
        IF(B(1,1,K).NE.B(1,1,K)) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(2,1,K).NE.B(2,1,K)) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(3,1,K).NE.B(3,1,K)) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(4,1,K).NE.B(4,1,K)) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(1,2,K).NE.B(2,1,K)) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(2,2,K).NE.B(1,1,K)) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(3,2,K).NE.(-B(4,1,K))) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(4,2,K).NE.(-B(3,1,K))) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(1,3,K).NE.CMPLX(-AIMAG(B(2,1,K)),REAL(B(2,1,K),KIND=16)
     $   ,KIND=16)) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(2,3,K).NE.CMPLX(AIMAG(B(1,1,K)),-REAL(B(1,1,K),KIND=16)
     $   ,KIND=16)) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(3,3,K).NE.CMPLX(AIMAG(B(4,1,K)),-REAL(B(4,1,K),KIND=16)
     $   ,KIND=16)) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(4,3,K).NE.CMPLX(-AIMAG(B(3,1,K)),REAL(B(3,1,K),KIND=16)
     $   ,KIND=16)) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(1,4,K).NE.B(1,1,K)) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(2,4,K).NE.(-B(2,1,K))) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(3,4,K).NE.(-B(3,1,K))) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
      DO K=1,4
        IF(B(4,4,K).NE.B(4,1,K)) THEN
          CALL TEST_TERMINAL_WL_2_1(A,LCUT_SIZE,B,IN_SIZE,OUT_SIZE,OUT
     $     ,WL_ENTRY_INEXACT)
          RETURN
        ENDIF
      ENDDO
C     FACTOR_FAST_PATH
      OUT(:,:,:)=CMPLX(0.0E0_16,0.0E0_16,KIND=16)
      DO J=1,OUT_SIZE
        M=0
        DO K=1,IN_SIZE
          UPDATER_COEF = B(J,M,K)
          IF (UPDATER_COEF.EQ.CMPLX(0.0E0_16,0.0E0_16,KIND=16)) CYCLE
          WL_SKIP_ZERO=.FALSE.
          IF(WL_NEAREST) WL_SKIP_ZERO=WL_IS_FINITE(REAL(UPDATER_COEF
     $     ,KIND=16)).AND.WL_IS_FINITE(AIMAG(UPDATER_COEF))
          DO I=J,MIN(J,LCUT_SIZE)
            DO L=0,14
              IF(WL_SKIP_ZERO) THEN
                IF(WL_AZERO(K,L,I)) CYCLE
              ENDIF
              NEW_POSITION = COMB_COEF_POS(L,M)
              OUT(J,NEW_POSITION,I)=OUT(J,NEW_POSITION,I) + A(K,L,I)
     $         *UPDATER_COEF
            ENDDO
          ENDDO
        ENDDO
      ENDDO
      U=CMPLX(0.0E0_16,0.0E0_16,KIND=16)
      DO I=1,LCUT_SIZE
        DO R=1,4
          IF(.NOT.NEEDED(R,I)) CYCLE
          DO K=1,IN_SIZE
            UPDATER_COEF=B(R,1,K)
            IF(UPDATER_COEF.EQ.CMPLX(0.0E0_16,0.0E0_16,KIND=16)) CYCLE
            DO L=0,14
              IF(WL_AZERO(K,L,I)) CYCLE
              U(R,L,I)=U(R,L,I)+A(K,L,I)*UPDATER_COEF
            ENDDO
          ENDDO
        ENDDO
      ENDDO
      DO I=1,MIN(1,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,1)
          OUT(1,NEW_POSITION,I)=OUT(1,NEW_POSITION,I)+U(1,L,I)
        ENDDO
      ENDDO
      DO I=1,MIN(1,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,2)
          OUT(1,NEW_POSITION,I)=OUT(1,NEW_POSITION,I)+U(2,L,I)
        ENDDO
      ENDDO
      DO I=1,MIN(1,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,3)
          OUT(1,NEW_POSITION,I)=OUT(1,NEW_POSITION,I)+CMPLX(-AIMAG(U(2
     $     ,L,I)),REAL(U(2,L,I),KIND=16),KIND=16)
        ENDDO
      ENDDO
      DO I=1,MIN(1,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,4)
          OUT(1,NEW_POSITION,I)=OUT(1,NEW_POSITION,I)+U(1,L,I)
        ENDDO
      ENDDO
      DO I=2,MIN(2,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,1)
          OUT(2,NEW_POSITION,I)=OUT(2,NEW_POSITION,I)+U(2,L,I)
        ENDDO
      ENDDO
      DO I=2,MIN(2,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,2)
          OUT(2,NEW_POSITION,I)=OUT(2,NEW_POSITION,I)+U(1,L,I)
        ENDDO
      ENDDO
      DO I=2,MIN(2,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,3)
          OUT(2,NEW_POSITION,I)=OUT(2,NEW_POSITION,I)+CMPLX(AIMAG(U(1
     $     ,L,I)),-REAL(U(1,L,I),KIND=16),KIND=16)
        ENDDO
      ENDDO
      DO I=2,MIN(2,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,4)
          OUT(2,NEW_POSITION,I)=OUT(2,NEW_POSITION,I)+(-U(2,L,I))
        ENDDO
      ENDDO
      DO I=3,MIN(3,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,1)
          OUT(3,NEW_POSITION,I)=OUT(3,NEW_POSITION,I)+U(3,L,I)
        ENDDO
      ENDDO
      DO I=3,MIN(3,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,2)
          OUT(3,NEW_POSITION,I)=OUT(3,NEW_POSITION,I)+(-U(4,L,I))
        ENDDO
      ENDDO
      DO I=3,MIN(3,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,3)
          OUT(3,NEW_POSITION,I)=OUT(3,NEW_POSITION,I)+CMPLX(AIMAG(U(4
     $     ,L,I)),-REAL(U(4,L,I),KIND=16),KIND=16)
        ENDDO
      ENDDO
      DO I=3,MIN(3,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,4)
          OUT(3,NEW_POSITION,I)=OUT(3,NEW_POSITION,I)+(-U(3,L,I))
        ENDDO
      ENDDO
      DO I=4,MIN(4,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,1)
          OUT(4,NEW_POSITION,I)=OUT(4,NEW_POSITION,I)+U(4,L,I)
        ENDDO
      ENDDO
      DO I=4,MIN(4,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,2)
          OUT(4,NEW_POSITION,I)=OUT(4,NEW_POSITION,I)+(-U(3,L,I))
        ENDDO
      ENDDO
      DO I=4,MIN(4,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,3)
          OUT(4,NEW_POSITION,I)=OUT(4,NEW_POSITION,I)+CMPLX(-AIMAG(U(3
     $     ,L,I)),REAL(U(3,L,I),KIND=16),KIND=16)
        ENDDO
      ENDDO
      DO I=4,MIN(4,LCUT_SIZE)
        DO L=0,14
          NEW_POSITION=COMB_COEF_POS(L,4)
          OUT(4,NEW_POSITION,I)=OUT(4,NEW_POSITION,I)+U(4,L,I)
        ENDDO
      ENDDO

      CONTAINS
      ELEMENTAL LOGICAL FUNCTION WL_IS_FINITE(X)
      REAL*16, INTENT(IN) :: X
      INTEGER*8, PARAMETER :: ONE_WORDS(2)=TRANSFER(1.0_16,(/0_8,0_8/))
      INTEGER, PARAMETER :: HI=MERGE(1,2,ONE_WORDS(1).NE.0_8)
      WL_IS_FINITE=.FALSE.
      IF(STORAGE_SIZE(X).NE.128.OR.DIGITS(X).NE.113.OR.RADIX(X)
     $ .NE.2.OR.MAXEXPONENT(X).NE.16384) RETURN
      IF(ONE_WORDS(HI).NE.ISHFT(16383_8,48).OR.ONE_WORDS(3-HI).NE.0_8)
     $  RETURN
      ASSOCIATE(WORDS=>TRANSFER(X,ONE_WORDS))
      WL_IS_FINITE=IBITS(WORDS(HI),48,15).NE.32767_8
      END ASSOCIATE
      END FUNCTION
      ELEMENTAL LOGICAL FUNCTION WL_BOUNDED(X)
      REAL*16, INTENT(IN) :: X
      INTEGER*8, PARAMETER :: BOUND_ONE(2)=TRANSFER(1.0_16,(/0_8,0_8/))
      INTEGER, PARAMETER :: BOUND_HI=MERGE(1,2,BOUND_ONE(1).NE.0_8)
      WL_BOUNDED=.FALSE.
      IF(STORAGE_SIZE(X).NE.128.OR.DIGITS(X).NE.113.OR.RADIX(X)
     $ .NE.2.OR.MAXEXPONENT(X).NE.16384) RETURN
      IF(BOUND_ONE(BOUND_HI).NE.ISHFT(16383_8,48).OR.BOUND_ONE(3
     $ -BOUND_HI).NE.0_8) RETURN
      ASSOCIATE(WORDS=>TRANSFER(X,BOUND_ONE))
      IF(IBCLR(WORDS(BOUND_HI),63).EQ.0_8.AND.WORDS(3-BOUND_HI).EQ.0_8)
     $  THEN
        WL_BOUNDED=.TRUE.
      ELSE
        WL_BOUNDED=IBITS(WORDS(BOUND_HI),48,15)
     $   .GE.15383_8.AND.IBITS(WORDS(BOUND_HI),48,15).LE.17383_8
      ENDIF
      END ASSOCIATE
      END FUNCTION

      ELEMENTAL LOGICAL FUNCTION GATHER_BOUNDED(X)
      REAL*16, INTENT(IN) :: X
      INTEGER*8, PARAMETER :: ONE(2)=TRANSFER(1.0_16,(/0_8,0_8/))
      INTEGER, PARAMETER :: HI=MERGE(1,2,ONE(1).NE.0_8)
      GATHER_BOUNDED=.FALSE.
      IF(STORAGE_SIZE(X).NE.128.OR.DIGITS(X).NE.113.OR.RADIX(X)
     $ .NE.2.OR.MAXEXPONENT(X).NE.16384) RETURN
      IF(ONE(HI).NE.ISHFT(16383_8,48).OR.ONE(3-HI).NE.0_8) RETURN
      ASSOCIATE(WORDS=>TRANSFER(X,ONE))
      GATHER_BOUNDED=IBITS(WORDS(HI),48,15)
     $ .GE.15383_8.AND.IBITS(WORDS(HI),48,15).LE.17383_8
      IF(IBCLR(WORDS(HI),63).EQ.0_8.AND.WORDS(3-HI).EQ.0_8)
     $  GATHER_BOUNDED=.TRUE.
      END ASSOCIATE
      END FUNCTION

      END
