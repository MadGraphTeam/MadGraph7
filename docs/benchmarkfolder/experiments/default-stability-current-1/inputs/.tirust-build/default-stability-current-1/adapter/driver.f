C     Isolated diagnostic ABI. Source templates are rendered by
C      build_harness.py.
C     No normalization, counterterms or R2 are added to the contracted
C      moments.
      INTEGER(C_INT) FUNCTION TIRUST_STABILITY_CONTRACT(MODE,
     & PL_INPUT,MASS_INPUT,MU2,NUMERATOR,RESULT)
     & BIND(C,NAME='tirust_stability_contract')
      USE, INTRINSIC :: ISO_C_BINDING
      USE, INTRINSIC :: IEEE_ARITHMETIC
      USE MTIRUST, ONLY: KI_QTIR
      IMPLICIT NONE
      INTEGER(C_INT), VALUE :: MODE
      REAL(C_DOUBLE), INTENT(IN) :: PL_INPUT(0:3,4)
      COMPLEX(C_DOUBLE_COMPLEX), INTENT(IN) :: MASS_INPUT(4)
      REAL(C_DOUBLE), VALUE :: MU2
      COMPLEX(C_DOUBLE_COMPLEX), INTENT(IN) :: NUMERATOR(126)
      COMPLEX(C_DOUBLE_COMPLEX), INTENT(OUT) :: RESULT(3)
      REAL(C_DOUBLE) PL(0:3,4),MU_R
      COMPLEX(C_DOUBLE_COMPLEX) MASSES(4),TENSOR(0:209,3)
      REAL(KI_QTIR) QPL(0:3,4)
      COMPLEX(KI_QTIR) QTENSOR(0:209,3),QRESULT(3)
      INTEGER I,J,CTMODE
      LOGICAL STABLE
      COMMON/AUDIT_COUPL/MU_R
      INCLUDE 'MadLoopParams.inc'
      RESULT=CMPLX(0,0,KIND=C_DOUBLE)
      TIRUST_STABILITY_CONTRACT=2_C_INT
      IF(MODE.NE.1.AND.MODE.NE.2.AND.MODE.NE.4.AND.MODE.NE.5) RETURN
      IF(.NOT.IEEE_IS_FINITE(MU2).OR.MU2.LE.0D0) RETURN
      CALL DEFAULTPARAM()
      MLREDUCTIONLIB=0
      MLREDUCTIONLIB(1)=9
      MLSTABTHRES=1D-3
      LOOPPOLEMODE=0
      TIRUSTCOMPUTEFINITE=.TRUE.
      MU_R=SQRT(MU2)
      CTMODE=INT(MODE)
      MASSES=MASS_INPUT
      TIRUST_STABILITY_CONTRACT=1_C_INT
      IF(MODE.LE.2) THEN
        PL=PL_INPUT
        CALL AUDIT_TIRUST_TENSOR_DIAGNOSTIC(CTMODE,4,5,PL,MASSES,
     &    TENSOR,STABLE)
        IF(.NOT.STABLE) RETURN
        DO I=1,3
          DO J=0,125
            RESULT(I)=RESULT(I)+NUMERATOR(J+1)*TENSOR(J,I)
          ENDDO
        ENDDO
      ELSE
        QPL=REAL(PL_INPUT,KIND=KI_QTIR)
        CALL AUDIT_MP_TIRUST_TENSOR_DIAGNOSTIC(CTMODE,4,5,QPL,
     &    MASSES,QTENSOR,STABLE)
        IF(.NOT.STABLE) RETURN
        QRESULT=CMPLX(0,0,KIND=KI_QTIR)
        DO I=1,3
          DO J=0,125
            QRESULT(I)=QRESULT(I)+CMPLX(NUMERATOR(J+1),
     &        KIND=KI_QTIR)*QTENSOR(J,I)
          ENDDO
          RESULT(I)=CMPLX(QRESULT(I),KIND=C_DOUBLE)
        ENDDO
      ENDIF
      DO I=1,3
        IF(.NOT.IEEE_IS_FINITE(REAL(RESULT(I),KIND=C_DOUBLE)).OR.
     &     .NOT.IEEE_IS_FINITE(AIMAG(RESULT(I)))) THEN
        RESULT=CMPLX(0,0,KIND=C_DOUBLE)
        RETURN
        ENDIF
      ENDDO
      TIRUST_STABILITY_CONTRACT=0_C_INT
      END

C     Execute the production accuracy formula, not the full rescue
C      policy.
      INTEGER(C_INT) FUNCTION TIRUST_HOST_ACCURACY(VALUES,COUNT,
     & ACCURACY,RESULT) BIND(C,NAME='tirust_host_accuracy')
      USE, INTRINSIC :: ISO_C_BINDING
      IMPLICIT NONE
      REAL(C_DOUBLE), INTENT(IN) :: VALUES(3,4)
      INTEGER(C_INT), VALUE :: COUNT
      REAL(C_DOUBLE), INTENT(OUT) :: ACCURACY,RESULT(3)
      REAL(C_DOUBLE) FULLLIST(3,0:1,4),ACC(0:1),ESTIMATE(0:3,0:1)
      INTEGER MAXSTABILITYLENGTH,I_LIB,LENGTH,I
      LOGICAL CHOSEN_SO_CONFIGS(1)
      COMMON/AUDIT_STABILITY_TESTS/MAXSTABILITYLENGTH
      COMMON/AUDIT_CHOSEN_LOOP_SQSO/CHOSEN_SO_CONFIGS
      COMMON/AUDIT_I_LIB/I_LIB
      INCLUDE 'MadLoopParams.inc'
      TIRUST_HOST_ACCURACY=2_C_INT
      ACCURACY=0D0
      RESULT=0D0
      IF(COUNT.LT.2.OR.COUNT.GT.4) RETURN
      CALL DEFAULTPARAM()
      MLREDUCTIONLIB=0
      MLREDUCTIONLIB(1)=9
      MLSTABTHRES=1D-3
      MAXSTABILITYLENGTH=4
      CHOSEN_SO_CONFIGS=.TRUE.
      I_LIB=1
      LENGTH=INT(COUNT)
      FULLLIST=0D0
      ESTIMATE=0D0
      ACC=0D0
      DO I=1,LENGTH
        FULLLIST(:,0,I)=VALUES(:,I)
        FULLLIST(:,1,I)=VALUES(:,I)
      ENDDO
      CALL AUDIT_COMPUTE_ACCURACY(FULLLIST,LENGTH,ACC,ESTIMATE)
      ACCURACY=ACC(1)
      RESULT=ESTIMATE(1:3,1)
      TIRUST_HOST_ACCURACY=0_C_INT
      END

