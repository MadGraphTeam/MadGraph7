def _module_path(name: str) -> Path | None:
    """The source file of first-party module ``name`` (a package's
    ``__init__.py``), or None when it is not a first-party source file."""

    root = Path(__file__).resolve().parents[1]
    if name != "pyamplicol" and not name.startswith("pyamplicol."):
        return None
    relative = Path(*name.split(".")[1:])
    for candidate in (root / relative / "__init__.py", root / f"{relative}.py"):
        if candidate.is_file():
            return candidate
    return None


def _program_sources(modules: tuple[str, ...]) -> tuple[Path, ...]:
    """The source files of ``modules`` (those that form and read a stored
    program) and of every first-party module they import directly,
    wherever the import stands (deferred imports in functions included):
    the code a stored program depends on. (The full import closure reaches
    most of the package through its ``__init__`` re-exports and costs
    about 3.5 s to scan.)"""

    found: set[Path] = set()
    for name in modules:
        path = _module_path(name)
        if path is None:
            continue
        found.add(path)
        package = name if path.name == "__init__.py" else name.rpartition(".")[0]
        imported: list[str] = []
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(node, ast.Import):
                imported.extend(alias.name for alias in node.names)
            elif isinstance(node, ast.ImportFrom):
                if node.level:
                    base = package.split(".")
                    base = base[: len(base) - node.level + 1]
                    stem = ".".join(base + ([node.module] if node.module else []))
                else:
                    stem = node.module or ""
                imported.append(stem)
                # ``from package import module`` names a module too.
                imported.extend(f"{stem}.{alias.name}" for alias in node.names)
        found.update(
            source
            for source in map(_module_path, imported)
            if source is not None and source.name != "__init__.py"
        )
    return tuple(sorted(found))


def _symbolica_identity() -> dict[str, Any]:
    """The loaded Symbolica build: its distribution and module versions and
    its extension module's size and modification time (a content digest of
    the extension, about 230 MB, costs about 0.9 s per generation; a
    rebuild of equal size and time would not be told apart)."""

    import symbolica

    from pyamplicol.models.loading import _distribution_version

    core = sys.modules.get("symbolica.core")
    extension = getattr(core, "__file__", None)
    stat = os.stat(extension) if extension else None
    return {
        "distribution": _distribution_version("symbolica", "missing"),
        "module": getattr(symbolica, "__version__", None),
        "extension_bytes": None if stat is None else stat.st_size,
        "extension_mtime_ns": None if stat is None else stat.st_mtime_ns,
    }


@functools.cache
def code_identity() -> dict[str, Any]:
    """What a stored program depends on besides the raw model (formed once
    per process): the cache schema, the package version, a SHA-256 of the
    first-party sources that form it (``_program_sources``, paths relative
    to the package), the Python version (``ast`` / ``tokenize`` read the
    sources), Symbolica and ufo-model-loader."""

    import pyamplicol
    from pyamplicol.models.loading import _distribution_version

    root = Path(__file__).resolve().parents[1]
    digest = hashlib.sha256()
    for path in _program_sources(_PROGRAM_MODULES):
        digest.update(path.relative_to(root).as_posix().encode() + b"\0")
        digest.update(path.read_bytes() + b"\0")
    return {
        "schema": SCHEMA_VERSION,
        "pyamplicol": pyamplicol.__version__,
        "sources_sha256": digest.hexdigest(),
        "python": list(sys.version_info[:2]),
        "symbolica": _symbolica_identity(),
        "ufo_model_loader": _distribution_version("ufo-model-loader", "missing"),
    }


def _canonical(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")


@dataclass
class PreparationStore:
    """The persistent per-user store of lowered scalar programs (module
    docstring), in ``directory``. A directory that cannot be read or
    written leaves the generation uncached (one log line), never failing
    it."""

    directory: Path
    # The state of this generation's use (``report``).
    events: Counter[str] = field(default_factory=Counter)
    seconds: dict[str, float] = field(default_factory=dict)
    # (id(raw), simplify) -> key, and the raw models so keyed (kept alive,
    # so that an id is never reused while it is a key).
    _keys: dict[tuple[int, bool], str] = field(default_factory=dict)
    _raws: dict[int, Any] = field(default_factory=dict)

    def report(self) -> dict[str, Any]:
        return {
            "directory": str(self.directory),
            **dict(sorted(self.events.items())),
            "seconds": dict(sorted(self.seconds.items())),
        }

    def _time(self, label: str, start: float) -> None:
        import time

        self.seconds[label] = self.seconds.get(label, 0.0) + time.perf_counter() - start

    def key(self, raw: Any, simplify: bool) -> str:
        """The entry key of ``raw``'s program under ``simplify`` (formed
        once per raw model object)."""

        import time

        memo = (id(raw), simplify)
        found = self._keys.get(memo)
        if found is None:
            start = time.perf_counter()
            self._raws.setdefault(id(raw), raw)
            found = self._keys[memo] = hashlib.sha256(
                _canonical(
                    {
                        "kind": ENTRY_KIND,
                        "raw": raw.to_dict(),
                        "simplify": simplify,
                        "code": code_identity(),
                    }
                )
            ).hexdigest()
            self._time("key", start)
        return found

    def path(self, key: str) -> Path:
        return self.directory / f"{key}{ENTRY_SUFFIX}"

    # -- load -------------------------------------------------------------

    def load(self, raw: Any, simplify: bool, derived: Any) -> Any:
        """The stored program of ``raw`` under ``simplify``, bound to its
        restricted model ``derived``, or None (missing, unreadable or not
        exactly this key's entry: ignored, the caller rebuilds it)."""

        import time

        key = self.key(raw, simplify)
        path = self.path(key)
        start = time.perf_counter()
        try:
            data = path.read_bytes()
        except FileNotFoundError:
            self.events["misses"] += 1
            return None
        except OSError as error:
            self._unusable("read", error)
            return None
        try:
            program = _program_from_entry(data, key, derived)
        except Exception as error:  # an entry is never trusted: rebuilt
            logger.info("loop preparation cache: ignored entry %s (%s)", path, error)
            self.events["rejected"] += 1
            return None
        self.events["hits"] += 1
        self._time("load", start)
        return program

    # -- save -------------------------------------------------------------

    def save(self, raw: Any, simplify: bool, program: Any) -> bool:
        """Store ``program`` atomically under its key (True when written)."""

        import time

        if self.events.get("unusable"):
            return False
        key = self.key(raw, simplify)
        start = time.perf_counter()
        data = _program_entry(program, key)
        try:
            _atomic_write(self.path(key), data)
        except OSError as error:
            self._unusable("write", error)
            return False
        self.events["saves"] += 1
        self._time("save", start)
        return True

    def _unusable(self, action: str, error: OSError) -> None:
        if not self.events.get("unusable"):
            logger.warning(
                "loop preparation cache %s: cannot %s (%s); this generation "
                "is not cached",
                self.directory,
                action,
                error,
            )
        self.events["unusable"] += 1


def _atomic_write(path: Path, data: bytes) -> None:
    """``data`` at ``path``: a unique temporary file in its directory,
    flushed to disk, then renamed over it (a reader never sees a partial
    entry; concurrent writers of one key both succeed, the last rename
    wins with a complete entry)."""

    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=path.parent
    )
    try:
        with os.fdopen(handle, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(temporary)
        raise


def _pack_head() -> Any:
    from pyamplicol._internal.physics.symbols import symbols

    return symbols.qualified("pyamplicol_loop_preparation::pack")


def _program_entry(program: Any, key: str) -> bytes:
    """The entry of a scalar program: one JSON header line (kind, schema,
    key, code identity, the payload's SHA-256, the definitions' records in
    the program's order and the lowered sources' texts) and the payload,
    Symbolica's own serialization (``Expression.save``: exact, the symbols
    by name) of one expression holding every definition's value and
    diagnostic, then every lowered source's (``ScalarFunctionLibrary.lower``
    without bindings, which the later stages read again)."""

    library = program.library
    sources = sorted(library._lowered.items(), key=lambda item: item[0])
    parts: list[Any] = []
    for definition in program.definitions.values():
        parts += (definition.value.expression, definition.diagnostic)
    for _source, lowered in sources:
        parts += (lowered.value, lowered.diagnostic)
    with tempfile.TemporaryDirectory(prefix="pyamplicol-loop-preparation-") as work:
        target = Path(work) / "payload"
        _pack_head()(*parts).save(str(target))
        payload = target.read_bytes()
    header = {
        "kind": ENTRY_KIND,
        "schema": SCHEMA_VERSION,
        "key": key,
        "identity": code_identity(),
        "payload_sha256": hashlib.sha256(payload).hexdigest(),
        "definitions": [
            [definition.collection, definition.id, definition.name]
            for definition in program.definitions.values()
        ],
        "sources": [[source, closed] for (source, closed), _lowered in sources],
    }
    return _canonical(header) + b"\n" + payload


def _program_from_entry(data: bytes, key: str, derived: Any) -> Any:
    """The program of a stored entry, checked: its kind, schema, key, code
    identity and payload digest, its definitions against ``derived``'s
    scalar declarations (records and names) and the payload's shape.
    Raises on any mismatch."""

    from symbolica import Expression

    from .model_expressions import LaurentExpression
    from .scalar_frontend import (
        ScalarExpression,
        ScalarFunctionLibrary,
        ScalarProgram,
        SourceScalarDefinition,
    )

    line, separator, payload = data.partition(b"\n")
    if not separator:
        raise ValueError("truncated entry")
    header = json.loads(line)
    if not isinstance(header, dict) or header.get("kind") != ENTRY_KIND:
        raise ValueError("not a loop preparation entry")
    if header.get("schema") != SCHEMA_VERSION or header.get("key") != key:
        raise ValueError("another schema or key")
    if header.get("identity") != code_identity():
        raise ValueError("another code identity")
    if hashlib.sha256(payload).hexdigest() != header.get("payload_sha256"):
        raise ValueError("payload digest differs")
    records = {
        (collection, record["id"]): record["name"]
        for collection in ("parameters", "counterterm_parameters", "couplings")
        for record in derived.collections[collection]
    }
    rows, sources = header["definitions"], header["sources"]
    if len(rows) != len(records) or len(
        {(collection, number) for collection, number, _name in rows}
    ) != len(rows):
        raise ValueError("definitions differ from the model's declarations")
    for collection, number, name in rows:
        if records.get((collection, number)) != name:
            raise ValueError("definitions differ from the model's declarations")
    # The library first: its predicates and helper heads exist (with their
    # attributes) before the payload's symbols are read by name.
    library = ScalarFunctionLibrary(derived)
    head = _pack_head()
    with tempfile.TemporaryDirectory(prefix="pyamplicol-loop-preparation-") as work:
        target = Path(work) / "payload"
        target.write_bytes(payload)
        whole = Expression.load(str(target))
    parts = list(whole)
    if whole.get_name() != head.get_name() or len(parts) != 2 * (
        len(rows) + len(sources)
    ):
        raise ValueError("payload shape differs")
    definitions = {}
    for index, (collection, number, name) in enumerate(rows):
        value, diagnostic = parts[2 * index], parts[2 * index + 1]
        definitions[collection, number] = SourceScalarDefinition(
            collection, number, name, LaurentExpression(value), diagnostic
        )
    offset = 2 * len(rows)
    for index, (source, closed) in enumerate(sources):
        if not isinstance(source, str) or not isinstance(closed, bool):
            raise ValueError("malformed lowered source")
        library._lowered[source, closed] = ScalarExpression(
            parts[offset + 2 * index], parts[offset + 2 * index + 1]
        )
    return ScalarProgram(library, MappingProxyType(definitions))
