"""The one-loop request-model preparation: shared within a generation and
prepared ahead in a persistent per-user cache.

A one-loop generation prepares the request model of its model
(``loops.v2.assemble.prepare_request_model``: the restricted declarations,
their scalar program, the covariant structure, the loop model and the
counterterm model) for the loop-order inference of a loop-induced process,
for every process slice, for the dry run and, with
``generation.loop_induced_probes``, for the probe and Goldstone slices.

**Within a generation.** A ``PreparationMemo`` is created per
``Generator.generate`` / ``Generator.plan`` call, passed explicitly to those
consumers and dropped with the call:

* the restricted declarations and their lowered scalar program
  (``model_restrictions.prepare_loop_restrictions``, which hands its program
  to ``covariant_model.build_covariant_structure``) are formed once per raw
  model and simplification: they read neither the order bounds nor the
  fixed parameters, so every preparation of the generation shares them;
* the request model of ``loops.compiler.prepare_loop_request_model`` (and
  its declared source-colour continuation) is formed once per recipe: the
  raw model, the simplification, the order bounds, the fixed parameters
  (with the source-colour ones and a probe's zeroed widths), the
  compatibility profile and the colour declaration, everything it reads.
  The refusals that read a request's process, veto or compiled model
  (``prepare_request_model``) run again for every request.

**Across generations** (``PreparationStore``, on by default): the lowered
scalar program of a raw model (its definitions and the lowered sources the
later stages read again) is kept in ``<model cache>/loop-preparations/``,
one JSON file per key. The key is a SHA-256 over the raw model's content as
the generation sees it (records and metadata: restriction card, loop
declaration, loop preparation, mass scheme), the simplification, the cache
schema and the code identity (package version, a digest of the first-party
sources that form the program, Symbolica and ufo-model-loader). An entry is
written atomically (a unique temporary file in its directory, fsync,
replace), carries its key, schema, identity and the digest of its payload,
all checked on load; anything else (missing, truncated, corrupt, foreign or
stale) is ignored and rebuilt. Nothing here ever deletes an entry. The
expressions are stored in Symbolica's own serialization (``Expression.save``
/ ``load``: exact, symbols by name; the payload of the electroweak UFO
``loop_qcd_qed_sm_Gmu`` is about 0.1 MB where canonical strings take 104 MB
and 4 s to parse). Measured entries: about 35 kB for ``loop_sm`` and
0.65-0.78 MB for ``loop_qcd_qed_sm_Gmu`` (the header lists the definitions
and the lowered sources), read in a generation in 0.3-0.4 s and 0.8-2.5 s
against 3-5 s to lower and check the electroweak program. The memo and the
store change no generated byte.

Never a model, process or name key: the keys are the inputs themselves.
"""

from __future__ import annotations

import ast
import contextlib
import functools
import hashlib
import json
import logging
import os
import sys
