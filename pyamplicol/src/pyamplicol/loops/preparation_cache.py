logger = logging.getLogger(__name__)

# The persistent cache (``PreparationStore``).
SCHEMA_VERSION = 1
ENTRY_KIND = "pyamplicol-loop-preparation"
ENTRY_SUFFIX = ".pyAmplicol-loop-preparation.json"
CACHE_SUBDIRECTORY = "loop-preparations"
CACHE_ENVIRONMENT = "PYAMPLICOL_LOOP_PREPARATION_CACHE"
_TRUE = frozenset({"1", "true", "yes", "on"})
_FALSE = frozenset({"0", "false", "no", "off"})
# The modules whose code forms and reads a stored program; the code identity
# hashes them and the first-party modules they import (``_program_sources``).
_PROGRAM_MODULES = (
    "pyamplicol.loops.model_restrictions",
    "pyamplicol.loops.scalar_frontend",
    "pyamplicol.loops.preparation_cache",
)


def preparation_cache_setting(value: Any, name: str) -> bool:
    """The one validator of the preparation-cache switch: a boolean (a
    configuration value) or, for the environment variable, one of
    1/0, true/false, yes/no, on/off (any case); anything else is refused
    with one message."""

    from pyamplicol.config.errors import ConfigurationError

    if isinstance(value, bool):
        return value
    if isinstance(value, str):
        text = value.strip().lower()
        if text in _TRUE:
            return True
        if text in _FALSE:
            return False
    raise ConfigurationError(
        f"{name} must be a boolean (true/false; in the environment 1/0, "
        "true/false, yes/no or on/off)"
    )


def environment_setting() -> bool | None:
    """``$PYAMPLICOL_LOOP_PREPARATION_CACHE`` (None when unset or empty)."""

    value = os.environ.get(CACHE_ENVIRONMENT)
    if value is None or not value.strip():
        return None
    return preparation_cache_setting(value, CACHE_ENVIRONMENT)


def store_for(model_config: Any) -> PreparationStore | None:
    """The persistent store of a run's ``[model]`` configuration, or None
    when it is off. One rule: the cache is used only when every switch
    allows it: ``model.cache`` (no model cache means none),
    ``model.loop_preparation_cache`` (default true; ``--no-loop-preparation-
    cache``) and ``$PYAMPLICOL_LOOP_PREPARATION_CACHE`` (a false value turns
    it off; true changes nothing). Its directory is the model cache's
    (``model.cache_dir``, else ``$PYAMPLICOL_CACHE_DIR/models``, else the
    per-user cache's ``models``) ``loop-preparations`` subdirectory."""

    if not (model_config.cache and model_config.loop_preparation_cache):
        return None
    if environment_setting() is False:
        return None
    from pyamplicol.models.loading import _default_model_cache_dir

    root = model_config.cache_dir
    root = _default_model_cache_dir() if root is None else Path(root)
    return PreparationStore(Path(root).expanduser() / CACHE_SUBDIRECTORY)


class PreparationMemo:
    """The request-model preparations of one generation (module docstring).

    ``store`` (a ``PreparationStore`` or None) serves the lowered scalar
    programs across generations. ``counts`` records what was formed, loaded
    and reused (``restrictions`` / ``restriction_hits``, ``lowerings``,
    ``program_loads`` / ``program_saves``, ``requests`` / ``request_hits``),
    for the generation's report and the tests."""

    def __init__(self, store: PreparationStore | None = None) -> None:
        self.store = store
        # id(raw) -> raw: the memo holds every raw model it keys, so an
        # object id is never reused for another model while it lives.
        self._raws: dict[int, Any] = {}
        self._sources: dict[tuple[int, bool], Any] = {}
        self._requests: dict[tuple[Any, ...], tuple[Any, Any]] = {}
        self.counts: Counter[str] = Counter()

    def _raw_key(self, raw: Any) -> int:
        self._raws.setdefault(id(raw), raw)
        return id(raw)

    def report(self) -> dict[str, Any]:
        """The memo's counts and the store's state (for the generation's
        log; never written into a plan or an artifact)."""

        record: dict[str, Any] = dict(sorted(self.counts.items()))
        record["store"] = None if self.store is None else self.store.report()
        return record

    # -- the restricted declarations and their scalar program --------------

    def restrictions(self, raw: Any, *, simplify: bool = True) -> Any:
        """``prepare_loop_restrictions(raw, simplify=simplify)``, formed once
        per raw model and simplification, always with the scalar program of
        its restricted model (from the store when one holds it): when the
        restriction does not lower it (no restriction card, or no
        simplification), it is lowered here from the same restricted model
        ``build_covariant_structure`` would lower, so every model's program
        is shared and stored alike."""

        from .model_restrictions import prepare_loop_restrictions

        key = (self._raw_key(raw), simplify)
        found = self._sources.get(key)
        if found is not None:
            self.counts["restriction_hits"] += 1
            return found
        self.counts["restrictions"] += 1
        lower = functools.partial(self._lower, raw, simplify)
        found = prepare_loop_restrictions(raw, simplify=simplify, lower=lower)
        if found.program is None:
            found = replace(found, program=lower(found.derived))
        self._sources[key] = found
        return found

    def _lower(self, raw: Any, simplify: bool, derived: Any) -> Any:
        """The scalar program of ``derived`` (``raw`` restricted with
        ``simplify``): loaded from the store, else lowered (and stored)."""

        from .scalar_frontend import lower_scalar_program

        if self.store is not None:
            program = self.store.load(raw, simplify, derived)
            if program is not None:
                self.counts["program_loads"] += 1
                return program
        self.counts["lowerings"] += 1
        program = lower_scalar_program(derived)
        if self.store is not None and self.store.save(raw, simplify, program):
            self.counts["program_saves"] += 1
        return program

    # -- the request model --------------------------------------------------

    def request_model(
        self,
        compiled: Any,
        recipe: dict[str, Any],
        prepare: Any,
    ) -> tuple[Any, Any]:
        """``prepare()`` (the prepared request model and its source-colour
        continuation, or None) once per recipe: ``compiled``'s raw model and
        simplification and ``recipe``, every other input of the preparation
        (JSON). A reused model is handed over to ``compiled`` (its owner)."""

        raw = compiled.raw_loop_model
        simplify = compiled.source.get("options", {}).get("simplify", True)
        try:
            text = json.dumps(recipe, sort_keys=True)
        except TypeError:
            # An input without a JSON form is never keyed: prepared afresh.
            self.counts["requests"] += 1
            return prepare()
        key = (self._raw_key(raw), simplify, text)
        found = self._requests.get(key)
        if found is None:
            self.counts["requests"] += 1
            found = self._requests[key] = prepare()
            return found
        self.counts["request_hits"] += 1
        prepared, continuation = found
        if (
            prepared.compiled_model is not None
            and prepared.compiled_model is not compiled
        ):
            prepared = replace(prepared, compiled_model=compiled)
        return prepared, continuation


