//! IR dipole operators per relabelling orbit (WP3.1 package C4,
//! `workspace/reports/engine-v2/wp31/RUST-MIGRATION.md` §3.C, §10 item 6 (a);
//! PLAN §3.7).
//!
//! Catani's prediction needs `C_ij[b, b'] = <b|T_i.T_j|b'>` at N_c = 3 over
//! the Born colour basis for every pair of coloured legs i != j
//! (`assemble.LoopSlice.dipoles`, the oracle). Relabelling summed adjoint
//! indices leaves a contraction unchanged, so for a permutation g of
//! identical external adjoint labels that maps the basis onto itself,
//! `g.b = s_b b''`, the entries obey
//!
//! ```text
//! C_{g i, g j}[g b, g b'] = C_ij[b, b'] / (conj(s_b) s_b')
//! ```
//!
//! The group is generated by the transpositions of identical labels that map
//! the basis onto itself (checked exactly). [`DipoleOrbits::build`] computes
//! one exact entry per orbit of (i, j, b, b'), checks colour conservation
//! (`sum_{j != i} T_i.T_j = -C_i` on every Born vector) exactly, and stores
//! the representatives with the generators' actions: tens of kB at seven
//! legs, portable (no paths, no host state). [`DipoleOrbits::expand`]
//! rebuilds every entry from them by orbit traversal, with index arithmetic
//! only: no basis tensors, no Python, no Symbolica state or licence.

use super::generate::cells::{
    Exact, Label, Leg, Structure, Tensor, Term, at_three, contract, emit, fraction_text,
};
use super::generate::{FastMap, FastSet};
use crate::loop_v2::dress::parse_rational;
use crate::{RusticolError, RusticolResult};
use rayon::prelude::*;
use serde::{Deserialize, Serialize};
use symbolica::domains::rational::Rational;

/// The format of [`DipoleOrbits::to_json`].
pub const FORMAT: &str = "pyamplicol-dipole-orbits-1";
const ADJOINT: i32 = 8;

fn invalid(message: impl Into<String>) -> RusticolError {
    RusticolError::invalid_argument(format!("dipole orbits: {}", message.into()))
}

/// One generator of the relabelling group: its action on the coloured legs
/// (by index) and on the basis elements (image, index into the scales).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Generator {
    pub legs: Vec<usize>,
    pub basis: Vec<(usize, usize)>,
}

/// The stored operator: orbit representatives and the group action.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DipoleOrbits {
    /// Coloured legs (label, representation), in leg order.
    pub coloured: Vec<Leg>,
    /// Basis size B.
    pub basis: usize,
    pub generators: Vec<Generator>,
    /// Distinct basis scales s (`g.b = s b''`); index 0 is one.
    pub scales: Vec<Exact>,
    /// (i, j, b, b', C_ij[b, b']) per orbit, i and j coloured-leg indices.
    pub representatives: Vec<(usize, usize, usize, usize, Rational)>,
    /// (b, b', <b|b'>) at N_c = 3 per orbit of basis pairs.
    pub gram: Vec<(usize, usize, Rational)>,
}

#[derive(Serialize, Deserialize)]
struct Stored {
    format: String,
    coloured: Vec<Leg>,
    basis: usize,
    generators: Vec<Generator>,
    scales: Vec<(String, String)>,
    representatives: Vec<(usize, usize, usize, usize, String)>,
    gram: Vec<(usize, usize, String)>,
}

/// `T_i |term>` (`apply_color_connection` with `EmitGluon(i, x)`): the image
/// on the legs plus the emitted adjoint `x`, normalisation 1/sqrt(2).
fn image(legs: &[Leg], term: &Term, emitter: Label, emitted: Label) -> RusticolResult<Tensor> {
    let mut out_legs = legs.to_vec();
    out_legs.push((emitted, ADJOINT));
    let terms = emit(&term.structure, emitter, emitted)?
        .into_iter()
        .map(|(sign, structure)| Term {
            coefficient: term.coefficient.scale(&Rational::from(sign)),
            structure,
            nc_power: term.nc_power,
        })
        .collect();
    Ok(Tensor::connected(out_legs, terms, 1))
}

fn real(value: Exact, what: &str) -> RusticolResult<Rational> {
    if !value.im.is_zero() {
        return Err(invalid(format!("{what} is not real")));
    }
    Ok(value.re)
}

/// The quadratic Casimir at N_c = 3 (`assemble._casimir`).
fn casimir(representation: i32) -> RusticolResult<Rational> {
    match representation {
        8 => Ok(Rational::from(3)),
        3 | -3 => Ok(Rational::new(8, 6)),
        other => Err(invalid(format!("colour representation {other}"))),
    }
}

/// Union-find root.
fn find(parent: &mut [usize], mut x: usize) -> usize {
    while parent[x] != x {
        parent[x] = parent[parent[x]];
        x = parent[x];
    }
    x
}

/// The basis action of the relabelling `rename`: per element, its image and
/// scale, or None where the basis is not mapped onto itself.
fn basis_action(
    items: &[Term],
    index: &FastMap<(Structure, i32), usize>,
    rename: &FastMap<Label, Label>,
) -> RusticolResult<Option<Vec<(usize, Exact)>>> {
    let map = |a: Label| *rename.get(&a).unwrap_or(&a);
    let mut out = Vec::with_capacity(items.len());
    let mut hit = vec![false; items.len()];
    for term in items {
        let image = term.structure.relabelled(&map);
        let Some(&target) = index.get(&(image, term.nc_power)) else {
            return Ok(None);
        };
        if std::mem::replace(&mut hit[target], true) {
            return Ok(None);
        }
        // g.t = c S' = (c / c') t'.
        let scale = term.coefficient.mul(&items[target].coefficient.inv()?);
        out.push((target, scale));
    }
    Ok(Some(out))
}

impl DipoleOrbits {
    /// Build the representatives from the Born basis (`basis[b]`, one term
    /// each, normalisation 0) on `legs`; `classes` are the candidate sets of
    /// identical external adjoint labels (one particle each). Colour
    /// conservation is checked exactly.
    pub fn build(legs: &[Leg], basis: &[Tensor], classes: &[Vec<Label>]) -> RusticolResult<Self> {
        let mut legs = legs.to_vec();
        legs.sort();
        let mut items = Vec::with_capacity(basis.len());
        for tensor in basis {
            if tensor.legs != legs {
                return Err(invalid("a basis tensor is not on the legs"));
            }
            if tensor.normalization != 0 || tensor.terms.len() != 1 {
                return Err(invalid(
                    "dipole operators need basis tensors of one term and no sqrt(2) normalisation",
                ));
            }
            items.push(tensor.terms[0].clone());
        }
        let coloured: Vec<Leg> = legs.iter().copied().filter(|leg| leg.1 != 1).collect();
        let position: FastMap<Label, usize> = coloured
            .iter()
            .enumerate()
            .map(|(k, leg)| (leg.0, k))
            .collect();
        let mut index: FastMap<(Structure, i32), usize> = FastMap::default();
        for (b, term) in items.iter().enumerate() {
            if index
                .insert((term.structure.clone(), term.nc_power), b)
                .is_some()
            {
                return Err(invalid("two basis elements share one structure"));
            }
        }
        // Verified transpositions of identical adjoint labels.
        let mut labels: Vec<Label> = Vec::new();
        for class in classes {
            for &label in class {
                if position
                    .get(&label)
                    .is_none_or(|&k| coloured[k].1 != ADJOINT)
                {
                    return Err(invalid(format!("label {label} is not an adjoint leg")));
                }
                labels.push(label);
            }
        }
        let slot: FastMap<Label, usize> = labels.iter().enumerate().map(|(k, &l)| (l, k)).collect();
        let mut parent: Vec<usize> = (0..labels.len()).collect();
        for class in classes {
            let mut members = class.clone();
            members.sort();
            for (k, &a) in members.iter().enumerate() {
                for &b in &members[k + 1..] {
                    let (ra, rb) = (find(&mut parent, slot[&a]), find(&mut parent, slot[&b]));
                    if ra == rb {
                        continue;
                    }
                    let swap: FastMap<Label, Label> = [(a, b), (b, a)].into_iter().collect();
                    if basis_action(&items, &index, &swap)?.is_some() {
                        parent[rb] = ra;
                    }
                }
            }
        }
        let mut groups: FastMap<usize, Vec<Label>> = FastMap::default();
        let mut roots = Vec::new();
        for (k, &label) in labels.iter().enumerate() {
            let root = find(&mut parent, k);
            groups
                .entry(root)
                .or_insert_with(|| {
                    roots.push(root);
                    Vec::new()
                })
                .push(label);
        }
        let mut scales: Vec<Exact> = vec![Exact::one()];
        let mut generators = Vec::new();
        for root in roots {
            let mut members = groups.remove(&root).expect("root");
            members.sort();
            for pair in members.windows(2) {
                let swap: FastMap<Label, Label> = [(pair[0], pair[1]), (pair[1], pair[0])]
                    .into_iter()
                    .collect();
                let action = basis_action(&items, &index, &swap)?
                    .ok_or_else(|| invalid("a generated transposition does not map the basis"))?;
                let legs_map = coloured
                    .iter()
                    .map(|leg| position[swap.get(&leg.0).unwrap_or(&leg.0)])
                    .collect();
                let basis_map = action
                    .into_iter()
                    .map(|(target, scale)| {
                        let k = match scales.iter().position(|s| *s == scale) {
                            Some(k) => k,
                            None => {
                                scales.push(scale);
                                scales.len() - 1
                            }
                        };
                        (target, k)
                    })
                    .collect();
                generators.push(Generator {
                    legs: legs_map,
                    basis: basis_map,
                });
            }
        }
        let mut orbits = Self {
            coloured,
            basis: items.len(),
            generators,
            scales,
            representatives: Vec::new(),
            gram: Vec::new(),
        };
        let (reps, gram_reps) = orbits.orbit_representatives()?;
        // Exact entries at the representatives (images cached per (i, b)).
        let emitted = legs.iter().map(|leg| leg.0).min().unwrap_or(0).min(0) - 1;
        let mut images: FastMap<(usize, usize), usize> = FastMap::default();
        let mut image_list: Vec<(usize, usize)> = Vec::new();
        for &(i, j, b, b2) in &reps {
            for key in [(i, b), (j, b2)] {
                images.entry(key).or_insert_with(|| {
                    image_list.push(key);
                    image_list.len() - 1
                });
            }
        }
        let tensors: Vec<Tensor> = image_list
            .par_iter()
            .map(|&(i, b)| image(&legs, &items[b], orbits.coloured[i].0, emitted))
            .collect::<RusticolResult<_>>()?;
        orbits.representatives = reps
            .par_iter()
            .map(|&(i, j, b, b2)| {
                let cell = contract(&tensors[images[&(i, b)]], &tensors[images[&(j, b2)]])?;
                Ok((i, j, b, b2, real(at_three(&cell), "a colour correlation")?))
            })
            .collect::<RusticolResult<_>>()?;
        orbits.gram = gram_reps
            .par_iter()
            .map(|&(b, b2)| {
                let cell = contract(&basis[b], &basis[b2])?;
                Ok((b, b2, real(at_three(&cell), "a Born colour metric entry")?))
            })
            .collect::<RusticolResult<_>>()?;
        orbits.check_conservation()?;
        Ok(orbits)
    }

    fn tuple_count(&self) -> usize {
        let c = self.coloured.len();
        c * c * self.basis * self.basis
    }

    fn tuple(&self, index: usize) -> (usize, usize, usize, usize) {
        let (c, n) = (self.coloured.len(), self.basis);
        let b2 = index % n;
        let rest = index / n;
        let b = rest % n;
        let rest = rest / n;
        (rest / c, rest % c, b, b2)
    }

    fn index(&self, (i, j, b, b2): (usize, usize, usize, usize)) -> usize {
        ((i * self.coloured.len() + j) * self.basis + b) * self.basis + b2
    }

    /// The first tuple of every orbit of (i != j, b, b') and of (b, b'), in
    /// index order.
    #[allow(clippy::type_complexity)]
    fn orbit_representatives(
        &self,
    ) -> RusticolResult<(Vec<(usize, usize, usize, usize)>, Vec<(usize, usize)>)> {
        let mut visited = vec![false; self.tuple_count()];
        let mut reps = Vec::new();
        let mut stack = Vec::new();
        for start in 0..self.tuple_count() {
            let (i, j, _, _) = self.tuple(start);
            if i == j || visited[start] {
                continue;
            }
            reps.push(self.tuple(start));
            visited[start] = true;
            stack.push(start);
            while let Some(current) = stack.pop() {
                let (i, j, b, b2) = self.tuple(current);
                for g in &self.generators {
                    let next = self.index((g.legs[i], g.legs[j], g.basis[b].0, g.basis[b2].0));
                    if !std::mem::replace(&mut visited[next], true) {
                        stack.push(next);
                    }
                }
            }
        }
        let n = self.basis;
        let mut seen = vec![false; n * n];
        let mut gram = Vec::new();
        for start in 0..n * n {
            if seen[start] {
                continue;
            }
            gram.push((start / n, start % n));
            seen[start] = true;
            stack.push(start);
            while let Some(current) = stack.pop() {
                let (b, b2) = (current / n, current % n);
                for g in &self.generators {
                    let next = g.basis[b].0 * n + g.basis[b2].0;
                    if !std::mem::replace(&mut seen[next], true) {
                        stack.push(next);
                    }
                }
            }
        }
        Ok((reps, gram))
    }

    /// The factor of one generator step: 1 / (conj(s_b) s_b').
    fn step(&self, g: &Generator, b: usize, b2: usize) -> RusticolResult<Option<Exact>> {
        let (s, s2) = (g.basis[b].1, g.basis[b2].1);
        if s == 0 && s2 == 0 {
            return Ok(None);
        }
        Ok(Some(self.scales[s].conj().mul(&self.scales[s2]).inv()?))
    }

    /// Visit every entry C_ij[b, b'] (i != j, coloured-leg indices) exactly
    /// once, by orbit traversal from the representatives. Fails on stored
    /// data whose orbits overlap or leave an entry uncovered.
    pub fn expand(
        &self,
        mut visit: impl FnMut(usize, usize, usize, usize, &Rational),
    ) -> RusticolResult<()> {
        let mut visited = vec![false; self.tuple_count()];
        let mut stack: Vec<(usize, Exact)> = Vec::new();
        let mut count = 0usize;
        for (i, j, b, b2, value) in &self.representatives {
            let start = self.index((*i, *j, *b, *b2));
            if *i == *j || std::mem::replace(&mut visited[start], true) {
                return Err(invalid("overlapping or diagonal orbit representatives"));
            }
            stack.push((start, Exact::real(value.clone())));
            while let Some((current, value)) = stack.pop() {
                let (i, j, b, b2) = self.tuple(current);
                visit(i, j, b, b2, &value.re);
                count += 1;
                for g in &self.generators {
                    let next = self.index((g.legs[i], g.legs[j], g.basis[b].0, g.basis[b2].0));
                    if !std::mem::replace(&mut visited[next], true) {
                        let image = match self.step(g, b, b2)? {
                            None => value.clone(),
                            Some(factor) => value.mul(&factor),
                        };
                        if !image.im.is_zero() {
                            return Err(invalid("a colour correlation is not real"));
                        }
                        stack.push((next, image));
                    }
                }
            }
        }
        let c = self.coloured.len();
        if count != c * (c.saturating_sub(1)) * self.basis * self.basis {
            return Err(invalid("the representatives do not cover every entry"));
        }
        Ok(())
    }

    /// Every Born metric entry `<b|b'>` at N_c = 3, by orbit traversal.
    pub fn expand_gram(
        &self,
        mut visit: impl FnMut(usize, usize, &Rational),
    ) -> RusticolResult<()> {
        let n = self.basis;
        let mut visited = vec![false; n * n];
        let mut stack: Vec<(usize, Exact)> = Vec::new();
        let mut count = 0usize;
        for (b, b2, value) in &self.gram {
            let start = b * n + b2;
            if std::mem::replace(&mut visited[start], true) {
                return Err(invalid("overlapping Born metric representatives"));
            }
            stack.push((start, Exact::real(value.clone())));
            while let Some((current, value)) = stack.pop() {
                let (b, b2) = (current / n, current % n);
                visit(b, b2, &value.re);
                count += 1;
                for g in &self.generators {
                    let next = g.basis[b].0 * n + g.basis[b2].0;
                    if !std::mem::replace(&mut visited[next], true) {
                        let image = match self.step(g, b, b2)? {
                            None => value.clone(),
                            Some(factor) => value.mul(&factor),
                        };
                        stack.push((next, image));
                    }
                }
            }
        }
        if count != n * n {
            return Err(invalid(
                "the Born metric representatives do not cover every entry",
            ));
        }
        Ok(())
    }

    /// SHA-256 of the operators in the order of `LoopSlice.dipoles`: per
    /// pair (i, j != i) of coloured legs in leg order, a block header
    /// `"(label_i, label_j) BxB"` (the Python repr of the dict key and the
    /// block shape), then every entry's exact text (`fraction_text`) by
    /// rows b and columns b', one line each. Equal digests mean the same
    /// pairs and shapes in the same order with equal entries. A dense value
    /// index (four bytes per entry) keeps the 7-leg comparison cheap.
    pub fn digest(&self) -> RusticolResult<String> {
        use sha2::{Digest, Sha256};
        let mut ids = vec![u32::MAX; self.tuple_count()];
        let mut values: Vec<Rational> = Vec::new();
        let mut index: FastMap<Rational, u32> = FastMap::default();
        let (c, n) = (self.coloured.len(), self.basis);
        self.expand(|i, j, b, b2, value| {
            let id = *index.entry(value.clone()).or_insert_with(|| {
                values.push(value.clone());
                (values.len() - 1) as u32
            });
            ids[((i * c + j) * n + b) * n + b2] = id;
        })?;
        let texts: Vec<String> = values.iter().map(fraction_text).collect();
        let mut hasher = Sha256::new();
        for (k, &id) in ids.iter().enumerate() {
            let (i, j) = (k / (n * n) / c, k / (n * n) % c);
            if i == j {
                continue;
            }
            if k % (n * n) == 0 {
                let (a, b) = (self.coloured[i].0, self.coloured[j].0);
                hasher.update(format!("({a}, {b}) {n}x{n}\n").as_bytes());
            }
            hasher.update(texts[id as usize].as_bytes());
            hasher.update(b"\n");
        }
        Ok(hasher
            .finalize()
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect())
    }

    /// Dense binary64 operators, `[i][j][b][b']` over coloured-leg indices
    /// (zero on i = j), each entry one correct rounding of its exact value.
    pub fn expand_f64(&self) -> RusticolResult<Vec<f64>> {
        let mut out = vec![0.0; self.tuple_count()];
        let (c, n) = (self.coloured.len(), self.basis);
        self.expand(|i, j, b, b2, value| {
            out[((i * c + j) * n + b) * n + b2] = super::dress::cast(&0.0f64, value);
        })?;
        Ok(out)
    }

    /// Colour conservation, exactly: sum_{j != i} C_ij[b, b'] = -C_i <b|b'>
    /// for every coloured i, on one row b per orbit of basis elements (the
    /// relation is equivariant) and every column b'.
    pub fn check_conservation(&self) -> RusticolResult<()> {
        let n = self.basis;
        let c = self.coloured.len();
        // One row per orbit of basis elements.
        let mut seen = vec![false; n];
        let mut rows = Vec::new();
        let mut stack = Vec::new();
        for start in 0..n {
            if seen[start] {
                continue;
            }
            rows.push(start);
            seen[start] = true;
            stack.push(start);
            while let Some(b) = stack.pop() {
                for g in &self.generators {
                    let next = g.basis[b].0;
                    if !std::mem::replace(&mut seen[next], true) {
                        stack.push(next);
                    }
                }
            }
        }
        let row_of: FastMap<usize, usize> = rows.iter().enumerate().map(|(k, &b)| (b, k)).collect();
        let mut sums = vec![Rational::zero(); c * rows.len() * n];
        let mut gram = vec![Rational::zero(); rows.len() * n];
        self.expand(|i, _j, b, b2, value| {
            if let Some(&k) = row_of.get(&b) {
                let slot = &mut sums[(i * rows.len() + k) * n + b2];
                *slot = &*slot + value;
            }
        })?;
        self.expand_gram(|b, b2, value| {
            if let Some(&k) = row_of.get(&b) {
                gram[k * n + b2] = value.clone();
            }
        })?;
        for (i, leg) in self.coloured.iter().enumerate() {
            let casimir = casimir(leg.1)?;
            for k in 0..rows.len() {
                for b2 in 0..n {
                    let expected = (&casimir * &gram[k * n + b2]).neg();
                    if sums[(i * rows.len() + k) * n + b2] != expected {
                        return Err(invalid(format!(
                            "colour correlators of leg {} violate colour conservation",
                            leg.0
                        )));
                    }
                }
            }
        }
        Ok(())
    }

    /// The portable stored form (JSON; no paths or host state).
    pub fn to_json(&self) -> RusticolResult<String> {
        let stored = Stored {
            format: FORMAT.to_owned(),
            coloured: self.coloured.clone(),
            basis: self.basis,
            generators: self.generators.clone(),
            scales: self.scales.iter().map(Exact::texts).collect(),
            representatives: self
                .representatives
                .iter()
                .map(|(i, j, b, b2, v)| (*i, *j, *b, *b2, fraction_text(v)))
                .collect(),
            gram: self
                .gram
                .iter()
                .map(|(b, b2, v)| (*b, *b2, fraction_text(v)))
                .collect(),
        };
        serde_json::to_string(&stored).map_err(|e| invalid(e.to_string()))
    }

    /// Load the stored form; indices and group actions are validated.
    pub fn from_json(text: &str) -> RusticolResult<Self> {
        let stored: Stored = serde_json::from_str(text).map_err(|e| invalid(e.to_string()))?;
        if stored.format != FORMAT {
            return Err(invalid(format!("unknown format {:?}", stored.format)));
        }
        let (c, n) = (stored.coloured.len(), stored.basis);
        let scales = stored
            .scales
            .iter()
            .map(|(re, im)| Exact::parse(re, im))
            .collect::<RusticolResult<Vec<_>>>()?;
        if scales.first().is_none_or(|s| !s.is_one()) || scales.iter().any(Exact::is_zero) {
            return Err(invalid("scale table must start with one and hold no zero"));
        }
        for g in &stored.generators {
            let legs: FastSet<usize> = g.legs.iter().copied().collect();
            let basis: FastSet<usize> = g.basis.iter().map(|x| x.0).collect();
            if g.legs.len() != c
                || legs.len() != c
                || g.legs.iter().any(|&k| k >= c)
                || g.basis.len() != n
                || basis.len() != n
                || g.basis.iter().any(|&(b, s)| b >= n || s >= scales.len())
            {
                return Err(invalid("a generator is not a permutation"));
            }
        }
        let representatives = stored
            .representatives
            .iter()
            .map(|(i, j, b, b2, v)| {
                if *i >= c || *j >= c || *b >= n || *b2 >= n {
                    return Err(invalid("representative out of range"));
                }
                Ok((*i, *j, *b, *b2, parse_rational(v)?))
            })
            .collect::<RusticolResult<_>>()?;
        let gram = stored
            .gram
            .iter()
            .map(|(b, b2, v)| {
                if *b >= n || *b2 >= n {
                    return Err(invalid("Born metric representative out of range"));
                }
                Ok((*b, *b2, parse_rational(v)?))
            })
            .collect::<RusticolResult<_>>()?;
        Ok(Self {
            coloured: stored.coloured,
            basis: n,
            generators: stored.generators,
            scales,
            representatives,
            gram,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn trace_basis(labels: &[Label]) -> Vec<Tensor> {
        // All single traces of the labels with the first one fixed.
        let legs: Vec<Leg> = labels.iter().map(|&l| (l, ADJOINT)).collect();
        let mut out = Vec::new();
        let rest: Vec<Label> = labels[1..].to_vec();
        let mut permutations = vec![rest];
        let mut k = 0;
        while k < permutations.len() {
            let p = permutations[k].clone();
            for i in 0..p.len() {
                for j in i + 1..p.len() {
                    let mut q = p.clone();
                    q.swap(i, j);
                    if !permutations.contains(&q) {
                        permutations.push(q);
                    }
                }
            }
            k += 1;
        }
        permutations.sort();
        for p in permutations {
            let mut trace = vec![labels[0]];
            trace.extend(p);
            out.push(Tensor::connected(
                legs.clone(),
                vec![Term {
                    coefficient: Exact::one(),
                    structure: Structure::new(Vec::new(), vec![trace]),
                    nc_power: 0,
                }],
                0,
            ));
        }
        out
    }

    #[test]
    fn four_gluon_orbits_expand_to_the_direct_entries() {
        let labels = [1, 2, 3, 4];
        let legs: Vec<Leg> = labels.iter().map(|&l| (l, ADJOINT)).collect();
        let basis = trace_basis(&labels);
        let built = DipoleOrbits::build(&legs, &basis, &[labels.to_vec()]).unwrap();
        let alone = DipoleOrbits::build(&legs, &basis, &[]).unwrap();
        assert!(built.representatives.len() < alone.representatives.len());
        let mut grouped = FastMap::default();
        built
            .expand(|i, j, b, b2, v| {
                grouped.insert((i, j, b, b2), v.clone());
            })
            .unwrap();
        let mut direct = FastMap::default();
        alone
            .expand(|i, j, b, b2, v| {
                direct.insert((i, j, b, b2), v.clone());
            })
            .unwrap();
        assert_eq!(grouped, direct);
        let stored = DipoleOrbits::from_json(&built.to_json().unwrap()).unwrap();
        assert_eq!(stored, built);
    }
}
