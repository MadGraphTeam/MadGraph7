"""Make an onia-compatible copy of a UFO model.

    tools/make_onia_model.py SOURCE_UFO DESTINATION_UFO [--boundstates FILE]

The copy is the source model plus what models/sm_onia adds to models/sm:
  - boundstates.py, the Fock states (quarkonia, leptonia); by default the
    one of models/sm_onia, keeping the states whose constituents are
    particles of the source model;
  - the Boundstate class and all_boundstates in object_library.py;
  - dual_mass_scheme = True and the citation header in __init__.py.
Everything else (particles, couplings, CT vertices and parameters of a loop
model, restriction cards) is copied unchanged. models/loop_sm_onia is
tools/make_onia_model.py models/loop_sm models/loop_sm_onia.
"""

import argparse
import ast
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The Fock states of the sm_onia model (downloaded by 'import model sm_onia'),
# else those shipped with loop_sm_onia
BOUNDSTATE_SOURCES = [os.path.join(ROOT, 'models', 'sm_onia', 'boundstates.py'),
                      os.path.join(ROOT, 'models', 'loop_sm_onia', 'boundstates.py')]
GENERATED_TAG = '# Fock states generated by tools/make_onia_model.py from'


def default_boundstates():
    for path in BOUNDSTATE_SOURCES:
        if os.path.isfile(path):
            return path
    return BOUNDSTATE_SOURCES[0]

BOUNDSTATE_CLASS = '''

all_boundstates = []



class Boundstate(UFOBaseClass):
    """A Fock state"""

    require_args=['pdg_code', 'name', 'particles', 'principal', 'spin', 'orbital', 'J', 'color', 'charge', 'texname']

    require_args_all = ['pdg_code', 'name', 'particles', 'principal', 'spin', 'orbital', 'J', 'color', 'charge', 'texname']

    def __init__(self, pdg_code, name, particles, principal, spin,
                 orbital, J, color, charge, texname, **options):

        args= (pdg_code, name, particles, principal, spin,
               orbital, J, color, charge, texname)

        UFOBaseClass.__init__(self, *args,  **options)

        global all_boundstates
        all_boundstates.append(self)
'''

INIT_BLOCK = '''

# Bound states (quarkonia, leptonia) of boundstates.py, added by
# tools/make_onia_model.py to the model %(source)s.
dual_mass_scheme = True

__header__ = \\
"""------------------------------------------------------------------------
By loading this model the calculation can involve quarkonia or leptonia.
Please cite refs. 'arXiv:2510.26773' and 'arXiv:2607.26739' when using
results from this code.
------------------------------------------------------------------------
"""
'''

IGNORED = shutil.ignore_patterns('__pycache__', '*.pyc', '*.pkl', '*.pickle')


def particle_pdgs(particles_py):
    """{name: pdg} for the particles (and antiparticles) declared in a
    particles.py, read from the source without importing the model."""
    tree = ast.parse(open(particles_py).read(), particles_py)
    pdgs = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and getattr(node.func, 'id', None) == 'Particle':
            kws = dict((kw.arg, kw.value) for kw in node.keywords)
            pdg = kws.get('pdg_code')
            if not isinstance(pdg, ast.Constant):
                continue
            # a self-conjugate particle (name == antiname) keeps its code
            for key, sign in (('name', 1), ('antiname', -1)):
                if isinstance(kws.get(key), ast.Constant):
                    pdgs.setdefault(kws[key].value, sign * pdg.value)
    return pdgs


def boundstate_blocks(boundstates_py):
    """Split a boundstates.py into its header (imports) and one block per
    Boundstate(...) assignment: (constituent names, source lines, position
    (line, first column, last column) of the particles list in those lines)."""
    source = open(boundstates_py).read()
    lines = source.splitlines(keepends=True)
    tree = ast.parse(source, boundstates_py)
    blocks = []
    first = None
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call) \
                and getattr(node.value.func, 'id', None) == 'Boundstate':
            if first is None:
                first = node.lineno - 1
            constituents, where = None, None
            for kw in node.value.keywords:
                if kw.arg == 'particles':
                    constituents = [e.value for e in kw.value.elts]
                    if kw.value.lineno == kw.value.end_lineno:
                        where = (kw.value.lineno - node.lineno, kw.value.col_offset,
                                 kw.value.end_col_offset)
            blocks.append((constituents, lines[node.lineno - 1:node.end_lineno], where))
    header = ''.join(lines[:first]) if first is not None else source
    return header, blocks


def rename_constituents(text, where, names):
    """The block's source lines with its (one-line) particles list replaced
    by `names`."""
    if where is None:
        raise ValueError('a multi-line particles list cannot be renamed')
    line, c0, c1 = where
    text = list(text)
    text[line] = text[line][:c0] + repr(list(names)) + text[line][c1:]
    return text


def make_onia_model(source, destination, boundstates=None, force=False):
    source = os.path.abspath(source)
    destination = os.path.abspath(destination)
    boundstates = os.path.abspath(boundstates or default_boundstates())
    if not os.path.isfile(os.path.join(source, 'particles.py')):
        raise SystemExit('%s is not a UFO model (no particles.py)' % source)
    if not os.path.isfile(boundstates):
        raise SystemExit('no Fock states to add: %s does not exist' % boundstates)
    # Read the Fock states first: they may come from the model being replaced
    header, blocks = boundstate_blocks(boundstates)
    lines = header.splitlines(keepends=True)
    if lines and lines[0].startswith(GENERATED_TAG):
        # regenerating from a generated file: drop its provenance lines
        lines = lines[3:]
    header = ''.join(lines)
    reference = os.path.join(os.path.dirname(boundstates), 'particles.py')
    reference_pdgs = particle_pdgs(reference) if os.path.isfile(reference) else None
    if os.path.exists(destination):
        if not force:
            raise SystemExit('%s exists (use --force to replace it)' % destination)
        shutil.rmtree(destination)
    shutil.copytree(source, destination, ignore=IGNORED)

    # object_library.py: the Boundstate class
    objlib = os.path.join(destination, 'object_library.py')
    text = open(objlib).read()
    if 'class Boundstate' not in text:
        open(objlib, 'a').write(BOUNDSTATE_CLASS)

    # boundstates.py: the Fock states whose constituents the model has. The
    # constituents are matched by PDG code, so a model naming them otherwise
    # (loop_sm: m-, tt- for mu-, ta-) keeps its leptonia.
    model_pdgs = particle_pdgs(os.path.join(destination, 'particles.py'))
    model_names = dict((pdg, name) for name, pdg in model_pdgs.items())
    reference_pdgs = reference_pdgs or model_pdgs
    kept = []
    for constituents, text, where in blocks:
        if not constituents:
            continue
        renamed = [p if p in model_pdgs else model_names.get(reference_pdgs.get(p))
                   for p in constituents]
        if None in renamed:
            continue
        if renamed != constituents:
            text = rename_constituents(text, where, renamed)
        kept.append(''.join(text) + '\n')
    dropped = len(blocks) - len(kept)
    with open(os.path.join(destination, 'boundstates.py'), 'w') as out:
        out.write('%s\n# %s\n\n' % (GENERATED_TAG, os.path.relpath(boundstates, ROOT)))
        out.write(header)
        out.writelines(kept)

    # __init__.py: the dual mass scheme and the citation header
    init = os.path.join(destination, '__init__.py')
    text = open(init).read()
    if 'dual_mass_scheme' not in text:
        open(init, 'a').write(INIT_BLOCK % dict(source=os.path.basename(source)))
    return len(kept), dropped


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('source', help='the UFO model to copy')
    parser.add_argument('destination', help='the onia-compatible UFO to write')
    parser.add_argument('--boundstates', default=None,
                        help='the boundstates.py to take the Fock states from '
                             '(default: models/sm_onia/boundstates.py if present, '
                             'else models/loop_sm_onia/boundstates.py)')
    parser.add_argument('--force', action='store_true', help='replace an existing destination')
    args = parser.parse_args(argv)
    kept, dropped = make_onia_model(args.source, args.destination, args.boundstates, args.force)
    print('%s: %d Fock states%s' % (args.destination, kept,
          ' (%d dropped: constituents not in the model)' % dropped if dropped else ''))


if __name__ == '__main__':
    sys.exit(main())
